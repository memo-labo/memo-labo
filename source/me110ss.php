<h2>三菱 ME110SS 電子式マルチメーター</h2>

<p><strong>ME110SSシリーズは、電流・電圧・電力・電力量・力率・周波数などを1台で表示できる電子式指示計器です。</strong></p>

<img src="images/me110ss1.jpg" style="max-width:500px;" alt="三菱 ME110SS 電子式マルチメーター"><br>

<p>シリーズ内でも計測項目、通信、出力、補助電源などの仕様が異なるため、<strong>本体の完全な形名を確認して取扱説明書を照合</strong>します。</p>

<h2>主な計測項目</h2>

<ul>
  <li>交流電流</li>
  <li>デマンド電流</li>
  <li>交流電圧</li>
  <li>有効電力・デマンド電力</li>
  <li>有効電力量</li>
  <li>無効電力・無効電力量</li>
  <li>力率</li>
  <li>周波数</li>
  <li>高調波電流・高調波電圧（対応機種）</li>
</ul>

<h2>配線を見るときのポイント</h2>

<img src="images/me110ss2.png" style="max-width:500px;" alt="ME110SSの配線例"><br>

<p>計器には主に次の入力があります。</p>

<ul>
  <li><strong>電流入力</strong>：CT二次側から入力</li>
  <li><strong>電圧入力</strong>：VTTやVT二次側から入力</li>
  <li><strong>補助電源</strong>：計器本体を動作させる電源</li>
  <li><strong>外部入力・出力</strong>：機種によりパルス、警報、通信、外部スイッチなど</li>
</ul>

<p>端子番号・極性は形名によって異なるため、写真や別現場の配線をそのまま流用せず、本体側面の結線図と取扱説明書を確認します。</p>

<h2>CT配線で注意すること</h2>

<p>CT入力では、k・lの極性を逆にすると電力・力率・位相表示が不自然になる場合があります。</p>

<p><strong>通電中のCT二次回路を不用意に開放しない</strong>ことも重要です。試験・交換時はCTTなど設備の指定手順に従います。</p>

<h2>VT・VTT配線で注意すること</h2>

<p>電圧入力の相順や相の取り違えがあると、電圧値自体が正常に見えても電力・力率の表示が異常になることがあります。</p>

<p>CT側だけでなく、電圧入力の相順もセットで確認します。</p>

<h2>誤結線判別サポート機能</h2>

<p>対応機種ではテスト機能を使い、電圧・電流入力の位相関係などから誤結線の判別を補助できます。</p>

<p>表示例として、CT逆接続などを示すメッセージや、低電圧・低電流・不平衡など試験条件不足を示す表示があります。</p>

<p><strong>「not found」などの表示が出ても結線が必ず正常という意味ではありません。</strong>負荷が小さい、力率が特殊、入力が不平衡など、判別条件を満たしていない場合があります。</p>

<h2>電力がマイナス表示になる場合</h2>

<p>受電している設備で有効電力が想定外にマイナスになる場合は、次を確認します。</p>

<ul>
  <li>CTのk・lが逆になっていないか</li>
  <li>R相・T相などCT入力の取り違えがないか</li>
  <li>電圧入力の相順が正しいか</li>
  <li>実際に逆潮流していないか</li>
</ul>

<p>太陽光発電や発電機がある設備では、実際の逆潮流でマイナスになることもあるため、表示だけで誤結線と断定しません。</p>

<h2>力率のLEAD・LAG表示</h2>

<ul>
  <li><strong>LEAD</strong>：進み力率</li>
  <li><strong>LAG</strong>：遅れ力率</li>
</ul>

<p>進相コンデンサの投入状況や軽負荷運転によって、進み力率になることがあります。</p>

<h2>デマンド表示</h2>

<p>デマンド電流・デマンド電力は、瞬時値とは異なり一定時間の平均や設定された時限に基づく値です。設定条件は機種・システムによって異なるため、デマンド監視に利用する場合は時限設定を確認します。</p>

