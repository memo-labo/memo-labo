アース線をコンデンサ筐体の接地端子に取り付ける。<br>
筐体がアースされていないと絶縁不良が発生した際に筐体が充電状態となる。<br>
そうすると人体への感電等の危険が生じる。<br>

<h2>本体に書かれた注意事項</h2>

<img src="images/scchange3.jpg" style="max-width:400px;"><br>
ロックナットは電線が確実に締付けられていることを確認後、締付けてください。<br>
運搬時に碍子を持って持ち上げるなど碍子に大きな力を加えることは絶対に避けてください。<br>
運転中は油の膨張によりケースが膨れます。この許容限度は片側当り下記の寸法です。<br>
それ以上の膨れは、何らかの異常と考えられますので電源より切り離し使用を中止してください。<br>
10～30kVA…8mm　50～100kVA…10mm<br>
コージェーサを自動制御にて開閉する場合及び回路より切り離し後は5分以上経て再投入したり、端子部に触れないでください。<br>
