<h2>高圧進相コンデンサの異常、交換推奨、交換工事</h2>

交換時期<br>
「更新推奨時期」を過ぎると交換時期。<br>
または油漏れ、表面のふくらみ、放射温度計による温度異常などでも。<br><br>

現地で下見<br>
今付いているコンデンサの同じ穴に、新しいコンデンサのボルトが留めることができるか。<br>
既存のKIPケーブルの長さで、新しいコンデンサに繋ぐことができるかどうか。<br><br>

古いタイプのコンデンサは、サイズが大きくて高さが高いタイプがある。<br>
新しいタイプのコンデンサは、省スペースで背の低いタイプがある。<br>
また古いコンデンサは重くて大きいので搬出時に腰を痛めない注意が必要。<br><br>

KIP線とコンデンサの接続部分<br>
KIP線の導体部分をそのまま挟み込めるようになっている。<br>
⇒<a href="kip.php">KIP線とは？</a><br><br>


