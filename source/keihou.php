<h2>キュービクルの警報試験（シーケンス制御）</h2>
LBSのPF溶断、変圧器温度異常、過負荷異常、コンデンサ異常、リアクトル異常など、盤の表にオレンジ色の表示灯がついている。<br>
異常があった際に、そのランプが点灯すると同時にブザー音が鳴る。<br>
それらが正常に働くか、制御電源を入力した状態で各a接点を動作させ確認する試験のこと。<br>

<h2>警報の種類</h2>
<ul>
<li>PF溶断（LBSストライカ動作）
<li>PF溶断（VMCのヒューズ溶断）
<li>漏電遮断器動作
<li>LGR（漏電火災警報器）動作
<li>SC（コンデンサ）動作
<li>SR（リアクトル）動作
<li>変圧器温度異常
<li>盤内温度異常
<li>デマンド異常
</ul>

<h2>試験方法</h2>
<ul>
<li>正確には電気設備図面のシーケンス回路に詳しく書いてあるのでそれを見る。
<li>それがなく、現場で判断する場合はまずオレンジ表示灯の裏の線番を見る。
<li>たいだいそこに制御電源の線番名の片方が書いてある。もう一方は警報回路番号。
<li>制御電源のMCCBをOFFにして、２次側に電源を入力する（ACかDCかは停電前に確認）
<li>PFであればストライカを手動で動作、コンデンサであればa接点を短絡、サーマルリレーであればテストボタンなど、各a接点を動作または短絡させる。
</ul>

