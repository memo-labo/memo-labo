<h2>LA内蔵型PASの耐圧試験上の注意</h2>
直流耐電圧試験はDC17kV以上を印加すると避雷器が動作し壊れてしまう。<br>
商用周波耐電圧試験はAC12kV以上を印加すると避雷器が動作し壊れてしまう。<br>
耐圧試験器が容量不足を起こすと、出力電圧が歪み、波高値が異常に高くなることがある。<br><br>

SOG制御装置内部には雷害対策のためSA（避雷器）がついている。<br>
各端子間に電圧が印加されるとSAや電子部品が故障する可能性がある。<br><br>

■PASのSOG制御装置の耐圧試験前処置<br>
SOG制御装置についている配線は外す。<br>
制御線P1P2は、各々テーピングで絶縁する。<br>
他の制御ケーブルは、一括で接地をする。<br>

<h2>VT、CT、変圧器の耐圧試験</h2>
VT、CT、変圧器、共通で低圧側（２次側）はすべてジャンパー線で短絡。<br>
短絡させた上で接地に接続してアースへ。<br>
VT、CT、変圧器の筐体の金属部もアースへ。<br>
高圧側（充電部）をジャンパー線で短絡させて電圧を印加。<br>
高圧充電部⇔２次側・筐体アース間との絶縁耐力を試験できる。<br>
２次側にアースがとられていないと１次側と２次側の耐圧試験ができない。<br>

