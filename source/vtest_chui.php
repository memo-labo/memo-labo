<h2>PASやUGSで３相短絡させていない事によるVT焼損</h2>
PASやUGSの「VT内蔵タイプ」は、３相のうち２相が内蔵VTの１次側に配線。<br>
内蔵VT１次側の１相のみに電圧を印加すると、静電容量分の充電電流が流れる。<br><br>

内蔵VTの容量は25VA程度、一次定格電流は3.8ｍA程度。<br>
内蔵VTに定格以上の電流が流れてVTが焼損、極度の絶縁低下や短絡が発生。<br>
内蔵VTの焼損に気づかずPAS投入し、焼損VTによる高圧部の相間短絡でPASが爆発した例も。<br>
