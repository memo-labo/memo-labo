<h2>地絡方向継電器DGRの絶縁耐力試験</h2>
<a href="zpd.php">ZPD（零相電圧検出器）</a>からのY1Y2線がDGR継電器に取り付いている状態で主回路の絶縁耐力試験を行う場合。<br>
この場合、継電器に想定以上の零相電圧が印可されて継電器が破損する可能性がある。<br>
DGR継電器側のY1とY2端子の結線を外し、ZPDと継電器を分離した方が安全。<br>
