<h2>耐電圧試験中に試験機ストップ！「抜ける」とは？</h2>
１０分間の10350Vの絶縁耐力試験中に、急に試験機がストップしてしまう現象。<br>
高圧CVケーブルなどに傷があり、被試験物に印加された高電圧が、その絶縁不良箇所から放電して大電流が流れることで、試験機の保護回路が働き、試験機がストップ。<br><br>

耐圧試験がストップした事例<br>
①CVケーブル端末の施工不良。耐圧試験中に煙が出た。<br>
②中古トランスを使用出来るかの確認依頼、試験前の絶縁メガも50MΩ程度。耐圧中にトランスが膨らんだ。<br>
③変圧器を新品に交換する工事でトランス耐圧中に試験ストップ。メーカーに送り返して調査。<br>
④中古の高圧引き込みケーブルを10350Vで耐圧試験。抜けて絶縁測定したらガクンと落ちたていた。<br><br>

この情報からわかること。<br>
新品の製品でメーカーの試験成績書があったとしても、絶縁耐力試験をクリアする保証はない。<br>
実際に取り付ける直前で現地で絶縁耐力試験をしないと結果はわからない。<br>
新品でも試験機がストップして絶縁破壊を起こす可能性もある。<br>

