<h2>耐圧試験中に接地線が外れたらどうなる？</h2>

疑問<br>
耐圧試験中、試験用トランスに繋がった接地線が外れたらどうなる？<br><br>

Twitter上の声（信憑性は不明）<br>
・音がジージーと鳴る。<br>
・試験機を接地していなければ試験機に触れたら試験者が感電する。<br>
・試験機の形で地面が焦げる。<br>
・双興の場合、カウンターが高確率で故障する。<br>
・ムサシ IP-R1500で耐圧トランスに接地線付け忘れて昇圧⇒3000V～5000V付近で試験器の電源落ちた。<br>
　保護回路が働いた？試験器本体にアース繋いでて助かった。<br><br>

接地線が外れていることに気がつく方法<br>
・充電電流の「つまみ」を「最小メモリ」に合わせてから昇圧する。<br>
・1000V、2000Vと昇圧しても、充電電流の針が全く触れなかったら接地線が外れてる可能性。<br>
・目視と同時に、すべての箇所をメガーを使用して接地されているか確認する。<br>
