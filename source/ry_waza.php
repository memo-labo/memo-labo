<h2>PASのSOGのa1-acが故障して試験できない時の対処法</h2>
SOG制御装置のa1-ac警報回路はa接点。<br>
その場合、Va-Vcの配線を外し、試験機からの信号線をVa-Vcに接続する。<br>
SOGが動作するとVa-VcからPASトリップ電圧が出力される。<br>
なのでDGR試験機の「接点⇔電圧」を電圧にして試験すれば出来る。<br>
もしVa-Vcで試験出来るのであれば、a1-acの警報接点が故障している。<br><br>

a1-acの警報接点不良は指摘事項に記載「交換を推奨」<br>
PASのSOGは、同じメーカー・型式なら単体で交換することが出来るらしい。<br>
また、警報回路といえど異常が見つかれば制御回路や基板上に何らかの異常ある可能性も。<br>

<h2>OCRやDGRで許容値が外れた場合の裏技</h2>
ツマミをグリグリと動かして、また最初の整定値に戻す。<br>
こうすることで動作値が許容値内に収まることがある。<br><br>

CTTジャックに接続するクリップの調整<br>
CTT金属部分とOCR試験クリップ部分の接触不良で許容値を外れる。<br>
サビをとり、再度つけなおすことで改善される場合がある。<br>

