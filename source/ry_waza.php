<h2>小さい裏端子を掴む延長クリップ</h2>
保護継電器の裏端子はネジが小さく、試験器のクリップが劣化していると取り付けにくい。<br>
またOCR試験器の配線本体は重みがあるため、そのまま端子へ掛けるとクリップが外れやすい。<br><br>
小さい端子を掴める延長クリップを使い、試験器本体側の配線は床置きなどで支持すると、端子へ掛かる重量を減らせる。<br>
<strong>クリップの把持状態、絶縁、端子間の短絡がないことを確認してから試験する。</strong><br>

