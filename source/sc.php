<h2>低圧コンデンサの保護装置</h2>
E形コンデンサには保安装置を内蔵されている。<br>
コンデンサに事故（内部素子の絶縁破壊）が発生した場合、ケースが膨む。<br>
そして保安装置が作動してコンデンサは回路から開放される。<br>
この場合、コンデンサは機能を失うので、必ず取り替える。<br>


<h2>低圧コンデンサの火災事故（1975年以前に製造）</h2>
1975年（昭和50年）以前に製造された低圧進相コンデンサ。<br>
保安装置が内蔵されておらず、経年劣化で火災事故が発生する恐れ。<br>
使用中止および交換が促されている。<br>
とりわけ梅雨から9月にかけて多発するらしい。<br>


