<h2>サージ比較試験・専用診断</h2>
モーターやコイルでは、サージ比較試験（サージテスト）など、巻線間絶縁の異常を検出する専用試験が使われることがある。<br>
高い試験電圧を扱うため、対象機器の仕様と試験規格に適合した測定器・手順で実施する。<br>

<h2>事故事例：同じ相のヒューズが繰り返し切れる</h2>
例<br>
1. 電灯用PCの1相でヒューズ溶断<br>
2. 停電してヒューズ交換<br>
3. 絶縁抵抗測定では大きな異常なし<br>
4. 復電すると同じ相が再び溶断<br>
5. 詳細調査で変圧器巻線内部の異常が判明<br><br>

このような場合、ヒューズだけを繰り返し交換して復電せず、負荷側短絡・変圧器巻線・端子・ケーブルなど原因を切り分ける。<br>

<h2>層間短絡を疑ったときの確認順</h2>
・外観、異音、異臭、温度上昇を確認<br>
・過去の負荷・保護装置動作履歴を確認<br>
・絶縁抵抗測定<br>
・巻線抵抗の相間比較<br>
・変圧比・励磁電流の測定<br>
・油入変圧器なら油中ガス分析を検討<br>
・必要に応じてメーカー診断・専用試験を実施<br>

