<h2>レアショート（層間短絡）とは？</h2>
レアショート（layer short、層間短絡）は、変圧器・モーター・リアクトルなどの巻線内部で、巻線同士の絶縁が破壊して短絡する故障。<br><br>

巻線の一部が短絡すると、その部分だけ巻数が少ない短絡ループのような状態になり、大きな循環電流・局部発熱が発生することがある。<br>
進行すると巻線焼損、絶縁油の劣化、ヒューズ溶断、保護装置動作などにつながる。<br><br>

