<h2>層間短絡の主な原因</h2>
・過負荷や冷却不良による長期的な温度上昇<br>
・短絡電流などによる電磁機械力<br>
・振動による巻線・絶縁物の摩耗<br>
・サージ電圧による局部的な絶縁ストレス<br>
・製造時や修理時の巻線絶縁損傷<br>
・経年による絶縁材料の劣化<br>
・異物、汚損、絶縁油の劣化など<br>

<h2>メガーだけでは層間短絡を見つけにくい</h2>
一般的な絶縁抵抗測定は、巻線と大地間、巻線相互間などの絶縁状態を見る試験。<br>
同一巻線の途中で数ターンだけ短絡していても、対地絶縁抵抗が高いままの場合がある。<br><br>

そのため、<strong>メガー値が正常だから層間短絡なしとは言い切れない。</strong><br>
逆に、メガー値低下だけで層間短絡と断定することもできない。<br>

<h2>層間短絡を疑う症状</h2>
・同じ相のヒューズが繰り返し溶断する<br>
・無負荷電流・励磁電流の相間差が大きい<br>
・異常なうなり音・振動が出る<br>
・局部的な温度上昇がある<br>
・油入変圧器で絶縁油の異臭・変色・ガス発生がある<br>
・巻線抵抗の相間差が増える<br>
・保護継電器が原因不明で動作する<br>

<h2>直流巻線抵抗測定</h2>
各相の巻線抵抗を測定し、相間差や過去データ、メーカー基準値と比較する。<br><br>

巻線の一部が短絡すれば有効巻数・電流経路が変化するため、抵抗値に変化が現れる場合がある。<br>
ただし短絡ターン数が少ないと直流抵抗だけでは差が小さく、検出しにくい場合もある。<br><br>

温度によって銅抵抗が変化するため、比較するときは測定温度も考慮する。<br>

<h2>変圧比・励磁電流を比較する</h2>
層間短絡では有効巻数が変化するため、変圧比や励磁電流に異常が現れる場合がある。<br><br>

診断では、<br>
・変圧比測定（TTR）<br>
・無負荷電流・励磁電流の相間比較<br>
・巻線抵抗測定<br>
などを組み合わせると原因を絞りやすい。<br><br>

設備を不用意に加圧して「発熱するか試す」のではなく、専用測定器・メーカー診断・安全な試験回路を使用する。<br>

<h2>油入変圧器は絶縁油診断も有効</h2>
油入変圧器では、巻線の局部加熱・放電・アークによって絶縁油が分解し、特徴的なガスが発生することがある。<br>
DGA（油中ガス分析、溶解ガス分析）は内部異常の診断に使われる。<br><br>

水素、メタン、エチレン、アセチレン、一酸化炭素などのガス組成・発生量・増加傾向から、熱的異常や放電の可能性を評価する。<br>
特定のガスが出たから即「層間短絡」と断定するものではなく、他の試験結果と合わせて判断する。<br><br>

