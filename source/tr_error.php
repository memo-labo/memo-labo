<h2>変圧器の焼損・爆発・事故</h2>

■トランスの設置場所の問題<br>
・不安定な場所<br>
・振動が激しい場所<br>
・温度や湿度などの環境が苛酷な場所<br><br>

■コイル内部の短絡や過負荷<br>
・コイルの異常発熱<br>
・白煙<br>
・焦げた臭い<br><br>

■「ブーン」低いうなり音<br>
・トランス設置ボルトの緩み<br>
・コアやコイルのがたつき<br><br>

<h2>変圧器内の絶縁油の発火</h2>
油入タイプ変圧器の場合、短絡電流などで急加熱されると発火する可能性。<br>
それに対して<a href="mold.php">モールド変圧器</a>の場合には発火しない。<br>


