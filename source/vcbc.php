<h2>真空度チェックの基本手順</h2>
<ol>
  <li>VCBを主回路から安全に切り離す。</li>
  <li>VCBを「切」状態にし、接点を開極させる。</li>
  <li>対象相の固定接点側・可動接点側へ試験器を接続する。</li>
  <li>指定された試験電圧・時間を設定する。</li>
  <li>漏れ電流または試験器の良否表示を確認する。</li>
  <li>必要な各相を1相ずつ試験する。</li>
  <li>終了後は十分に放電し、配線・VCB状態を復帰する。</li>
</ol>

<h2>「22kV・10mA」はすべてのVCB共通ではない</h2>

<p>VCBチェッカーでは22kVを使用する例がありますが、これは<strong>VCB・真空バルブ・試験器の形式に応じた試験条件</strong>です。</p>

<p>たとえば三菱電機の特定機種とVCB-02を組み合わせる試験例では、次の条件が示されています。</p>

<ul>
  <li>適用クラス：3.6/7.2kV</li>
  <li>試験器：VCB-02</li>
  <li>一次入力：AC100V</li>
  <li>出力接続：U-V</li>
  <li>出力電圧：AC22kV</li>
  <li>印加時間：10秒</li>
  <li>適用する開極距離：指定範囲内</li>
</ul>

<p>参考：<a href="https://dl.mitsubishielectric.co.jp/dl/fa/members/document/manual/vcbvmc/jnec-si-0747/jnec-si0747-p.pdf" target="_blank" rel="noopener">三菱電機 VCB取扱説明書</a></p>

<h2>試験器の良・不良表示</h2>

<p>試験器によっては、設定時間内の漏れ電流が一定値を超えた場合に「不良」、超えなかった場合に「良」と表示するものがあります。</p>

<p><strong>この電流値をVCB一般の合否基準として横展開せず、使用する試験器の取扱説明書に記載された判定値で判断します。</strong></p>

<h2>11kV出力と22kV出力の例</h2>

<p>一部のVCBチェッカーでは、端子の組み合わせで出力電圧が変わります。</p>
<ul>
  <li>U-E接続：低い試験電圧側</li>
  <li>U-V接続：高い試験電圧側</li>
</ul>

<p>具体的な出力値は試験器の形式によって異なるため、端子名だけを見て判断しません。</p>

<h2>試験時の注意</h2>
<ul>
  <li>VCBを主回路から確実に切り離す</li>
  <li>開極状態を確認する</li>
  <li>試験対象以外の回路へ高電圧が回り込まないことを確認する</li>
  <li>試験終了後は必ず放電する</li>
  <li>メーカー指定外の試験電圧・印加時間を使用しない</li>
  <li>試験結果だけでなく機械動作・外観・操作機構も合わせて点検する</li>
</ul>

