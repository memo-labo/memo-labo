<h2>VCBチェッカーとは？</h2>

<p><strong>VCBチェッカーは、真空遮断器（VCB）の真空バルブ極間へ試験電圧を印加し、真空度低下の有無を確認する試験器です。</strong></p>

<p>真空バルブの真空度が低下すると、開極状態での絶縁性能や遮断性能に影響するおそれがあります。</p>

<p>参考：<a href="http://www.soukou.co.jp/pdf/0152.pdf" target="_blank" rel="noopener">VCBチェッカー取扱説明書</a></p>

<h2>試験で何を見る？</h2>
<ul>
  <li>真空バルブの極間絶縁が保たれているか</li>
  <li>試験中の漏れ電流が判定基準以内か</li>
  <li>各相で大きなばらつきがないか</li>
</ul>

<p><strong>判定電圧・印加時間・漏れ電流の基準値はVCBと試験器の組み合わせで異なるため、メーカー指定値を優先します。</strong></p>

