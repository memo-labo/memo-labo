スイッチ｢無｣：試験ボタンスイッチを押しても接点が動作しない。<br>
実際に絶縁不良や漏電があった場合、スイッチ｢無｣でも接点は通常通り動作する。<br>
自己診断異常の場合、スイッチ｢無｣でも接点は通常通り動作する。<br><br>

無の場合、誤って試験SWを押した場合、接点動作で外部警報や遮断動作してしまう事を防ぐ。<br>
警報動作の確認や連動遮断動作の確認を行うとき以外は、スイッチ「無」の方が安全。<br>

<h2>リレー試験方法</h2>
Ior検出方式なのでZCTに電流を流しただけでは動作しない。<br>
ZCTに電流を流すと同時に、電流と同位相の試験電圧を印加する。<br><br>

■配線方法<br>
・試験機/継電器<br>
・T(+) → L端子<br>
・E(-) → E端子<br>
・Lt(+) → ZCTのKt端子<br>
・Kt(-) → ZCTのLt端子<br>
・接点 → a2-c2端子（漏電監視警報出力用の無電圧a接点）<br><br>

LIG-12のL端子、N端子、E端子配線のスイッチを開放し、低圧系統回路から断路する。<br>
(スイッチが無い場合、LIG-12の端子配線を外して電路から切り離す)<br><br>

※LIG-12のKt-Lt配線は、一般のDGRの試験配線とは極性が逆になる。<br>
※復帰方式は手動/自動を選択可能。<br>

<h2>感度電流試験</h2>
電圧出力(Vo出力)<br>
LIG-12の監視する電路に合わせて電圧を設定。<br><br>

・型式 - 試験電圧<br>
・1φ2Ｗ 100V - 100V<br>
・1φ3Ｗ 200/100V - 100V<br>
・3φ3Ｗ Ｙ 中性点接地 420V - 420/√3≒242V<br>
・3φ3Ｗ Δ 中性点外接地 200V - 200V<br><br>

電圧と電流の位相差：0°（同相）<br>
電流を0から徐々に増加させ動作値を測定<br><br>

漏電監視警報は整定タップ値の70%位の電流値で動作する。<br>
例えば0.2Aタップ整定であれば、約0.14Aで動作する。<br>

<h2>動作時間試験</h2>
配線、設定は感度電流試験とほぼ同じ。<br>
電流出力：整定電流値の100%<br>
電圧出力：上記設定値（型式による）
電圧と電流を同時に出力しカウンタスタートさせ動作した時間を計測。<br><br>

動作時間の許容値<br>
0.3-0.5-0.8-1.0（ｓ）タップの場合<br>
+0.15（s）～-0.1（s）<br><br>

2.0（ｓ）ﾀｯﾌﾟの場合<br>
+ 0（s）～-0.3（s）<br>

<h2>注意点</h2>
ＺＣＴへのＢ種接地線の貫通方向は、Ｂ種接地極側がＫ、変圧器側がＬになる。<br>
系統からの漏洩電流は接地極側から変圧器側に向かって流れるから。<br>
（極性を誤ると不要動作や不動作の原因となる）<br>


