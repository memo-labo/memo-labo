Ior 検出方式 漏電方向リレー<br><br>

方向性機能があり、直接接地系低圧電路における貰い動作を回避できる。<br>
方向性機能の Ior（アイ･ゼロ･アール）検出で容量分を分離した抵抗分による漏電検出。<br><br>

数台の変圧器に共通のＢ種接地工事を施している場合、大電流を伴う漏電事故が１つの系統で発生した際、
他の健全な系統の漏電リレー(ELR)が電路の対地静電容量の影響で「もらい動作」をすることがある。<br>
Iorは機能は対地電圧とIo電流との位相関係を検出し、漏電事故の方向を判別する。<br><br>

