<h2>ELRでもらい動作が発生する仕組み</h2>
１系統で漏電事故発生。<br>
漏電により大きな電流が流れる。<br>
大きな漏電電流によりB種接地極に電圧が発生。<br>
B種接地極に発生した電圧で健全な系統の対地静電容量に電流が流れる。<br>
健全な系統のELRが充電電流により貰い動作。<br>

