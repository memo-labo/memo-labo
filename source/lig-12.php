RS-232（Recommended Standard 232）<br>
シリアルポートのインタフェース規格のこと。<br>
ホストコンピュータ（データ端末装置）とモデム（データ回線終端装置）を繋ぐもの。<br>
パソコン同士の直接接続や、あらゆる周辺機器の接続用に広く使われている。<br>

