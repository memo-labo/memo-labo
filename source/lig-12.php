<h2>各種設定</h2>
「電路設定」スイッチ<br>
使用される電路の電気方式に合わせて、適用電路を設定する。<br>
設定：1φ2W、1φ3W、3φY、3φ△（使用電路電圧はAC440V以下）<br><br>

設定変更後は、反映させるために必ず｢復帰スイッチ｣を押すか、LIG-12の制御電源を入れ直す。<br>
これを行わないと設定が反映されない。<br><br>

<h2>試験トリップ</h2>
