RS485とは？<br>
RS422をバス用にレベルアップさせた規格のこと。<br>
RS422とはツイストペアの信号線2本で構成される平衡伝送のこと。<br>
RS-485は電気機器の二地点間通信用の電子インターフェイスと物理層を定義する産業仕様。<br>
電気的にノイズが多い環境で長距離のケーブル敷設が可能。<br>
同一バス上で複数のデバイスをサポートできる。<br>

