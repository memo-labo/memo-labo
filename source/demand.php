<h2>デマンドとは？</h2>

<p><strong>電気料金でいう「デマンド」は、一般に30分ごとの平均使用電力[kW]をもとにした最大需要電力を指します。</strong></p>

<p>30分デマンドが高くなるほど、その月の最大需要電力も高くなります。実量制の契約では、この最大需要電力が契約電力に影響します。</p>

<h2>30分デマンドの計算</h2>

<p>30分間に使用した電力量[kWh]から、平均使用電力[kW]を求めます。</p>

<p><strong>デマンド[kW] ＝ 30分間の使用電力量[kWh] × 2</strong></p>

<p>例：</p>
<ul>
  <li>30分間の使用電力量：100kWh</li>
  <li>デマンド：100 × 2 ＝ 200kW</li>
</ul>

<p>逆に、30分デマンドを300kW以内に抑えたい場合、その30分間で使える電力量の目安は150kWhです。</p>

<h2>途中で負荷を落とすとどうなる？</h2>

<p>デマンドは30分間の平均なので、時限の前半で大きな電力を使っても、後半で負荷を落とせば30分平均を下げることができます。</p>

<p>ただし、すでに30分間で消費した電力量そのものは戻りません。デマンド監視装置は現在の使用量から時限終了時の値を予測し、設定値を超えそうな場合に警報や負荷制御を行います。</p>

<h2>実量制と契約電力</h2>

<p>東京電力エリアの高圧・特別高圧契約の案内では、契約電力500kW未満の場合、<strong>当月を含む過去1年間の各月の最大需要電力のうち最も大きい値</strong>を契約電力とする実量制が案内されています。</p>

<p>500kW以上では、負荷設備や受電設備の内容などをもとに協議して契約電力を決定する方式が案内されています。</p>

<p>⇒<a href="keiyaku.php">契約電力の決まり方</a></p>

<p><strong>契約方法・料金単価・超過時の扱いは電力会社・小売事業者・契約メニューで異なるため、現在の契約約款を確認します。</strong></p>

<h2>一度デマンドが上がるとどうなる？</h2>

<p>実量制では、ある月に大きな最大需要電力を記録すると、その値が過去1年間の最大値として残る間、契約電力へ影響することがあります。</p>

<p>そのため、短時間だけ大きな負荷を同時使用した場合でも、30分平均が高くなれば契約電力へ影響する可能性があります。</p>

<h2>デマンドが上がりやすい例</h2>

<ul>
  <li>空調を一斉に起動する</li>
  <li>大型ヒータと生産設備を同時に使用する</li>
  <li>始業直後に多数の設備をまとめて起動する</li>
  <li>蓄電池・EV充電器・電気炉など大容量負荷を同時運転する</li>
</ul>

<h2>デマンドを抑える方法</h2>

<ul>
  <li>大容量負荷の運転時間をずらす</li>
  <li>空調・ヒータを段階的に起動する</li>
  <li>デマンド監視装置で予測警報を出す</li>
  <li>優先度の低い負荷を自動で一時停止する</li>
  <li>蓄電池などをピークカットに利用する</li>
</ul>

<h2>最大需要電力はどこで確認する？</h2>

<p>高圧受電設備では、電力需給用複合計器やデマンド監視装置で現在需要電力・最大需要電力を確認できる場合があります。</p>

