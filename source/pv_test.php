<h2>注意点</h2>
低圧（直流の場合、750V以下）は現地での絶縁耐力試験は不要らしい。<br>
ただし「工場試験成績書」があり「JIS規格に適合していること」が証明できることが条件。<br><br>

耐圧試験を行う際は電圧印加範囲からパワコンを切り離す。<br>
パワコン内にブレーカーがある場合も、ブレーカーからPVケーブルを切り離す。<br>

