<h2>絶縁監視装置とは？</h2>

<p><strong>絶縁監視装置は、低圧電路の漏れ電流や停電、温度などを常時監視し、異常を遠隔通知する装置です。</strong></p>

<p>高圧受電設備の外部委託保安では、設備条件を満たし適切な絶縁監視装置を設置することで、月次点検頻度の特例が認められる場合があります。</p>

<h2>何を監視する？</h2>

<ul>
  <li>低圧電路の漏れ電流</li>
  <li>停電・復電</li>
  <li>変圧器などの温度</li>
  <li>接点入力による機器警報</li>
</ul>

<p>異常を検出すると、監視センターや保安担当者へ通信で通知し、必要に応じて現地点検につなげます。</p>

<h2>I0・Ior・Iocの違い</h2>

<p>低圧電路の漏れ電流には、絶縁抵抗低下による抵抗成分と、対地静電容量による容量成分が含まれます。</p>

<ul>
  <li><strong>I0</strong>：漏れ電流の合成値</li>
  <li><strong>Ior</strong>：主に絶縁抵抗低下に関係する抵抗性成分</li>
  <li><strong>Ioc</strong>：対地静電容量による容量性成分</li>
</ul>

<p>Ior方式では、容量性成分や高調波の影響を抑えながら、絶縁劣化に関係する成分を監視する方式があります。</p>

<p>⇒<a href="leak.php">I0・Ior・Iocの違い</a></p>

<h2>警報設定の考え方</h2>

<p>外部委託制度の運用では、低圧電路の絶縁状態を監視する装置について、<strong>漏えい警報の設定上限値を50mA</strong>とする基準が示されています。</p>

<p>また、設定値以上の漏れ電流を連続して5分以上受信した場合、または5分未満の警報を繰り返し受信した場合を「警報発生時」として扱う規定があります。</p>

<p><strong>50mAは「50mAまでなら安全」という意味ではありません。</strong>警報値は制度上の上限であり、設備の平常値や用途に応じて適切な設定を行います。</p>

<h2>2025年4月から月次点検頻度の特例が拡大</h2>

<p>2025年4月1日の制度改正により、一定の設備条件を満たし、低圧電路の絶縁状態と負荷を的確に監視できる装置を備え、主遮断装置や責任分界点から主遮断装置までの設備が適切に更新されている需要設備では、<strong>外部委託制度の月次点検を3月に1回以上</strong>とすることが認められる枠が設けられました。</p>

<p>従来からある隔月点検の特例と、新しい3か月点検の特例は要件が同じではありません。</p>

<p><strong>絶縁監視装置を付けただけで自動的に3か月に1回になるわけではありません。</strong>設備更新、監視内容、外部委託承認など所定の要件を満たす必要があります。</p>

<p>⇒<a href="muteiden.php">無停電年次点検・2025年制度改正</a></p>

<h2>監視装置を設置するときの確認項目</h2>

<ul>
  <li>監視する変圧器バンク・低圧系統</li>
  <li>ZCT・電流センサの変流比と方向</li>
  <li>I0方式かIor方式か</li>
  <li>警報設定値・遅延時間</li>
  <li>通信回線・アンテナの状態</li>
  <li>停電・温度・接点入力などの監視項目</li>
  <li>警報先・連絡責任者</li>
  <li>本体接地のメーカー指定</li>
</ul>

<h2>ZCT・電流センサ交換時の注意</h2>

<p><strong>既設センサをそのまま流用できるとは限りません。</strong>変流比、出力方式、極性、対応する監視装置が異なる場合があります。</p>

<p>交換時は本体・センサ・電圧アダプタなどの組み合わせ適合を確認します。</p>

<p>また、受電中の接地線やCT・ZCT二次配線を現場判断で切り離さず、機器の取扱説明書と安全な作業手順に従います。</p>

<h2>本体接地について</h2>

<p>監視装置の接地端子は、ノイズ対策・安全・計測基準電位などの目的で設けられている場合があります。</p>

<p><strong>キュービクルのボルトや仮設クリップへ適当に接続せず、メーカーが指定する接地方法・接地端子を使用します。</strong></p>

<h2>警報が出たら？</h2>

<ol>
  <li>警報の種類と発生時刻を確認する</li>
  <li>単発か継続か、過去にも同じ警報があるか確認する</li>
  <li>該当バンク・回路を特定する</li>
  <li>現場の漏れ電流・絶縁状態を確認する</li>
  <li>必要に応じて負荷を切り分ける</li>
  <li>原因と対応を記録する</li>
</ol>

<p>警報をリセットするだけで終わらせず、常時値の上昇や繰返し警報は絶縁劣化の兆候として追跡します。</p>

<h2>代表的な絶縁監視装置</h2>

<p>監視王シリーズ、LSシリーズ、IGRシリーズなど各社から絶縁監視装置が販売されています。通信方式やチャンネル数、Ior対応、温度入力などは機種ごとに異なります。</p>

<p>通信サービスは3G終了など通信網の更新影響を受けるため、古い装置では現在利用可能な通信方式と保守対応を確認します。</p>

