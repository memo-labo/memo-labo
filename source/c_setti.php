<h2>C種接地</h2>
300Vを超える低圧電気機械器具の金属製外箱や金属管などに施す。<br>
主に400Vで使用している電動機、ファン類、コンプレッサなどの外箱や鉄台に施す。<br>
高圧太陽光発電設備においてパネル躯体やパネルを支える構造体にも。<br><br>

※コンプレッサーとは？<br>
圧縮した気体をタンクに貯めて気体を動力源とする工作機械を使用するための装置のこと。<br><br>

C種接地抵抗：10Ω以下<br>
（漏電遮断器の動作時間が0.5秒以内なら500Ω以下）<br><br>

A種とC種接地の共用<br>
各種接地工事の接地線を、共通の接地極につなぐ接地工事。<br>
総合接地抵抗値が10Ω以下の場合、A種、C種、D種は、共用とすることができる。<br><br>

感電等の災害防止用として<br>
