太陽光の架台とパワーコンディショナは別々のアースに接続する。<br>
理由：スイッチングノイズ対策らしい。<br>

<h2>スイッチングノイズとは？</h2>
高周波のノイズ成分で、電子回路がスイッチングを行う際に発生する。<br>
電気回路のオン・オフを切り替える行為をデジタル回路や直流・交流変換回路などで行うこと。<br>
スイッチングが行われる過渡状態のとき、高周波が発生し、ノイズが発生することがある。<br><br>

パワコンはEMC対策がされていても多少のノイズは生じてしまう。<br>
太陽電池アレイは面的に広がり、その電路はノイズのアンテナのような役目を果たすから。<br><br>

外部からの進入ノイズの影響を避けて安定した運転動作を得るため低インピーダンスの専用接地が効果的<br>

<h2>EMC対策とは？</h2>

EMC（電磁環境両立性）<br>
EMC = Electromagnetic Compatibility<br>
機器は電磁的妨害源とならないように、電磁的な干渉を受けないように。<br>
あるいは受けても正常に動作する（両立する）ようにする。<br>

