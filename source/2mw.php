<h2>2MW以上の太陽光発電所</h2>

<p>太陽光発電所の出力が1MW（1,000kW）を超える設備は、一般に「メガソーラー」と呼ばれます。</p>

<p>発電所の安全を保つため、電気主任技術者は設備の工事や運用を監督します。設置者は、規模などに応じて電気主任技術者を選任する必要があります。</p>

<h2>2,000kW以上の発電所では、外部委託できる場合があります</h2>

<p>2021年4月の制度改正により、一定の条件を満たす太陽光発電所は、電気主任技術者の保安管理業務を外部へ委託できるようになりました。</p>

<p>対象となるのは、出力が2,000kW以上5,000kW未満で、連系電圧が7,000V以下の発電所です。外部委託には所定の要件があり、所轄の産業保安監督部の承認が必要です。</p>

<p>この制度を利用すると、条件に応じて発電所に電気主任技術者を選任せず、委託先に保安管理を任せることができます。兼任の要件は外部委託とは別に定められています。</p>

<h2>制度改正の概要</h2>

<p>改正前は、外部委託できる太陽光発電所の出力上限は2,000kW未満でした。2021年4月の改正で、上限が5,000kW未満に広がり、2,000kW以上の発電所も条件を満たせば対象になりました。</p>

<p>具体的な要件や申請方法は、<a href="https://www.meti.go.jp/policy/safety_security/industrial_safety/oshirase/2021/04/20210401.html">経済産業省の改正資料</a>と、所轄の産業保安監督部の案内をご確認ください。</p>

