<h2>OCB 油入遮断器</h2>

<img src="images/ocb3.jpg" style="max-width:400px;" /><br /><br />


<p>絶縁油中で電流の開閉を行う遮断器。構造が簡単で安価のため、古くから使用されてきた。</p>

<h3>絶縁油に関する注意点</h3>
<ul>
<li>絶縁油は可燃性のため、防災上の問題がある。</li>
<li>絶縁油の交換など、メンテナンス上の問題もある。</li>
<li>発ガン性物質であるPCB（ポリ塩化ビフェニル）が含まれている絶縁油がある。</li>
</ul>

<h3>ほかの遮断器への移行</h3>
<p>油入遮断器は、徐々に電力系統の大容量化・高信頼性化に追従できなくなった。絶縁油を必要としない空気遮断器が主流となっていった。</p>
<p>現在は、大容量のものはガス遮断器、小容量のものは真空遮断器（VCB）へと置き換えられていった。</p>

