<h2>太陽光パネル・架台の接地はC種？D種？</h2>

<p>太陽光発電設備の金属製外箱・架台・機器の接地は、単純に「ストリングの開放電圧が300Vを超えたらC種」とだけで判断するものではありません。</p>

<p>電気設備の技術基準の解釈では、機械器具の金属製外箱などに対する一般的な接地工事は、<strong>その機械器具の使用電圧</strong>に応じて整理されています。</p>

<ul>
  <li>低圧・300V以下：D種接地工事</li>
  <li>低圧・300Vを超えるもの：C種接地工事</li>
  <li>高圧・特別高圧：A種接地工事</li>
</ul>

<p>ただし、太陽電池モジュール・架台・接続箱・PCSには、絶縁方式や構造、漏電保護、メーカー指定などによる扱いがあります。<strong>設備全体を一つの数字だけで決めず、設計図・機器仕様・メーカー施工要領・適用する技術基準を確認します。</strong></p>

<h2>パネル枠・架台のボンディング</h2>

<p>太陽電池モジュールの金属枠や金属架台は、絶縁不良などで金属部に危険な電位が生じないよう、保護接地へ確実につながる導通経路を確保します。</p>

<img src="images/panel-e.jpg" style="max-width:600px;" alt="太陽光パネルのアースボンド"><br>

<p>導通の取り方には、アースボンド線を使用する方法のほか、メーカー指定の接地金具・アースプレート・接地対応クランプなどがあります。</p>

<p><strong>「金属同士をボルトで締めているから必ず導通している」とは限りません。</strong>アルマイト処理、塗装、酸化被膜、異種金属、締付不足などで接触抵抗が大きくなることがあります。</p>

<h2>アースプレート・接地金具を使う場合</h2>

<p>爪付きアースプレートなどは、金属表面へ食い込ませてモジュール枠と架台の電気的な導通を確保するために使われます。</p>

<ul>
  <li>モジュール・架台メーカーが指定または許容している部材か</li>
  <li>指定された位置・締付トルクで施工されているか</li>
  <li>異種金属接触による腐食の問題がないか</li>
  <li>施工後に必要な導通が確保されているか</li>
</ul>

<p>を確認します。</p>

<p>モジュール枠へのドリルビス加工は、製品保証や防食性能に影響することがあります。<strong>メーカーが認めていない穴あけを前提にしない</strong>ようにします。</p>

<h2>接続箱・集電箱・PCSの接地</h2>

<p>接続箱、集電箱、パワーコンディショナーの接地は、それぞれの機器の定格・絶縁方式・メーカー仕様・設備設計に従います。</p>

<p>パネル枠と同じ接地線へまとめられる構成もありますが、<strong>すべての設備で同じ接地方式になるとは限りません。</strong>機器の取扱説明書と単線結線図・接地系統図を確認します。</p>

<h2>接地を確認する理由</h2>

<p>太陽光発電設備では、日射がある限り直流電圧が発生します。絶縁不良が起きたとき、金属部の保護接地やボンディングが不適切だと、感電・地絡検出不良・機器損傷などにつながる可能性があります。</p>

<p>なお、<strong>保護接地と雷保護は目的が異なります。</strong>パネル・架台を接地しただけで雷害を防げるわけではなく、必要に応じてSPD、等電位化、配線経路などを含めて雷保護を検討します。</p>

<h2>点検時の確認ポイント</h2>

<ul>
  <li>パネル枠・架台・接地線に腐食や緩みがないか</li>
  <li>接地金具やボンディング部材がメーカー指定どおりか</li>
  <li>接続箱・PCSを含む接地系統が図面と一致しているか</li>
  <li>増設・交換したモジュールだけ接地経路が切れていないか</li>
  <li>必要な導通・接地抵抗が確保されているか</li>
</ul>

