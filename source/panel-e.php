<h2>太陽光パネルの接地はC種？</h2>

開放電圧がDC300Vを超える太陽電池ストリングの場合<br>
金属製外箱・架台等に<a href="setti.php">C種接地（10Ω以下）</a>を施す。<br><br>

金属杭、金属架台、パネル枠、すべてをアース線で繋ぐ。<br>
接続箱、集電箱、パワーコンディショナーなどもアース線で繋ぐ（パネルと同じ？それとも別？）<br>
パネル同士、パネルと架台を固定する金属で締め付ける事で導通がとれるタイプもある。<br>
その場合、アースによる渡り線は必要ない。<br><br>

