アースプレート<br>
隣り合う太陽光パネルの導通を取る部材。<br>
ドリルビスで取り付け。<br>
既に施工が完了した太陽光発電設備にも使用できる。<br><br>

爪付きアースプレート<br>
パネル押え金で固定させる前に屋根金具の上に置いて使用。<br>
爪が太陽光パネルの筐体の下部に刺さる。<br><br>

爪付きアースプレート等のデメリット<br>
施工不良で確実に接続されておらず導通抵抗が高くなる場合も。<br>
パネルの金属枠をドリルビスで打ち込みアースボンド線で渡らせる。<br>
パネルすべてを確実に導通をとってアースに落とした方が良い。<br><br>

太陽光パネルに接地をしないとどうなる？<br>
パネルは常に直流の電圧を発電し続ける。<br>
もしパネルに絶縁不良が発生した場合、パネル金属部分に電圧が充電される可能性。<br>
もしその状態で人が触れた場合、人が感電する。<br>
また雷の影響を受けやすくなりバイパスダイオードやPCSが焼損する可能性も。<br>

