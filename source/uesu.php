<h2>キュービクル清掃で使うウエスと水拭き</h2>

<p>キュービクルや電気室の清掃では、ホコリだけでなく、床や盤面にこびりついた汚れを落としたい場面がある。乾拭きで落ちない汚れには、停電・検電など必要な安全措置を行ったうえで、固く絞ったウエスを使う方法がある。</p>

