<h2>ウエスとは？</h2>
<p>機械の油、汚れ、不純物などを拭き取るときに使う布のこと。使い捨て用の布切れとして、設備清掃でも使いやすい。</p>
<p>乾いたウエスでの清掃に加えて、軽いホコリを手早く取りたい場合は<a href="qb_clean.php">サッサを使ったキュービクル清掃</a>も便利。</p>

<h2>キュービクルを水拭きするときのポイント</h2>
<p>水道水を含ませたウエスは、水が垂れない程度まで固く絞って使用する。ホコリや砂、乾拭きでは落ちにくい汚れを取りやすい。</p>
<p>特に床面をきれいにしておくと、油漏れ、雨漏り、動物の侵入跡や死骸、床面の穴など、設備異常の兆候にも気づきやすくなる。</p>
<p><strong>注意：</strong>充電中の機器や充電部の近くで水拭きを行わない。停電・検電・接地など必要な安全措置を行い、機器内部や端子部へ水分が入らないようにする。</p>

<h2>水道水・精製水・蒸留水の違い</h2>

<h3>水道水</h3>
<p>ナトリウム、カルシウム、マグネシウムなどの成分を含み、浄水処理の過程で塩素が加えられている。安価で準備しやすいため、床面などの清掃に使いやすい。</p>

<h3>精製水</h3>
<p>水道水や井戸水などを原水として、蒸留、イオン交換、ろ過、逆浸透などによって不純物を取り除いた水。水道水よりコストはかかる。</p>

<h3>蒸留水</h3>
<p>蒸留によって精製した水。蒸留水は精製水の一種で、用途に応じて使い分ける。</p>

