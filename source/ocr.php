<h2>限時要素</h2>
限時要素は短絡事故や突入電流による瞬間的な大電流を保護するものではない。<br>
複数の負荷の同時運転や過負荷などによって発生する過電流から設備を保護する。<br>
定格電流以上の電流が長時間に渡って流れ、危険領域に達した場合に動作する。<br>
OCRの内部接点を動作させてVCBをトリップさせたり警報を発砲させる。<br><br>

継電器の表面にある「動作表示器」で動作したかどうかの区別がつく。<br>
R相、T相、瞬時動作、限時動作、どこか動作したのか、その判別ができる。<br>

<h2>限時要素の種類</h2>

超反限時 EI<br>
電流の２乗に反比例した時限特性。<br>
発熱（ジュール熱）特性にあっており、電気機器の過負荷保護に適している。<br>
MCCBやヒューズなどの保護機器の特性とも合っているので、保護協調がとりやすい。<br><br>

強反限時 VI<br>
電気機器の過負荷特性に合っている。<br>
配電線の保護や変圧器の保護に適している。<br><br>

反限時 NI<br />
送電線の短絡保護に適している。<br><br>

定限時<br>
電流の大きさにかかわらず、設定した時間が経過すると動作する特性。<br>
主に電力系統の保護リレーで、保護協調を取りやすくしたい場合に使われる。<br>

<h2>タップ整定値 計算方法</h2>
限時要素
通常時の負荷変動レベルでは動作しないように整定。<br>
整定値は契約電力の負荷電流✕150%程度。<br><br>

計算式<br />
I(整定値) = {I1×(5/Ict1)} × 1.5<br>
・I1=契約電力の電流値=P/√3V<br>
・Ict1=CT１次<br><br>

■限時タップ値 計算例<br />
契約電力：200kW<br />
受電ＣＴ比：30/5A<br />
整定計算値 = {200kW ÷ (√3 × 6.6kV)} × (5/30) × 1.5 = 4.4[A]<br />
なので、整定値は4.4Aよりも大きい値の中で最小の 5A となる。<br /><br />

■限時タップ値 計算プログラム<br />
<form name="ocr">
