<h2>瞬時要素の試験方法</h2>
整定値 × 200%の電流を流した時、0.05s以下で動作すれば良い。<br><br>

例：OCRの瞬時整定値=30A<br>
OCRの瞬時要素の整定値を最小（例：10A）まで下げる。<br>
試験機から20A（200%）を流して試験を行う。<br><br>

現状の30Aの200%=60Aの場合、発電機にも試験機にも無理が生じて危険。<br>
試験を行った後、瞬時要素の値の戻し忘れに注意。<br><br>

