瞬時要素の整定値<br>
一般的にトランス容量から計算される電流値の1000～1500%で設定する。<br>
需要家のOCRは、電力会社の限時値・瞬時値よりも早く動作させる必要がある（保護協調）<br><br>

■配電側OCR（配変OCR）の動作時間<br>
①720A-0.5秒<br>
②1440A-0.2秒<br><br>

慣性特性<br>
・誘導形：動作時間の60％<br>
・静止形：動作時間の90％<br>

開極時間<br>
・50Hz 3サイクル = 0.06秒<br><br>

実際の配電側OCRの動作時間<br>
① = 0.5 ✕ 90% ー 0.06 = 0.39秒<br>
② = 0.2 ✕ 90% ー 0.06 = 0.12秒<br><br>

構内設備が短絡により受電OCRの瞬時要素が0.05秒以内で動作したとする。<br>
0.05秒 + 0.06秒 = 0.11秒<br><br>


■保護協調を間違えた場合の危険性<br>
・需要家で短絡事故が発生<br>
・OCRの保護協調を間違えたため需要家より先に電力会社側の配電用変電所OCRが動作<br>
・配電用変電所の遮断器が開放<br>
・地域停電が発生<br>

