function Add(){
  var kw = document.ocr.kw.value;
  var Ict1 = document.ocr.Ict1.value;
  document.ocr.Itap.value = ((kw / (1.732 * 6.6)) * (5 / Ict1) * 1.5).toFixed(1);
}
</script>


