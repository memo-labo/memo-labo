整定値の130%を超えたあたりから動作時間は0.05秒で一定。<br>
OCRの瞬時が20Aの場合、20A✕150%=30A程度でも試験結果に大差はない。（0.05秒以下）<br><br>

<h2>OCR瞬時要素試験の注意点</h2>

注意点１<br>
瞬時試験で40Aを作る際、試験器の内部抵抗を1Ωや0.5Ωで作ると、電源が過負荷でストップする。<br>
その場合、試験器の内部抵抗を0Ω（Short）にして試験電流を作ると上手くいく。<br>
落ちる兆候は、スライダックを回してもそれ以上に電流値が上がらなくなるあたり。<br>
エコフローなどの大容量バッテリーでストップしがち。<br><br>

注意点２<br>
流す試験電流が大きいので、電流引き外しの場合、流し続けてしまうとVCBのトリップコイルが焼損する。<br>
本来は0.05秒で動作するので、すぐに試験機が止まらなかったらすぐにOFFボタンを押す癖をつける。<br>

<h2>復電時のトラブル VCB投入⇒OCR瞬時動作⇒VCB開放</h2>
変圧器の励磁突入電流は「定格電流の10倍の電流が0.1秒間継続」という特性がある。<br>
コンデンサを多数組み込んでいる設備の場合、通電した瞬間にコンデンサへの充電が行われるため、充電が完了するのまでの間に大きな電流が流れる。<br><br>

瞬時要素の整定値に問題ない場合、もう一度投入を試してみる。だいたいは２回目は成功する。<br>
２回とも瞬時要素で開放されてしまった場合、瞬時要素の整定値自体に問題がある可能性あり。<br>
その場合の復電は、励磁突入を防ぐため、VCBより下位にあるLBSを開放してからVCBを投入し、その後でLBSを投入する。<br>
ただこれだと地域停電が発生⇒復電の際、またVCBが瞬時で開放される危険性あり。瞬時の見直しが必要。<br>

<h2 id="r1">OCRとVCBとの連動遮断試験</h2>
OCRの接点が動作した際のVCBの開極動作時間が正常かどうかを試験する。<br />
試験機のトリップ信号線を、VCBの一次側と二次側に接続し、試験スタートから接点閉⇒接点開に切り替わるまでの時間を計測する。<br><br>

VCBの開極時間<br>
VCBは、50Hz使用域において、３サイクル定格の場合、3/50 = 0.06s以内に遮断する。<br />
高圧交流遮断器には定格遮断時間が、５サイクル = 5/50 = 0.1sもある。<br /><br />

OCRとVCBの連動試験 許容時間<br>
OCR単体試験の限時整定300%の公称値±17%の範囲内であれば問題ない。<br /><br />

例<br />
超反限時、レバー１<br />
300%⇒公称値 1s<br />
連動試験の試験結果⇒1.15s<br />
OCR単体300%許容値⇒1s±17%<br />
判定：許容値内なので異常なし<br />

<h2>OCR試験時のダイヤル（時間整定）</h2>

①ダイヤル１に変えて試験する<br>
②ダイヤル１０に変えて試験する<br>
③例えば運用時がダイヤル３だったら変えないで試験する<br><br>

JISで決められた基準より各メーカーで決めた基準の方が厳しい。<br>
なので各メーカーの機種により取扱説明書を参照して試験するのが理想。<br>
お客様（設置者）の希望に従う場合でも、試験内容はJISを満たしている必要がある。<br><br>

ダイヤルを１０に変えて試験した場合、戻し忘れの危険がある。<br>
例えば本来、動作時間１で運用していたのに、１０に変えてしまったら保護協調が取れない。<br>
その際、過負荷が発生した場合、需要家側のOCRより配電側のOCRが先に動作してしまう。<br><br>

ただ需要家のOCRが動作する場合の多くは瞬時動作＝短絡事故であるらしい。<br>
限時動作で需要家側VCBが開放されるような事例は滅多にないらしい。<br>
また短絡事故が発生した場合、短絡電流によりLBSやPCのPFヒューズが切れる。<br>
なので最悪なのは試験のために瞬時をロック（不動作）にしたまま戻し忘れ<br><br>

また、ダイヤル３から１に変更して試験をして戻し忘れた場合も怖い。<br>
この場合、通常の使用状態でも過負荷でVCBが開放され停電してしまう恐れがある。<br><br>

予想される失敗例<br>
試験のためにダイヤル１からダイヤル１０に変更して戻し忘れ（保護協調外）<br>
試験のためにダイヤル３からダイヤル１に変更して戻し忘れ（通常運用で限時動作の恐れ）<br>
限時動作試験のため瞬時動作ダイヤルをロック（不動作）または最大値にして戻し忘れ<br>

