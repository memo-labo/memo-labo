<h2>バイパスダイオードとは？</h2>

バイパスは英語でbypass。<br>
交通中心地の混雑緩和のために、迂回(うかい)して周辺地などを通らせる道路。<br>
<br>
太陽光のバイパスダイオードとは？<br>
