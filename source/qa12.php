<h2>地震が起きると停電が発生する理由とは？</h2>

誘導円板形タイプの継電器が地震の振動で接点が閉じて、遮断機がトリップする。<br><br>
地面の液状化や揺れで電柱が揺れたり傾くことで架空電線が他所と触れ、短絡や地絡を起こす。<br><br>
電気室が屋上の場合、揺れが大きいので、損壊する確率が高い。<br><br>
固定がしっかりできていない変圧器が倒壊する。<br><br>
変圧器二次側のブスバーが揺れで接触して短絡事故。<br><br>
地面の液状化や地面の揺れで地中に埋設しているケーブルが損傷し地絡や短絡事故。

