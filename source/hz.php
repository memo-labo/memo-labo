<h2>周波数とは？</h2>
周波数とは、１秒間に流れる電気が変化する回数のこと。<br>
交流の電気は、定期的にプラスとマイナスが何度も入れ替わる。<br>
電流の向きは交互になる。<br><br>

乾電池やバッテリーに使われる電気が「直流」<br>
電力会社から供給される電気は「交流」<br>

<h2>周波数の境目</h2>
日本には、地域によって「50Hz」と「60Hz」という２種類の周波数が存在する。<br>
おおまかに、東日本が50Hz、西日本が60Hz<br>
静岡県の富士川と新潟県の糸魚川あたりが境目となっている。<br>

<h2>なぜ日本には50Hzと60Hzの２つがあるのか？</h2>
明治時代、発電機を外国から輸入する際、東京と大阪の発電所がそれぞれ異なる発電機を導入した。<br>
東京はドイツから50Hzの周波数を持つ発電機を、大阪はアメリカから60Hzの周波数を持つ発電機を取り入れた。<br>
それから何度も周波数を統一しようという試みがあった。<br>
しかしそれが叶わず、現在でも関東が50Hz、関西が60Hzという周波数になっている。<br>

