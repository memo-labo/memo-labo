<h2>周波数の違いによる電化製品の影響</h2>

50Hzもしくは60Hzを基準として作られている電化製品を、異なる周波数の状況下で使用した場合<br><br>

・モーターの回転数が変わって性能が低下<br>
・過剰に働いて火災の原因となる<br>
・電化製品が痛み、故障を早めてしまう可能性もある。<br>

<h2>周波数に関係なくそのまま使用できる機器の例</h2>
・エアコン・テレビ・パソコン・こたつ・温水器・電気ストーブ<br>
・モーターの周波数を適切に変えて回転数を調整する「インバーター」が内蔵されている、ヘルツフリー製品<br><br>

■使用可能だが多少性能が落ちる可能性のある電化製品<br>
掃除機・扇風機・ミキサー・ドライヤー<br><br>

■周波数の確認が必要な電化製品<br>
洗濯機や乾燥機・冷蔵庫・電子レンジ・蛍光灯（インバーター内蔵ならOK）<br><br>

※電子レンジや蛍光灯は未だに50Hzもしくは60Hz専用のものが多い。<br>


<h2>周波数が変動する原因</h2>
周波数は使う電気の大きさ＝電力の大きさで変わる。<br>
電力が大きくなると、電気を作る発電機の回転速度が遅くなり、周波数が下がる。<br>
使う電気と作る電気の大きさを合わせることで周波数を一定に保つ。<br><br>

周波数の変動による影響<br>
・電動機の回転数が変わるため、産業用機器などの不安定動作により品質が低下<br>
・生産ラインの停止<br><br>

太陽光発電と風力発電は、天気や風の強さによって発電量が変化するので不安定。<br>
周波数を一定に保つためには出力調整ができる水力発電や火力発電が必要。<br>
※東日本50Hz、西日本60Hzの±0.2Hzまたは±0.3Hz以内に周波数を保っている。<br>

