太陽電池側の直流回路上、電位差のある２点以上の箇所で地絡が発生した場合。<br>
直流地絡検出装置が地絡を検出してパワコン停止したとしても危険。<br>
太陽光パネル受光⇒地絡点を通して循環電流が流れ続ける。<br>

<h2>直流分検出機能</h2>
トランスレス方式は、直流側と交流側を絶縁するためのトランスを用いない。<br>
パワコンの出力電流に直流分を検出すると、運転を停止し点検コードを出力。<br>
検出された出力電流レベルは1.5Vの電圧信号に載せ、マイクロプロセッサに入力。<br>
直流成分の電流が発生したとき、この電圧信号の平均値は1.5Vより変動する。<br>
この電圧信号の平均値が1.5Vから変動する量を計算し、直流成分が存在を判定。<br>


