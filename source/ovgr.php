<h2>OVGRの目的と必要性</h2>
OVGR 地絡過電圧継電器の記号<br>
<img src="images/ovgr11.png" style="max-width:150px;" alt="OVGR 地絡過電圧継電器 記号"><br>

高圧電路のケーブルや機器の絶縁劣化、電路と大地間が接触して起こる地絡事故を検出する保護装置。<br>
太陽光発電設備では、電力系統側で地絡故障が発生した場合、故障した場所の探査や故障の除去作業をする作業員への感電を防止するため、PCS（パワーコンディショナー）を停止させる必要がある。<br /><br />
そのため、OVGRで地絡過電圧を監視し、高圧系統側での地絡を検知した場合、パワーコンディショナの発電を停止させる必要がある。<br />

<h2>OVGR 配線例</h2>
<img src="images/ovgr_haisen.svg" style="max-width:300px;" /><br>
・ZPDのY1・Y2⇒OVGRのY1・Y2（Y2側が接地）<br>
・MCCBのAC100V⇒ブロック電源 or UPS（AC100V/DC24V変換）⇒OVGRのS1・S2（DC24V）<br>
・PCS（パワコン）⇒OVGRの地絡検出出力接点<br><br>

OVGRの動作接点例<br>
・地絡過電圧出力（通常監視状態OFF、地絡検出時ON）<br>
・系統遮断/復電検出出力（自動・手動の設定が可能）<br>
・自己診断出力<br>

<h2>OVGRの原理</h2>
系統側の地絡は、電流ではなく電圧で監視する。<br>
その理由は、系統事故時、発電設備設置者側から流出する地絡電流（充電電流Ic）は小さい。<br />
地絡電流では不動作となる場合があるのでOVGR（Vo=零相電圧）により地絡電圧を検出する。<br /><br>

零相電圧は回路全体（電力会社の変圧器の二次側 6.6kV側）に発生する。<br>
なので同じ変圧器に繋がっていれば、どこで地絡が発生しても等しく零相電圧が発生する。<br>
零相電圧では地絡点の特定は困難。<br>

<h2>系統地絡とOVGRの関係</h2>

地絡事故１があった場合<br />
DGR１動作⇒配変電所VCB開放⇒PCSからの電力供給も停止させる必要があるため需要家OVGR動作にて系統切離し。<br /><br />

地絡事故２があった場合<br />
DGR２動作⇒配変電所VCB開放⇒事故系統と健全系統は切り離され、PCSからの電力供給を停止させる必要はなく、需要家の零相電圧もなくなるのでOVGRは動作せず。<br />

<h2>OVGRの整定値</h2>
動作時間<br>
配電変電所DGRの動作時間よりも長くして、健全系統の不要動作を防止する。<br />
電力会社からの指定で、多くは「1秒」に整定される事が多い。<br /><br>

手動⇔自動<br>
自動：OVGR動作でパワコン停止した後、自動でパワコン復帰させ発電したい場合。<br>
手動：OVGR動作でパワコン停止した場合、手動で電気主任技術者が復帰させる場合。<br>
※原則「手動」が望ましいが「自動」の設定になっている現場もあるらしい。<br>

<h2>OVGRの150%試験は印加電圧に注意</h2>
整定値10%でT-E間の動作電圧が約381Vとなる構成なら、150%試験は約571V（381V×1.5）になる。普段より高い試験電圧になるため注意する。<br><br>

試験前の確認事項<br>
・50Hz／60Hzの設定<br>
・試験器の出力レンジ、ツマミ位置<br>
・ZPDのT-E間へ印加する試験電圧<br>
・メーカー、ZPD・継電器の機種と試験要領<br><br>

<strong>T-E間の試験電圧はメーカー・機種によって異なる。同じ電圧を一律に印加せず、必ずメーカー資料・試験要領を確認する。</strong><br>
富士電機ZPD-1など570Vで試験する構成については<a href="zpd2.php">ZPD V0が5%で570Vの場合</a>も参照。<br>
三菱ZPDは試験電圧の扱いが異なるため<a href="zpdm.php">三菱 ZPD 試験電圧</a>を確認。<br>

