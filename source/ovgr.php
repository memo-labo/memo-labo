<h2>系統地絡とOVGRの動作</h2>
配電系統で地絡事故が発生すると、配電用変電所側の保護継電器が事故区間を切り離す。<br>
その間、需要家側PCSが系統へ電力を供給し続けないよう、OVGRでV0を検出してPCSを停止させる構成がある。<br><br>

事故区間が上位側で切り離され、需要家側の零相電圧が消失した場合には、OVGRは復帰する。<br>

<h2>OVGRの整定</h2>
<strong>動作時間</strong><br>
配電用変電所DGRとの時間協調を考慮して設定する。<br>
上位DGRより早く動作させると健全系統でも不要動作する可能性があるため、電力会社との協議値を優先する。<br><br>

<strong>自動復帰・手動復帰</strong><br>
自動：OVGR復帰後にPCSを自動復帰させる構成。<br>
手動：OVGR動作後、確認してから手動でPCSを復帰させる構成。<br>

<h2>OVGR試験</h2>
ZPDのT-E端子などへ試験電圧を印加し、OVGRの最小動作値や動作時間を確認する。<br>
ただし、試験電圧・倍率・印加端子はZPDとOVGRのメーカー・機種によって異なる。<br><br>

試験前の確認事項<br>
・50Hz／60Hz設定<br>
・試験器の出力レンジ<br>
・ZPDのT-E間へ印加する試験電圧<br>
・ZPDとOVGRの組み合わせ<br>
・メーカー試験要領<br>

<h2>150%試験時の注意</h2>
整定値10%でT-E間の動作電圧が約381Vとなる構成では、150%試験時は約571Vとなる。<br>
高い試験電圧になるため、試験器レンジと機器の許容電圧を事前に確認する。<br><br>

<strong>T-E間の試験電圧はメーカー・機種によって異なる。</strong><br>
富士電機ZPD-1などについては<a href="zpd2.php">ZPD V0が5%で570Vの場合</a>を参照。<br>
三菱ZPDについては<a href="zpdm.php">三菱 ZPD 試験電圧</a>を参照。<br>

<h2>OVGRの省略条件</h2>
PCS容量や契約電力との比率、PCSの保護機能などによって、OVGRを省略できる場合がある。<br>
・PCS出力容量10kW以下<br>
・PCS出力容量が契約電力の5%以下<br>
<a href="https://www.fa.omron.co.jp/data_pdf/cat/k2zc-k2gv-nc_sgte-908_1_9.pdf">K2ZC-N カタログ</a><br>

<h2>試験時の注意点</h2>
OVGRの制御電源がDC24Vの場合、低圧MCCBからブロック電源を介して供給されている構成がある。<br>
試験時は、既設電源への逆印加を防ぐため、どこで電源を切り分けるかを確認してから補助電源を供給する。<br>

