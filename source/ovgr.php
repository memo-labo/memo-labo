<h2>注意点</h2>
OVGRの制御電源端子、S1、S2は、継電器の定格制御電源がDC24Vとなっている。<br>
OVGRの試験をする際、配線は電源側から低圧MCCB⇒S8TS⇒OVGRとなっていたら、MCCBをOFFにした状態で、MCCB２次側にAC110V印加させる。<br>

