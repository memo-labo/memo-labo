<h2>OVGR 地絡過電圧継電器とは？</h2>
OVGRは、零相電圧V0を監視して地絡事故を検出する保護継電器。<br>
高圧電路のケーブルや機器の絶縁劣化などによって地絡が発生した場合に、系統の零相電圧上昇を検出する。<br><br>

OVGR 地絡過電圧継電器の記号<br>
<img src="images/ovgr11.png" style="max-width:150px;" alt="OVGR 地絡過電圧継電器 記号"><br>

太陽光発電設備では、系統側で地絡事故が発生した際にPCSから系統へ電力を供給し続けないよう、OVGRの動作信号でPCSを停止・解列する構成がある。<br>

<h2>OVGRの原理</h2>
系統側の地絡を、零相電流ではなく零相電圧V0で監視する。<br>
発電設備側から系統事故点へ流れる地絡電流が小さい場合でも、系統全体には零相電圧が発生するため、OVGRで地絡を検出できる。<br><br>

零相電圧は同一系統全体に現れるため、V0だけでは地絡点の方向や場所を特定することはできない。<br>

<h2>OVGR 配線例</h2>
