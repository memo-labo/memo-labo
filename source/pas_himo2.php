<h2>PASの紐に植物（ツタ）が絡まって開放操作が出来ない場合</h2>

事前対策<br>
もし月次点検でそれを発見した場合、根元で切っておく。<br>
しばらくすると、切断したところから上の部分に水分がいかずに枯れていく。<br>
停電する予定がないのに紐をむやみに触らない。<br>
年次点検が予定されている日まで放置しておいた方が良い？<br><br>

年次点検直前で発見した場合<br>
胴綱とフルハーネスを使用して電柱に登る。<br>
危険なのでPASをSOGのテストボタンで開放させた後で登る。<br>
ただし、ツタがPASの方まで達していた場合は危険なので登らない。<br>
費用と手間がかかっても、ASを開放してもらい、高所作業車等で撤去する。<br>

