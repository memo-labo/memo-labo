<h2>PV用メガー</h2>
PVメガーは太陽電池パネルが発電中でもP相とN相を短絡させずに測定が可能。<br>
PVメガーは絶縁劣化箇所に左右されずに正確に測定することができる。<br><br>

PV用メガーの原理・仕組み<br>
測定開始後、太陽光パネルの電圧、電流を計測する。<br>
同時に、メガーから電圧を印加した後の電圧、電流を計測する。<br>
そして演算により太陽光パネルの影響を排除した抵抗値を算出している。<br>

<h2>太陽光パネルの絶縁抵抗測定方法</h2>
接続箱の主開閉器をOFFにしてパワーコンディショナーとの接続を切る。<br>
すべてのストリングの断路器をOFFにする。<br>
測定回路に避雷器がある場合は避雷器を回路から切り離す。<br>
