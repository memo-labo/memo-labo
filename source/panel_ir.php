<h2>太陽光パネルの絶縁抵抗測定方法</h2>

HIOKI IR4053<br>
太陽光パネル用 絶縁抵抗計<br><br>

従来の絶縁抵抗計で測定する場合、絶縁が悪い場合、正確な測定ができない。<br>
その対策として、PVのP相とN相を短絡させてから測定する方法がある。<br>
この場合は短絡用開閉器が必要で、また日中は発電状態のため、短絡時にアークが発生する。<br>
さらに短絡した後、パネルには電流が流れ、もしパネルが故障していた場合、パネルが発熱して、火災に繋がる場合もある。<br>
もしこの方法を採用するとしたら、発電していない夜の時間帯にやるべき。<br><br>


短絡させない方法で測定をすると、発電中のPVの電圧の影響を受ける。<br>
従来の絶縁抵抗計では、PVからの発電電圧が、絶縁抵抗測定の値に影響を与える。<br>
また絶縁抵抗計に電圧が印加されて、メガーを破損する可能性がある。<br>
絶縁が悪い状態でN相を測定すると、モジュールやバイパスダイオードを破損する恐れ。<br>

<h2>PとNの開放電圧測定</h2>
