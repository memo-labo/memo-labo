P(+)とN(-)にプローブをあて、開放電圧値と極性を確認する。<br>
極性が誤っている場合、赤色点灯でお知らせ。<br>
IR4053,IR4055の端子間最大定格電圧はDC1000V/AC600V。<br>



<h2>従来のメガーでPV絶縁測定</h2>
夜間、パネルが発電してない状態であれば通常のメガーでパネル絶縁測定が可能。<br>
その場合、PとNを短絡した状態で絶縁抵抗測定を行えば測定誤差は発生しない。<br><br>

P側が地絡している場合のP側測定<br>
太陽電池からの発電電流は絶縁抵抗計に流れ込むルートがないため正確に測定できる。<br>
※ただしCATⅢ600Vまでの機器の場合、太陽光PVがDC600V以上の場合、機器が故障する可能性。<br>
<img src="images/202206291.svg" style="max-width:600px;"><br>

N側が地絡している場合のP側測定<br>
太陽電池からの発電電流は絶縁抵抗計に流れ込むルートがあり電流が加算され測定値は本来よりも小さくなる。<br>
この場合に測定した絶縁抵抗の数値は誤差が大きく全く信用ができない。<br>
