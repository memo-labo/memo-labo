<h2>a接点・b接点の使い方</h2>

<p>サーマルリレーの補助接点は、停止・警報・自己保持解除などの制御に使います。</p>

<ul>
  <li><strong>a接点</strong>：動作時に閉じる。警報などに使用</li>
  <li><strong>b接点</strong>：動作時に開く。MCコイルの遮断などに使用</li>
</ul>

<p>端子番号は機種によって異なります。95-96、95-98などの表記例がありますが、実機の端子図を優先します。</p>

<h2>整定電流はどう決める？</h2>

<p>モータ用では、モータ定格電流・運転条件・始動時間・周囲温度などを考慮し、メーカーの選定表に従って整定します。</p>

<p>例としてTH-N20のように、ヒータ呼びごとに調整可能な電流範囲が設定されている機種があります。</p>

<p><strong>「3.5～3.9Aが多い」などの固定値ではなく、対象負荷・CT比・機器仕様に応じて決めます。</strong></p>

<h2>サーマルリレーとMCCBの違い</h2>

<ul>
  <li><strong>サーマルリレー</strong>：モータなどの継続的な過負荷保護が主目的</li>
  <li><strong>MCCB</strong>：短絡・過電流から電路を保護</li>
</ul>

<p>モータ回路では両者を組み合わせて保護する構成が一般的です。サーマルリレーだけで短絡保護を行うものではありません。</p>

<h2>試験・点検時の確認ポイント</h2>

<ul>
  <li>整定値が対象負荷に合っているか</li>
  <li>リセット方式が手動か自動か</li>
  <li>a・b接点が正しく切り替わるか</li>
  <li>MCとの組み合わせではトリップ時にMCが確実に開放するか</li>
  <li>CT二次回路型ではCT回路を不用意に開放しない</li>
  <li>過去の整定値だけを根拠にせず、銘板・回路図・メーカー資料を確認する</li>
</ul>

<h2>過負荷保護の省略について</h2>

<p>電動機の過負荷保護装置を省略できる条件は、設備条件や適用する技術基準・内線規程等によって定められています。</p>

<p><strong>「小容量だから必ず省略できる」と一律に判断せず、対象回路に適用される規定と保護方式を確認します。</strong></p>

