<h2>CT二次回路の例</h2>

<img src="images/thr4.png" style="max-width:700px;" alt="CTと熱動継電器の配線例"><br>

<p>図のようにCT二次電流を熱動継電器・電流計へ流し、設定値を超える状態が続いたときに警報接点を動作させる回路があります。</p>

