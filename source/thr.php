<h2>サーマルリレー（熱動継電器）とは？</h2>

<p><strong>サーマルリレーは、過電流による発熱を利用して過負荷を検出する継電器です。</strong><br>
主にモータの過負荷保護や、盤内の過電流警報回路などに使われます。</p>

<img src="images/thr1.jpg" style="max-width:450px;" alt="サーマルリレー外観"><br>
<img src="images/thr2.jpg" style="max-width:450px;" alt="熱動継電器外観"><br>

<h2>動作原理</h2>

<p>電流が流れるとヒータが <strong>I²R</strong> に応じて発熱し、その熱でバイメタルが変形します。一定以上の過負荷が続くと機構が動作し、補助接点を切り替えます。</p>

<p>バイメタルは、熱膨張率の異なる金属を組み合わせ、温度変化で曲がる性質を利用した部品です。<br>
⇒<a href="by.php">バイメタルの詳細</a></p>

<h2>モータ用サーマルリレー</h2>

<p>一般的なモータ用サーマルリレーは、電磁接触器（MC）と組み合わせて使用します。</p>

<ol>
  <li>モータに過負荷電流が流れる</li>
  <li>サーマルリレーが加熱される</li>
  <li>補助b接点が開く</li>
  <li>電磁接触器のコイル回路が切れる</li>
  <li>MCが開放し、モータへの給電を停止する</li>
</ol>

<p>⇒<a href="mc.php">電磁接触器（MC）とは？</a></p>

<h2>CT二次側で使う熱動継電器</h2>

<p>受電盤などでは、主回路電流をCTで5Aなどへ変換し、CT二次回路に熱動継電器を入れて過電流を監視する構成もあります。</p>

