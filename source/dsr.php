<h2>電流動作試験</h2>
時間整定値⇒最小0.1s<br>
電圧⇒20V以上～不足動作電圧整定値以下<br>
位相⇒進み180°<br>
ストップ信号⇒接点<br>
カウンタ⇒OFF（ブザー音とランプ点灯で接点動作確認）<br><br>

電流⇒徐々に流して継電器の検出表示LEDが点灯した時の電流を読む。<br>
電流タップ整定2Aだった場合の動作値誤差は整定値±10％＝1.8A～2.2A<br><br>
※単相での試験では電圧LEDは点灯する。<br>

<h2>不足動作電圧試験</h2>
時間整定値⇒最小0.1s<br>
継電器本体の不足電圧要素スイッチ⇒「あり」<br>
ストップ信号⇒接点<br>
カウンタ⇒OFF（ブザー音とランプ点灯で接点動作確認）<br><br>

電流⇒電流整定値以上（整定値の130% = 2A整定の場合2.6A）<br>
電圧⇒110V<br>
位相⇒進み180°<br>
電圧⇒定格値から徐々に下げると不足動作電圧整定値付近で接点動作<br>
動作値誤差：整定値±10％<br>

<h2>位相試験</h2>
時間整定値⇒最小0.1s<br>
電圧⇒不足動作電圧整定値の70％<br>
電流⇒電流整定値の130％<br>
ストップ信号⇒接点<br>
カウンタ⇒OFF<br>
位相⇒0°（つまみ中央）<br>
※位相0°だと継電器は動作せず、位相を遅れ・進みに変化させる事である値にて動作する。<br><br>

試験スイッチON⇒進み位相、遅れ位相、２つを計測<br>
動作値誤差：進み130±15度、遅れ 90±15度<br>


<h2>動作時間試験</h2>
時間整定値⇒整定値<br>
電圧⇒不足動作電圧整定値の70％<br>
電流⇒電流整定値の130％<br>
位相⇒進み180°<br>
ストップ信号⇒接点<br>
カウンタ⇒ON<br><br>

試験スイッチON⇒（接点動作でサイクルカウンタと出力がストップ、時間計測）<br>
動作値誤差：整定値±10％(最小誤差±50ms）<br>

