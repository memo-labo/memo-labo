<h2>DSR 短絡方向継電器</h2>
DSR = Directional Short-circuit relay。<br>
同期発電機の運用にDSRが必要で、系統側の短絡事故を検出する。<br>
設置相数は３相を基本とし、DSRの動作で発電機側のCBを遮断する<br>

<h2>誘導発電機の場合はDSRが不要</h2>
回転子がカゴ形のものは励磁装置がなく、接続されている系統から励磁電流をとる。<br />
系統の短絡事故の場合、電源電圧がなくなり、励磁電流がとれないので、自動的に発電が停止する。<br />
なので、系統に短絡電流を流さないので、DSRが必要ない。

