<h2>DSRの標準的な整定例</h2>
電流整定：DSRから見た系統最遠方の地点で2相短絡が発生した時、発電機より流出する短絡電流の 30～50％で検出する整定値（発電機の並列投入時の動揺時間を考慮する）<br>
不足電圧：90V<br>
動作時間：0.7s（配電用変電所の同バンク・他フィーダーのOCRとの時間協調をとる）<br>


<h2>K2ZC-K2DS-Nの動作条件</h2>
DSRの動作条件<br>
①発電機側から系統側に流れる短絡電流が整定値を上回る。<br />
②短絡電流と測定電圧の位相が動作域に入っている。<br />
③系統短絡時に発生する系統側の不足電圧で電圧が不足電圧整定値よりも下回る。<br />
（不足電圧はスイッチでロック状態も可）<br />

<h2>逆潮流の検出にRPRとDSRの２つが必要な理由</h2>
<ul>
    <li>RPRは系統側の断線・停電による逆潮流を検出可能だが、短絡事故検出は不可能。
    <li>RPRの電流検出は１相だけ、２線短絡事故の検出は不可能。
    <li>短絡事故は電圧が降下しても電流が増大するため√3VIcosθが変化しない可能性。
    <li>短絡事故は遅れ力率で電力量は少なくなる。
</ul>

<h2>DSRだけではなくRPRが必要な理由</h2>
<ul>
    <li>断線停電時には逆潮流の電流は短絡電流ほど流れない。
    <li>DSRだけでは逆潮流の検出が不可能。
</ul>

<h2>配線例</h2>
3CT、DSR、UPR、OCR、RPR、DSRの構成の場合<br>
R相CT(k)⇒OCR C1R-C2R⇒DSR C1R-C2R⇒AM⇒R相CT(l)<br>
S相CT(k)⇒UPR C1S-C2S⇒RPR C1S-C2S⇒DSR C1S-C2S⇒AM⇒S相CT(l)<br>
T相CT(k)⇒OCR C1T-C2T⇒DSR C1T-C2T⇒AM⇒R相CT(l)<br>


<h2>DSRの検出方法</h2>
相電流Irに対しての位相は線間電圧Vstとの関係で検出。<br />
系統が健全状態では、線間電圧Vsrに対し、相電流Irは90°位相が進み。<br />
系統側で短絡が発生した場合、短絡電流Irは配線のリアクタンスの影響をうけて90度遅れ。<br />

<h2>DSR 試験時の配線方法</h2>

■配線方法（R相）<br>
電圧：P2 と（P1・P3：短絡）<br>
