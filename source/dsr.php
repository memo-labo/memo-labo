位相：P2とC1Rは同相<br><br>

■配線方法（S相）<br>
電圧：P3 と（P1・P2：短絡）<br>
電流：C1S と C2S<br>
位相：P3とC1Sは同相<br><br>

■配線方法（T相）<br>
電圧：P1 と（P2・P3：短絡）<br>
電流：C1T と C2T<br>
