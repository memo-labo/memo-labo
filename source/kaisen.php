<h2>２回線受電方式とは？</h2>

２回線受電方式<br>
常用・予備線方式（同系統）<br>
常用・予備線方式（異系統）<br><br>

常用線停電時には予備線から受電できる。<br>
１回線受電方式に比べ供給信頼度は高くなる。<br><br>

異系統の場合、それぞれ異なる変電所から電力を供給するので、同系統より信頼度が高い。

