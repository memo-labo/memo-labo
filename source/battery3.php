<h2>バッテリー用語の意味</h2>

浮動充電<br>
蓄電池の充電方法のひとつ。<br>
フロート充電、フローティングチャージ、とも呼ばれる。<br>
整流器に対して負荷と蓄電池を並列に接続する。<br>
一定電圧を連続的に印加して、負荷を運転しつつ、蓄電池を充電する。<br>
蓄電池は常に充電と放電が継続した状態となり、かつ満充電が維持される。<br>
電池の自己放電には充電装置から充電を行い、自己放電よりも負荷電流が大きくなった場合には電池から放電をして負荷に対応する。<br><br>

回復充電<br>
鉛蓄電池は24時間、アルカリ蓄電池は8時間の回復充電時間が必要。<br>
回復充電中に異音や異常発熱をきたし、回復充電が停止するなど安全装置がついている場合がある。<br><br>

充電終止電圧<br>
安全に充電を行える充電電圧の最高値<br><br>

放電終止電圧<br>
安全に放電を行える放電電圧の最低値<br><br>

過充電<br>
充電終止電圧を上回る電圧で充電した状態<br><br>

過放電（かほうでん）<br>
充電を繰り返すことで再利用が可能な二次電池は、安全に放電が行える放電電圧の最低値がある。<br>
その電圧値を「放電終止電圧」と呼び、その電圧に至った時点でそれ以上放電してはいけない。<br>
放電終止電圧を超えてさらに放電を続ければ過放電となる。<br>
すると電池の劣化や事故などに繋がる恐れがある。<br><br>

リチウムイオン電池の場合、充電は残量が20％から80％の間で行うのベストらしい。<br>
過放電・過充電は、電池のサイクル回数（寿命）にも大きな影響を及ぼす。<br>
なのですべて使い切る前に継ぎ足し充電を行うほうが良い。<br>
過放電を防止するためにMC（マグネット）で回路をOFFする直流電源装置もある。<br>
