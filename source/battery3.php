<h2>モバイルバッテリー</h2>

リチウムイオン電池<br><br>

リチウムとは？<br>
元素記号：Li<br>
白銀色の軟らかい元素。<br>
すべての金属元素の中でもっとも軽い。<br>
比熱容量は全固体元素中でもっとも高い。<br><br>

リチウムはイオン化傾向が大きい。<br>
（イオン化傾向：イオンへのなりやすさ）<br><br>

電池は、正極と負極でイオン化傾向に差があるほど、起電力（電圧）が高くなる。<br>
イオン化傾向の大きいリチウムは、電池の電圧を高められる。<br>

<h2>バッテリーの充電時間計算</h2>

充電時間 = バッテリー容量[mAh] ÷ （入力電流[mA] × 時間[h] × 充電効率 0.6）<br><br>

ただし入力電流は、モバイルバッテリー入力定格電流よりモバイルバッテリーを充電する充電器の出力定格電流が低い場合、低いほうの値になる。<br>


