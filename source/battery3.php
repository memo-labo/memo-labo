<h2>鉛蓄電池の原理</h2>

①Pb：鉛<br>
②PbO2：二酸化鉛<br>
③H2SO4：希硫酸<br><br>

①と②を③に浸けて①と②を導線で繋ぐ電気が流れる。<br><br>

電池＝酸化還元反応を利用して電子を取り出す。<br><br>

鉛の酸化<br>
Pb + SO42- → PbSO4 + 2e-<br><br>

酸化鉛の還元<br>
PbO2 + 4H+ + SO42- + 2e- → PbSO4 + 2H2O<br>


