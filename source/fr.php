■周波数継電器<br>
FR = Frequency Relays<br>
制御器具番号 95<br><br>

■UFR 不足周波数継電器とは？<br>
上位送電側の事故時に起きる、周波数の低下を検出する。<br>
主に、系統側事故の短絡を検出することができる。<br>
発電機の容量と、系統負荷のバランスがとれていると、動作しないことがある。<br><br>

■OFR 過周波数継電器とは？<br>
電圧低下による負荷脱落時の周波数上昇を検出する。<br>
電力が供給過多になった時、周波数が上昇し、同期できなくなった発電機は解列される（系統から切り離される）<br><br>

<h2>整定値</h2>

動作値、動作時間などの整定値は電力会社との協議により決定する。<br><br>

一般的な整定値<br>
UFR<br>
1s 定格周波数 - 1Hz<br>
動作周波数：48.5～49.5Hz/58.2～59.4Hz<br>
動作時間：0.5～2秒<br><br>

OFR 1s 定格周波数 + 1Hz<br>
動作周波数：50.0～51.5Hz/60.6～61.8Hz<br>
動作時間：0.5～2秒<br>

