<h2>試験方法</h2>
S1-S2に制御電源を印加<br>
P1-P2にACの定格電圧110Vを印加<br>
a-a の接点に信号線<br><br>

■動作周波数の試験<br>
UFR<br>
動作時間を最小値0.1sに変更<br>
定格周波数から徐々に周波数を低下<br>
検出表示LEDが動作する時の周波数を読む<br><br>

OFR<br>
動作時間を最小値0.1sに変更<br>
定格周波数から徐々に周波数を上昇させる<br>
検出表示LEDが動作する時の周波数を読む<br><br>

■動作時間の試験<br>
UFR<br>
POWER1を定格電圧・定格周波数に調整<br>
POWER2をUFR設定値より 5Hz低下させた周波数に調整。<br>
POWER1からPOWER2に切り替え、サイクルカウンタが動作した時の値を読む。<br><br>

OFR<br>
POWER1を定格電圧・定格周波数に調整<br>
POWER2をOFR設定値より 5Hz上昇させた周波数に調整。<br>
POWER1からPOWER2に切り替え、サイクルカウンタが動作した時の値を読む。<br><br>

■判定基準<br>
動作周波数：整定値の±0.1Hz<br>
動作時間：整定値の±10% (最少誤差±50ms)<br>


<h2>コージェネレーション試験機 CGRT-02K</h2>

試験の際の注意<br>
動作周波数の測定はカウンタスイッチ「OFF」で継電器動作が確認できる。<br>
表示がホールド状態になり、動作ランプが点灯し、内部ブザーが鳴る。<br><br>

■単相周波数の場合<br>
電圧出力コード：V->P1、E->P2<br>
試験切替スイッチ：単相周波数<br>
相切替スイッチ：A相<br>
位相調整ツマミ：０（中央位置）<br><br>

■動作時間測定<br>
「周波数調整」部分<br>
①基準周波数->50Hz or 60Hz（使用地域による）<br>
②試験周波数->継電器整定値の±5Hz<br>
カウンタ->ON<br>
試験OFF->基準周波数にて電圧出力<br>
試験ON->カウンタスタートと同時に試験周波数で電圧出力<br>
接点動作、カウンタ動作、出力停止、時間計測。<br>

