<h2>高調波とは？</h2>

高調波<br>
周波数は基本波の2倍以上の整数倍。<br>
一般的には40倍程度（～数kHz）までで、40倍であれば40次と表記する。<br><br>

高周波<br>
空気中を伝播する電磁ノイズ。<br>
商用電源周波数に同期しない。<br>
一般的に2kHzを超える高調波を高周波と呼ぶ。<br><br>

ひずみ波交流の中に含まれている、基本波の整数倍の周波数をもつ正弦波、のこと。<br>
基本波の３倍の周波数を第3高調波、５倍の周波数を第５高調波と呼ぶ。<br>
この２つを重点的に確認し、抑制することが高調波対策として有効。<br><br>

高調波は、電気機器、電路、進相コンデンサに悪影響を及ぼす。<br>
進相コンデンサに高調波電流が流れることによる燃損など。<br>
具体的には、機器、ヒューズ、ブレーカ等の過熱、振動など。<br><br>

力率改善用の進相コンデンサは、高調波に弱いといわれる。<br>
コンデンサは容量性リアクタンス（1/2πfC）なので、インピーダンスは周波数に反比例する。<br>
周波数が増えるとインピーダンスは下がるので流れる電流は増加し、コンデンサが焼損する。<br><br>

n次高調波のリアクタンス<br>
リアクトルの場合⇒n倍<br>
コンデンサの場合⇒1/n倍<br>

