<h2>直列リアクトルがコンデンサ容量の6%の意味</h2>

ω = 2πf<br /><br />

コンデンサの、交流に対する容量性リアクタンス<br />
XC = 1/ωC<br /><br />

リアクトルの、交流に対する誘導性リアクタンス<br />
XL = ωL<br /><br />

第5調波の容量性リアクタンス<br />
XC(5) = (1/5) * (1/ωC) = (1/5)XC<br /><br />

第5調波の誘導性リアクタンス<br />
XL(5) = 5 * ωL = 5XL<br /><br />

第５調波以上の高調波に対し、回路のリアクタンスを誘導性にすると高調波が抑えられる。<br /><br />

XL(5) - XC(5) > 0<br />
5XL - (1/5)XC > 0<br />
XL > (1/25)XC<br />
XL > 0.04 XC<br /><br />

回路の誘導性リアクタンスが容量性リアクタンスの4%以上であれば回路のリアクタンスは誘導性となる。<br>
多少の余裕を設けて4%ではなく6%としている。<br><br>

つまりコンデンサ容量に対して直列リアクトル容量を6%に設定しているのは、第5調波以上の高調波に対して回路の合成リアクタンスを誘導性にするためである。


<h2>直列リアクトルがコンデンサ容量の13%の意味</h2>

第３調波以上の高調波に対し、回路のリアクタンスを誘導性にすると高調波が抑えられる。<br /><br />

XL(3) - XC(3) > 0<br />
3XL - (1/3)XC > 0<br />
XL > (1/9)XC<br />
XL > 0.11 XC<br /><br />

回路の誘導性リアクタンスが容量性リアクタンスの11%以上であれば回路のリアクタンスは誘導性となる。<br>
多少の余裕を設けて11%ではなく13%としている。<br><br>

つまりコンデンサ容量に対して直列リアクトル容量を13%に設定しているのは、第３調波以上の高調波に対して回路の合成リアクタンスを誘導性にするためである。

