<h2>ひずみ波とは？</h2>
正弦波ではない繰り返しを持つ波のこと。<br>
基準波に対して周波数がn倍の波を第n調波という。<br>
第２調波以降を高調波という。<br>
直流成分は周波数が0の波と言える。<br><br>

V1=基準波<br>
V3=第３調波<br>
V0=直流成分<br>
