<h2>モールドジスコン（MDS）とは？投入・開放・復電時の注意</h2>
モールドジスコン（MDS）は、地中引込の高圧受電設備で使われる断路器の一種。<br>
古い高圧キャビネットに残っていることがあり、投入・開放時は下流のDS・LBS・VCBの状態、地絡保護、投入直後の電圧確認まで含めて復電手順を考える必要がある。<br><br>

