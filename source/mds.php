<h2>モールドジスコンとは？</h2>
電力側6600V高圧を需要設備に引き込む際、電力側キャビネット内のお客様側回路に取り付ける断路器。<br>
手動ハンドルで挿入・引き抜きを行い、高圧回路を断路する。<br><br>

MDSは負荷電流を遮断するための遮断器ではないため、操作時は設備構成に応じて下流のVCB・LBSなどを開放し、負荷電流が流れない状態を確認してから操作する。DSを含む操作順序は設備構成や劣化状態で変わるため、単線結線図、メーカー資料、現場手順を優先する。<br>

<h2>操作用工具（ハンドル）</h2>
バネとフック型の穴で構成されている。<br>
モールドジスコンにハンドルを押し込み、ハンドルフックをMDS先端の突起に掛けて固定する。<br>
<img src="images/mds/2.jpg" alt="モールドジスコン操作用ハンドル" style="max-width:400px;"><br>

<h2>モールドジスコンのタイプ</h2>
モールドジスコンには「単極型」と「三極型」がある。<br>
・単極型：1相ずつ開放・投入するタイプ<br>
・三極型：3相をまとめて開放・投入するタイプ<br>

<h2>投入と開放時の注意</h2>
<img src="images/mds3.jpg" alt="モールドジスコンをハンドルで引き抜く部分" style="max-width:700px;"><br><br>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：落下・破損にも注意する</span>
引き抜き時にハンドルのロックからMDSが外れると、落下して割れたり欠けたりすることがある。操作前にハンドルの掛かり方を確認し、無理な力を加えない。
</div>

MDSの入切操作では、設備の作業手順に従い、高圧ゴム手袋など所定の保護具を使用する。屋外や湿潤環境では絶縁性能や足元の状態にも注意する。<br><br>

単極型MDSを、VCBやLBSを投入したまま変圧器まで受電している状態で1相だけ引き抜くと、欠相状態となり、変圧器から異音が出る可能性がある。停電操作では、下流の遮断器・開閉器の状態を確認してからMDSを操作する。<br>

<h2>復電時の基本確認</h2>
VCBやLBSを投入する前に、GRなど必要な保護継電器の制御電源が正常に入っていることを確認する。<br>
保護継電器の制御電源が切れたまま復電すると、地絡が発生しても保護装置が期待どおり動作しないおそれがある。<br><br>

復電時は、設備構成に応じて下流機器を切り分け、MDS投入後にまず高圧側の電圧を確認する。その後、DS・LBS・VCBなどを順次操作する。具体的な順序は現場ごとの単線結線図と手順書に従う。<br>

<h2>モールドジスコン・ピラージスコン投入時のDS操作をどう考えるか</h2>
区分開閉器を投入する際、キュービクル側DSを開放しておくと、下流設備まで一度に励磁しないため、変圧器などの突入電流や投入時の影響を小さくしやすい。<br><br>

ただし、MDSやピラージスコンが残っている設備は古いことが多く、キュービクル側DSも酸化・腐食・機械部の劣化などで操作が重くなっている場合がある。充電状態で硬いDSを何度も押し込み、投入状態を確認するような操作はリスクが高い。<br><br>

<strong>モールドジスコンの場合</strong><br>
現場条件によっては、VCB・LBSを確実に開放したうえで、無電圧状態のうちにキュービクル側DSを投入しておき、その後MDSを投入する方が、劣化したDSを充電状態で操作せずに済む場合がある。<br>
ただし、この方法ではMDS投入時にDSより下流の高圧母線や機器の一部まで充電されるため、突入電流、地絡時の影響範囲、保護範囲を事前に確認する。<br><br>

<strong>ピラージスコンの場合</strong><br>
ピラー内でのジスコン操作は、構造や充電部との位置関係によって作業条件が厳しい設備がある。キュービクル側DSを開放してピラー側の投入を先に完了する考え方が適する場合もある。<br>
その後DSを充電状態で操作する場合は、所定の保護具を使用し、設備がその操作を想定した構造か、操作棒・インターロック・離隔・作業手順を確認する。<br><br>

<div class="article-warning">
<span class="article-warning-title">⚠ 注意：操作順序を一律に決めない</span>
古いDSの操作不良リスクと、区分開閉器投入時に下流を充電するリスクの両方を比較する。単線結線図、メーカー資料、電力会社との取決め、現場の作業手順・リスクアセスメントを優先し、充電部に近接した状態で硬いDSを力任せに繰り返し操作しない。
</div>

<h2>モールドジスコン投入直後は二次側電圧をすぐ確認する</h2>
MDSを投入した瞬間に需要家側ケーブルなどで地絡が発生すると、配電側の地絡保護が動作して送電が停止することがある。<br>
そのため、MDS投入直後は需要家側に電圧が正常に来ているかをすぐ確認する。<br><br>

投入直後に電圧が確認できない場合は、そのままDS・LBS・VCBなどの復電操作を進めず、異常を疑う。原因を確認せず再投入を繰り返さない。<br><br>

可能であれば、MDS投入操作と電圧確認を別の作業者で分担すると、投入直後の異常を把握しやすい。ただし、実際の人員配置や検電位置、再送電時の対応は現場の作業手順に従う。<br>

<h2>モールドジスコン、VCB、GRの組み合わせによる波及事故</h2>
MDSから構内キュービクルVCBまでのケーブルで地絡が起きた場合、構内VCBより電源側の事故となるため、需要家側VCBでは事故を切り離せない構成がある。その場合、電力側の地絡保護が動作して送電が停止する。<br><br>

地絡原因が残ったまま再閉路・再送電されると、同じ箇所で再び地絡し、波及事故へ発展する可能性がある。<br><br>

高圧ケーブルの経年劣化は構内地絡事故の代表的な原因の一つ。責任分界点付近の事故を需要家側で切り離せる構成にする目的で、設備更新時にUGSなどの区分開閉器を検討する場合がある。<br>

<h2>高圧キャビネットの種類</h2>
<strong>二回路形（A1形）</strong><br>
受電した高圧系統を、そのまま送電するスイッチ機能を持つタイプ。<br><br>

<strong>三回路形</strong><br>
隣接需要家へ高圧電路を渡せるタイプ。<br><br>

高圧キャビネット内部にはUGSやMDSなどの区分機器が設置される。責任分界点の位置は設備構成や電力会社との取決めによるため、実際の図面・契約資料を確認する。<br>

