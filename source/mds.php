<h2>モールドジスコンとは？</h2>
電力側6600V高圧を需要設備に引き込む時に電力側キャビネット内の第三回路（お客様側回路）に取付ける。<br>
手動ハンドルにて挿入、引き抜くことで、電気回路を入切できる断路器。<br>
モールドジスコン操作時は、下流のVCB等の遮断器や断路器DSは開放状態で操作を行う。<br>

<h2>操作用工具（ハンドル）</h2>
バネとフック型の穴で構成されている。<br>
モールドジスコンにハンドルを押し込む。<br>
ハンドルフックがMDS先端の突起にひっかかる。<br>
ハンドルバネが戻ることで固定される。<br>
<img src="images/mds/2.jpg" alt="" style="max-width:400px;"><br>


<h2>モールドジスコンのタイプ</h2>
モールドジスコンには「単極型」と「三極型」がある。<br>
１相ずつ開放・投入するタイプが「単極型」<br>
３相いっぺんに開放・投入するタイプが「三極型」<br>


<h2>投入と開放時の注意</h2>

↓これをハンドルを使って引き抜くことで断路する<br>
<img src="images/mds3.jpg" alt="" style="max-width:700px;"><br><br>

落として割る<br>
モールドジスコンを引き抜く際、ハンドルのロックからモールドジスコンが外れて落下。<br>
モールドジスコンを割る、または欠けてしまう。<br><br>

モールドジスコンの入切操作時には、高圧ゴム手袋を装着して行う。<br>
屋外で雨に濡れた状態で操作した場合、体を通して足に地絡し感電する恐れ<br>

<img src="images/mds/3.jpg" alt="" style="max-width:300px;"><br>

モールドジスコンが１相ずつ引き抜くタイプで、かつVCBやLBSを投入状態で変圧器まで受電状態で引き抜くと、引き抜いた瞬間に欠相状態となり、変圧器から異音が発生する。<br><br>
なので、停電の際にはVCBやLBSは開放状態にしてから、モールドジスコンを引き抜く。<br><br>

<h2>復電時の注意</h2>

VCBやLBSを入れる前に、GRの制御電源用MCCBをON状態にする。<br>
MDSを投入し、次にVCBを投入した際、瞬間的にGR電源が入り、地絡が発生したらVCBが開放される。<br>
もしGR電源がOFFであると地絡が発生してもGRが動作せずVCBが開放されず波及事故に。<br><br>

復電手順<br>
DS、LBS、VCBを開放状態にしておいてから、モールドジスコンを投入する。<br>
まずモールドを３相すべて投入し、高圧の電圧計で電圧が来ていることを確認する。<br>
続いてDSを投入する。<br>
LBS or VCBを入れる。<br>

<h2>モールドジスコン・ピラージスコン投入時のDS操作をどう考えるか</h2>
区分開閉器を投入する際は、キュービクル側のDSを開放しておく方が、下流設備まで一度に励磁しないため、変圧器などの突入電流や投入時の影響を小さくしやすい。<br>
そのため、設備条件と作業手順が許すなら、下流のDS・LBS・VCBを開放した状態で区分開閉器を投入するのが基本的な考え方になる。<br><br>

ただし、モールドジスコンやピラージスコンが残っている設備は古いことが多く、キュービクル側DSも酸化・腐食・機械部の劣化などで操作が重くなっている場合がある。<br>
このようなDSを区分開閉器投入後の充電状態で何度も押し込み、投入状態を確認するような操作は、無電圧時に操作する場合より作業リスクが高くなる。<br><br>

<strong>モールドジスコンの場合</strong><br>
現場条件によっては、VCB・LBSを確実に開放したうえで、無電圧状態のうちにキュービクル側DSを投入しておき、その後にモールドジスコンを投入する方が、劣化したDSを充電状態で操作せずに済む場合がある。<br>
ただし、この方法では区分開閉器投入時にDSより下流の高圧母線や機器の一部まで充電されるため、突入電流、地絡時の影響範囲、保護範囲を事前に確認する必要がある。<br><br>

<strong>ピラージスコンの場合</strong><br>
ピラー内でのジスコン操作は、構造や充電部との位置関係によってモールドジスコンより作業条件が厳しく感じる設備がある。<br>
このため、ピラージスコン投入時はキュービクル側DSを開放しておき、まずピラー側の投入を完了してから次工程へ進む考え方を優先したい。<br>
その後のDS投入が充電状態での操作になる場合は、高圧ゴム手袋など所定の保護具を使用し、設備が充電状態での操作を想定した構造か、操作棒・インターロック・離隔・作業手順が適切かを確認する。<br><br>

<strong>「どちらの順序が常に正しい」とは決めない。</strong><br>
古いDSの操作不良リスクと、区分開閉器投入時に下流を充電するリスクの両方を比較し、単線結線図、メーカー資料、電力会社との取決め、現場の作業手順・リスクアセスメントに従って決める。<br>
充電部に近接した状態で、硬いDSを力任せに何度も操作するような作業は避ける。<br>

<h2>モールドジスコン投入直後は二次側電圧をすぐ確認する</h2>
モールドジスコンを投入した瞬間に、需要家側ケーブルなどで地絡が発生すると、配電側の地絡保護が動作して送電が停止することがある。<br>
そのため、MDSを投入した直後は需要家側に電圧が正常に来ているかをすぐ確認する。<br><br>

<strong>投入直後に二次側で電圧が確認できない場合は、そのまま復電作業を進めず、異常を疑ってMDSを開放する。</strong><br>
地絡によって配電側からの送電が停止しているにもかかわらず、それに気づかずDS・LBS・VCBなどの復電操作を進めると、配電側から再送電された瞬間に再び地絡する可能性がある。<br>
一度目の地絡で停電し、再送電で二度目の地絡事故を起こすと、波及事故へ発展するおそれがある。<br><br>

このため、可能であればモールドジスコンの投入作業は2人1組で行い、<br>
・1人：MDSの投入操作<br>
・1人：需要家側の電圧確認・検電準備<br>
のように役割を分けると、投入直後の異常を早く把握しやすい。<br><br>

ただし、実際の投入・開放手順や検電位置、再送電時の対応は、設備構成や電力会社との取決め、現場の作業手順に従う。<br>
異常時は原因を確認せずに再投入を繰り返さない。<br>

<h2>モールドジスコン、VCB、GRの組み合わせによる波及事故</h2>
モールドジスコンから構内キュービクルVCBの間のケーブルで地絡が起きた場合、構内キュービクルVCBから見て電源側（モールドジスコン側）には、電力側の保護継電器しかないので、電力側の地絡継電器が動作して、遮断器が動作し、送電が停止される。<br><br>

もし最閉路されても、ケーブルでの地絡の原因は解消していないので、再度地絡を発生し、保護継電器動作、遮断器が遮断され、波及事故となる。<br><br>

構内地絡事故は、高圧ケーブルの経年劣化によるものがほとんどらしいので、構内ケーブル地絡事故から波及事故への被害拡大を防止するためにも、UGS（地中線用負荷開閉器）への交換が推奨される。


<h2>高圧キャビネットの種類</h2>

二回路形（A1形）<br>
受電した高圧系統を、そのまま送電するスイッチ機能のみを持つタイプ<br><br>

三回路形<br>
隣接需要家に高圧電路を渡ることが可能なタイプ<br><br>

高圧受電では隣接需要家への渡りが原則であり、通常は三回路形が選定される。<br><br>

高圧キャビネット内部には、UGSやモールドジスコンなど需要家が必要とする断路器を設置し、電力会社との責任分界点は、断路器の一次側となる。<br>

