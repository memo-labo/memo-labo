ZPDの裏にはボルト穴が２つある<br>
<img src="images/zpd.jpg" style="max-width:500px;"><br><br>

ZPDの取り付け位置<br>
取扱説明書によれば、VCB（52R）の２次側。<br>
ただ場所によってはDSの二次側、VCBの１次側にある場合も。<br>
52F1、52F2のようにフィーダーがある場合、ZPDは52Rの２次側と52F1の１次側の間。<br>

<h2>零相電圧変換器</h2>
<img src="images/zpd1.jpg" style="max-width:300px;"><br>
継電器に適した零相電圧を得るための変換器。<br>
変圧器の1次側と2次側の間は絶縁されているので安全。<br>
零相電圧変換器のY1,Y2と、地絡方向継電器のY1,Y2を接続する。<br>
配線図で確認すると、E端子はA種接地、Y2はD種接地がされている。<br><br>

DGRやOVGRの試験をする際、Vo測定においてT端子とE端子に線を接続する。<br>
この時、DGRやOVGRの位置と、零相電圧変換器の位置が遠い場所に設置されている場合がある。<br>
その場合、長めの延長線が１本あれば、延長線をT端子にとりつけ、アース線はキュービクルのA種接地に接続。<br>
こうすればわざわざ２本の線を遠くまで伸ばす必要はなくなる。<br>

<h2>周波数</h2>
短絡する端子を変更すると50Hzと60Hzの切替が可能。<br>
竣工検査や増設の場合、この部分もチェックする必要がある。<br>
50Hz用の短絡を設定した場合、T端子直下のコンデンサの下にコンデンサが並列で１つ追加となる。<br><br>

コンデンサを直列に接続すると電圧は静電容量に比例して分圧。<br>
コンデンサを並列に接続するとコンデンサの和が合成静電容量となる。<br>
並列部を直列に変換した時のコンデンサ容量は増える。<br>
するとリアクトルにかかる部分の電圧は上昇する。<br><br>

OVGRやDGRの零相電圧Voの最小動作値が許容値の範囲外だった場合<br>
この場合、ポータブル電源や試験機の周波数の設定を疑う。<br>
継電器は50Hzなのに60Hz設定で試験すると値がずれてしまい許容範囲を超える。<br>

<h2>ZPDの配線</h2>
電磁波ノイズなどの影響を受けるため、２芯シールド線（0.75m㎡ 以上）を使用する。<br>
また、電線の長さは極力短くなるようにする。<br><br>

使用するケーブルは「CVV-S ビニル絶縁ビニルシースケーブル」<br>
これは静電遮へいの必要がある制御用回路に使用される。<br>
ケーブルのノイズ対策をするため、銅テープの接地は、片端で行う。<br>
