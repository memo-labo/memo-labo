<h2>ZPD（零相電圧検出装置）とは</h2>
ZPDは、<a href="v0.php">零相電圧V0</a>を検出してDGRやOVGRへ信号を送る装置。メーカーや機種によってZVT・ZPCなどの名称が使われる場合もある。<br><br>

<img src="images/20261010-3.jpg" alt="ZPD 零相電圧検出装置"><br>

<h2>ZPDの基本構成</h2>
ZPDは大きく、各相の対地電圧を取り込む<strong>零相電圧検出用コンデンサ</strong>と、継電器で扱える電圧へ変換する<strong>零相電圧変換器</strong>で構成される。<br>
検出した信号はY1-Y2などの端子からDGR・OVGRへ送る。<br>

<h3>零相電圧検出用コンデンサ</h3>
各相に接続するコンデンサを3相分持ち、対地電圧の不平衡から零相電圧成分を取り出す。がいし形でキュービクル内へ設置するタイプもある。<br>
