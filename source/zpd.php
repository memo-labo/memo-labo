<h2>テスト端子Tと静電容量</h2>
ZPDボックスのテスト端子Tの先にあるコンデンサ「C1」の静電容量は750pF。<br>
高圧のエポキシ樹脂「C1」は１個250pFなので、一次側三相一括にした場合と等価。<br>

<h2>エポキシ樹脂がいし部分にあるT端子</h2>
テスト端子がボックスタイプではなくエポキシ樹脂がいし部分にあるタイプもある。<br>
メーカーにもよるが、V0整定値が5%=190Vではなく、5%=190V × 3 = 570Vの場合もある。<br>
ただし、T端子がエポキシ樹脂がいし部分にあっても、V0整定値が5%=190Vの場合もある。<br>
この場合、T端子に印加できる電圧の上限が決められているので注意が必要。<br><br>

さらにDGR試験にて最小動作電流試験や動作時間試験を行う際、V0印加電圧を整定値の150%に整定する事が多いが、メーカーによってはV0印加電圧を整定値の130%としている製品もある。


