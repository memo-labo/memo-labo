<h2>零相電圧検出用コンデンサ（がいし型）</h2>
零相電圧を得るため、コンデンサで各相ごとに１個ずつ設置できるように、３個に分割したもの。<br>
キュービクル内のアングルのポスト碍子と同じように使用できて省スペース。<br>
