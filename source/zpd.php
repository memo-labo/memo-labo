<h2>ZPDの仕組みと試験時の電圧印加方法</h2>

<img src="images/v0/7.png" style="max-width:400px;"><br>
C1 = ZPDのT端子（テスト端子）のコンデンサの容量<br>
C2 = ZPDの検出用コンデンサの容量<br>
C3 = U、V、Wの各コンデンサの容量<br><br>

零相電圧は、U・V・W各相のコンデンサC3と、検出用コンデンサC2で分圧される。<br>
検出用コンデンサC3にかかる電圧を、さらに変圧器で小さくしたものが「Y1-Y2」間に電圧として発生する。<br>
Y1Y2で継電器用に降圧すると同時に、この変圧器で１次側と２次側が絶縁される。<br>

