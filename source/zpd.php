<h2>零相電圧検出装置 ZPDとは？</h2>
ZPDは、<a href="v0.php">零相電圧V0</a>を検出するための装置。<br>
Zero-Phase-sequence Potential Deviceの略で、メーカーによってZVT・ZPCなどの名称も使われる。<br><br>

<img src="images/20261010-3.jpg" alt="ZPD 零相電圧検出装置"><br>

<h2>ZPDの構成</h2>
ZPDは、各相に接続する零相電圧検出用コンデンサと、継電器へ信号を送る零相電圧変換器で構成される。<br>
DGRやOVGRへ、検出した零相電圧信号をY1-Y2から出力する。<br>

<h2>零相電圧検出用コンデンサ</h2>
各相に1個ずつ接続するコンデンサを3個に分けた構成。<br>
がいし型にしてキュービクル内へ設置するタイプもある。<br>
<img src="images/v0/2.jpg" style="max-width:500px;" alt="零相電圧検出用コンデンサ"><br><br>

ZPD裏面には取付用のボルト穴がある。<br>
<img src="images/zpd.jpg" style="max-width:500px;" alt="ZPD 裏面"><br>

<h2>零相電圧変換器</h2>
<img src="images/zpd1.jpg" style="max-width:300px;" alt="零相電圧変換器"><br>
継電器で扱える電圧へ変換し、一次側と二次側を絶縁する。<br>
Y1-Y2をDGRやOVGRのY1-Y2へ接続する。<br>
配線例では、E端子をA種接地、Y2をD種接地としている構成がある。<br>

<h2>ZPDの取り付け位置</h2>
取扱説明書では、受電VCB二次側に設置する構成がある。<br>
実設備ではDS二次側・VCB一次側に設置されている場合もある。<br>
フィーダーVCBがある場合は、受電VCB二次側とフィーダーVCB一次側の間に設置される例がある。<br><br>

<img src="images/zpd1.svg" style="max-width:800px;" alt="ZPD 取り付け位置"><br>

<h2>ZPDの配線</h2>
Y1-Y2信号線には、ノイズ対策として2芯シールド線を使用する。<br>
電線長はできるだけ短くする。<br>
CVV-Sなどのシールド付き制御ケーブルを使用し、シールドは片端接地とする構成がある。<br>
⇒<a href="noise.php">ケーブルのノイズ対策・静電しゃへい・シールドとは？</a><br>

<h2>周波数設定</h2>
ZPDには、端子短絡の変更で50Hz／60Hzを切り替えるタイプがある。<br>
竣工検査・増設・継電器試験では、試験機とZPDの周波数設定が一致しているか確認する。<br>
周波数設定が合っていないと、最小動作値が許容範囲からずれる場合がある。<br>

<h2>ZPDの仕組み</h2>
<img src="images/v0/7.png" style="max-width:400px;" alt="ZPD コンデンサ分圧"><br>

C1 = テスト端子T側のコンデンサ<br>
C2 = 検出用コンデンサ<br>
C3 = U・V・W各相のコンデンサ<br><br>

U・V・W各相のコンデンサと検出用コンデンサで零相電圧を分圧し、さらに変圧器で継電器用の低い電圧へ変換してY1-Y2へ出力する。<br>

<h2>コンデンサ分圧の計算例</h2>
⇒<a href="c.php">コンデンサの直列と並列について</a><br><br>

C3 1個 = 250pF<br>
3個並列なので C3合計 = 750pF<br>
C2 = 0.15μF = 150000pF<br><br>

C3合計 : C2 = 1 : 200<br>
したがって V0 : V2 = 200 : 1<br><br>

完全一線地絡時のV0を3810Vとすると、<br>
3810 : V2 = 200 : 1<br>
V2 = 19.05V<br><br>

変圧比20:1なら、Y1-Y2間は約0.95Vとなる。<br>

<h2>試験時の電圧印加方法</h2>
<strong>T-E端子へ印加する方法</strong><br>
ZPDのT端子とE端子へ試験電圧を印加する。<br><br>

<strong>高圧側三相一括へ印加する方法</strong><br>
T端子がない場合、U・V・Wを一括した側とE端子間へ印加する方法がある。<br>
高圧回路へ電圧を印加するため、感電・回り込みに十分注意する。<br>

<h2>試験配線を長く引く場合</h2>
ZPDとDGR・OVGRが離れている場合、T端子側だけ延長線を使い、E側はキュービクルの接地端子を利用する方法がある。<br>
ただし、接地系統と試験回路が正しいことを確認してから行う。<br>

<h2>テスト端子Tと静電容量</h2>
ボックスタイプのテスト端子T側にあるC1が750pFの場合、一次側3相を一括した状態と等価になるよう構成されている。<br>

<h2>エポキシがいし側にT端子があるタイプ</h2>
テスト端子がボックスではなく、エポキシがいし部にあるタイプもある。<br>
メーカー・機種によって、V0整定5%に対応する試験電圧が190V系・570V系など異なる。<br>
T端子へ印加できる上限電圧も機種ごとに異なるため、試験前に取扱説明書を確認する。<br><br>

DGR試験時のV0印加倍率も、150%ではなく130%を指定する機種がある。<br>

