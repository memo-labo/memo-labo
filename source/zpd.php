<h3>零相電圧変換器</h3>
<img src="images/zpd1.jpg" style="max-width:300px;" alt="ZPD 零相電圧変換器"><br>
検出した電圧を継電器で扱える低い電圧へ変換し、一次側と二次側を絶縁する。Y1-Y2をDGRやOVGRへ接続する構成が多い。接地端子の扱いはメーカー結線図を優先する。<br>

<h2>ZPDの取り付け位置</h2>
ZPDの設置位置は受電設備の構成によって異なる。受電VCB二次側に置く構成もあれば、DS二次側・VCB一次側などに設置されている例もある。<br>
どこに設置されているかで、どの範囲の地絡を検出するかが変わるため、単線結線図で保護範囲を確認する。<br><br>

<img src="images/zpd1.svg" style="max-width:800px;" alt="ZPDの取り付け位置と保護範囲"><br>

<h2>ZPDの配線</h2>
Y1-Y2などの信号線は微小電圧を扱うため、ノイズの影響を受けにくいようシールド付き制御ケーブルを使う構成がある。<br>
シールドの接地方法や接地点は機種・設備によって異なるため、自己判断で多点接地にしない。<br>
⇒<a href="noise.php">ケーブルのノイズ対策・シールド</a><br>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：試験で値がずれるときは周波数設定も確認</span>
ZPDには50Hz／60Hzを端子短絡などで切り替えるタイプがある。試験機とZPDの設定周波数が一致していないと、最小動作値や試験値が許容範囲から外れる場合がある。
</div>

<h2>ZPDの仕組み</h2>
<img src="images/v0/7.png" style="max-width:400px;" alt="ZPD コンデンサ分圧の仕組み"><br>

U・V・W各相の検出用コンデンサと内部コンデンサで零相電圧を分圧し、さらに変圧器などで継電器用の低い電圧へ変換して出力する。<br>

<h2>コンデンサ分圧の計算例</h2>
例として、各相250pFのコンデンサが3個あり、合計750pF、内部側が0.15μF（150000pF）なら、比は概ね1:200。<br><br>

完全一線地絡時のV0を3810Vとすると、分圧後は約19V。さらに変圧比20:1なら、継電器側のY1-Y2は約0.95Vになる計算。<br>
実際の変換比や出力値は機種ごとに異なるため、試験ではメーカー資料を基準にする。<br>
⇒<a href="v0.php">V0（零相電圧）と3810Vの考え方</a><br>

<h2>ZPDの試験方法</h2>
代表的には、ZPDのテスト端子を使う方法と、高圧側三相を一括して印加する方法がある。<br>

<h3>T-E端子へ印加する方法</h3>
テスト端子TとEの間へ所定の試験電圧を印加し、ZPDとDGR・OVGRの動作を確認する。必要電圧は機種によって異なる。<br>

<h3>高圧側三相一括へ印加する方法</h3>
T端子がない構成では、U・V・W側を一括して対地へ試験電圧を印加する方法がある。高圧回路側を扱うため、対象回路の切り分けと回り込み確認が重要。<br>

<div class="article-warning">
<span class="article-warning-title">⚠ 注意：試験電圧はZPDごとに違う</span>
同じ「V0 5%」の試験でも、190V系・570V系・19V系など機種によって試験端子へ加える電圧が異なる。試験前に形式、T端子の位置、周波数、メーカー試験方法を確認する。別機種の値をそのまま流用しない。
</div>

<h2>試験配線を長く引く場合</h2>
ZPDと継電器が離れている現場では延長線を使う場合があるが、接地側をどこから取るかによって試験回路が変わる。接地系統と試験回路を図面で確認し、不要な回り込みがないことを確認してから試験する。<br>

<h2>テスト端子Tの種類</h2>
テスト端子Tが変換器ボックス側にあるタイプと、エポキシがいし側にあるタイプがある。内部静電容量や試験倍率も異なるため、外観が似ていても同じ扱いと決めつけない。<br>

<h2>DGR・OVGRとの関係</h2>
DGRはZPDから得たV0とZCTから得たI0の位相関係を見て地絡方向を判定する。OVGRは主にV0の大きさを監視する。<br>
