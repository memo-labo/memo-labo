マイクロ µF 10^-6<br>
ナノ nF 10^-9<br>
ピコ pF 10^-12<br><br>

C3_All = 750pF = 750 * 10^-12<br>
C2 = 0.15μF = 0.15 * 10^-6 = 150000 * 10^-12<br><br>

C3_All:C2 = 1:200<br>
