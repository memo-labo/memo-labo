<h2>試験時の配線方法</h2>
１．ZPDのT端子とE端子に電圧を印加する。<br>
２．ZPDにT端子がない場合、U・V・W（高圧母線１次側）をすべて短絡した側と、ZPDのE端子に電圧を印加する。<br><br>

１の場合、本来の回路には電圧が印加されていないので、正確な測定とは言えない。<br>
２の場合、正確な測定ではあるが、高圧回路に電圧を印加するので感電する恐れがあり、危険。<br>

