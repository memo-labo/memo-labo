<h2>絶縁耐力試験（耐電圧試験）とは</h2>
高圧ケーブルや受電設備機器へ規定された交流または直流の試験電圧を印加し、所定時間、絶縁が耐えられることを確認する試験。<br><br>

試験電圧や試験方法には設備・機器ごとの条件や例外があるため、電気設備技術基準の解釈、メーカー仕様、試験対象の取扱説明書を確認する。<br>

<h2>試験前に充電電流を計算する</h2>
ケーブルなど静電容量を持つ被試験物へ交流電圧を印加すると、絶縁が正常でも充電電流が流れる。<br>
試験前に静電容量Cを把握し、想定される充電電流と必要な試験器容量を計算しておく。<br><br>

交流回路の充電電流は、基本的に、<br>
<strong>I = 2πfCV</strong><br>
で考える。<br><br>

