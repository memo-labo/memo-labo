<h2>試験回路を作るときの基本確認</h2>
主回路を一括して対地耐圧する場合は、試験範囲に応じて三相を同電位になるよう接続して試験する方法がある。<br>
ただし、VT・LA・ZPD・SOG制御回路・電子機器など、試験電圧をそのまま印加してはいけない機器が含まれる場合がある。<br><br>

試験前に単線結線図を確認し、<br>
・どこからどこまでが被試験範囲か<br>
・開閉器の投入／開放状態<br>
・切り離す機器<br>
・接地を外す箇所／残す箇所<br>
・試験後に復旧する配線<br>
をチェックする。<br>

<h2>機器単体で充電電流が小さい場合</h2>
PAS、UGS、VCBなど機器単体では静電容量が小さく、試験器の電流計で変化が見えにくい場合がある。<br>
その場合は試験器の適切な電流レンジを選び、必要に応じて微小電流を測定できる計器を補助的に使用する。<br><br>

想定した電流が流れない場合は、そのまま昇圧を続けず、試験回路、接地、短絡、切り離し状態を確認する。<br>

<h2>充電電流が大きい場合は耐圧用リアクトルを使う</h2>
ケーブルが長いなど充電電流が大きい場合、<a href="re.php">耐電圧試験用リアクトル</a>を使用し、進みの充電電流を遅れ電流で補償する方法がある。<br>
これにより試験用変圧器や発電機の負担を小さくできる。<br>

<h2>充電電流とリアクトル電流の考え方</h2>
V2：高圧出力電圧<br>
I2：試験用変圧器の二次電流<br>
I3：充電電流（進み）<br>
I4：リアクトル電流（遅れ）<br>
<img src="images/20211215-4.png" style="max-width:200px;" alt="耐圧試験の充電電流とリアクトル電流"><br><br>

例1<br>
充電電流300mA - リアクトル電流200mA = 100mA<br><br>

例2<br>
充電電流380mA - リアクトル電流200mA × 2 = -20mA<br><br>

電流計は通常、進み・遅れの符号ではなく電流の大きさを表示するため、リアクトルの投入本数と理論値を把握しておく。<br>

<h2>試験中の「ジジジ」という放電音</h2>
耐圧試験中に音が発生した場合、端子部などのコロナ放電、接続部の局部放電、絶縁物内部の部分放電などが考えられる。<br><br>

音が大きくなる、異臭・発光・煙・異常な電流増加などを伴う場合は、いったん試験を停止し、十分に放電・接地してから接続状態や絶縁物を確認する。<br><br>

