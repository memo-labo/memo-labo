<h2>絶縁耐力試験（耐電圧試験）</h2>

高圧ケーブルや受電設備機器に、規定された直流電圧もしくは交流電圧を印加。<br>
そのとき絶縁破壊を起こすかどうかで絶縁強度を測定する試験。<br><br>

印加電圧と印加時間<br>
最大使用電圧が7,000V以下の場合<br>
最大使用電圧 × 1.5倍の電圧を10分間、電圧を印加する。<br>
※1.5は安全係数らしい<br><br>

【例】公称配電電圧が6600V系統の場合<br>
最大使用電圧（6.9kV） ✕ 1.5 = 10350V<br><br>

最大使用電圧<br>
公称電圧6.6kVの最高電圧（最大使用電圧）= 6.6kV ✕（1.15 ÷ 1.1）= 6.9kV<br>
接続される機器の配電線路の変圧器の送り出し側の最高タップ電圧のこと<br>
※最大使用電圧が500V未満の場合、試験電圧は500V<br>

<h2>充電電流の計算</h2>
絶縁耐力試験を行う前に、被試験物（高圧ケーブル、コンデンサ、変圧器など）は、静電容量（C）を測定する。<br>
PAS、UGS、DS、VCB、LBS、PC等、すべて投入状態を確認した上で、対地静電容量を測定する。<br>
その際、３相すべてを導電性のある銅線等で短絡させておく。<br><br>

静電容量の測定は、静電容量測定機能を持つテスター等を使用する。<br>
静電容量値から<a href="vtest.php">耐圧試験時に被試験物に流れる電流を計算にて算出</a>する。<br><br>

充電電流の値が大きい場合、<a href="re.php">充電電流を打ち消すために耐電圧試験用リアクトルを使用</a>する。<br>
すると、耐圧用変圧器、試験機、試験用発電機への電力負担を減らすことができる。<br>

