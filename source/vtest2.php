<h2>試験中の放電音</h2>
耐圧試験中、ジジジと音がなることがある。<br>
これは部分放電、コロナ放電、絶縁物のボイド（空隙）による内部放電の可能性あり。<br>
高圧用VT、モールド変圧器、モールド型リアクトル付近からよく音が鳴る。<br><br>

モールド樹脂内部には微小な空隙（ボイド）が存在する場合があり、高電圧印加時にその部分で局所的な放電（部分放電）が発生して「ジジジ」という音として聞こえることがある。また、端子部や導体の角部では電界集中によりコロナ放電が発生することもある。<br><br>

放電音の増大、異臭、発光などを伴う場合、接続不良の可能性もあるので一旦中止し、放電し、配線等の接続や位置を確認する。<br><br>

