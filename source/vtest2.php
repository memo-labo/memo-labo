	<li>P1P2以外の制御ケーブルはすべて一括で短絡して接地をする。
</ul>

<h2>柱上VCTだった場合の対処法</h2>
VCTがキュービクル内ではなく柱上だった場合、耐圧試験時にはVCTは接続されていない。<br>
PAS２次側リード線と高圧引き込みケーブルは柱上で断絶された状態となっている。<br>
この場合、耐圧試験前に柱に登り、PAS２次側と引き込みケーブルを短絡させなければならない。<br>
そうならないために事前に工事会社に連絡をとり、耐圧試験前に短絡をお願いしておいたほうが良い。<br><br>

VCTをキュービクル内ではなく柱上など外部に設置する方式は、コンパクトタイプの省スペースキュービクルで採用されることが多い。<br>
小規模で敷地が狭く、屋外キュービクルをできるだけコンパクトにしたい場合に適している。コンビニなどの小規模店舗でよく見られる。<br>

<h2>継電器DGRの絶縁耐力試験</h2>
<a href="zpd.php">ZPD（零相電圧検出器）</a>からのY1Y2線がDGRに取り付いている状態で主回路の絶縁耐力試験を行う場合。<br>
この場合、継電器に想定以上の零相電圧が印可されて継電器が破損する可能性がある。<br>
DGR継電器側のY1とY2端子の結線を外し、ZPDと継電器を分離した方が安全。<br>

<h2>ステンレス製のSOG制御装置ボックスの接地</h2>
開閉器の接地方式が一点接地の場合、ステンレス製のSOG制御装置ボックスは、5.5㎟以上の接地線でＤ種接地。<br>
または、PAS筐体のA種接地と共用接地でも可。<br>


<h2>高圧CVTケーブルの金属遮蔽層がアースされていなかった場合</h2>
【予想】<br>
CVTケーブルの耐圧試験時にケーブルシースアース（金属遮蔽層）が接地されていなかった。<br>
ケーブル銅線部分だけに電圧が印加され、ケーブル絶縁層の絶縁性能を測定していることにならない。<br>
なので耐圧試験中も静電容量分の充電電流が一切流れない。<br>


<h2>耐電圧試験中に試験機がストップ！「抜ける」とは？</h2>
１０分間の絶縁耐力試験中に、急に試験機がストップしてしまう現象。<br>
高圧CVケーブルなどに傷があり、被試験物に印加された高電圧が絶縁不良箇所から放電して大電流が流れ、試験機の保護回路が働き、試験機がストップ。

