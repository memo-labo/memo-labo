<h2>柱上VCTがある場合</h2>
VCTがキュービクル内ではなく柱上に設置される設備では、工事時の切り離し箇所によってPAS二次側リード線と引込ケーブルが分離された状態になる場合がある。<br><br>

耐圧試験範囲を事前に工事会社と共有し、必要な短絡・接続処置を停電工事の段階で行えるよう打合せしておく。<br>

<h2>DGR・ZPDを含む回路の注意</h2>
ZPDからDGRへ接続される零相電圧回路がある場合、主回路の耐圧試験によって継電器側へ過大な信号が加わらないようにする。<br>
Y1・Y2などの端子処置は機種ごとに異なるため、ZPD・DGRメーカーの試験要領を確認して必要な切り離しを行う。<br><br>

