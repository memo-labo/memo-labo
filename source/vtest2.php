<h2>VT内蔵PAS・UGSなどを含む試験の注意</h2>
VT内蔵形の開閉器では、内蔵VTの一次回路へ不適切な試験電圧が加わると過励磁・焼損につながる場合がある。<br>
特に一相だけへ試験電圧が加わるような誤った接続を避け、メーカーが指定する耐圧試験方法を確認する。<br><br>

「三相をどうまとめるか」「P1・P2をどう処置するか」は製品形式によって異なるため、型式を確認して取扱説明書に従う。<br>

<h2>LA内蔵PASの注意</h2>
LA（避雷器）内蔵形では、LAの動作開始電圧や耐電圧条件が試験方法を制限することがある。<br>
AC・DCそれぞれの許容試験電圧は製品によって異なるため、「LA内蔵PASなら一律○kV」とせずメーカー資料を確認する。<br>

<h2>SOG制御装置の耐圧試験前処置</h2>
PAS内蔵VTやSOG制御装置がある場合、試験電圧が制御装置側へ回り込まないよう事前処置が必要になる。<br><br>

代表的にはP1・P2や制御ケーブルの切り離し・短絡・接地処置を行う例があるが、具体的な方法はSOG・PASの形式ごとに異なる。<br>
必ずメーカーの耐圧試験要領を確認する。<br><br>

