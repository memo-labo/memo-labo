<h2>6.6kV受電設備の絶縁耐力試験はなぜAC10.35kV？</h2>
6.6kV系統では、公称電圧6.6kVに対する最高電圧（最大使用電圧）を6.9kVとして扱う。<br>
最大使用電圧7,000V以下の高圧電路で、最大使用電圧の1.5倍を試験電圧とする条件の場合、<br><br>

6.9kV × 1.5 = <strong>10.35kV</strong><br><br>

となる。<br>
試験時間は適用する法令・規格・設備条件に従う。高圧受電設備で商用周波耐電圧試験を10分間行う例が代表的。<br><br>

