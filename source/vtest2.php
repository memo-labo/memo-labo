<h2>高圧CVTケーブルの金属遮へい層</h2>
高圧ケーブルの金属遮へい層は、通常、所定の方法で接地される。<br>
耐圧試験時に遮へい層の接地状態が想定と異なると、試験電界や充電電流も変わり、正しい試験条件にならない可能性がある。<br><br>

「充電電流がほとんど流れない」など想定値と大きく違う場合は、ケーブルの接続・遮へい層接地・試験範囲を確認する。<br>

<h2>耐圧試験中に試験器が停止する「抜ける」現象</h2>
10分間の試験中などに急に試験器が停止した場合、被試験物の絶縁不良、放電、試験回路の異常などで過電流保護が動作した可能性がある。<br><br>

高圧ケーブルの損傷部などで放電すると電流が急増し、試験器の保護回路が動作することがある。<br>
再投入を繰り返さず、十分に放電・接地してから絶縁状態と試験回路を確認する。<br>

<h2>耐圧試験前チェック</h2>
・試験電圧と試験時間の根拠を確認<br>
・静電容量から充電電流を予測<br>
・必要な試験器容量を確認<br>
・VT、LA、ZPD、SOG、電子機器の切り離し要否を確認<br>
・三相の接続状態と接地を確認<br>
・試験終了後の放電・接地手順を確認<br>
・切り離した配線の復旧チェックを残す<br>

