<h2>VT（計器用変圧器）の焼損事故</h2>

<p><strong>VTが焼損した場合、二次側短絡、巻線内部故障、絶縁劣化、サージなど複数の原因が考えられます。</strong>焼損したVTだけを見て原因を断定せず、一次側・二次側・周辺機器を含めて調査します。</p>

<h2>事故例</h2>

<p>高圧受電設備で停電が発生し、区分開閉器の地絡保護が動作。設備を確認するとVTのモールド部に焼損跡が見つかった、というケースです。</p>

<img src="images/vt_jiko1.jpg" style="max-width:500px;" alt="VT焼損事故の例"><br>

<h2>考えられる原因</h2>

<ul>
  <li><strong>VT二次側短絡</strong>：二次回路の短絡により過大電流が流れた</li>
  <li><strong>巻線内部故障</strong>：層間短絡・絶縁劣化などで内部発熱した</li>
  <li><strong>一次側絶縁破壊</strong>：端子部・モールド部などで地絡や相間短絡が発生した</li>
  <li><strong>雷・開閉サージ</strong>：異常電圧が絶縁へストレスを与えた</li>
  <li><strong>接続不良・局部過熱</strong>：端子部の緩みなどが発熱・絶縁劣化へつながった</li>
</ul>

<p>実際には複数要因が重なる場合があります。</p>

<h2>事故後に見るポイント</h2>

<ul>
  <li>VT本体のひび、膨れ、炭化、溶損</li>
  <li>端子・KIP線・母線のアーク痕</li>
  <li>一次側ヒューズの状態</li>
  <li>二次側ヒューズ・MCCB・配線の短絡痕</li>
  <li>VCB、DS、CTなど周辺機器の煤・変色</li>
  <li>保護継電器の動作表示・事故記録</li>
  <li>落雷・系統事故など事故発生時の外部状況</li>
</ul>

<h2>異音・異臭・煙がある場合</h2>

<p>異音、焦げ臭、煙、炭化、発光などがある場合は、VTだけでなく周辺の高圧機器にも異常が及んでいる可能性があります。</p>

<p><strong>原因確認前に再送電しないことが重要です。</strong>区分開閉器や遮断器を再投入して事故点へ再度電圧を加えると、故障が拡大するおそれがあります。</p>

<h2>復電前に必要な判断</h2>

<p>焼損VTを回路から切り離して仮復旧できる設備もありますが、<strong>高圧配線の切離し方法を現場判断で即席施工しない</strong>ようにします。</p>

<p>復電可否は次を確認して判断します。</p>

<ul>
  <li>故障点がVTに限定されていること</li>
  <li>主回路・周辺機器の絶縁が健全であること</li>
  <li>VTを外した状態で失われる計測・保護・制御機能</li>
  <li>メーカー・工事会社が指定する安全な切離し方法</li>
  <li>保安規程上、仮復旧で運転可能か</li>
</ul>

<p>VTがUVR、GR、計器、制御電源などへ使われている場合、VTを切り離すだけで本来の保護機能が失われることがあります。</p>

<h2>VT二次短絡が危険な理由</h2>

<p>VTは電圧変成器なので、二次側を短絡すると大きな電流が流れ、巻線過熱・ヒューズ溶断・焼損につながるおそれがあります。</p>

