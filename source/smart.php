内部に過負荷ブレーカー機能が搭載されている。<br>
従来の分電盤に設置されていた、契約アンペア数が書かれたアンペアブレーカーは、不要となる。<br>
一般的には、スマートメーター導入時に撤去される（電力会社により対応が異なる）<br>
スマートメーターがついているのに、アンペアブレーカーも利用している場合もある。<br>

<h2>スマートメーターの見方・読み方</h2>

スマートメーターかどうか、確認する方法<br>
・円盤が回るタイプ⇒従来の古いタイプ<br>
・液晶盤で文字が表示されている⇒スマートメーター<br><br>

