<h2>スマートメーターのメリット</h2>
<ul>
<li>通信機能により遠隔での検針ができるので、訪問による検針が不要。防犯面でも安心。
<li>今まではアンペア数の変更をすると、分電盤内のアンペアブレーカー（リミッター）を交換する必要があったが、スマートメーターによって遠隔操作でアンペア数を変更できるようになった。
<li>スマートメーターには過負荷ブレーカー機能が備わっており、電気を一度に多く使い過ぎると、スマートメーター内のブレーカーを開放し、約10秒で自動復旧する。
<li>電気の「見える化」で、契約している電力会社サイトから、電気の使用量をグラフなどで確認できる。
</ul>

<h2>スマートメーターのデメリット</h2>
過負荷で停電し、10秒後に自動復旧するので、この機能を知らない人は急に電気が止まった思い、機器の故障かと勘違いをしてしまう。

<h2>スマートメーターの交換時期</h2>
スマートメーターは一般送配電事業者（地域の電力会社）の所有物。<br>
一般送配電事業者がメーターの耐用年数（10年）に応じて交換する。<br>
スマートメーターの機器代や設置工事費用は無料。<br>


