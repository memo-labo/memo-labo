２種類の画面が約10秒間隔で交互に切り替わる。<br>
矢印なし：お客様の電気使用量を表示（ここで電気料金を算定）<br>
矢印あり：再生可能エネルギー発電設備を設置されているお客さまからの、電力会社の購入電力量<br>
