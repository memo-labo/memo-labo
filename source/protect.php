<h2>絶縁用保護具・防具の定期自主検査とは</h2>
絶縁用保護具等は、使用前点検だけでなく、定期的に絶縁性能を確認する必要がある。<br><br>

安衛則351条では、絶縁用保護具等について<strong>6月以内ごとに1回</strong>、定期に絶縁性能の自主検査を行うことが定められている。<br>
また、安衛則352条では、使用を開始する前の点検について定められている。<br><br>

