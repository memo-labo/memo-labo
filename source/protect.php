<h2>絶縁用保護具の使用前点検</h2>
安衛則 第三百五十二条。<br>
事業者は、対象となる電気機械器具等を使用するとき、その日の使用を開始する前に所定の点検を行い、異常を認めた場合は補修または取り換えを行う。<br>
