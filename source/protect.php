・乾燥状態<br>

<h2>オゾン亀裂（クラック）とは？</h2>
オゾンや紫外線などの影響により、ゴム表面にひび割れが発生する劣化現象。<br>
オゾン劣化とも呼ばれる。<br>
ゴム製の絶縁用保護具では、表面の細かな亀裂や硬化なども使用前点検で確認する。<br>

<h2>保護具試験中の独特な匂いとオゾン</h2>
高電圧試験では、電極・金具・水面付近など電界が集中する場所でコロナ放電が発生することがある。<br>
空気中の酸素が放電の影響を受けるとオゾン（O3）が生成され、独特な匂いを感じる場合がある。<br><br>

オゾンは酸化力が強く、高濃度では人体にも有害なので、試験場所では換気にも注意する。<br>

<h2>耐電圧試験中の「ジジジ」という音</h2>
保護具の耐電圧試験中に「ジジジ」という音が発生する場合がある。<br><br>

音が発生しやすい箇所の例<br>
①昇圧トランスのクリップと水槽など、金属導体の接続部分<br>
②針金・電極などと水面の接触箇所<br><br>

高電界部で発生する<a href="houden2.php">コロナ放電</a>などが原因として考えられる。<br>
<img src="images/protect2.png" style="max-width:700px;" alt="耐電圧試験中のコロナ放電"><br><br>

VTや乾式リアクトルなどの耐圧試験でも、電極形状や接続状態によって放電音が聞こえる場合がある。<br>
音だけで良否を判断せず、試験電圧・漏れ電流・放電箇所・絶縁状態を確認する。<br>

<h2>点検・試験時の確認ポイント</h2>
・定期自主検査の周期を確認する<br>
・試験対象に合った試験電圧・方法を確認する<br>
・使用前にひび、破れ、硬化、湿りなどを確認する<br>
・耐電圧試験中に異常な放電や局部的な発熱がないか確認する<br>
・試験記録を残す<br>

