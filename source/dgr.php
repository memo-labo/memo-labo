<h2>DGRの種類</h2>
DGRは大きく、電圧引き外しタイプと電流引き外しタイプに分けて考えると分かりやすい。<br>

<h3>電圧引き外しDGR</h3>
例：三菱 MDG-A1V<br>
<img src="images/dgr1.png" style="max-width:500px;" alt="三菱 MDG-A1V"><br>

<ul>
<li>零相電流I0をZCTで検出し、Z1-Z2へ入力</li>
<li>零相電圧V0をZPDで検出し、Y1-Y2へ入力</li>
<li>本体制御電源はVT二次側などからP1-P2へ入力</li>
<li>DGR動作時は内部接点が動作し、VCBなどをトリップ</li>
<li>M-N端子は、親DGRから子DGRへ零相電圧信号を送る構成などで使用</li>
</ul>

<h3>電流引き外しDGR</h3>
I0・V0の検出原理は電圧引き外しタイプと同じ。電流引き外し方式では、制御電源とは別にトリップ用電源を用いる構成がある。<br>
<ul>
<li>電流引き外しOCR＋電流引き外しVCBと組み合わせて使用</li>
<li>VCBのトリップ回路と一部を共用する構成がある</li>
<li>トリップ用補助箱などの内部リアクトルで電流を制限する構成がある</li>
</ul>
