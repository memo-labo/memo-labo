<h2>DGRの種類</h2>
・電圧引き外しタイプ<br>
・電流引き外しタイプ<br>

<h2>電圧引き外しDGR</h2>
例：三菱 MDG-A1V<br>
<img src="images/dgr1.png" style="max-width:500px;" alt="三菱 MDG-A1V"><br>

・零相電流I0をZCTで検出し、Z1-Z2へ入力<br>
・零相電圧V0をZPDで検出し、Y1-Y2へ入力<br>
・本体制御電源はVT二次側などからP1-P2へ入力<br>
・DGR動作時は内部接点が動作し、VCBなどをトリップ<br>
・M-N端子は、親DGRから子DGRへ零相電圧信号を送る構成などで使用<br>

<h2>電流引き外しDGR</h2>
I0・V0の検出原理は電圧引き外しタイプと同じ。<br>
電流引き外し方式では、制御電源とは別にトリップ用電源を用いる構成がある。<br><br>

・電流引き外しOCR＋電流引き外しVCBと組み合わせて使用<br>
・VCBのトリップ回路と一部を共用する構成がある<br>
・トリップ用補助箱などの内部リアクトルで電流を制限する構成がある<br>
