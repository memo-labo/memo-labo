<h2>DGRの整定値</h2>
DGRの整定では、次の協調を確認する。<br>
① 配電用変電所DGRとの感度・時間協調<br>
② 構内フィーダーDGRとの時間協調<br>
③ 系統の残留分で不要動作しないV0整定<br><br>

<strong>零相電流</strong><br>
0.2Aなどの整定例がある。<br><br>

<strong>零相電圧</strong><br>
5%などの整定例がある。<br>
系統の残留分でV0検出表示が点灯する場合は、7.5%以上に変更する例もある。<br><br>

<strong>動作時間</strong><br>
0.2秒などの整定例がある。<br>
多回線母線用では0.4秒以上とする場合もある。<br>
上位保護との協調が重要なので、電力会社との協議内容を優先する。<br><br>

<strong>動作位相</strong><br>
非接地系：遅れ30°の例<br>
リアクトル接地系：遅れ60°の例<br>
系統方式やケーブル条件などにより位相条件が変わるため、実設備では整定資料や人工地絡試験結果を確認する。<br>

<h2>DGR試験方法</h2>
例：LDG-71K＋LVG-7系統<br><br>

電流：試験機 Kt・Lt ⇒ ZCT Kt・Lt<br>
電圧：試験機 V・E ⇒ ZPC-9B T・E<br>
信号：試験機 T1・T2 ⇒ a1・c1<br>
補助電源：試験機 P1・P2 ⇒ LDG-71K / LVG-7 P1・P2<br>

<h2>電流引き外しDGR試験の注意点</h2>
連動試験では、DGR本体の制御電源に加えて、VCBの引き外し用電源が必要になる場合がある。<br>
試験前に、トリップ用電源の供給元を配線図・線番で確認する。<br><br>

LDG-71Kなどで自動/手動復帰切替が手動の状態の場合、動作後も接点状態が維持される構成がある。<br>
そのままトリップ電源が印加され続けると、VCBトリップコイルに通電が継続するおそれがあるため、試験時は回路構成と復帰方式を確認する。<br>

<h2>DGR試験中のトラブル例</h2>
盤面のKt・Lt端子と、ZCT本体のKt・Ltが逆に接続されている例。<br><br>

・盤面Kt ⇒ ZCT Lt<br>
・盤面Lt ⇒ ZCT Kt<br><br>

この状態ではI0の位相が反転するため、所定の位相条件でDGRが動作しない。<br>
I0とV0を整定値以上に出力し、位相を反転させると動作する場合は、極性・配線方向を確認する。<br>

<h2>DGRの制御電源とトリップ電源</h2>
DGR制御電源P1-P2の供給元として、次の構成がある。<br>
・VT二次側<br>
・電灯トランス二次側<br>
・直流電源装置<br><br>

トリップ電源も、VT・電灯トランス・直流電源装置などから供給する構成がある。<br><br>

よくある組み合わせ<br>
・P1-P2がVT、トリップが電灯トランス<br>
・P1-P2もトリップも電灯トランス<br>
・P1-P2もトリップもVT<br>

<h2>制御電源とトリップ電源を分ける理由</h2>
<strong>DGR制御電源をVTから取る場合のメリット</strong><br>
・VCBの状態にかかわらずDGRを検出可能状態にできる<br>
・VCB投入直後から地絡検出が可能<br>
・自己保持形では動作後も接点状態を維持できる<br><br>

<strong>トリップ電源を電灯トランス二次側から取る場合のメリット</strong><br>
・VCB開放後にトリップ電源が消失する構成にできる<br>
・トリップコイルへの継続通電を防ぎやすい<br>
・VTへの継続負担を避けやすい<br>

