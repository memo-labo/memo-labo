<h2>DGR 地絡方向継電器とは？</h2>
DGR（Directional Ground Relay：地絡方向継電器）は、零相電流I0と零相電圧V0を検出し、その位相関係から地絡事故の方向を判別する保護継電器。<br>
GRのように零相電流だけを見るのではなく、V0との位相差を見ることで、需要家構内の地絡か、系統側の地絡かを判別しやすくする。<br><br>

DGR 地絡方向継電器の記号<br>
