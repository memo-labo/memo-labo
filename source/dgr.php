<h2>DGRの整定値</h2>
整定値は単独で決めるのではなく、上位・下位保護との協調を見て決める。<br>
<ul>
<li>配電用変電所DGRとの感度・時間協調</li>
<li>構内フィーダーDGRとの時間協調</li>
<li>系統の残留分で不要動作しないV0整定</li>
</ul>

<h3>零相電流 I0</h3>
0.2Aなどの整定例がある。実際には系統の地絡電流、ZCT、上位保護との協調条件を確認する。<br>

<h3>零相電圧 V0</h3>
5%などの整定例がある。系統の残留分でV0検出表示が点灯する場合は、設備条件に応じて7.5%以上に変更する例もある。<br>

<h3>動作時間</h3>
0.2秒などの整定例があり、多回線母線用では0.4秒以上とする場合もある。上位保護との協調が重要なので、電力会社との協議内容を優先する。<br>

<h3>動作位相</h3>
非接地系では遅れ30°、リアクトル接地系では遅れ60°とする例がある。系統方式やケーブル条件などにより位相条件が変わるため、実設備では整定資料や人工地絡試験結果を確認する。<br>

<div class="article-warning">
<span class="article-warning-title">⚠ 整定値は「よくある値」だけで決めない</span>
I0・V0・時間・位相は、設備構成や電力会社との保護協調条件で変わる。既設値を変更する場合は、整定表・単線結線図・メーカー資料・協議値を確認する。
</div>

<h2>DGR試験方法</h2>
例：LDG-71K＋LVG-7系統<br>
<ul>
<li>電流：試験機 Kt・Lt ⇒ ZCT Kt・Lt</li>
<li>電圧：試験機 V・E ⇒ ZPC-9B T・E</li>
<li>信号：試験機 T1・T2 ⇒ a1・c1</li>
<li>補助電源：試験機 P1・P2 ⇒ LDG-71K / LVG-7 P1・P2</li>
</ul>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：試験前に「制御電源」と「トリップ電源」を分けて確認</span>
電流引き外しDGRの連動試験では、DGR本体の制御電源に加えて、VCBの引き外し用電源が必要になる場合がある。試験前に、P1-P2とトリップ回路それぞれの供給元を配線図・線番で確認しておくと切り分けしやすい。
</div>

<h2>電流引き外しDGR試験の注意点</h2>
LDG-71Kなどで自動/手動復帰切替が手動の状態の場合、動作後も接点状態が維持される構成がある。<br><br>

そのままトリップ電源が印加され続けると、VCBトリップコイルに通電が継続するおそれがあるため、試験時は回路構成と復帰方式を確認する。<br>

<h2>DGR試験中のトラブル例</h2>
<h3>Kt・Ltが逆に接続されている</h3>
盤面のKt・Lt端子と、ZCT本体のKt・Ltが逆に接続されている例がある。<br>
<ul>
<li>盤面Kt ⇒ ZCT Lt</li>
<li>盤面Lt ⇒ ZCT Kt</li>
</ul>
この状態ではI0の位相が反転するため、所定の位相条件でDGRが動作しない。I0とV0を整定値以上に出力し、位相を反転させると動作する場合は、極性・配線方向を確認する。<br>

<h2>DGRの制御電源とトリップ電源</h2>
DGR制御電源P1-P2の供給元として、次の構成がある。<br>
<ul>
<li>VT二次側</li>
<li>電灯トランス二次側</li>
<li>直流電源装置</li>
</ul>

トリップ電源も、VT・電灯トランス・直流電源装置などから供給する構成がある。<br>

<h3>よくある組み合わせ</h3>
<ul>
<li>P1-P2がVT、トリップが電灯トランス</li>
<li>P1-P2もトリップも電灯トランス</li>
<li>P1-P2もトリップもVT</li>
</ul>

<h2>制御電源とトリップ電源を分ける理由</h2>
<h3>DGR制御電源をVTから取る場合</h3>
<ul>
<li>VCBの状態にかかわらずDGRを検出可能状態にできる</li>
<li>VCB投入直後から地絡検出が可能</li>
<li>自己保持形では動作後も接点状態を維持できる</li>
</ul>

<h3>トリップ電源を電灯トランス二次側から取る場合</h3>
<ul>
<li>VCB開放後にトリップ電源が消失する構成にできる</li>
<li>トリップコイルへの継続通電を防ぎやすい</li>
<li>VTへの継続負担を避けやすい</li>
</ul>

