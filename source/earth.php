<h2>測定器の接続方法</h2>
<img src="images/earth3.png" style="max-width:450px;" class="img-fluid" alt=""><br><br>

コアが独立したタイプの場合、矢印の方向を揃える。<br>
電流が流れる回路を作り、コアから見て機器側に渡り線をつけ、多重接地状態にする。<br>
１つ目のクランプで、回路に一定の電圧を印加する。<br>
２つ目のクランプで、回路の電流を測る。<br>
電圧と電流から、接地抵抗を測定する。<br><br>

例えばA種接地抵抗を測定したい場合、A種接地側とは逆側の機器側を、短絡クリップなどを使って補助極P、Cなどと並列に接続し、Rsの値を下げると、正確なA種の接地抵抗が測定できる。<br><br>

接地ループが成立していないと計測は出来ない。<br />
避雷針等の、他の接地との接続がない単独の接地には使用できない。<br />
多重で接続された極数が多く、低抵抗であるほど正確な抵抗値が測定できる。<br><br>

