フィルタ機能（高調波ノイズを除去）<br>
電流測定時に使用できる。<br>
ローパスフィルタが有効となり高調波成分をカットした漏れ電流を測定する。<br>
接地抵抗測定時にフィルタ機能を有効にすると表示値のふらつきが安定する。<br>
ただし「NOISE」マークが点灯している場合のノイズ除去には使えない。<br><br>

NOISEマークの点灯<br>
接地線に流れる電流が大きい場合、<br>
（50/60Hzにおいて2.5A以上、1KHzの高調波成分において100mA以上）<br>
測定値に影響が出るため抵抗測定が出来ない。<br>
この場合、まずは接地線に流れる電流値を計測する。<br><br>

インダクタマークの点灯<br>
接地線が短絡している可能性がある。<br>
短絡線とクランプ計測位置を再確認する。<br><br>

キャパシタンスマークの点灯<br>
接地線が断線している可能性がある。<br>
または接地ループが成立していない可能性があるので、短絡線を再確認。<br><br>

回路ができていない場合、一定の印加電圧に対して電流が流れず、高抵抗で測定不可となる。<br>
多重接地回路ができていない場合、測定対象接地抵抗の正確な数値が測定できない（大きな値になる？）<br><br>

入力電流の大きさ、および周波数によっては共振でクランプセンサ部分から音が発生する。<br>

<h2>動作確認用 抵抗</h2>
1Ω、25Ω、各ループにおいて許容範囲内の数値を表示することを確認する。<br>
1Ω：0.95～1.05Ω<br>
25Ω：24.3～25.7Ω<br>

<h2>多重接地にする理由</h2>
多重接地すればするほど、並列部分が増え、合計抵抗値が下がり、無視することができる。<br /><br />
Rs = 1/(1/R1+1/R2+1/R3+1/R4…）<br />
Rx >> Rs<br />
Rx + Rs = Rx = V/I<br />

<h2>危険</h2>
感電事故を防ぐため、使用中はバリア（障壁）より先を触らない。<br>
クランプセンサの先端部は高精度を得るために精密に製造されている。<br>
振動、衝撃、無理な力が加わらないよう注意する。<br><br>

最大許容電流を超えて使用しない（例：AC100A-連続・AC200A-2分間）<br>
本器を破損し人身事故に繋がる可能性がある。<br>

