<h2>点検時の確認ポイント</h2>

<ul>
  <li>コンデンサ容量・定格電圧に適合した放電コイルか</li>
  <li>端子の緩み、変色、異臭、ひび割れがないか</li>
  <li>自動力率調整器による投入間隔が設備仕様に合っているか</li>
  <li>開放後、所定時間内に残留電圧が低下する設計になっているか</li>
</ul>

<p><strong>コンデンサを開放した直後でも、無電圧と決めつけません。</strong>点検作業では設備の定められた放電時間を確保し、必要な安全確認を行います。</p>

