<h2>放電コイルとは？</h2>

<p>放電コイル（Discharge Coil）は、高圧進相コンデンサなどを電路から切り離したあとに残る電荷を、短時間で安全な電圧まで低下させるための放電装置です。</p>

<p>コンデンサは開放後もしばらく電荷を保持するため、残留電圧が高いまま再投入・点検すると、感電や異常な過渡現象の原因になります。</p>

<h2>放電抵抗との違い</h2>

<p>進相コンデンサには放電抵抗を内蔵する製品もあります。放電抵抗は構造が簡単ですが、放電に一定の時間が必要です。</p>

<p>放電コイルは、コンデンサを自動力率調整器などで頻繁に入切する設備のように、<strong>次の投入までにより短時間で残留電圧を下げたい場合</strong>に使用されます。</p>

<table>
  <tr><th>方式</th><th>特徴</th></tr>
  <tr><td>放電抵抗</td><td>構造が簡単。放電時間はコンデンサ・抵抗値・規格による。</td></tr>
  <tr><td>放電コイル</td><td>短時間放電に向く。コンデンサ容量・電圧に適合する機種を選定する。</td></tr>
</table>

<h2>「5秒で50V以下」はすべて同じ？</h2>

<p>放電時間や残留電圧の仕様は、放電コイル・コンデンサの組み合わせやメーカー仕様によって異なります。</p>

<p><strong>「必ず5秒で50V以下」「放電抵抗なら必ず5分」と一律には扱いません。</strong>実設備では、使用しているコンデンサと放電装置の銘板・カタログ・取扱説明書に示された放電特性を確認します。</p>

