<h2>放電コイルとは？</h2>
放電コイル = DISCHARGER COIL<br>
コンデンサは、回路より開放した後も電荷が残る。<br>
なので安全性の確保、再投入時の過渡過電圧抑制のため、放電装置が必要。<br>
コンデンサに内蔵の放電抵抗は、放電まで５分かかる。<br>
放電コイルが必要になるのは、自動制御で多頻度開閉するような、短時間内の放電が必要な場合。<br>
放電コイルは5秒で50V以下まで放電される。<br>

