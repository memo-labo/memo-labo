<h2>特徴</h2>
コイルをモールドしているエポキシ樹脂は自己消化性を有している。<br>
なので難燃性、被爆性であり、万一の場合、アークが発生しても発火・爆発の心配がない。<br><br>

導体の周囲にはボイドレスのエポキシ樹脂を含浸注形している。<br>
なので交流及びインパルス共、耐電圧特性に優れている。<br>
また充電部がモールドされているので、吸湿による絶縁劣化は少ない。<br>
よって絶縁に対する信頼性が高い。<br>

