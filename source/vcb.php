<h2>無電圧引き外し（常時励磁式）</h2>

UVC：不足電圧引き外しコイル<br>
目的：不足電圧保護<br>
コイル印加電圧が20％～60％に低下したとき遮断器を引外す装置<br>
常時負担VAは8VA<br><br>

常時励磁式<br>
投入コイルが励磁されている間だけ投入状態を維持する。<br>
投入コイルの励磁が解けると開放される。<br>


