<h2>VCBの引外し方式</h2>
VCBの引外し方式は設備によって異なる。代表的には電流引外し、電圧引外し、コンデンサ引外し、不足電圧引外しがある。<br>

<h3>電流引外し</h3>
保護継電器の動作でトリップコイルへ必要な電流を流してVCBを開放する方式。機種ごとにコイル抵抗や必要電流が異なるため、測定値や試験値は取扱説明書と照合する。<br>

<h3>電圧引外し</h3>
トリップコイルへ所定の電圧を印加して開放する方式。AC/DCの操作電源構成は機種・盤仕様によって異なる。<br>

<h3>コンデンサ引外し電源装置（CTD）</h3>
CTDはコンデンサを充電しておき、停電時でも継電器の引外し接点からVCBトリップコイルへ放電できるようにする装置。<br>
⇒<a href="ctd.php">CTD（コンデンサ引外し電源装置）</a><br>

<h3>不足電圧引外し</h3>
不足電圧引外しコイル（UVC）を用い、制御電圧が低下・消失したときにVCBを開放する構成がある。動作電圧範囲や常時励磁条件は機種ごとに確認する。<br>
⇒<a href="uvr.php">UVR（不足電圧継電器）</a><br>

<h2>電動ばね操作形VCB</h2>
電動ばね操作形では、ばね蓄勢回路、投入指令回路、引外し回路が分かれている。端子番号やAC/DC電圧は機種ごとに異なるため、現物の結線図を基準に確認する。<br><br>

