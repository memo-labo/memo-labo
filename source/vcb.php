<h2>VCBの開極時間</h2>
VCB（高圧交流遮断器）は、３サイクル定格、５サイクル定格がある。<br>
50Hz使用において、３サイクル定格の場合、3/50 = 0.06s以内に遮断可能。<br>
50Hz使用において、５サイクル定格の場合、5/50 = 0.1s以内に遮断可能。<br>
通常は３サイクルの方を選べば良いらしい（５サイクルがあるのはなぜ？）<br><br>

物理的な遮断はもっと速いが、実際の事故電流の遮断はアークにより表示サイクルに近くなる。
遮断時間が遅いと電流振幅が減少しているので5サイクルは3サイクルに比べサージが小さくなる。

<h2>引出し型VCB（ネット情報調べ）</h2>
１次側活線状態でVCB本体の精密点検やVCB２次側の点検を行いたい場合、当該VCBを開放状態にしてVCB引き出しにより試験位置に断路することで点検可能。<br>
上流にブリッジ（母線連絡遮断器）で遮断可能であれば、当該VCB１次側も無停電状態に出来て安全。<br>
引出し型VCBの場合、開放しないと断路できないインターロックが重要。<br>
制御ケーブルは外さないようにする。<br>
１次側活線状態でVCBを押し込むと挿入時にチリチリと音がするらしい。<br>
VCB投入状態でVCBを押し込まない。<br>
VCBを引き抜いて分解整備、VCB交換作業が容易に行える。<br>

<h2>母線連絡遮断器</h2>
大規模の設備では、停電範囲を限定したい場合、母線連絡遮断器で停電範囲を限定させて点検を行う。<br />
母線連絡遮断器１台ではVCB本体の点検に全停電が必要なので、VCB２台を直列で設ける必要がある。<br />
保全上有利な方式だが、VCBの数が増えるのでコストアップになる（VCBは高価）<br />
母線連絡遮断器VCBの表記は「52B」と表記される。<br /><br />

また、小規模の場合には商用電源利用の変圧器と非常電源利用の変圧器の系統を分離することができる。<br />
※商用電源利用の際には通常負荷と非常負荷、非常電源利用の際には非常負荷のみ給電。<br />


