<h2>VCB（真空遮断器）とは</h2>
VCBはVacuum Circuit Breakerの略で、日本語では真空遮断器。高圧受電設備で負荷電流や短絡電流を遮断するために使用する。<br>
真空中で接点を開くと発生したアークが急速に拡散・消弧するため、高圧回路を高速に遮断できる。OCRやDGRなどの保護継電器から引外し指令を受けて動作する構成が多い。<br><br>

