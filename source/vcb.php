<h2>VCBの主な定格</h2>
<h3>定格電圧</h3>
遮断器を使用できる系統電圧の基準。6.6kV系統では7.2kV級のVCBが用いられる。3.3kV系統では3.6kV級が一般的。<br>

<h3>定格電流</h3>
規定の温度上昇限度内で連続して流せる電流。選定時は最大負荷電流だけでなく、将来増設や盤構成も確認する。<br>

<h3>定格遮断電流</h3>
VCBが安全に遮断できる短絡電流の上限。12.5kA級などがあるが、必要遮断容量は受電点の短絡電流計算と設備仕様から決める。<br>

<h3>定格耐電圧</h3>
所定条件で規定時間印加しても絶縁破壊しない電圧の基準。耐圧試験値とは対象や試験条件を混同しないようにする。<br>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：更新では「定格」だけでなく取付寸法も確認</span>
同じ7.2kV・同じ定格電流でも、外形寸法、主回路端子位置、補助接点、操作電源、引外し方式が異なる。更新前は銘板だけでなく外形図・結線図まで確認しておくと手戻りを減らせる。
</div>

