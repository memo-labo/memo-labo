<h2>VCB引き外しの種類</h2>

電流引き外し<br>
電流引き外しタイプVCBのトリップコイル抵抗値：4Ω前後<br>
VCB引き外しに必要な電流量：約3A<br>
VCB内部トリップ回路２つの内部には52aはついておらず常時閉路。<br><br>

電圧引き外し<br>
交流操作と直流操作がある。<br>
VCB内部トリップ回路１つの内部には52aがついていてVCB開閉操作と連動するa接点。<br><br>

<h2>コンデンサ引外し電源装置（CTD）</h2>
コンデンサを充電しておき、継電器等の引外し指令接点を閉じることで電圧引外しコイル（STC）に放電して遮断器を引外す。<br>
整流器にはシリコン整流器、コンデンサは電解コンデンサを使用している。<br>
充電時間は１～2秒程度であり、停電後30秒においても、引外しが可能。<br>
