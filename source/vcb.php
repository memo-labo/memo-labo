<h2>VCBの遮断時間</h2>
VCBには3サイクル、5サイクルなどの遮断時間区分がある。例えば50Hzで3サイクルなら、3÷50=0.06秒が一つの時間目安になる。<br>
ただし、保護協調ではVCBだけでなくOCRなど保護継電器の動作時間を加えた事故除去時間で考える。<br>
⇒<a href="ocr.php">OCRとVCBの連動・遮断時間</a><br>

<h2>引出し形VCB</h2>
引出し形VCBは、遮断器本体を接続位置・試験位置・断路位置などへ移動できる構造。点検や更新がしやすい反面、位置インターロックやシャッター機構の確認が重要になる。<br>

<ul>
<li>投入状態のまま引出し操作をしない</li>
<li>接続位置・試験位置・断路位置を表示で確認する</li>
<li>操作前に対象設備の一次・二次側状態を単線結線図で確認する</li>
<li>インターロックを無理に解除しない</li>
</ul>

<div class="article-warning">
<span class="article-warning-title">⚠ 注意：活線状態での引出し操作は設備固有の手順を優先</span>
引出し形VCBは設備によって活線母線に近接するため、一般化した操作手順だけで判断しない。メーカーの操作要領、盤のインターロック、現場の保安手順に従う。
</div>

<h2>母線連絡遮断器</h2>
大規模設備では、母線を分割し母線連絡VCBで停電範囲を限定する構成がある。図面では52Bなどの記号で表す例がある。<br>
非常用発電機系統と商用系統を分け、非常時に必要負荷だけへ給電する構成でもVCBが用いられる。<br>
