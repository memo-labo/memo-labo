<h2>VCBの寿命・更新時期</h2>
VCBは使用年数だけでなく、遮断回数、負荷開閉回数、短絡遮断履歴、機械部の劣化などを総合して更新を判断する。メーカーによって推奨更新時期や規定開閉回数が異なるため、使用中の形式の保守基準を確認する。<br><br>

