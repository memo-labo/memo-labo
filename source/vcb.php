VCBとは英語でVacuum Circuit Breaker、日本語で真空遮断器。<br>
真空中におけるアークの拡散・消弧作用を利用した遮断器のこと。<br>
遮断時、接触子間に発生したアークが高真空で強力な拡散作用を受け、自然消滅させる。<br>
機械的・電気的インターロックで「接続位置」「断路位置」の移動が出来るタイプもある。<br><br>

定格遮断電流（kA）<br>
遮断できる電流の限度値のこと。<br>
一般的なVCBの定格遮断電流は12.5[kA]<br><br>

定格電圧(kV)<br>
規定の条件で遮断器に加えることができる電圧の上限のこと。<br>
線間電圧（実効値）で表す。<br>
公称電圧3.3kVの場合、定格電圧は3.6kV<br>
公称電圧6.6kVの場合、定格電圧は7.2kV<br><br>

定格耐電圧<br>
その電圧を規定の時間、遮断器に印加しても異常が認められない電圧の限度のこと。<br><br>

定格電流(A)<br>
定格電圧及び定格周波数の下で、規定の温度上昇の限度を超えず、遮断器に連続して流せる電流の限度。<br>
定格電流は、JIS C 4603 では、400Aと600Aがある。<br>
最大負荷電流の1.5倍以上を目安に選定する。<br>
将来の負荷の増加も考慮する。<br>

