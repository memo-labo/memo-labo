<h2>G4Q ラチェットリレー</h2>

特徴<br>
パルスごとに２極の各接点が交互切り換え動作を行う。<br>
モータなどの交互運転、切り換え運転に適している。<br>
独自のラチェット機構の採用により接点の切り換えを行う。<br><br>

外観<br>
<img src="images/g4q1.jpg" style="max-width:400px;" /><br><br>

動作<br>
コイル印加をパルスで使用する場合、印加パルス100ms以上で使用する。<br>
動作時間以下のパルス印加だと、カムが回転しきらない場合がある。<br>
<img src="images/g4q2.jpg" style="max-width:500px;" /><br><br>

構造<br>
コイルへのパルス印加によってカムが回り接点が動作する。<br>
<img src="images/g4q3.jpg" style="max-width:700px;" /><br><br>

注意点<br>
取りつけ板を垂直にする。<br>
コイルが上、カムが下になる方向に取りつける。<br>

