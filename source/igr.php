<h2>Igr方式とは？</h2>
<img src="images/leak3.png"><br>
電路に対して数ボルトの微弱な低周波監視電圧を注入する。<br>
静電容量による電流を取り除き、精度の高い絶縁抵抗電流の測定を行う。<br>
中性線を含めた全電路の監視ができるため、より安全性が高い監視が可能。<br><br>

注意点<br>
負荷設備の稼働状況により強いノイズが発生するような場合、Igr方式の重畳信号や検出信号に影響を与え、正常に絶縁監視が出来ない場合がある。<br><br>

