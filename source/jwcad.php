<h2>PDFファイルをjwcadに読み込んで編集する方法</h2>
PDFをDXF形式に変換する。オンラインサービス「PDF to DXF」を使用する。<br>
jwcadを開いてDXFファイルを読み込む。これでjwcad上で編集できる。<br>
jwcadで編集した方がinkscapeよりも動作が軽い。<br>
ただjwcadの操作に慣れないと使いにくい。<br>

