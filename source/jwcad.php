<h2>建築図へ電気設備を書き込む流れ</h2>

<ol>
  <li>元図を複製し、編集用ファイルを作る</li>
  <li>建築図を下図として読み込む</li>
  <li>縮尺を確認する</li>
  <li>電気設備用のレイヤを分ける</li>
  <li>照明・コンセント・盤・配線などを追記する</li>
  <li>凡例・注記・回路番号を追加する</li>
  <li>印刷前に線種・文字サイズ・縮尺を確認する</li>
</ol>

<h2>PDFをJw_cadで使いたい場合</h2>

<p>PDFには、CADデータ由来のベクターPDFと、紙図面をスキャンした画像PDFがあります。</p>

<ul>
  <li><strong>ベクターPDF</strong>：変換すると線データとして扱える場合がある</li>
  <li><strong>画像PDF</strong>：変換しても画像のままで、線として直接編集できない場合がある</li>
</ul>

<p>DXFなどへ変換してJw_cadへ読み込む方法もありますが、変換時に文字化け、線種変化、縮尺ずれ、円弧の崩れなどが起きることがあります。</p>

<h2>オンラインPDF変換サービスの注意</h2>

<p><strong>受変電設備図・建築図・構内図には、施設名、設備配置、セキュリティ情報などが含まれる場合があります。</strong></p>

<p>外部のオンライン変換サービスへアップロードする前に、機密性・社内ルール・利用規約を確認します。機密図面では、ローカルPC内で処理できるソフトを使う方が安全です。</p>

<h2>図面を軽く保つコツ</h2>

<ul>
  <li>不要な画像を大量に貼らない</li>
  <li>建築図と電気設備をレイヤ分けする</li>
  <li>同じ図記号はコピーして統一する</li>
  <li>文字・線種・線幅のルールを決める</li>
  <li>元図を残して編集版を別名保存する</li>
</ul>

<h2>Jw_cadとInkscapeの使い分け</h2>

<ul>
  <li><strong>Jw_cad</strong>：寸法・縮尺を持つ平面図や設備図の編集向き</li>
  <li><strong>Inkscape</strong>：Web掲載用の説明図・SVG・見栄えを整えた図の作成向き</li>
</ul>

<p>単線結線図のような説明図はどちらでも作れます。既存の建築CAD図へ追記するならJw_cad、Webで見やすいSVGを作るならInkscapeという使い分けがしやすいです。</p>

