<h2>jw cadとは？</h2>

⇒<a href="https://blog.memo-labo.com/?cat=174" target="_blank">jw cadの使い方 練習（でんきブログ）</a><br>

動作が非常に軽く性能の低いパソコンでもサクサク動く。<br>
jwwで保存したファイルサイズは容量が軽い。<br>
操作性にクセがあり初心者は戸惑うが２次元作図に特化しているので慣れると最強。<br><br>

電気関係で使用される例<br>
・すでに完成済の建築図面に照明、コンセント、スイッチなど記入<br>
・太陽光発電設備のパネル、接続箱、パワコン、ケーブル配線図の作成<br>
・高圧受電設備の単線結線図や構内図の作成<br>
・消防設備の配線図の作成<br>
・無料ソフトなので地方自治体で人気らしい<br>

