<h2>Jw_cadとは？</h2>

<p><strong>Jw_cadは、2次元図面の作成・編集に使われる無料CADです。</strong>建築図や設備図へ電気記号・配線・注記を書き込む用途でも使われています。</p>

<p>動作が比較的軽く、JWW形式で図面を管理できるため、既存の建築平面図へ電気設備を追記したいときに便利です。</p>

<h2>電気設備で使う例</h2>

<ul>
  <li>照明・コンセント・スイッチの配置図</li>
  <li>太陽光パネル・接続箱・PCS・配線図</li>
  <li>高圧受電設備の単線結線図</li>
  <li>構内配置図・ケーブルルート図</li>
  <li>消防設備・弱電設備の配線図</li>
</ul>

