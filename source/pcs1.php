<h2>太陽光のノイズでAMラジオにノイズが混じる</h2>
ノイズ障害事例<br>
太陽光を工場の屋根に設置して、系統連系を開始した。<br>
それ以来、AMラジオにノイズが混ざるようになった。<br>
太陽光パネルの配線が網目状⇒周辺のノイズを拾うアンテナ代わりに。<br>
拾われたノイズ⇒太陽光パネルのケーブル⇒PCS⇒Tr⇒送電線⇒敷地内でAMラジオの受信障害。<br><br>

改善方法<br>
