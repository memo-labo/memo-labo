<h2>パネルとPCS間の直流線にフェライトコアでノイズ対策</h2>

放送用無線回線の周波数にノイズが混入。<br>
晴れだとノイズレベルが高く、曇りだと低くなる。<br>
太陽光のパワコンからノイズと予想。<br>
監視機器で放送受信所の周辺を調査。<br>
一般住宅よりノイズ確認。パワコン停止でノイズ低減を確認。<br>
パワコンの位置と放送受信所の受信アンテナ指向方向が影響していた。<br><br>

対応策<br>
パネルからPCS間の直流線に高周波のフェライトコアを挿入。<br>
これで輻射ノイズを低減（△15～20dB）し受信所への影響は無くなったそう。<br><br>


フェライトコアとは？<br>
強磁性を示す金属酸化物。<br>
高周波用磁性材料としても活用されている。<br>
ノイズ輻射をもたらす高周波電流を阻止する。<br>
ノイズ電流が流れているケーブルにフェライトコアを取り付ける。<br>
フェライトコアの磁化に応じてケーブルのインピーダンスが増加しノイズ電流の伝播を抑える。<br>
コアの磁化に伴いノイズのエネルギーを吸収し熱に変える働きもある。<br>
パソコンやデジタル家電製品などの電気・電子機器のケーブルにも数多く用いられてる。<br>

