<h2>パワコン内部の基板が焼損</h2>
フィルター基板上、コイルのリードのはんだ接続部の「はんだ付け不良」が原因で焼損。<br>
コイルなど「重量のある部品」の「はんだ接続部」が焼損原因。<br>

<h2>パワコン配管に水がたまり短絡・焼損</h2>
屋上パネルから壁かけパワコンの間は、直流線は配管を通っている。<br>
配管は、壁かけパワコン付近でU字に曲がり、パワコンに接続される。<br>
配管に水抜き穴がなく、水が溜まり、パワコン内に侵入、絶縁不良で短絡して焼損。<br>

