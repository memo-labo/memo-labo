<h2>ネジが真鍮の理由を考察</h2>

真鍮、ステンレス、鉄の３素材で比較。<br><br>

真鍮<br>
最も導電性に優れ、耐食性も高い。<br><br>

ステンレス<br>
耐食性は高いが導電性が低い。<br><br>

鉄<br>
導電性も低く耐食性も低い。<br><br>

上記より、真鍮はA種接地用のネジとして使用するのに優れた素材である。

