<h2>ケーブルシースアースのネジ</h2>

外観<br>
<img src="images/shield8.jpg" style="max-width:400px;" alt=""><br>

なべねじ M6 首下10mmくらい<br>
プラスドライバー３番<br><br>

ドライバーの種類<br>
・1番：ときどき使う（小さい）<br>
・2番：よく使う（普通）<br>
・3番：あまり使わない（大きい）<br><br>

ドライバー２番で３番ねじを外そうとするとサイズが合わない（ドライバ側が小さい）<br>
するとネジあなが噛み合わず、力をいれるとねじ頭がナメてしまう。<br><br>

ねじ頭を潰さない、なめないように緩める方法<br>
ドライバーをねじに対して押し付けて回す。<br>
押し付けが足りないとネジがナメてしまう。<br>

<h2>シースアースと圧着端子</h2>
・ネジと圧着端子の穴の大きさが合っていない。<br>
・圧着端子の太さとシースアースの太さが合っていないので抜けてしまう。<br>
