<h2>自立型PAS（キャビネット）</h2>
柱上型PASと比べてキャビネット内なので錆、ホコリ、塩害から防げる。<br>
UGSと比べてケーブルの引き込み、繋ぎ込みが容易。<br>
UGSに比べると本体価格が安い。<br><br>

正面から見て左が電源側、右が負荷側（それぞれ銘板あり）<br>
PASを開放しても左の電源側は充電状態でケーブルに触ると感電する。<br>
PASを開放し、さらにその上流のASも開放されていれば無電圧状態。<br>
PAS1次側はPASの保護範囲ではないので波及事故。<br><br>

