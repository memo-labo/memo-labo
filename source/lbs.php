<h2>LBS 高圧交流負荷開閉器とは？</h2>
LBS（Load Break Switch）は、高圧回路を三相一括で開閉する負荷開閉器。<br>
アークシュートでアークを消弧するため、通常の負荷電流を開閉できる。<br>
短絡電流はLBS本体では遮断せず、PF（パワーヒューズ）で遮断する。<br>

