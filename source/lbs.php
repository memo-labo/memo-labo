<h2>LBS 高圧交流負荷開閉器</h2>
LBS (Load Break Switch) <br />
三相一括で開閉する。<br />
アークシュートでアーク消弧されるため、負荷電流を遮断できる。<br />
継電器を使用して連携遮断ができる。<br />

