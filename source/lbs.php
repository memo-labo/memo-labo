<h2>LBSの開閉寿命と更新</h2>
電気的開閉寿命：200回程度<br>
機械的開閉寿命：1000回程度<br>
多頻度開閉には適さない。<br><br>

更新推奨時期の例<br>
・高圧交流負荷開閉器：使用開始後15年、または負荷電流開閉回数200回<br>
・高圧限流ヒューズ：15年<br>

<h2>LBSの補助接点とアーク消弧</h2>
LBSの開放時は、主接点が先に離れ、その後にアークブレード側で電流を遮断する。<br>
発生したアークはアークシュート（消弧室）で冷却・分割されて消弧される。<br>

<h2>通電中にLBSを開放すると？</h2>
負荷電流が流れている状態でLBSを開放するとアークが発生する。<br>
アークシュートで消弧されるが、可能であれば変圧器二次側負荷を開放し、負荷電流を小さくしてから操作する。<br><br>

進相コンデンサ回路などでは、負荷MCCBを開いていてもコンデンサ電流が流れている場合があるため注意する。<br>

<h2>LBSの汚損・絶縁不良</h2>
LBSは充電部が空気中に露出しているため、粉塵・油・湿気などの影響を受けやすい。<br>
汚損した絶縁部が吸湿すると、絶縁低下や地絡・相間短絡につながることがある。<br>
エポキシ樹脂部のひび割れ・トラッキングなどは、清掃だけで性能を回復できない場合がある。<br><br>

