LBS：500[KVA]以下<br>
PC：300[KVA]以下<br>


<h2>ストライカ（動作表示装置）引き外し式</h2>
LBSに短絡電流が流れると、ヒューズが溶断し、溶断表示棒が飛び出す。<br>
この際、トリップレバー（ヒューズ下の金属プレート）を押し出し、ラッチが動作する。<br>
ヒューズ溶断と同時に三相すべてが開放されるので、欠相運転を防止することが出来る。<br><br>

ストライカが、ヒューズの下ではなく上に飛び出すタイプもあるらしい。<br>
メーカーでいうと、エナジーサポート、富士電機、東芝などにあるらしい。<br>

<h2 id="pf">ヒューズ動作表示スイッチ</h2>
LBSのPF（パワーヒューズ）が溶断されるとヒューズ下の金属プレート板が押し出される。<br>
するとヒューズ後ろにある金属の横棒が動き、それに連動してLBS右側にある金属の縦棒が上に動く。<br>
するとLBS右上にあるスイッチを押し上げ、常時開路状態の接点が閉路して警報回路が完成する。<br>
ここに自己保持、オレンジランプ点灯、ブザー、リセット回路を用意することでPF溶断回路が作れる。<br>
