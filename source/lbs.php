<h2>VCB・LBS・PCの使い分け</h2>
変圧器保護用としての目安<br>
・VCB：500kVAを超える設備<br>
・LBS：500kVA以下<br>
・PC：300kVA以下<br>

<h2>LBSで開閉できる電流</h2>
通常負荷電流：開閉可能<br>
過負荷電流・短絡電流：LBS本体では遮断せず、PFで遮断<br><br>

定格遮断電流の例：200A<br>
定格を超える電流を無理に遮断すると、アークが消弧できず、焼損や相間短絡につながる可能性がある。<br>

<h2>ストライカ引き外し式</h2>
短絡事故でPFが溶断すると、溶断表示棒（ストライカ）が飛び出す。<br>
ストライカがトリップレバーを押し、ラッチが動作してLBS三相を一括開放する。<br>
これにより、1相だけPFが切れた状態での欠相運転を防ぐ。<br><br>

メーカーによって、ストライカがヒューズ上側へ飛び出す構造もある。<br>

<h2 id="pf">PFヒューズ動作表示スイッチ</h2>
PFが溶断すると、ヒューズ下部の機構が動き、LBS側面の補助スイッチを動作させる構成がある。<br>
補助接点を警報回路へ使用し、表示灯・ブザー・自己保持・リセット回路などを組み合わせる。<br>
