<h2>LBS 遮断電流</h2>
定格遮断電流：200[A] ✕ 200回。
定格遮断容量を間違えると電流が遮断できずにアークが発生、遮断器の焼損、相関短絡に至る場合も。
発生したアークが他の導体と接触することで短絡事故に。<br>

<h2>LBS 開閉可能・開閉不可能の条件</h2>

通常負荷（定格負荷）：遮断可能<br>
過負荷電流・短絡電流：遮断不可（PFヒューズで遮断）<br>

<h2>LBSの開閉寿命・更新推奨時期</h2>
電気的開閉寿命：200回<br />
機械的開閉寿命：1000回<br />
多頻度の開閉箇所には適さない<br /><br />

更新推奨時期（使用開始後）<br />
高圧交流負荷開閉器：15年 または負荷電流開閉回数 200回<br />
高圧限流ヒューズ：15年<br />


<h2>LBSの汚損・不具合・絶縁不良</h2>
三菱のがいしが茶色タイプのLBS。絶縁が悪くなりがち。<br>
<img src="images/lbs10.jpg" style="max-width:600px;"><br><br>


LBSは空気中に露出しているため、粉塵、グリース固着で接触不良が起こり加熱の可能性。<br>
LBSの絶縁部が汚損した状態で吸湿すると絶縁が低下し、地絡事故や相間短絡事故の可能性。<br>
エポキシ樹脂製のストライカーリンクの絶縁劣化は、ヒビ割れ、湿気侵入、トラッキング等。<br>
この場合、洗浄や補修などで性能が回復するのは不可能。<br>

<h2>LBS点検、清掃中の事故</h2>
<img src="images/lbs10.svg" style="max-width:300px;" /><br>
LBS投入状態で清掃、目視点検中にLBSのラッチ部分に触れてしまいLBSが勢いよく開放されLBSヒューズ部分が顔や頭に直撃。
ヘルメットを被っていてケガは避けられたとしてもPFヒューズを割ったり傷つけてしまう可能性も。
点検清掃中は必ず開いておく。

<h2>LBS 補助接点</h2>
補助接点は以下の２つで構成される<br />
・アークシュート（消弧室）<br />
・アークブレード（金属の刃のような形）<br /><br />

LBSの開放は、主接点が外れた後に、補助接点が開放される。<br />
この時、補助接点にアークが発生するが、補助接点のアークブレードは、アークシュートの作用で消滅する。<br /><br />

アークシュート（消弧室）の効果<br />
消弧室の細隙効果と冷却効果により、アークが消滅。<br />

<h2>LBSを通電中に開放すると？</h2>
変圧器２次側の負荷に電源を供給した状態でLBSを開放する場合、アークが発生する。<br>
音、光、熱を発するが、これはアークシュートにより消弧される。<br>
変圧器以降のMCCBをすべて開放し、負荷への供給をストップした状態であれば、アークは最小限に抑えられる。<br>
ただし通電状態でコンデンサ上のLBSを開放する場合、コンデンサには電流が流れているので、アークが発生する。<br>


<h2>カットアウトと比較したLBSのデメリット</h2>
LBSは充電部が露出しているため、水分、ほこり、汚れなど付着しやすい。<br>
それに伴い、LBSの筐体部分に生じた汚損より絶縁低下を起こしやすい。<br>
高圧カットアウトに比べて、耐用年数も短い。<br>



