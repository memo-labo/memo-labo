<h2>LBS点検・清掃時の事故</h2>
<img src="images/lbs10.svg" style="max-width:300px;" alt="LBS 清掃時注意"><br>

LBS投入状態でラッチ部に触れると、勢いよく開放してPFや可動部が作業者へ当たる可能性がある。<br>
点検・清掃時は開放状態を確認して作業する。<br>

<h2>ハンディモップ清掃時の注意</h2>
ハンディモップの繊維や残骸が、金具・ネジ・絶縁部へ引っかかって残ることがある。<br>
清掃後に異物が残ると、充電部付近で絶縁低下や地絡事故の原因になる可能性がある。<br>
清掃後はモップの繊維や残骸が残っていないか目視確認する。<br>

<h2>カットアウトと比較したLBSの特徴</h2>
LBSは充電部が露出しているため、水分・ほこり・汚れの影響を受けやすい。<br>
高圧カットアウトと比べ、汚損による絶縁低下に注意が必要。<br>

<h2>点検時の確認ポイント</h2>
・PFの溶断表示、ひび割れ、変色<br>
・アークシュートの汚損・破損<br>
・絶縁部のひび割れ、トラッキング、吸湿汚損<br>
・接触部の変色、加熱跡<br>
・ラッチ、ストライカ機構の動作<br>
・清掃後の異物残り<br>

