<h2>ヒューズホルダ</h2>
受電盤やRPR・OVGR専用盤などについている。<br>
受電盤VTTからの配線をヒューズホルダで切り分けて試験することができる。<br>
でっぱっている部分を引っ張ると蓋がとれて中のヒューズがむき出しになる。<br>
