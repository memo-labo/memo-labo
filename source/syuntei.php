<h2>瞬低（瞬時電圧低下）とは？</h2>

瞬時電圧低下の略。<br>
ある区間、ある時間（通常は１秒以内）電圧が低下する現象のこと。<br>
一般的に、0.01秒～0.001秒の間で回復する。<br>
電圧低下が回復しなかった場合、電力会社は落雷発生時点から0.02～2秒の間で、落雷した送電線を切り離す。<br>
この瞬低で高圧受電設備の受電盤のUVRが動作する場合がある。<br><br>

瞬低の原因<br>
・雷が送電線や変電所に影響を与え、電圧の急激な低下を引き起こす。<br>
・工場などで大規模な電力を消費する機械が急に動作を開始すると一時的に電力供給が不安定。<br>
・送電網や変電設備のトラブルにより電圧が一時的に低下。<br><br>

瞬低が発生するとどうなる？<br>
・完全に停電するわけではなく、電力は供給され続ける。<br>
・電子機器や電気機器が正常に動作しなくなる。<br>
・コンピュータやサーバー、精密機器などが正常に動作しなくなる。<br>
・産業用機械やロボットが誤作動し、製造ラインが一時的に停止する可能性。<br>
・照明器具の一時的なちらつきが発生。<br>
・モーターなどの電動機の停止や誤作動<br>
・ルーターやスイッチなどのネットワーク機器が再起動し一時的な通信障害。<br>
・コンピュータやサーバーが不意にシャットダウンで処理中データ損失、ファイル破損等<br><br>

瞬低の対策<br>
・UPS（無停電電源装置）<br>
・電圧調整装置（AVR）で電圧の変動を平滑化して安定した電力を供給<br>
・定期的なバックアップ体制<br>

<h2>瞬停とは？</h2>
瞬間的に「送電が止まる」現象。<br>
送電線への落雷などによる瞬間的な電圧低下によって電力会社が瞬間的に切り離した状態。<br>
瞬低（電圧の一時的な低下）とは異なり、瞬停は電力が完全に途絶える。<br>
しかしすぐに電力会社から再送電され、電気が正常に送られる。<br>
<a href="saiheiro.php">最閉路（再送電）</a>は自動的に行われ、電圧低下から再送電までの時間は約１分間。<br>
この約1分間の停電を「瞬停」と呼ぶ。<br><br>

１分以内の電力停止は電力会社が意図的に発生させている状態。<br>
なので電力会社では「停電」とは呼ばない。<br>

