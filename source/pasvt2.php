<h2>外部電源だった場合の配線ケーブルの種類</h2>
VVFケーブルは屋内用で、雨や紫外線で劣化し絶縁低下してしまうので屋外には使えない。<br>
屋外でも使用できる低圧CVケーブルの2.0sq、3.5sqあたりを使用する。<br>
キュービクルからSOGボックスまで距離がある場合、<a href="drop.php">電圧降下</a>を考慮して太い電線を使用する。<br>

