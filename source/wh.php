<h2>電力量計（電力メーター）とは？</h2>

<p><strong>電力量計は、使用した電力量[kWh]を積算して記録する計器です。</strong><br>
高圧受電設備では、電力量だけでなく最大需要電力（デマンド）や無効電力量などを表示できる複合計器も使われます。</p>

<p>参考：<a href="https://www.fujielectric.co.jp/products/whm/container/doc/d1hukugoukeiki201307.pdf" rel="noopener">富士電機 SP3ER-R 取扱説明書</a></p>

<h2>まず見るポイント</h2>
<ul>
  <li><strong>有効電力量[kWh]</strong>：実際に使用した電力量</li>
  <li><strong>最大需要電力[kW]</strong>：一定期間内の最大デマンド値</li>
  <li><strong>力率</strong>：有効電力と皮相電力の関係</li>
  <li><strong>乗率</strong>：表示値に掛ける倍率</li>
  <li><strong>検定有効期限</strong>：取引用計器として使用できる期限</li>
</ul>

<h2>「全日」とは？</h2>
<p>計器の表示項目にある「全日」は、時間帯別に分けず全時間帯をまとめて計量した値を示す表示として使われます。<br>
実際の表示内容は計器の形式・契約メニューによって異なるため、計器の表示名称と取扱説明書を確認します。</p>

<h2>実量制と最大需要電力</h2>
<p>実量制では、過去の最大需要電力（デマンド実績）をもとに契約電力が決まる方式があります。</p>

<p>具体的な契約電力の決定方法は電力会社・契約種別によって異なるため、現在の契約条件を確認します。<br>
⇒<a href="keiyaku.php">契約電力の考え方</a><br>
⇒<a href="demand.php">デマンド値とは？</a></p>

