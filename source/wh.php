<h2>画面表示の例</h2>
<p>複合計器は一定時間ごとに表示項目が切り替わる機種があります。表示例：</p>
<ol>
    <li>全日有効電力量</li>
    <li>力測用有効電力量</li>
    <li>力測用無効電力量</li>
    <li>最大需要電力・現在需要電力</li>
    <li>検針時の有効電力量</li>
    <li>検針時の最大需要電力</li>
    <li>累積最大需要電力・力率</li>
</ol>
<p>表示順・名称は機種によって異なります。</p>

<h2>乗率とは？</h2>
<p><strong>乗率は、計器の表示値に掛けて実際の一次側電力量を求める倍率です。</strong></p>

<p>VT・CTを使用する場合は、変成比をもとに倍率を考えます。</p>

<p>例：</p>
<ul>
  <li>VT比：6600V / 110V = 60</li>
  <li>CT比：200A / 5A = 40</li>
  <li>合成変成比：60 × 40 = 2400</li>
</ul>

<p>計器側で100kWhを計量し、実際に適用する乗率が2400なら、一次側換算値は240,000kWhです。</p>

<p><strong>注意：</strong>実際の取引用計器では、計器定数や計器自身の倍率を含めた「表示乗率」が指定されている場合があります。現場では銘板・検定票・電力会社の資料に記載された乗率を優先します。</p>

<h2>合成変成比と乗率は同じ？</h2>
<p>VT比×CT比で求める合成変成比は、乗率を理解する基礎になりますが、<strong>実際に画面表示値へ掛ける乗率が必ず合成変成比そのものとは限りません。</strong></p>

<p>「表示値 × 何倍か」を確認したい場合は、計器の銘板・検定票・仕様書に記載された乗率を確認するのが確実です。</p>

<h2>電力量計の有効期限</h2>
