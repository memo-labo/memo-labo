<h2>電力量計（電力メーター）とは？</h2>

⇒<a href="https://www.fujielectric.co.jp/products/whm/container/doc/d1hukugoukeiki201307.pdf">SP3ER-R 取扱説明書</a><br>
電力を積算して計量する電気計器。<br>
電力を買ったり売ったりする際、その電力量を計算するために必要。<br><br>

全日とは？<br>
前回の検針日から今回の検針日までの合計<br><br>

実量制とは？<br>
契約電力を、メーターで計量した過去１年間の最大需要電力で決定する。<br>
実際に使用した１年間の実績をもとに決定。<br>
<br>
例<br>
・2021/04から開始<br>
・2021/04の最大需要電力68kw⇒68kWで契約<br>
・2021/05の最大需要電力75kw⇒75kWで契約<br>
・2022/06の契約電力⇒2021/07から2022/06の間の最大需要電力で契約<br><br>

FFとは<br>
forward factor（フォワードファクター）<br>
現状が遅れではなく「進み力率」であることを表示している。<br><br>

