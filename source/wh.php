<h2>乗率とは？</h2>
計量器の指示値に乗じて、使用電力量を算出するための倍率のこと。<br>
一般に、変成器付計器に使用される。<br><br>


<h2>合成変成比とは？</h2>

合成変成比<br>
VTとCTの変成比を掛け合わせたもの<br><br>

例<br>
VT比=6600v/110v=60<br>
CT比=200A/5A=40<br>
合成変成比（乗率）=60×40=2400<br><br>

VTとCTの２次側計器（電力量計）で読み取った値を2400倍すると一次側（実電力）がわかる<br><br>

例１<br>
電力量計の指示値=100kWh<br>
実際の電力量=100 kWh×2400=240000 kWh<br><br>

例２<br>
電力量計の表示値：1234.56<br>
乗率：240<br><br>

表示値×乗率<br>
＝表示値×24×10^1<br>
＝1234.56×24×10^1<br>
＝296294.4[kWh]<br>

