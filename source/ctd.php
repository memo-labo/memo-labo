<h2>CTDからVCBトリップコイル抵抗値を測定</h2>
CTDのDC+端子とDC-端子の配線の先には、VCBのトリップコイルがある。<br>
テスターでトリップコイルの抵抗値を測定したい場合、配線を外さずに測定できるか？<br>
CTD側の内部に高抵抗240kΩがある場合、トリップコイルと並列で測定しても、CTD側の影響は限りなく小さい。<br>
故にCTDのDC出力端子に配線が接続されたままで測定したとしてもトリップコイル抵抗値は測定可能と予想。<br>


<h2>CTDの事故・トラブル例</h2>
<ul>
<li>LEDランプが点灯していない。
<li>DC側に電圧が出ていない。
<li>リレー試験の際、AC側端子にAC電圧を印加しようとしたが、誤ってDC側に配線を取り付けてしまいAC印加でCTD故障。
<li>リレー試験の際、CTDのAC側上流にあるブレーカーを投入状態のまま、CTDのAC端子に電圧を印加しVTにて逆昇圧。
<li>4端子ではなく3端子式のCTDで、AC側とDC側の判別がつかず、DC側にAC電圧を印加してしまいCTDを破壊。
</ul>

<h2>CTDのトラブル対策</h2>
<ul>
<li>LEDランプが点灯していることを確認する。
<li>DC側に電圧が出力されているか確認する。（OCR連動試験等で確認可能？）
<li>CTDの端子に直接電圧を印加することは避け、その上流のMCCB２次側に印加。その際、線番を確認。
</ul>

