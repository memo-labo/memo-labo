コンデンサ引外し電源装置は、交流入力電圧を整流する。<br>
そしてコンデンサに充電し、コンデンサに電荷を溜めておく。<br>
VCBトリップコイルの回路が閉路するとコンデンサの電荷が放電される。<br>
そしてその直流電圧によってコイルが励磁され遮断器の引外し操作が行われる。<br>
CTDへの交流入力電圧は、VT２次側より配線されているのが一般的。<br><br>

バッテリーと比較して小形で軽量。<br>
瞬時停電で電源電圧が降下しても約60秒以内であれば確実に引外し電圧を保持。<br><br>

CTDはRPRやOVGRの制御電源用としても使用される場合もある。<br>
配線：VT2次側P1-P2⇒CTD AC入力⇒CTD DC出力⇒RPRやOVGRの制御電源端子。<br>

<h2>外観</h2>

例：KF-100E<br>
表面にはPOWERのLEDランプと放電スイッチボタンがある。<br>
AC1、AC2にAC100V電圧が印加されるとLEDランプが光る。<br>
放電スイッチを押すとコンデンサの電荷が放電用抵抗にて放電される。<br>
CTDの表面からヒューズの取替ができるタイプもある（光商工 LC-9）<br><br>

