<br>

PWM制御<br>
PWM = Pulse Width Modulation = パルス幅変調。<br>
半導体を使った電力を制御する方式の１つ。<br>
オンとオフの繰り返しスイッチングを行い、出力電力を制御。<br>
直流から交流へ変換し、電圧や周波数を自在に変えることができる。<br>
優れた制御性と高効率が特長。<br><br>

PWMの仕組み<br>
IGBT（Insulated Gate Bipolar Transistor）などのパワートランジスタをスイッチング。<br>
そのON/OFFの間隔を変えて、幅の異なるパルス波を作る。<br>
それらを合成し、疑似的な正弦波にする。<br><br>

PWM制御のオンの時間幅(デューティー)を周期的に変化させる。<br>
これでモーター駆動に最適な正弦波の交流電圧を作ることができる。<br>
パルスのduty比を変化させることでモータを制御する。<br><br>

duty比[%]=(H/T)×100<br><br>
T=周期<br>
H=High（オン）の時間<br><br>

インバータの出力電源はパルス状。<br>
パルスがモータコイルで平滑され、正弦波の電流が流れる。<br>
そのため汎用インバータの出力は、一般的にモータ以外には使用できない。<br><br>

