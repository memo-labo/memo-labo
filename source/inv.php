<h2>インバーターの役割</h2>

<li>モーターの回転速度を自由に制御する。
<li>モーターの回転数を変えることで、送風機の風量を細かく調整できる。
<li>必要な分だけモーターを回転させるため、消費電力を大幅に削減できて省エネ。
<li>ソフトスタート（モーターをゆっくり加速）できるため、始動電流が小さくなる。
<li>その結果、ベルトや軸受など機械への負担も軽減できる。
<li>停止時は、ゆっくり減速させられるため、急停止による衝撃や振動を抑えられる。
<li>過電流や過負荷、異常時に保護機能が働き、モーターの故障を防ぐことができる。

