<h2>インバータの原理（スイッチング）</h2>
<img src="images/inv4.png" style="max-width:800px;" /><br>
インバータ回路は直流を交流に変換する。<br>
スイッチ切り替えで負荷に流れる電流の方向が切り替わる。<br>
プラスとマイナスの電圧で出力され、交流電流を作りだす。<br>
また、交流を直流に変換することもできる。<br>
スイッチ切替で負荷に対して常に同じ方向に電流を流すことで交流⇒直流が可能。<br>



