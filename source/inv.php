<h2>注意点</h2>
インバータの線間メガーは禁止。<br>
インバータ内部にはIGBTやダイオード、コンデンサなどの半導体部品が入っており、出力端子間（線間）を測定するとそれらを破損する恐れがある。<br>
大地間がOKなのは、半導体部品に電圧が直接印加されるわけではなく、メーカーが許可している場合がある。<br><br>

インバータの出力側には進相用コンデンサやサージキラーを取り付けてはならない。<br>
インバータ故障やコンデンサ等の破損を引き起こす可能性。<br>
インバータの出力は商用電源のような正弦波ではなく高周波PWM（パルス幅変調）波形。<br>
高周波電流⇒SC異常発熱⇒SC破損⇒INV過電流・過電圧トリップ⇒INV故障。<br>


