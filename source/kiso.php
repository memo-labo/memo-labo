<h2>ゲタ基礎のデメリット</h2>
耐震性<br>
ブロックや鋼材の上に乗せているため、地震などの揺れに対する耐性が弱くなる。<br>
大きな地震が発生した場合、キュービクルが移動したり、倒れるリスクも。<br><br>

安定性<br>
設置面が不均一な場合や荷重の分散がうまくいかない場合、基礎が偏ったり沈下する場合も<br><br>

経年劣化<br>
ゲタ基礎に使用されるコンクリートブロックや鋼材の経年劣化。<br>
雨風、湿気、紫外線によるコンクリートのひび割れや鋼材の錆び。<br><br>

まとめ<br>
耐震性や安定性が求められる場合、堅固なコンクリート基礎の方が良いらしい<br>

