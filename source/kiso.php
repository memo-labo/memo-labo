■ゲタ基礎でキュービクルの位置を地上から1mほど高くする理由<br>
津波や河川・内水氾濫のハザード浸水高さを考慮している可能性。<br>
それと豪雪地帯ではキュービクルに高さがないと雪で埋まってしまうらしい。<br>
施工性の問題で、ケーブルの量や太さによって高さが変わる。<br>
太陽光などの低圧大電流が流れる極太ケーブルの施工は曲げ半径を考慮する必要あり。<br>
保守性を考慮してゲタ基礎を伸ばしたり鋼製架台を作って盤前1,000mm程度を確保する場合も。<br><br>

点検用キャットウォークが必要（横幅の広さ等は安衛則に記載がある）<br>
