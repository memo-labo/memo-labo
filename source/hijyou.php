<h2>非常用発電機（自家発電設備）の点検方法</h2>

点検に関する関係法令<br>
電気事業法、消防法、建築基準法の３つ<br>

<h2>電気事業法による点検</h2>
常用、非常用を問わず、事業用電気工作物としての適用を受ける自家発電設備について、保安規定に基づき、自家発電設備の点検等を行わなければならない。
また、設備の保安を確保するため、設置者には点検等の基準の作成等が義務付けられている。<br><br>

内燃力発電設備は出力10kW以上、ガスタービン発電設備では全てのもの。<br>
保安規定において、設置者自らが基準を定め、この基準に基づき点検等を行う。<br>


<h2>電気事業法に関する点検</h2>

点検内容としては月次と年次の２通りがある。<br><br>

月次点検<br>
月に１回、発電機及び励磁装置の外観に異常があるかどうかの確認。<br><br>

年次点検<br>
自動起動と自動停止装置の状態に異常はないか。<br>
個々の部品の接続箇所や地面との接地面・接続部分に緩みが発生していないか。<br>
内部蓄電池の漏れ、接続と絶縁抵抗値の測定、起動装置と停止装置の動作に異常がないか。<br>
５分間程度の空ぶかしによるエンジン試運転。<br><br>

電気事業法の対象範囲<br>
ディーゼルエンジンの場合、出力１０キロワット以上のタイプのみ<br>
ガスタービンエンジンの場合、出力に関係なく全ての発電機<br>

<h2>点検終了時はブレーカー・自動試験モードの位置を写真で残す</h2>

<p>低圧非常用発電機では、発電機本体のメインブレーカー、自動・試験などのモード切替、制御盤内の小ブレーカーなど、非常時の動作に関係するスイッチや遮断器が複数ある。</p>

<p>これらを操作するのは保安管理を行う側だけとは限らない。非常用発電機の専門点検業者や出入りの保守業者が、試運転や点検のために自動試験モードへ切り替えたり、メインブレーカーをON・OFFしたり、制御盤内のブレーカーを操作することもある。</p>

<div class="article-warning">
<span class="article-warning-title">⚠ 復旧忘れに注意</span>
点検や試験のために位置を変更したあと、所定の状態へ戻さないまま作業を終了すると、次の月次点検・年次点検時には前回確認した位置と異なっていることがある。<br><br>
例えば、非常電源を必要とする防災設備へ電力を供給する構成で発電機のメインブレーカーがOFFのままになっていれば、火災や停電時に発電機が始動しても必要な負荷へ電力を供給できない可能性がある。スプリンクラー設備などの防災設備が非常電源に依存する構成では、本来期待した防災機能が働かない重大な状態につながり得る。
</div>

<p>ただし、メインブレーカーや各切替スイッチの「正常な位置」は設備構成や機種によって異なる。ONにすればよい、自動位置にすればよい、と一律に判断せず、メーカー取扱説明書、制御回路図、設備の運用手順、現場の管理基準に従って復旧状態を確認する。</p>

<h3>なぜ写真を残した方がいいのか</h3>

<p>あとから別の業者が設備を操作し、復旧忘れなどのトラブルが発生した場合、「いつ、誰が、どの状態にしたのか」が問題になることがある。</p>

<p>こちらが月次点検・年次点検を終えた時点で正常な状態へ復旧したとしても、その記録がなければ、後日状態が変わっていた際に当時の状況を説明しづらい。責任の所在は契約内容や作業記録、実際の操作状況などによって判断されるものだが、点検終了時の写真は少なくとも「その時点でどの位置だったか」を示す客観的な記録になる。</p>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：点検の最後に写真を撮る</span>
手間ではあるが、月次点検・年次点検の最後に、次のような箇所を写真で残しておくとよい。<br>
・非常用発電機のメインブレーカー位置<br>
・自動／手動／試験などのモード切替位置<br>
・制御盤内の小ブレーカーの状態<br>
・警報表示や状態表示灯など、復旧状態を判断できる表示<br><br>
写真は故障診断の資料になるだけでなく、点検終了時の状態を証明する記録としても役に立つ。
</div>

<p>特に複数の保守会社や設備業者が出入りする現場では、「前回見たときはこの位置だった」という記憶だけに頼らず、写真と点検記録をセットで残しておく方が安全管理上もトラブル対応上も強い。</p>

<h2>据置鉛蓄電池の点検</h2>
自家発電機の始動用バッテリーとして、鉛蓄電池が使用されている。<br>
まず最初に、据置鉛蓄電池は、ベント式か、制御弁式かをチェックする。<br>
ベント式据置鉛蓄電池は、蓄電池の中に電解液（希硫酸）が入っており、これは時間とともに気化して量が減る。<br>
なので、様子を見ながら定期的に精製水を補充していく必要がある。<br>
電槽（蓄電池の容器）の色が透明で、電解液の減り具合を見ることが出来るようになっている。<br>
電槽には、蓄電池に適切な電解液量が入っているか確認するための目印（上限、下限）がある。<br>
この目印の中間を超える電解液が入っていれば、適切な量と言える。<br>

