<h2>なぜ接地抵抗測定は交流なのか？</h2>

もし直流で測定したら？<br>
電気分解による分極作用が起こる。<br>
電極に電食が起こるため測定値に誤差が生じる。<br>
異種類のアース極による電池の生成の影響がある。<br><br>

土には水分や塩分などの不純物が含まれている。<br>
そこに直流電圧をかけると、電気分解が起こる。<br>
電極で水素や酸素や塩素の泡が発生（分極）し、最初は電流が流れていても、徐々に電流が流れにくくなる。<br>
時間の経過と共に、接地の抵抗値が変化してしまう結果となる。<br><br>

また、実際のアースは、鉄、炭素棒、亜鉛メッキ板など、いろいろある。<br>
電極が異なる種の材料の場合、それだけで電池を生成してしまう。<br><br>

電池が生成されると、直流電圧を加えてないのに、生成された電池だけで電流が流れてしまう。<br>
なので、測定で加えた直流電圧の向きによって、電流値が異なってしまう。<br>


<h2>補助極接地抵抗Rc・Rpについて</h2>

JIS規格（JIS C 1304）<br>
低圧配電系統において使用する交流電圧を用いた接地抵抗計についての規定<br>
2012年に廃止「JISの使用頻度が少なく国家標準としての意義が薄れたため」<br>
JIS規格に従い補助助接地極の名前をP（ポテンシャル、電位極）C（カレント、電流極）と呼んでいた。<br>
IEC61557-5の規定で補助接地極をS、Hと呼んでいるため、各メーカーも S(P)、C(H)、などのように表記している。<br><br>

※どうやらドイツ語らしい<br>
E：Erder（接地）<br>
S：Sonde（プローブ）<br>
H：Hilfserder（補助接地）<br><br>


<img src="images/setti.png" style="max-width:500px;"><br />
メーカーにもよるが、約1kΩ～10kΩ程度であれば測定可能<br />
標準測定状態：Rc・Rp=500Ω程度<br />
E接地極、P電位極、C電流は直列に、それぞれ5m～10m程度の距離をとる。<br />
P・Cは、10m以上離れていても大丈夫。<br />
E-C間に電圧をかけて電流を流し、そこから接地抵抗を割り出すが、E-C間だけだと、EとCの２つの接地抵抗を測ってしまう。<br />
なので電位極Pを中間に打ち込み、E-P間の電圧を測定する。<br />
E-C間の電流と、E-P間の電圧から、Eの接地抵抗が測定できる。<br />
Pにも接地抵抗があるが、電圧計の内部抵抗が大きいので、Pには電流がほとんど流れず無視できる。<br />
Pの位置は、EとCの直線上が好ましいが、30°程度までは許容できるとされている｡<br />
