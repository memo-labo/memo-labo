<h2>高圧受電設備のA種接地抵抗測定についての疑問</h2>
A種接地抵抗の測定をする際、極側と機器側を切り離し、極側だけを測ったほうがいいのか？<br />
それとも、極側と機器側を繋げた状態で測ってしまっても良いのか？<br /><br />

変圧器やVCBなど、高圧受電設備機器等の接地抵抗が極側と並列で合算された数値となる。<br />
なので、機器の移動や取り外しがあると、機器分が除外され、値が大きくなる可能性がある。<br />
ただし、機器の移動や増減設が起こり得ない事業場であれば、一括測定でも問題ないと考える。<br />
町工場や鉄工所など、機器の移動や変更の多いところは要注意。<br /><br />

<h2>A種・B種は極単体、C種・D種は機器側で接地抵抗が規定以上ならばOK？</h2>
とある方の意見では、電技解釈17条によると、<br />
A・B種は、接地極単体での接地抵抗値を規程している。<br />
C・D種は、機器の方で接地抵抗値が規定値範囲内であれば、接地極は無くてもいい。<br />
このような違いがある、とのこと。<br />

<h2>A種とB種の接地抵抗が異様に低かった。なぜか？</h2>
鉄筋コンクリート構造の建物や、鉄骨造りの建物の近くに変電設備がある場合、そのようなこともありえる。<br />
建物の基礎掘削により、接地極だけでは得られないような、深層土壌の影響を受けることもある。<br />
土壌が、砂礫層でなく粘土質だと、接地抵抗は低くなる傾向にある。<br />
接地棒を埋めるのでなく、建物の基礎鉄筋を接地極にしていた場合、1Ω以下になることもあり得る。<br />


<h2>等電位ボンディングとは？</h2>
雷サージとは、落雷により電源線や電話線又は水道管やガス管等に発生する非常に大きな過渡的な過電圧のことで、その大きさは数kVから十数kVに達する。<br />
これらの電圧が線又は管を伝わって室内に侵入すると、火花放電による火事を発生させたり、電気機器を絶縁破壊により破損させたりする。<br />
この対策として「等電位化」という対策がある。<br />
これは、建物の構造体接地極等を電気的に接続し、水道管や窓枠金属部分など、系統外導電性部分も含め、人が触れるおそれがある範囲にある全ての導電性部分を、共用の接地極に接続して等電位を形成する。<br />
これにより、金属部分から伝わってきたサージはすべて大地に放流され、接地と同電位（等電位）になり、火花放電や絶縁破壊の発生はなくなる。<br />
