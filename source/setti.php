<h2>接地端子盤に補助極 PとCを用意する理由</h2>
まず接地抵抗の測定には２つの補助極が必要（理由は上記）<br>
停電点検の際、その補助極を使用して、作業を簡単に、また正確な値を測定するために必要。<br>
もし補助極がなければ、地中に金属棒を埋め込み、補助極を用意しなければならない。<br>
周囲の地面が土などであれば良いが、アスファルトやビル屋上であった場合、補助極の用意が困難。<br>


<h2>接地抵抗の種類</h2>

■A種接地<br />
