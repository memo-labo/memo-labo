<h2>サビで接地が測定不可</h2>
補助極PとCの値は出るのに、Eの値が出ない。<br>
この場合、Eを接続したポイントにサビが発生している可能性あり。<br>
接地端子盤やキュービクルの平べったい金属バーなど緑青にて抵抗増。<br>
サビがない別の接続点を探し、再度計測してみる。<br>

