<h2>接地抵抗測定の原理</h2>
<img src="images/setti1.svg" style="max-width:600px;" /><br>
接地極EとCの間に交流電源を設置して、電流Iを流す。<br>
接地極EとCの電圧降下は曲線となり、その中間の電圧降下はほぼ一定となる。<br>
接地極Eの接地抵抗R = V(EP) ÷ I [Ω]で求められる。<br>

<h2>接地抵抗測定のミス・失敗・方法</h2>

B種接地極を測定したら、0Ωであった。<br>
補助極のPをB種接地極に接続して測定していた。<br>
EとPの電圧が0VなのでR=0÷IなのでR=0<br><br>

補助極Cが地面と接続されていなかった。<br>
この場合、電流Iが流れず接地抵抗測定不可。<br><br>

