キュービクル躯体、PAS躯体、避雷器、Tr躯体、VCB躯体、LBS躯体などに設置する。<br />
10Ω以下を確保するように接地極を埋設する。<br />
接地線の接地抵抗が小さければ、人体側に分流する電流も少なくなるため、感電時の被害が低減できる。<br /><br />

■B種接地<br />
高圧と低圧を変成する変圧器の低圧側１線に施す接地工事。<br />
