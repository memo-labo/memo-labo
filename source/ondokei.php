<h2>放射温度計の仕組み</h2>
物体は分子内振動により、表面から赤外線を放射している。<br>
物体表面の温度は赤外線の量によって決まる。<br>
赤外線は空間を伝ってエネルギーを運ぶという特徴がある。<br>
この空間を伝ってきた赤外線を光学的に読み取り温度を測定する。<br><br>

