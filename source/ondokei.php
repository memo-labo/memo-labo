ケーブルの支持部、結束部を中心に当てる。<br>
ブレーカー端子部、分電盤、低圧コンデンサ表面温度などを測定。<br>
日常的な自主保安で発熱異常に気が付き、大規模な火災事故を防げるかもしれない。<br>
ブレーカー端子部の異常発熱など細かい部分はなかなか気が付けない。<br><br>

