<h2>空けた穴を封する方法</h2>

ネジに接着剤をつけてネジ止めする。<br>
またはネジにゴムパッキンをハメてネジ止め（コチラの方が簡単？）<br><br>

樹脂・ゴムワッシャー<br>
ボルトやナットを締結する際、ボルトやナットの座面と相手材の間に入れる。<br>
締結時おける相手材への損傷や、電気的な絶縁などのために使用。<br><br>

ゴムパッキンでネジ止めした上から接着剤を塗るとさらに良い。<br>

