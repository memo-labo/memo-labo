<h2>なぜメーカーで角度が違って見える？</h2>

<p>DGRは零相電圧V0と零相電流I0の位相関係から、事故が需要家側か電源側かを判定します。</p>

<p>ところが、位相角の基準方向、進み・遅れの表記、内部の基準位相などは機種によって表現方法が異なります。そのため、<strong>「30°だから別メーカーの30°と同じ特性」とは限りません。</strong></p>

<p>交換工事では旧継電器の整定値をそのまま新機種へ写すのではなく、新旧機種の位相特性・動作範囲・系統接地方式を照合します。</p>

<h2>PC接地方式とは？</h2>

<p>PC接地方式は、ペテルゼンコイル（消弧リアクトル）を用いて、1線地絡時の容量性地絡電流を補償する接地方式です。</p>

<p>非接地系とは地絡時の零相電流の位相関係が変わるため、DGR側にもPC接地系に対応した位相設定が必要になる場合があります。</p>

<p>配電線に分散リアクトルなどが設置されている場合も、系統の零相電流特性が変化します。</p>

<h2>整定を決めるときの確認事項</h2>

<ul>
  <li>電力会社側の配電系統が非接地系かPC接地系か</li>
  <li>対象DGR・SOGのメーカーと正確な型式</li>
  <li>メーカー資料に示された最大感度位相角と動作位相範囲</li>
  <li>電力会社から指定されている整定条件がないか</li>
  <li>既設機器から更新する場合、新旧で位相角の定義が同じか</li>
</ul>

<p><strong>系統の接地方式が不明なまま、他現場や他メーカーの整定値を流用しない</strong>ようにします。必要に応じて管轄の一般送配電事業者へ確認します。</p>

