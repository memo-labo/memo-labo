<h2>PC接地系・進み成分が多い系統のDGR位相設定</h2>

<p>DGR（地絡方向継電器）の最大感度位相角は、配電系統の接地方式や対地静電容量だけでなく、<strong>継電器メーカー・機種ごとの位相角の定義</strong>によって表示値が異なります。</p>

<p>そのため、ある機種が45°、別の機種が30°だからといって、単純にどちらかが間違いとは判断できません。<strong>異なるメーカーの整定角を数字だけで直接比較しない</strong>ことが重要です。</p>

<h2>メーカー別の整定例</h2>

<p>以下は各機種のメーカー資料に基づく例です。実際の整定は対象機種の取扱説明書を優先します。</p>

<h3>富士電機 QHA-DG3</h3>

<ul>
  <li>非接地系・標準：45°</li>
  <li>非接地系・進み成分が多い場合：60°</li>
  <li>PC接地系・標準：20°</li>
  <li>PC接地系・進み成分が多い場合：30°</li>
</ul>

<p>製品例：<a href="qha-dg.php">富士電機 QHA-DG3 / QHA-DG4</a></p>

