<h2>ブレーカーの赤いプラスチックの固定アイテム</h2>
<img src="images/mccb21.jpg" style="max-width:200px;" alt=""><br>
ハンドルロックと呼ばれる。<br>
MCCBの操作部分をロックしてＯＮ状態に固定できる。<br>
MCCBの切操作を禁止（操作禁止用）として。<br><br>

トリップフリー（引きはずし自由）とは？<br>
遮断器をハンドルロックでＯＮ位置に拘束した状態でも過電流が流れると引きはずし動作（トリップ）する機能。<br>
これはJIS規格で定められているらしい。<br><br>

<h2>ロックアウトとは？</h2>
ブレーカーをOFF状態で固定し、操作禁止状態にする。<br>
ブレーカーのスイッチ部に挟み込み、南京錠でロックすることでスイッチ入力を防止。<br>
