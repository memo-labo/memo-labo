<h2>ブレーカーのハンドルロックとは？</h2>

<img src="images/mccb21.jpg" style="max-width:200px;" alt="ブレーカーのハンドルロック"><br>

<p>ブレーカーの操作ハンドルを所定の位置で固定するための部品です。メーカーによって「ハンドルロック」「ハンドルホルダ」など名称が異なります。</p>

<p>用途は、設備上の誤操作防止や、特定回路の操作状態を維持することです。</p>

<h2>ON位置で固定しても保護機能は働く？</h2>

<p>トリップフリー構造の遮断器では、ハンドルをON位置に保持していても、過電流などの引き外し条件が成立すると内部機構が動作して遮断します。</p>

<p><strong>ただし、すべての機種・付属品について同じ扱いとは限らないため、使用しているMCCB・ELBの取扱説明書とメーカー指定のハンドルロックを確認します。</strong></p>

<h2>ハンドルロックとロックアウトの違い</h2>

<p>見た目は似ていますが、目的が違います。</p>

<ul>
  <li><strong>ハンドルロック</strong>：設備上の誤操作防止や操作位置の保持に使う</li>
  <li><strong>ロックアウト</strong>：保守作業中などに、第三者が勝手に再投入できないようOFF状態で施錠する</li>
</ul>

<h2>ロックアウトとは？</h2>

<p>ブレーカーをOFF状態で固定し、南京錠などを使用して不用意な再投入を防止する方法です。</p>

<img src="images/lock1.jpg" style="max-width:200px;" alt="ブレーカーのロックアウト器具"><br>

<p>保守・点検で停電状態を確保するときは、単にハンドルをOFFにするだけでなく、作業手順に応じてロックアウト、表示、検電、残留電荷の確認などを組み合わせます。</p>

<h2>注意点</h2>

<ul>
  <li>ON位置の固定具を、保守作業時の安全確保用ロックアウトの代わりにしない</li>
  <li>遮断器と適合するメーカー指定品を使用する</li>
  <li>ロックアウト後も無電圧を確認してから作業する</li>
  <li>復電時は作業者・工具・接地・短絡器具などの撤去を確認してから解除する</li>
</ul>

