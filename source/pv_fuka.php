<h2>太陽光の使用前自己確認「負荷試験」</h2>

参考：<a href="https://www.hioki.co.jp/file/cmw/userguides/4741/pdf/?action=browser&log=0&lang=jp">HIOKI 太陽光使⽤前⾃⼰確認の⽅法 負荷試験</a><br><br>

発電設備を可能な限り定格出力、定格電圧、定格力率に保持する。<br>
機器各部の温度上昇が飽和状態になるまで連続運転させる。<br>
その状態で高調波（電圧歪率または電流歪率）を確認する。<br><br>

判定基準例<br>
・電圧総合⾼調波歪率 6.6kV配電系統で5%、特別⾼圧系統で3%<br>
・⾼調波抑制対策ガイドラインにおける各次数の⾼調波流出電流上限値<br>
・測定した⾼調波の最⼤値で判定基準を満たすかを確認<br><br>

6.6kV系統<br>
・5次︓3.5mA<br>
・７次︓2.5mA<br>
・11次︓1.6mA<br>
・13次︓1.3mA<br>
・17次︓1.0mA<br>
・19次︓0.9mA<br>
・23次︓0.76mA<br>
・23次超︓0.70mA（契約電⼒1kW当たりの値）<br><br>

