<h2>残留電荷の放電時間を計算</h2>

1MΩの放電抵抗棒により電圧が30Vに低下するまでに要する時間を計算<br>
<img src="images/houden1.png" style="max-width:500px;"><br><br>

E=440V<br>
C=400μF<br>
Vc=440V<br>
R=1MΩ<br><br>

定抵抗（負荷）放電の場合<br>
t = C × R × ln (E ÷ Vc)<br>
C:コンデンサ容量(F)<br>
R:放電抵抗(Ω)<br>
E:充電電圧(V)<br>
Vc:放電後電圧(V)<br><br>

コンデンサに440V充電<br>
1MΩの放電抵抗棒で電圧が30Vに低下<br>
t = C * R * log(440v ÷ 30v) ≒ 1073秒 ≒ 18分<br>

