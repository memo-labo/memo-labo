<h2>コンデンサと放電時間</h2>

高圧進相コンデンサー<br>
変圧器などの巻線によって直流的に短絡状態⇒電荷はすぐに中和<br>
放電抵抗が並列に接続されており、すぐに放電⇒残留電荷は消滅<br>
なので接地線を付けてもほとんど火花は出ない<br><br>

高圧進相コンデンサの内部放電抵抗で5分以内に50V以下まで放電<br>
⇒<a href="rc.php">高圧進相コンデンサの内部放電抵抗</a><br><br>


低圧回路の負荷設備の力率改善用の進相コンデンサー<br>
放電抵抗が接続されていない<br>
放電抵抗接地棒を使用して接地させても静電容量が大きい関係で、電圧が減衰するのに時間がかかる<br><br>


放電抵抗接地棒<br>
