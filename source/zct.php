二次端子（kとl）<br>
試験用端子（ktとlt）<br><br>

ZCTTとは？<br>
ZCT（零相変流器）の試験用端子のこと。<br>
配線の名称は一般的にktとltで表記される。<br>
KtとLtに対して電流を流すことで、ZCTの穴に配線を通し電流を流すことと同義になる。<br>
GR、DGR、ELRなどの保護継電器の試験をする際によく見かける。<br><br>

受電盤の場合、KがUGSやPAS側（電源側）で、LがVCBやLBS側（負荷側）<br>
下から上へのケーブル立ち上がりの場合、ZCTの下面がK、上面がL。<br><br>

<h2>GR試験の際の注意</h2>

配線<br>
GRのZ1⇒ZCTのk<br>
GRのZ2⇒ZCTのl<br>
盤のKt端子⇒ZCTのKt<br>
盤のLt端子⇒ZCTのLt<br>

<img src="images/zct-kl.jpg" style="max-width:300px;"><br>

注意<br>
試験電流はKtとLtに流す。<br>
ZCTのkとlに対して流してはいけない。<br>
GRのZ1Z2に過大な電流が流れGR本体が壊れる。<br>

<h2>ZCTの選定</h2>
適用規格　JEC-1201-2007<br><br>

定格零相一次電流：200mA<br>
定格零相二次電流：1.5mA<br><br>

窓径：定格一次電流（A）<br>
60mm 300A<br>
90mm 600A<br>
110mm 1000A<br>
170mm 1200A<br>
周波数：50/60Hz両用<br>
確度階級：L級（零相電流検出用）<br><br>

ZCTの励磁インピーダンスは二次配線などの誘導・零相電流特性にも影響する。<br>
なので大きい程良く、JEC規格では5Ω以上又は10Ω以上をL級として規定している。<br>
重要回路では 20Ω以上のH級を採用する場合もある。<br>
標準は >10Ω である。<br>


