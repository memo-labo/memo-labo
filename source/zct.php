<h2>ZCT 零相変流器</h2>

<img src="images/zct1.jpg" style="max-width:200px;"><br>

３相分の配線を一括でZCTの穴に通して電流を流す。<br>
対称な３相交流である３相の電流は120°ずつ位相がずれている。<br>
健全な状態では各相のベクトルを合成すると打ち消し合ってゼロになる。<br><br>

しかし３相のうち１相が絶縁不良等で地絡を起こすと地面に電流が流れる。<br>
地面に流れた電流は健全相の電線の「対地静電容量」で健全相に電流が流れ込む。<br>
健全相に流れ込んだ電流は変圧器１次巻線を通過した後、地絡相の地絡事故点に向かって流れる。<br>
一線地絡が発生した場合、このようなループで地絡電流は流れ続ける。<br><br>

この状態は、３相の電流が不均衡状態であり、合成してもゼロにならない。<br>
この不均衡状態をZCTのにより検知し、ZCT２次側端子（k,l）から出力する。<br><br>

ZCTの中身はドーナツ状の鉄心と、それにぐるぐる巻にされたコイル。<br>
不均衡電流が鉄心を通過すると磁束Φを発生、これが鉄心（磁気コア）にΦ'として誘導される。<br>
磁気コアのΦ'はコイル巻線に起電力を与える。<br>
コイル巻線の先はZCTの２次側、kとlにつながっており、ここに電圧が発生する。<br>
（※ZCTを不使用の場合、kとlに電圧を発生させないため、電線で短絡させた方が良い？）<br><br>

