<h2>波及事故とは？</h2>

自家用電気工作物の事故等により電力会社の配電線のフィーダを停電させ、<br>
同一のフィーダに接続されている他の電気使用者への電力供給ができなくなる事故のこと。

<h2>波及事故を発生させた場合の対応・義務</h2>

■速報<br>
事故の発生を知ったときから24時間以内<br>
所轄の産業保安監督部に事故発生を電話等で報告。<br><br>

■詳報<br>
発生を知った日から起算して 30 日以内<br>
電気事故報告書を文書で提出。<br><br>

電気事故報告規則<br>
波及事故、電気火災事故、感電等による死傷事故、<br>
主要機器等の損壊事故などが電気事故報告の対象。<br>


<h2>波及事故の主な原因</h2>

波及事故の90%が、主遮断装置の電源側から発生している。<br>
構内１号柱または地中引込用開閉器から主遮断装置の間のケーブル、または主遮断装置本体など。<br><br>

