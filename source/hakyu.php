■波及事故の例<br>
モールドジスコン２次側からVCB１次側の高圧CVケーブルの劣化による地絡事故<br>
PAS２次側からVCB１次側の高圧CVケーブルの劣化による地絡事故<br>
VCBやOCBの主遮断装置の劣化による相間短絡事故<br>
PAS内部の劣化によりSOG制御装置が働かない事による波及事故<br>
PAS内部の劣化によるPAS１次側での相間短絡 or 地絡事故<br>


<h2>波及事故になる可能性の高い設備</h2>

■責任分界点の区分開閉器に<a href="mds.php">モールドジスコン</a>、<a href="pds.php">ピラージスコン</a>を使用。<br>
受電盤までの引き込みケーブル中で地絡や短絡が発生しても無保護状態なので即波及事故。<br><br>

■<a href="pgs.php">PGS（高圧ガス開閉器）</a>を使用。<br>
PGSは長年の使用でPGS内のガス圧が低下する可能性。<br>
ガスで消弧ができない状態（大気状態）で遮断すると、開放する際に発生するアークを消弧できない。<br>
極間にアークが発生し、相間短絡（三相短絡）に至る可能性。<br><br>

波及事故を防ぐ方法<br>
モールドジスコンやピラージスコンの場合、すぐにUGSに交換する。<br>
耐用年数を大幅に過ぎた設備は、区分開閉器、主遮断装置、CVケーブルなど優先的に交換する。<br><br>

