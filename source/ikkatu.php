<h2>メモ</h2>
分譲マンションの場合、高圧受電～配電盤までが管理組合所有（区分所有）<br>
マンション住人から管理費の徴収が適切に行われないと、後の高圧受電設備更新費用が心配。<br>
マンションは共用部を含めて夜間も電力を使用するので年間負荷率は高い。<br>
