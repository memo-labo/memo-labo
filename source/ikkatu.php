<h2>借室電気室</h2>
電気の需要家から提供された場所（借室）に電力会社が所有する変電設備を設置。<br>
マンション構内に電力を供給する配電方式のこと。<br>
50kVAを超え2000kVA以下の集合住宅などの需要家に適用される。<br>
一般に設置場所は需要家から無償で提供される。<br><br>

一般用電気工作物となる場合、電力会社が電気の保安責任を持つ。<br>
なので電気室の管理は電力会社が行う。<br>
需要家は電力会社係員の立会いなしの入室が禁止される。<br>
変電設備（借室）には高圧から低圧への変圧器・電力ヒューズなどが設置される。<br>

<h2>一括受電マンションのデメリット</h2>
既存マンションに導入する場合は工事が必要。マンション全体で停電が発生。<br>
サービス導入後、停電点検のため、年１回（または３年に１回）の停電が発生。<br>
地絡や短絡事故が起きた場合、事故原因を取り除き復旧作業完了まで停電状態。<br>
電力全面自由化であるが、住人個人単位では他の電力会社に乗り替え不可能。<br>
波及事故にでもなれば管理組合理事長の責任となる。<br>
東電受電に比べ、マンション管理側の責任や手間が大きい。<br>

<h2>低圧受電</h2>
１つの建物に対して１系統の引込みが基本。<br>
電力の契約容量が50kVA未満が低圧引込み、50kVA以上が高圧引込み。<br><br>

例外として「低圧弾力供給」というものがある。<br>
これは、一つの建物に対し複数系統に分けて電力を引込むことができる。<br>
その各系統の契約容量を50kVA未満とすることで建物全体を低圧引込みにできる。<br>
低圧弾力供給協議事前確認票の提出が必要。<br><br>

<h2>低圧受電マンションの配線例</h2>
パターン１<br>
・電柱から幹線でマンションに引込み<br>
・ブレーカーなしで各住戸までケーブル分岐<br>
・各住戸の電力メーター<br>
・各住戸の分電盤<br><br>

パターン２（団地）<br>
・低圧幹線引込<br>
・上位ブレーカーあり<br>
・各住戸の電力メーター<br>
・各住戸の分電盤<br>

