<h2>マンションの電気</h2>

戸建てとマンションは、電力供給の仕組みが異なる。<br>
マンションは多くの世帯があり、エレベーターや給水ポンプなどの共用の動力設備がある。<br>
一度に大量の電力を使用することがある。<br><br>

戸建ての場合<br>
送電線からの高圧電力を電柱にある柱上変圧器で低圧にして引込線にて屋内に引き込む。<br><br>

小規模なマンションの場合<br>
各戸の契約電力と共用部の契約電力の合計が50kw未満の場合。<br>
柱上変圧器で低圧電力に変圧された後、電灯用幹線と動力用幹線の２系統をマンション内に引き込む。<br>
電灯用は、引込開閉器盤を通った後、共用部と専有部（住居部）に分かれる。<br>

