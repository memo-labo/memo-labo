<h2>塩害（えんがい）とは？</h2>

塩害（えんがい）<br>
塩分が原因で、植物や各種建築物・構造物への、害の総称のこと。<br>
特に海岸近くでは海水に含まれる塩分により種々の塩害が生じる。<br><br>

塩分を含んだ潮風が吹き付ける。<br>
通常は海岸から数kmまでの地域で生じる。<br>
しかし台風の強風で海岸から遠く離れた内陸部まで被害が及ぶ場合もある。<br>
塩害は海だけでなく塩湖周辺でも起きる。<br><br>

塩害の例<br>
キュービクルや分電盤の金属が錆びて穴が開き中に湿気が入る。<br>
コンデンサやリアクトルの金属部分が錆びて穴が開き油が外に漏れる。<br><br>

なぜ塩は金属を錆びさせるのか？<br>
さびの発生を促進するものは、①酸素、②水分、③塩（塩化ナトリウム）<br>
塩分は吸湿性が高く、大気中の水分を吸う。<br>
金属に塩が付着すると、その塩が水分を吸収し、この水分が金属のさびを進める。<br>
さびは水に金属のイオンが溶け出すことで発生する。<br>
さびを防ぐためには保護対象物を酸素と水から遮断する。<br>


