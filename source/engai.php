<h2>ネット上のクチコミ・評価</h2>

・ステンレスは意外に錆びる。<br>
・メンテナンスを怠るとsusでも錆びる。とくにsus303だと尚更。<br>
・使用年数が長いなら溶融亜鉛メッキもあり。<br>
・数年程度ならsus盤に下地処理+上塗り塗装を計画的に施工した方が安上がりかも。<br>
・亜鉛メッキのドブづけは外注になるので運搬費もかかり値段も高くなる。<br>
・内線規程に抽象的に書いてあるらしい（塩害地域は勧告、おそれのある場所は推奨）<br>
<br>
SUS303とは？<br>
オーステナイト系ステンレスの一種。<br>
代表的なオーステナイト系ステンレスであるSUS304に硫黄やリンを添加してつくられる。<br>
SUS303は硫黄やリンの添加で粘り気が減って加工性や切削性に優れる<br>
耐焼付性が良好で摩擦による凝着が少ない。<br>

