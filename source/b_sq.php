変圧器一相分の容量とは？<br>
単相３線式100/200Vと三相３線式200Vは、200V級を参照<br>
三相変圧器の場合、定格容量の1/3の容量<br><br>

単相変圧器Ｖ結線の場合<br>
・同じ容量のＶ結線の場合、単相変圧器の１台分の定格容量<br>
・違う容量のＶ結線の場合、大きい容量の単相変圧器の定格容量<br>

