<h2>300kVA・三相200Vの例</h2>
三相3線式200V、300kVA変圧器の場合。<br><br>

三相変圧器なので、変圧器1相分の容量は、<br>
300kVA ÷ 3 = 100kVA<br><br>

200V級の表を見ると、125kVA以下の欄に該当するため、接地線は38mm²以上となる。<br><br>

ここで「300kVAだから60mm²では？」と迷いやすいが、表では変圧器全体の300kVAではなく、三相変圧器なら1/3した100kVAで見る。<br>

<h2>0.052×Inで確認する方法</h2>
接地線の熱的強度から、次の式で確認する方法がある。<br><br>

<strong>A = 0.052 × In</strong><br><br>

A：銅接地線の断面積［mm²］<br>
In：低圧側を保護する過電流遮断器の定格電流［A］<br><br>

この式は「変圧器二次側の定格電流をそのまま入れる式」と考えるより、低圧側の過電流遮断器を基準に接地線の熱的強度を確認する式として考える方が分かりやすい。<br><br>

例えば低圧側主遮断器が800Aの場合、<br>
800 × 0.052 = 41.6mm²<br><br>

標準サイズでは直近上位の60mm²を選ぶ。<br><br>

この場合、<br>
・変圧器容量から表で選定：38mm²<br>
・800A遮断器から計算：60mm²<br>
となるため、60mm²を採用する考え方になる。<br>

<h2>なぜ表と0.052式でサイズが違うことがある？</h2>
表は「変圧器1相分の容量」を基準にした選定方法。<br>
一方、0.052式は過電流遮断器の定格電流を基準に、短時間に流れる故障電流に対する接地線の熱的強度を確認する考え方。<br><br>

そのため、同じ設備でも両者の結果が一致しないことがある。<br>
表だけ見て終わりにせず、低圧側の主遮断器容量も確認する。<br>

