<h2>B種接地工事とは</h2>
B種接地工事は、高圧または特別高圧電路と低圧電路を結合する変圧器で、混触事故が発生したときに低圧電路側の電位上昇を抑えるために行う接地工事。<br>
一般的には、変圧器低圧側の中性点に施す。低圧電路の使用電圧が300V以下で中性点への接地が難しい場合は、低圧側の一端子に接地する場合もある。<br><br>

B種接地では、<br>
・接地抵抗値<br>
・接地線の太さ<br>
を分けて考える。<br>
このページでは主に「接地線の太さ」について整理する。<br>

<h2>B種接地線の太さを決める方法</h2>
実務では、まず「変圧器1相分の容量」から表で接地線サイズを選定し、必要に応じて低圧側の過電流遮断器の定格電流から計算したサイズも確認する。<br><br>

表から選定した接地線より、過電流遮断器を基準に計算した接地線の方が太くなる場合は、太い方を採用する。<br>

