<h2>B種接地抵抗値は接地線サイズとは別</h2>
B種接地工事では、接地線を太くすればそれで完了というわけではない。<br>
接地抵抗値は、高圧側または特別高圧側の1線地絡電流 Ig と、混触時の自動遮断時間によって決まる。<br><br>

代表的には、<br>
・通常：150 / Ig［Ω］以下<br>
・1秒を超え2秒以内に自動遮断：300 / Ig［Ω］以下<br>
・1秒以内に自動遮断：600 / Ig［Ω］以下<br>
という考え方。<br><br>

つまり、<strong>接地線サイズの選定</strong>と<strong>必要な接地抵抗値</strong>は別々に確認する必要がある。<br>

<h2>現場で確認するポイント</h2>
・変圧器の相数、容量、二次電圧<br>
・三相変圧器なら「1相分＝定格容量÷3」で表を見る<br>
・単相3線式100/200Vは200V級で見る<br>
・V結線では各変圧器容量を確認する<br>
・低圧側主遮断器の定格電流も確認する<br>
・表選定値と遮断器基準の計算値を比較し、細い方を安易に採用しない<br>
・B種接地抵抗値は別途、1線地絡電流と遮断時間から確認する<br>
・設計仕様書、内線規程、公共建築工事標準仕様書など、採用している基準がある場合はその基準を優先する<br>

