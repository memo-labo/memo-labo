<h3>「変圧器1相分の容量」とは</h3>
・三相変圧器の場合：定格容量の1/3<br>
・単相3線式100/200V：200V級を適用<br>
・単相変圧器を同容量でΔ結線またはY結線：単相変圧器1台分の定格容量<br>
・単相変圧器を同容量でV結線：単相変圧器1台分の定格容量<br>
・異容量のV結線：大きい方の単相変圧器の定格容量<br>
・複数変圧器を並行運転する場合：対象となる各変圧器の1相分容量を合計して考える<br><br>

