<h2>GRとLBSの連動試験で動作時間が遅れる現象</h2>

例<br>
・GR単体での動作時間：0.15s<br>
・LBSとの連動での動作時間：0.40s～0.60s<br><br>

GR単体動作と連動試験動作の差分が0.2s以上ある。<br>
GR動作は正常、LBSの開極動作に異常あり。<br><br>

原因<br>
・LBS本体の劣化<br>
・開極動作電源の容量不足<br>
・開極動作電源の波形ひずみ<br><br>

対策<br>
・LBSの摺動部にCRCを吹きかけて開閉を滑らかにしてから再び試験<br>
・モバイルバッテリーの使用を避け、ガソリン型発電機を使用（出力容量の問題）<br>

