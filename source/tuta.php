ツタやツルの成長速度<br>
先月の月次点検で確認できなかったものが、今月の月次点検でキュークル内に侵入という例も。<br>
除草しても１～２ヶ月程度でツルが成長し、事故に繋がった例もある。<br>
下記の参考動画では１ヶ月どころか、わずか数日でぐんぐん伸びている。<br>
