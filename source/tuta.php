事故例<br>
蔦の導電性は、高圧メガーを使用すると、ほぼゼロを示すらしい。<br>
蔦がLBSの相間を短絡し、回路に短絡電流が流れ、PF溶断＆焼損、LBS本体も焼損。<br>
ヒューズが割れ、LBSストライカ引外し、LBSにより回路は開放状態。<br>
しかしDSやLBS１次側で短絡した場合、蔦が炭化⇒導電性を持つ状態に。<br>
PASがSO動作で開放、その後は<a href="saiheiro.php">最閉路</a>、原因が取り除かれていなければ<a href="hakyu.php">波及事故</a><br><br>


ツタがLBS１次側に巻き付き地絡事故（予想）<br>
