<h2>接地抵抗測定の補助接地極とは？</h2>

<p>補助接地極は、接地抵抗計で接地抵抗を測定するときに使用する測定用の電極です。</p>

<p>一般的な3電極法では、測定対象の接地極Eに加えて、次の2本を使用します。</p>

<ul>
  <li><strong>P極</strong>：Potential（電位極）</li>
  <li><strong>C極</strong>：Current（電流極）</li>
</ul>

<p>接地抵抗計はC極へ測定電流を流し、P極で電位差を測定して接地抵抗を求めます。</p>

<h2>建物に常設する補助接地極</h2>

<p>地下電気室、屋上、全面舗装された敷地など、将来P極・C極を打ち込む場所を確保しにくい設備では、建設時に測定用補助極をあらかじめ設けることがあります。</p>

<p>竣工後に測定不能となると追加施工が難しいため、設計図に補助極が記載されている場合は、工事中の段階で設置位置・端子・配線を確認しておくと安心です。</p>

<h2>補助極の抵抗が高いと測定できない？</h2>

<p>許容される補助接地抵抗は接地抵抗計によって異なります。</p>

<p>たとえば、一部の接地抵抗計では補助接地抵抗がかなり高くても測定できる設計になっています。一方で、補助極抵抗が測定器の許容範囲を超えると警告表示や測定エラーになります。</p>

<p><strong>「P極・C極は○Ω以下」と一律に決めず、使用する接地抵抗計の取扱説明書にある補助接地抵抗の許容範囲を確認します。</strong></p>

<h2>補助極の抵抗が高いとき</h2>

<ul>
  <li>補助接地棒を十分に土へ打ち込む</li>
  <li>極の位置・間隔を見直す</li>
  <li>乾燥した地面では測定器メーカーが認める方法で接触状態を改善する</li>
  <li>リード線の断線・接触不良を確認する</li>
  <li>常設補助極の場合は端子・埋設配線の断線も疑う</li>
</ul>

<h2>補助極が打てない場合</h2>

<p>舗装面や建物内などで通常の補助接地棒を設置できない場合は、測定器によって簡易測定法・2極法・クランプ式など別の測定方法が利用できる場合があります。</p>

<p><strong>電柱の支線、金属水道管、建物の鉄骨・ドアヒンジなどを、確認せず補助極代わりに使用しない</strong>ようにします。これらは他の接地系統や設備と電気的につながっている可能性があり、測定結果が本来の接地抵抗を表さなくなることがあります。</p>

<p>代替方法を使用する場合は、接地抵抗計のメーカーが示す測定方法と、対象設備の接地系統を確認します。</p>

<h2>測定値がおかしいときの確認</h2>

<ul>
  <li>P・C端子の接続を間違えていないか</li>
  <li>補助極リード線が断線していないか</li>
  <li>補助極が地面と十分接触しているか</li>
  <li>補助極同士や測定対象との距離が適切か</li>
  <li>他の接地線・金属配管・構造体による並列経路の影響がないか</li>
</ul>

