<h2>碍子の清掃とCRCの効果</h2>
CRC（クレ556）とは？<br>
成分：鉱物油、防錆剤、石油系溶剤<br><br>

用途<br>
防錆・潤滑・防湿・除湿効果に優れ、微細なすき間にも入り込む。<br>
さびを落とし、動きを良くする。<br>
金属表面の水分を置換し、薄い被膜を作る。<br>
電気系統の除湿、防湿、電気接点の清浄にも使用可能。<br><br>

個人的感想<br>
鉱物油なので、吹きかければ一時的に絶縁は上がる。<br>
金属表面に薄い皮膜を作り、潤滑効果、防錆効果を生む。<br>
微細な隙間に浸透し、古い油脂を溶かす。<br><br>

ただしその後、砂や埃を吸着しやすくなり、汚れやすくなる。<br>
石油系溶剤を含んでいるため、ゴム、樹脂類プラスチック、塗装面などを溶かしてしまう。<br>
石油系溶剤の匂いによる他作業者への身体的負担（頭痛・めまい・吐き気等）<br>


<h2>碍子の清掃方法</h2>
ウエスで乾拭き、もしくは固く絞ったウエスで水拭き。<br>
塵埃（じんあい）や、ばい煙などで汚損が激しく水拭きできれいにならない場合、ガイシ清掃剤。<br>
無水エタノールを水で薄めウエスに含ませ清掃すると、揮発性が高く、碍子に水分が残らない。<br>
エタノールは油を溶かす性質があり、しつこい油汚れやカビ落としに効果的。<br>
アルコールはエタノールを使用。メチルの場合、換気の悪いと頭痛・めまい等を誘発する。<br>

<h2>停電時の点検方法</h2>
表面の汚損、放電こん、き裂、トラッキングの有無を確認する。<br>
がいし・クリート本体に対して1000vメガーで対地絶縁抵抗測定を行う。<br>
1000MΩ以上であれば製品としておおよそ正常と判定。<br>

