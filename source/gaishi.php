<h2>がいしの経年劣化</h2>
温度変化、風、ホコリ、砂、湿気、塩分などにさらされ、経年劣化していく。<br>
目視できないレベルの小さなヒビや亀裂、表面変色、湿気を吸湿により絶縁低下。<br>
がいしの水拭き、乾拭きで絶縁が回復しない場合は、交換が必要。<br>
放置しておくと、地絡事故に発展するおそれがある。<br>

