<h2>G端子（ガード端子）とは？</h2>
G端子とは、高圧ケーブル絶縁測定時、ケーブル端末に仮設するガード電極を接続して、<br />
シース外皮に流れる沿面電流による測定誤差を防止するために使用されるもの。<br />
高圧ケーブルの心線と、高圧ケーブルのシールド間の絶縁抵抗（Rc）を、<br />
接続されたままの高圧機器の絶縁抵抗の影響を減少させることで推定する方法。<br />


