<h2>直流用検電器とは？</h2>

<p>直流用検電器は、直流電路の充電状態や、コンデンサなどに残った直流の残留電圧を確認するための検電器です。</p>

<p>交流用検電器と直流用検電器では検出原理や使用条件が異なるため、<strong>測定対象の電圧・AC/DC・使用環境に適合した検電器を使います。</strong></p>

<h2>製品例：HSN-6A1</h2>

<img src="images/kenden_dc1.jpg" style="max-width:800px;" alt="直流用検電器 HSN-6A1"><br>

<p>長谷川電機工業 HSN-6A1のように、交流高圧の検電と、所定の条件で直流電圧・残留電圧の確認に対応する製品があります。</p>

<p>対応電圧範囲、伸縮状態、接地線の使用有無などは機種ごとに異なります。<strong>銘板・取扱説明書に示された使用範囲を超えて使用しません。</strong></p>

<h2>直流検電で接地線を使う理由</h2>

<img src="images/kenden_dc2.jpg" style="max-width:500px;" alt="直流検電用の接地線"><br>

<p>直流は交流のように周期的に電界が変化しないため、検電器によっては大地を基準とした電位差を検出するための接地線を使用します。</p>

<p>接地線の接続方法や接続順序は製品ごとに定められているため、メーカーの取扱説明書に従います。</p>

<h2>残留電荷の確認</h2>

<p>進相コンデンサ、直流回路、太陽光発電設備などでは、電源を切り離したあとも電荷が残っていることがあります。</p>

<p><strong>「遮断器を切った＝無電圧」と判断せず、設備に定められた放電時間を確保し、対象に適した検電器で確認します。</strong></p>

<p>交流用検電器は直流残留電圧を正しく検出できない機種があります。直流の残留電圧を確認する場合は、直流検電に対応した機器を使用します。</p>

<h2>使用前後に確認すること</h2>

<ul>
  <li>対象が交流か直流か</li>
  <li>検電器の使用電圧範囲内か</li>
  <li>本体・先端・絶縁部・接地線に損傷がないか</li>
  <li>使用前に既知の充電部やチェッカー等で動作確認できるか</li>
  <li>検電後も短絡接地・放電など、設備の正式な安全手順が必要か</li>
</ul>

<h2>直流検電器を使う主な設備</h2>

<ul>
  <li>蓄電池・直流操作電源</li>
  <li>非常用発電機の始動・制御回路</li>
  <li>進相コンデンサなどの残留電圧確認</li>
  <li>太陽光発電設備などの直流回路</li>
</ul>

<p>検電は安全確認の一工程です。<strong>検電結果だけで作業可能と判断せず、設備ごとの停電作業手順・放電・短絡接地などと組み合わせます。</strong></p>

