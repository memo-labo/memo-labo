<h2>PAS・SOGのZ2/E接地とは？</h2>
PASとSOG制御装置のZ2/E端子は、製造時期・形式によって接地方法が異なる。<br>
古い仕様では外部接地配線が必要な構成があり、新しい仕様ではPAS内部でZ2と外箱側が接続され、SOG側から別途接地しない構成がある。<br><br>

<strong>「Z2/Eは必ず接地」「Z2/Eは必ず接地不要」と一律には判断しない。</strong><br>
PAS・SOGの型式、製造時期、結線図、メーカー資料を確認して判断する。<br><br>

参考：<a href="https://www.togami-elec.co.jp/infomation/release_20150202.pdf">戸上電機製作所 PAS Z2接地仕様変更資料</a><br>

<h2>仕様変更後の考え方</h2>
メーカー仕様変更後の一部機種では、PAS内部でZ2系統とPAS本体側の接地回路が接続される構成がある。<br>
この場合、PAS本体の所定の接地によってZ2側の接地も確保されるため、SOG制御装置のZ2/E端子から別の接地線を追加すると、不要な多点接地となる可能性がある。<br><br>

零相電圧・零相電流を扱う回路は接地方法の影響を受けるため、更新時に「既設と同じだから」とそのまま配線を移さない。<br>

<h2>旧仕様・新仕様の見分け方</h2>
PAS底面の識別マーク、銘板、製造番号などで仕様を判別できる機種がある。<br>
ただし、識別色や表示方法は製品シリーズ・製造時期で異なる可能性があるため、色だけで判断せず、該当型式のメーカー資料で確認する。<br><br>

確認するもの<br>
・PASの型式<br>
・製造年月、製造番号<br>
・SOG制御装置の型式<br>
・PAS本体とZ2/E間の結線図<br>
・メーカーの仕様変更資料<br>

<h2>Z2/EでPASのA種接地抵抗が測れない場合</h2>
Z2/E端子とPAS本体の接地が内部で共通になっていない旧仕様などでは、SOG側Z2/E端子からPAS本体のA種接地抵抗を測定できない場合がある。<br><br>

この場合は、<strong>既設接地線の被覆を傷つけて測定点を作らない。</strong><br>
接地端子、中継端子箱、接地極側の測定端子など、設備として設けられた測定可能な箇所を使用する。<br><br>

測定点が確保できない場合は、停電・無電圧を確認したうえで、接地線の端子部を適切に切り離すなど、設備を傷めない方法を工事担当者・保安担当者と検討する。<br>

<h2>PAS更新時に注意すること</h2>
既設PASではSOGのZ2/E端子に接地線が接続されていても、新設PASが内部接地方式なら、その接地線をそのまま移設するとは限らない。<br><br>

更新時は、<br>
1. 旧PASの接地方式を確認<br>
2. 新PASの接地方式をメーカー結線図で確認<br>
3. Z2/EとPAS本体の内部接続有無を確認<br>
4. 不要な多点接地が生じないことを確認<br>
5. 更新後にSOG・DGR要素の試験を行う<br>
という順で確認する。<br>

<h2>多点接地が問題になる理由</h2>
SOG・DGRは零相電圧V0や零相電流I0を使って地絡を判定する。<br>
意図しない複数箇所で接地すると、接地線を通じた循環電流や信号経路の変化によって、誤動作・不動作の原因になる可能性がある。<br><br>

「念のためアースを追加する」という考え方が、零相回路では逆効果になることがある。<br>
必ずメーカー指定の接地方式に合わせる。<br>

<h2>点検時の確認ポイント</h2>
・PASとSOGの型式、製造時期<br>
・Z2/E端子に外部接地線が必要な仕様か<br>
・PAS本体との内部導通の有無<br>
・接地線の緩み、腐食、断線<br>
・不要な多点接地がないか<br>
・更新前後で接地方式が変わっていないか<br>
・SOG試験後に配線を正しく復旧したか<br>

