<h2>非接触の使用上の注意</h2>
ブスバー、シールド線などへは使用できない。被覆電線を被覆上からクリップする。<br>
対地間電圧が70V以下の場合にはLEDは点灯しない。<br>
接地相でも、電圧が発生している場合がある。<br>


<h2>相回転の確認作業</h2>
UGS、PAS等の受電設備の更新の際は、正相と逆相に注意する。<br />
工事前に、低圧の動力ブレーカー１次側にて検相を確認し、正相か逆相かどうかチェック。<br />
絶縁耐力試験終了⇒工事完了⇒高圧受電⇒電圧確認と、ここまで来たら、低圧ブレーカーを入れる前に、再度検相を確認する。<br />

