<h2>検相器はVTTから測定可能？</h2>
AC70Vから動作する検相器もある（例：PD3129-日置電機）<br>
この場合、動力MCCB１次側で測定せずに、VTTから測定可能か？<br><br>
⇒<a href="vtt.php">VTTとは？電圧試験端子（テストターミナル）</a><br><br>

差し込みプラグで行う場合、差し込む際に端子部分に電圧が発生するので感電の危険性。<br>
また充電中にVTTのVT側の相間を短絡するとVT２次側短絡により短絡電流が流れVTが焼損する。<br>
VTTがショートバータイプであれば検相器の非接触型でクリップを挟めばそのまま測定可能？<br><br>

ＶＴ二次回路の結線が間違ってる例もあるのでVTTで検相確認は確実ではない。<br>
受電VT二次側と動力Tr二次側、２点以上で確認をしたほうが良い。<br>
動力トランスが複数ある場合、誤配線でトランス別に相順が違う可能性もある。<br>

<h2>非接触式検相器の測定原理</h2>
静電誘導による電圧検出。<br>
活線電路⇒クリップ⇒検相器本体⇒人体⇒大地が接触することで各物体が静電結合し閉回路を形成、微少電流が流れる。<br>
微少電流は検相器内部の高抵抗に電圧降下として現れ、大地を基準とする対地間電圧に応じた波形を取得。<br>
この電圧検出で三相それぞれの電圧波形を取得し、相順を判定する。<br>
