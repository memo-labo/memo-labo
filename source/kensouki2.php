<h2>検相器とは？</h2>
３相誘導電動機は3相3線式の電源に接続することで回転する。<br>
モーターの回転方向は接続する電線の位相の順番で決まる。<br>
電源と負荷を接続する前に（低圧動力MCCBを投入する前に）電源の位相を測定する必要がある。<br>
位相の相順を確認する機器を「検相器」と呼ぶ。<br><br>

検相器で測定した結果が正相なら正回転、逆相なら逆回転をする。<br />
<a href="kensouki.php">逆相</a>で動作をさせると故障する機器もある。<br />

検相器の例<br>
sanwa：KS1（接触型）<br>
共立電気計器 (KYORITSU)：8035（非接触型）<br>

<h2>接触型検相器を使用した危険なやり方</h2>
プローブがなくワニグチしかなかった、とある電気工事士。<br>
ドライバー３本を使用してMCCB１次側につっこみ、ドライバにワニグチを挟んだ。<br>
隣り合うドライバの金属部分が触れれば変圧器２次側で短絡事故を起こす。<br>
ドライバ部分に手が触れたり、グリップ部分の絶縁が不十分であれば感電事故を起こす。<br>
