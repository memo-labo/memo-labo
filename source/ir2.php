<h2>メガーで電圧を測定する際の注意点</h2>

テストリードは、必ずブレーカーの２次側を測定する。<br>
２次側であれば、万が一短絡があっても、ブレーカーにて保護できる。<br>
１次側だと、電流容量が大きく、短絡事故があった場合、損傷が大きくなる。<br>
電圧測定中にMEASUREキーを押してはいけない。回路が破損して人身事故に繋がる。<br>
測定中に他のファンクションに切り替えてはいけない。<br>
正弦波以外の波形では誤差を生じる。<br>

<h2>測定カテゴリ</h2>

測定カテゴリⅡ<br>
コンセントに直接接続する機器の電源プラグから機器の電源回路まで<br><br>

測定カテゴリⅢ<br>
分電盤から電力を直接取り込む機器（固定設備など）の電源配線と電源回路、および分電盤からコンセントの裏側の配線端子までの配電路<br><br>

測定カテゴリⅣ<br>
建造物への引き込み電路、引込口から電力量メータおよび分電盤までの電路


