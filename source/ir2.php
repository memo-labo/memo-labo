<h2>絶縁抵抗測定の測定原理</h2>
測定対象の絶縁抵抗⇒Rx<br>
測定対象に電圧Vを印加する<br>
測定対象に流れる電流Iを測定する<br>
Rx=V/Iを求める<br>

<h2>絶縁抵抗測定の電圧極性</h2>
EARTH（黒）⇒ プラス<br>
LINE（赤）⇒ マイナス<br>
「JIS C 1302」で定められている<br><br>

絶縁電線などと大地間の絶縁抵抗を直流で測定する場合、被測定物の芯線にマイナス側、大地にプラス側を接続して測定したほうが、
逆の極性で測定した場合に比べ、測定値が小さくなるのが普通で、絶縁不良を検出するにはこの極性で測定した方が適しているため。<br><br>

※ただし、測定対象が接地されていない場合は、印加電圧の極性は任意。<br>

