<h2>低圧電灯回路（単相３線・単相２線）の場合</h2>
照明器具が付いていない（引掛けシーリングのみなど）の場合、スイッチ切だと、スイッチと照明器具間の電線は測定できない。照明器具が取り付いていると、スイッチが切れていても照明器具を経由して測定ができる。基本的にはスイッチはすべて入った状態で測定する。<br><br>

単相３線の場合、L1・N・L2の３線とも全て絶縁抵抗測定をする。電灯回路の単相３線式の場合、100V回路、100V回路、200V回路の３種類の使われ方がある。どの回路に絶縁不良があるかわからないので、３つとも全て測定する。<br><br>

2P100V回路の場合、接地側（N：白相）も絶縁抵抗測定する。<br><br>

1Pのブレーカー中性端子は、1Pブレーカーを落とし、かつ中性端子開放レバー（ニュートラルスイッチ）を開放して測定する。<br><br>

<h2>絶縁不良 0.1MΩ、1mAの意味</h2>
1mA = 1 * 10^-3[A]<br>
0.1MΩ = 0.1 * 10^6[Ω]<br><br>

1mA * 0.1MΩ<br>
=（1 * 10^-3）*（0.1 * 10^6）<br>
= 0.1 * 10^3<br>
= 100[V]<br><br>

100V回路において、対地絶縁抵抗値が0.1MΩであった場合、漏洩電流が1mA流れる。<br>


