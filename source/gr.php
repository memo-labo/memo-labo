<h2>GR（地絡継電器）とは</h2>
GR（Ground Relay）は、<a href="zct.php">ZCT（零相変流器）</a>で高圧回路の零相電流I0を検出し、設定値を超えた地絡電流が一定時間継続すると接点を動作させ、VCBやLBSなどを開放する保護継電器。器具番号は51G。<br><br>

<img src="images/gr10.png" alt="GR 地絡継電器 51Gの図記号"><br>

本体例：OMRON AGF-1-P5<br>
<img src="images/agf1.jpg" style="max-width:400px;" alt="OMRON AGF-1-P5 地絡継電器"><br>

<h2>GRの基本構成</h2>
代表的な端子の役割は次のとおり。端子名称は機種ごとに異なる。<br>
<ul>
<li>Z1-Z2：ZCTからの零相電流入力</li>
<li>P1-P2：GR本体の制御電源</li>
<li>a-b-c：警報・引外し用接点</li>
</ul>

<img src="images/20260406-1.jpg" style="max-width:800px;" alt="GR 地絡継電器の端子構成"><br>
<img src="images/20261005-1.jpg" alt="GR 地絡継電器の配線例"><br>

<h2>GRが使われる設備</h2>
GRは、受電盤のVCB・LBSや構内送り回路の地絡保護に使われる。MDSなどの区分開閉器を採用している古い設備で、受電盤側の地絡保護として設置されている例もある。<br>

<h2>GRとDGRの違い</h2>
GRは基本的にI0の大きさで地絡を判定する。一方、<a href="dgr.php">DGR（地絡方向継電器）</a>はI0とV0の位相関係から事故方向を判定する。<br>
高圧ケーブルが長く対地静電容量が大きい設備では、他需要家の地絡事故で流れる充電電流によりGRが不要動作することがあるため、DGRを採用する場合がある。<br>
⇒<a href="moraijiko.php">他需要家の地絡による「もらい事故」</a><br>

<h2>GRの引外し方式</h2>
<h3>電圧引外し</h3>
GRの接点を介して、VT二次側や操作用変圧器などからVCB・LBSのトリップコイルへ所定電圧を印加する方式。<br>

<h3>電流引外し</h3>
電流引外し形OCR・VCBと組み合わせ、専用の引外し回路を構成する方式。リアクトルなどでトリップ電流を制限する機種もある。<br>
⇒<a href="agf2.php">AGF-2-R2 電流引外しGR</a><br>

<div class="article-warning">
<span class="article-warning-title">⚠ 注意：トリップコイルへの継続通電を避ける</span>
引外し回路はVCBやLBSの開放後にトリップコイルへの通電が継続しない構成になっていることが重要。接点構成やパレットスイッチの有無は機種ごとに異なるため、試験前に結線図で確認する。
</div>

<h2>GRの整定値</h2>
0.2A、0.4A、0.6Aなどの感度整定を持つ機種がある。実際の整定は、構内の充電電流、ケーブル長、上位系統との保護協調、電力会社との協議値をもとに決める。<br><br>

0.2Aはよく使われる整定例だが、構内充電電流が大きい設備で一律に0.2Aとするのは適切ではない。<br>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：ケーブルが長い設備は充電電流を確認</span>
高圧CVケーブルが長いほど対地静電容量が増え、健全回線にも零相電流が流れやすくなる。GRの感度電流に対して充電電流が大きい場合は、不要動作対策としてDGR採用を検討する。
</div>

<h2>GRの動作時間と保護協調</h2>
GRは受電設備内だけでなく、上位の配電用変電所側の地絡保護とも協調させる必要がある。動作時間は機種や整定によって異なるため、メーカー特性と電力会社の協調条件を確認する。<br>

<h2>GRの試験</h2>
一般に確認する項目は、最小動作電流、動作時間、復帰、警報接点、遮断器・開閉器との連動など。判定値は使用しているGRの形式・規格・整定値に従う。<br>

<div class="article-warning">
<span class="article-warning-title">⚠ 注意：判定値を別機種から流用しない</span>
「130%入力時」「400%入力時」などの試験倍率や許容時間は、継電器の形式や適用規格によって異なる。試験成績書・取扱説明書・保安規程を基準に判定する。
</div>

<h2>GRとVCB・LBSの連動試験</h2>
連動試験では、GR単体の動作時間に加えてVCBやLBSの機械的な開放時間が加わる。したがって、単体試験と連動試験の時間を同じ基準で比較しない。<br>
連動試験の判定は、対象開閉器の規格・メーカー資料・現場の試験要領を確認する。<br>
⇒<a href="vcb.php">VCB（真空遮断器）</a><br>
⇒<a href="lbs.php">LBS（高圧交流負荷開閉器）</a><br>

<h2>トリップコイルの抵抗・絶縁確認</h2>
GRからVCB・LBSへつながる引外し回路の抵抗値や絶縁抵抗を測定する場合は、制御電源を確実に切り分け、対象端子と回路構成を図面で確認してから行う。<br>
<img src="images/gr9.png" style="max-width:700px;" alt="GRとLBSのトリップ回路測定例"><br>

<h2>充電電流による不要動作</h2>
GRは方向判定を行わないため、他回線事故時に自回線の対地静電容量を通じて流れる電流を地絡電流として検出する場合がある。これが「もらい動作」の一因。<br>
ケーブル長や静電容量が大きい設備では、地絡保護方式そのものをDGRへ変更した方が適切な場合がある。<br>

