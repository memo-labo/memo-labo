<h2>GR継電器動作＋VCB開極時間 判定基準</h2>
GR+遮断器の開極時間の判定。<br>
GR単体試験の判定基準内であれば良。<br><br>

GR+LBSの動作時間の判定基準は？（予想）<br>
LBSの連動 ≒ VCBの連動 =（1/50）✕ 5サイクル = 0.1s<br>
連動試験の許容値 = GR単体試験の許容値 + 0.1s程度<br><br>

0.2sの連動試験の場合、単体の許容値は0.1s～0.3s。<br>
連動試験の許容値は0.1sをプラスして0.2s～0.4s程度と予想。<br><br>

