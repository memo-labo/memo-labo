GRの注意点<br>
高圧ケーブルが長い場合、他の需要家の地絡事故が原因による<a href="moraijiko.php">もらい事故</a>を引き起こす可能性あり。<br>
なので出来ればGRではなく<a href="dgr.php">DGR（地絡方向継電器）</a>の設置が推奨される。<br>

<h2>GRの種類（電流引き外し・電圧引き外し）</h2>
電圧引き外しタイプ<br>
・制御電源とは別にトリップ用電源をVT２次側または電灯トランス２次側から使用<br>
・トリップ用電源をGR内部のa接点を介してLBSへのトリップコイル（TC）へ接続する<br>
・GRが動作するとGR内部a接点を通りLBSのTCに電圧が印加されLBSがトリップする<br><br>

電流引き外しタイプ（詳細は<a href="agf2.php">AGF-2-R2ページ</a>）<br>
・制御電源とは別にトリップ用電源をVT２次側または電灯トランス２次側から使用<br>
・OCR電流引き外し+VCB電流引き外しとセットで使用されることが多い。<br>
・S1にはリアクトルがあり、インピーダンス（リアクタンス＋レジスタンス）を増加させることで電流を制限する。<br>
・電流引き外しタイプのVCBはトリップコイルがR相、T相の２相に用意されている。<br>
・OCRのR相は、OCRが動作した時のみ利用する。<br>
・OCRのT相は、GRの引き外しコイルと兼用する。<br><br>

OCRのT相が動作した時の電流の流れ<br>
CT（T相 k側）⇒C1T⇒T1T⇒o1（GR）⇒T1⇒TC2（VCB）⇒T2⇒o2⇒AS⇒CT（T相 l側）<br><br>

GRが動作した時の電流の流れ<br>
P1-P2にGR制御電源が印加された状態で、地絡電流を感知するとGR内部接点[x]が動作する。<br>
S1-S2に引き外し用電源としてVCBパレットスイッチを介してAC100Vを印加しておく。<br>
VCB引き外し電流の流れは、S1⇒T1⇒TC2⇒T2⇒S2。<br>

引き外し電源をVCBパレットスイッチを介する理由<br>
VCBが開放された状態においてはトリップコイルに電流を流さないようにするため。<br>
コイルに電流を流し続けるとトリップコイルが焼損してしまう。<br>

<h2>GR＋LBSのトリップコイル抵抗値・絶縁抵抗値の測定</h2>
<img src="images/gr9.png" style="max-width:700px;" /><br>
<strong>測定前に制御電源MCCBをOFFにし、実際の回路・端子構成を確認する。</strong><br><br>

抵抗値の測定例<br>
・LBSにパレットスイッチがある場合はLBSを投入状態にする。<br>
・GR本体の(C)端子－P2端子間で測定する。<br><br>

絶縁抵抗の測定例<br>
・制御電源MCCBをOFF。<br>
・LBSにパレットスイッチがある場合はLBSを投入状態にする。<br>
・GR本体の(C)端子またはP2端子など、対象回路を確認して測定する。<br><br>

端子名称や回路構成は機種・現場配線によって異なるため、メーカー資料と現場の配線図を確認してから測定する。<br>

<h2>GR 電流整定値</h2>
通常は0.2Aで整定。<br>
検出感度が良すぎて微弱電流で動作してしまう場合は0.4Aに整定。<br />
0.6A以上に整定する場合、配電用変電所の保護範囲と接近し保護協調がとれなくなる可能性がある。<br>
この場合には電力会社と相談する。<br /><br />

構内充電電流が50mA以下：200mA<br />
構内充電電流が50～100mA：400mA<br />
構内充電電流が100mAを超える：600mA<br /><br />

構内の高圧ケーブル（6kV CVT100sq）が124m以上の場合、Ig = 200mA以上となるので、もしGRの整定が200mA整定だった場合、電源側の地絡事故により、<a href="moraijiko.php">不必要動作（もらい事故）</a>をする可能性がある。

<h2>地絡継電器 動作時間の保護協調</h2>
受電設備の地絡継電器は、配電用変電所のGRと、保護協調をとる必要がある。<br />
整定電流値の130%<br />
動作時間：0.1s～0.3s<br />
整定電流値の400%<br />
動作時間：0.1s～0.2s<br />
構内の対地静電容量による充電電流が200mA以上になると、<br />
GR方式では電源側の地絡事故で、もらい動作する場合がある。<br /><br />

<h2>継電器試験 判定基準</h2>

動作電流値<br>
整定値の±10%<br><br>

0A→整定値の130％[A]の場合<br>
瞬時：ー（判定基準なし）<br>
0.2s：0.1～0.3s<br><br>

0A→整定値の400％[A]の場合<br>
