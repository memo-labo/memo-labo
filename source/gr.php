<h2>GR 地絡継電器</h2>
GR 地絡継電器とは？<br>
<a href="zct.php">零相変流器（ZCT）</a>で高圧回路の零相電流（地絡電流）を検出し、それがある値（一般的には0.2A程度）を一定時間検出したら接点を動作させ、VCBやLBSなどの遮断器をトリップさせる保護継電器。<br><br>

現場でよく見かけるパターン<br>
・区分開閉器がモールドジスコンの現場で、受電盤のLBSやVCBとセットで設置。<br>
・主変から２変送りのLBSとセットで設置。<br><br>

地絡継電器の器具番号は51G<br>
地絡継電器は英語でGround Relay<br><br>
