<h2>ケッチヒューズ</h2>
ケッチは英語でCatch（キャッチ）の意味<br>
低圧引込の一般住宅のメーターの先は、低圧ケッチヒューズ、低圧カットアウトがある。<br>
さらに柱状変圧器の１次側には高圧カットアウトがある。<br><br>

住宅側で短絡事故を起こしても、それが電力側へ影響しないような仕組みになっている。<br>

