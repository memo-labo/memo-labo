<h2>ケッチヒューズとは？</h2>

<p><strong>ケッチヒューズは、低圧配電線や引込線で短絡・過電流が発生したときに、事故区間を切り離すためのヒューズです。</strong></p>

<p>一般住宅などへの低圧引込設備で、柱上変圧器の低圧側から需要家へ向かう回路に設置される例があります。地域・設備年代・配電方式によって構成は異なります。</p>

<h2>何のためにある？</h2>
<ul>
  <li>需要家側や引込線の短絡事故を配電線全体へ波及させにくくする</li>
  <li>事故区間だけを切り離す</li>
  <li>柱上変圧器や低圧配電設備を保護する</li>
</ul>

<p>ヒューズが溶断した場合は、原因を確認せずに交換・再投入せず、短絡や設備故障がないことを確認してから復旧します。</p>

