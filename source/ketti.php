<h2>低圧カットアウトとの違い</h2>

<p>現場では「ケッチ」「低圧カットアウト」など複数の呼び方が使われます。構造やヒューズの組み合わせは設備によって異なるため、名称だけで判断せず実物・銘板・配電会社の仕様を確認します。</p>

<h2>高圧カットアウトとの違い</h2>

<p>柱上変圧器の一次側（高圧側）には、高圧カットアウト（PC）が使用されることがあります。</p>

<ul>
  <li>ケッチヒューズ：低圧側で使われる例</li>
  <li><a href="pc.php">高圧カットアウト（PC）</a>：高圧回路で変圧器などを保護</li>
</ul>

<h2>低圧引込工事で使うもの</h2>

<p>単相100/200Vなどの低圧電源を住宅・店舗などへ供給する引込工事では、設備条件に応じて引込線、がいし、接続材料、保護器具などを使用します。</p>

<p><strong>引込設備は電力会社設備と需要家設備の責任分界が関係するため、工事・交換・操作は設備所有者と配電事業者の区分を確認して行います。</strong></p>

