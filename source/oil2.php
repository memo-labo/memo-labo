<h2>変圧器の上蓋（ハンドホール）から油漏れ</h2>
絶縁油は、ほとんど蒸発しない。<br>
絶縁油（鉱油）の常圧換算沸点は250～600 ℃。<br><br>

上蓋から油が漏れた後がある現象の原因とは？<br>
油の入れ替えや採油時にこぼして軽く拭いた状態が後になって残った。<br>
上蓋のボルト留めがしっかりできておらず、隙間が空いていた。<br>
上蓋のゴムパッキン部分の劣化により気密性が減少していた。<br>

<h2>どうしたら吹き出しを防げる？</h2>

吹き出した理由を考察<br>
・受電中、変圧器の油の温度が上昇<br>
・停電し、その直後に蓋を開けた<br>
・変圧器内部の空気が膨らみ圧力が上昇<br>
・蓋を開けた途端、空気とともに液が吹き出した<br><br>

対策<br>
・停電前に表面温度を測定<br>
・熱かったら停電後にすこし時間を置く<br>
・少し冷めた状態で蓋を開ける<br>

