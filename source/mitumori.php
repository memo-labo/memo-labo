<h2>法定福利費とは？</h2>
「事業者に負担が義務付けられている福利厚生の費用」<br>
健康保険法、労働基準法、厚生年金保険法など、様々な法律・法令で定められている。<br>
国、平成25年から「法定福利費込の見積書の提出」を求める。<br>
建設業界の「社会保険未加入問題」を解決するため。<br><br>

国土交通省<br>
「社会保険の加入に関する下請指導ガイドライン」<br>
「平成29年度以降については、元請企業に対し、社会保険に未加入である建設企業を下請企業として選定しないよう要請するとともに、適切な保険に加入していることを確認できない作業員について、特段の理由がない限り現場入場を認めない取扱い」<br><br>

