年次点検<br>
１回15000円～35000円、場合によってはそれ以上と値段の幅が広い。<br>
価格は各個人が所属している団体や仲間内によって決まることが多いらしい。<br>
中には清掃作業のみで１回30000円支給される場合もある。<br>
応援費は高速代、交通費、駐車場代、すべて込みの値段で支給されることが多い。<br><br>

時期<br>
11月～年末年始～2月あたりが人手が足りないらしい。<br>

