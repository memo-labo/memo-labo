<h2>巻数比・変圧比・変流比</h2>

<h3>記号の意味</h3>
<ul>
<li>N1=変圧器一次側の巻数</li>
<li>N2=変圧器二次側の巻数</li>
<li>I1=変圧器一次側の電流</li>
<li>I2=変圧器二次側の電流</li>
<li>E1=変圧器一次側の誘導起電力</li>
<li>E2=変圧器二次側の誘導起電力</li>
</ul>

<h3>変圧比とは？</h3>
<p>
無負荷時の一次電圧と二次電圧の比のこと。<br>
変圧比＝一次電圧÷二次電圧＝一次巻数÷二次巻数。</p>

<h3>変流比とは？</h3>
<p>
変圧器の一次電流と二次電流の比のこと。<br>
変圧比と逆数の関係になる。</p>

<h3>巻数と起電圧の関係</h3>

コイルは鎖交する磁束が増えると電圧が高くなる。<br>
逆に磁束が減ると電圧が低くなる。<br>
N1=100、N2=10とする。<br>
１次巻線も２次巻線も同じ鉄心に巻かれているため、磁束は同じ。<br>
とすると、１次巻線は100回鎖交し、２次は１０回鎖交する。<br>
よって起電圧は巻数に比例する。<br><br>

<h3>巻数比αの関係式</h3>
＝（N1÷N2）<br>
＝（E1÷E2）<br>
＝（I2÷I1）<br><br>

<h3>関係式を理解するための疑問</h3>
①なぜ巻数と起電圧は比例する？<br>
②なぜ変圧比と変流比は逆数になる？<br><br>

<h3>変圧比と変流比が逆数になる理由</h3>
変圧器は一次側と二次側で電力が変わるわけではなく一定である。<br>
電力W = E1*I1 = E2*I2で一定。<br>
この式を変形すると E1÷E2 = I2÷I1 となる。<br>

