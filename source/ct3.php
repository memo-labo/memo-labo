<h2>高圧CTの変わった使い方</h2>

※ネット上の情報を元にメモ。本来の正しい使い方ではない。<br><br>

OCR瞬時試験のための電流ブーストとして<br>
CT２次側に電流を流すとCT１次側にCT比倍された電流が流れる。<br>
<img src="images/ct31.jpg" style="max-width:800px;" /><br>

高圧CTを直列に２つ並べればCT２次側に流した電流をCT比倍✕２の電流が流せる。<br>
<img src="images/ct32.png" style="max-width:600px;" /><br>

使用例<br>
円盤の誘導型OCRで瞬時の整定値を変更できない、しない方が良い場合。<br>
仮にOCR瞬時整定値が40Aの時、試験電流は80Aを作らねばならない。<br>
そのようなとき、この高圧CTを使用して電流値を増幅させ試験するらしい。<br>

