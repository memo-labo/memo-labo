<h2>電源トランスの励磁突入電流</h2>

電源トランスは通電初動時、定格電流の２０～３０倍の励磁突入電流が1/2サイクルの間、流れる。<br><br>

初動時の励磁突入電流には不動作であって欲しく、通電中の過負荷や短絡時には速やかに動作して欲しい。<br><br>

この条件に適合する回路保護として、<br>
時延遮断型（ディレーオフ）<br>
サーキットブレーカー（プロテクタ）<br>
などがある。<br>

<h2>保護素子の位置</h2>
電源トランスの１次側⇒サーキットプロテクタ（CP）or 電流ヒューズ（F）<br>
電源トランスの２次側⇒電流ヒューズ（F）<br><br>

※保護素子に速断型、普通溶断型を使用すると不要動作で不都合が生じる。

