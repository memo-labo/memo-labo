複巻トランスなので、絶縁トランス。<br>
この絶縁トランスにより、１次側と２次側が絶縁が保たれている。<br>


<h2>電源トランスの用途</h2>

負荷部分の過電圧カテゴリの制約を合わせるための絶縁トランス。<br><br>

用途例<br>
モータ回路に商用電源を使用していたが、感電と漏電の危険があるため安全対策のために電源トランスを使用。また医療機器やコンピュータ系統の電源にも使用される。<br><br>

