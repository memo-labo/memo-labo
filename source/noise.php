シールドの接地は、１点接地（片端接地）をする。<br>
接地を施さなかったり、両端接地をすると、しゃへい効果が減少したり、逆に誘導を拾いやすくなる。<br>
シールドの接地抵抗値が小さいほど、しゃへい効果は大きくなる。<br>
アナログ入力信号は、電流信号を電圧信号に変換するコンピュータ側で接地する。<br>

