<h2>B種接地線が外れていたらどうなる？</h2>

<p>B種接地は、変圧器の高圧側と低圧側が混触したときなどに、低圧側の対地電位が危険な値まで上昇することを抑える重要な接地です。</p>

<p><strong>B種接地線が外れても、通常運転中の負荷電圧がただちに大きく変化するとは限りません。</strong>しかし、低圧系統の対地基準が不安定になり、地絡・混触事故時の感電保護や絶縁監視に重大な影響が出る可能性があります。</p>

<h2>単相3線式の100V・200Vはどうなる？</h2>

<p>単相3線式では、変圧器二次巻線の中性点NがB種接地される構成が一般的です。</p>

<p>B種接地線だけが外れても、L1-N・L2-Nの負荷電圧は変圧器巻線と中性線によって決まるため、<strong>それだけを原因として90V／110Vのような電圧不平衡になるとは限りません。</strong></p>

<p>100V側の大きな電圧不平衡は、中性線の断線・接触不良などを別に疑う必要があります。</p>

<p>関連：<a href="chusei.php">単相3線式の中性線欠相</a></p>

<h2>三相動力負荷への影響</h2>

<p>B種接地線の断線だけで、三相モータの線間電圧が直接不平衡になったり、ただちに過電流が流れたりするわけではありません。</p>

<p>ただし、系統の対地電位や地絡時の電流経路が本来の設計と異なるため、<strong>地絡保護・漏電監視・感電保護の前提が崩れる</strong>ことが問題です。</p>

<h2>地絡事故が起きたときの問題</h2>

<p>B種接地が正常なら、低圧電路の地絡時には機器のD種・C種接地などを通じて大地へ流れた電流が、B種接地側へ戻る経路を形成します。</p>

<p>B種接地線が断線していると、この帰路が本来どおり成立せず、地絡電流が小さくなったり不安定になったりすることがあります。</p>

<ul>
  <li>地絡・漏電保護装置が想定どおり動作しない可能性</li>
  <li>金属外箱などの対地電位が上昇する可能性</li>
  <li>高低圧混触時に低圧側の対地電位を抑える機能が失われる</li>
  <li>他の接地・配管・構造体など、想定外の経路へ電流が流れる可能性</li>
</ul>

<h2>ELBは必ず不動作になる？</h2>

<p>ELB（漏電遮断器）は、回路を行き来する電流の差をZCTで検出します。そのため、<strong>B種接地線が外れたから即座にELBが使えなくなる、という単純な関係ではありません。</strong></p>

<p>ただし、地絡電流の戻り経路そのものが変化すると、事故条件によっては十分な漏電電流が流れず、期待した保護が得られない可能性があります。</p>

<h2>絶縁監視装置への影響</h2>

<p>B種接地線をZCTへ通して漏れ電流を監視する方式では、B種接地線の断線・誤配線は監視機能へ直接影響します。</p>

<ul>
  <li>B種接地線に流れるI0を正しく測定できない</li>
  <li>絶縁監視装置が異常を検出できない可能性</li>
  <li>測定値が極端に小さい・不自然な場合、接地線断線も確認対象になる</li>
</ul>

<h2>B種接地線の断線を疑ったら</h2>

<p>受電中に接地線を不用意に外したり、活線状態で導通確認を行ったりしません。設備を安全な状態にしたうえで、図面・接地端子・接続部・接地抵抗値などを確認します。</p>

<p><strong>B種接地は「普段は電流がほとんど流れていないから不要」な線ではありません。</strong>異常時の安全を成立させるための重要な保護要素です。</p>

