<h2>大垣電機と戸上電機のPASは本体サイズが違う</h2>
PAS（高圧交流負荷開閉器）は、メーカーによって本体の大きさがかなり異なる場合がある。<br><br>

現場で大垣電機製と戸上電機製のPASを比較すると、<strong>大垣電機製PASは戸上電機製PASに比べて、本体が約1.5倍ほど大きく見える機種がある。</strong><br>
これは古いPASだけの特徴ではなく、新品のPASでも同様にサイズ差が見られる。<br><br>

<h2>PAS更新時は既設品の寸法だけで判断しない</h2>
PAS更新では、定格電圧・定格電流・短時間耐電流・SOGとの組み合わせなどの電気的仕様だけでなく、外形寸法も確認しておく。<br><br>

メーカーを変更する場合、既設PASと同程度の容量・仕様であっても、本体の幅・高さ・奥行き、ブッシング位置などが同じとは限らない。<br>
特にPAS周辺に腕金、電線、引込ケーブル、避雷器などが近接している設備では、更新品が問題なく収まるか事前確認が必要。<br><br>

<h2>大垣電機と戸上電機で異なるSOG制御線の端末処理</h2>
PAS更新時は、本体寸法だけでなくSOG制御線の先端処理にも注意する。<br><br>

現場で確認した大垣電機製PASでは、SOG制御線の先端がY端子などで端子上げされておらず、被覆をむいた導体が露出した状態になっているものがあった。<br>
この場合は、施工側で接続する端子台・機器の仕様に合わせて適切な端子を取り付け、必要に応じて絶縁キャップなどで端末処理を行う。<br><br>

一方、現場で確認した戸上電機製PASでは、SOG制御線の先端があらかじめY端子で端子上げされていた。<br><br>

<strong>メーカーが変わると、PAS本体の大きさだけでなく制御線の納入状態や端末処理も異なる場合がある。</strong><br>
更新工事では「既設と同じように接続できる」と思い込まず、新品PASの制御線先端を事前に確認して、必要な圧着端子・絶縁処理材・工具を準備しておく。<br><br>

なお、端末処理の仕様は型式や製造時期によって異なる可能性があるため、実際の施工では対象機種の取扱説明書・結線図・メーカー指定の施工方法を確認する。<br>

<h2>現地調査で確認したいポイント</h2>
<ul>
<li>既設PASのメーカー・型式・製造年</li>
<li>更新予定PASの外形寸法</li>
<li>ブッシング・端子位置</li>
<li>腕金や取付金具との位置関係</li>
<li>高圧電線・ケーブルの取り回し</li>
<li>周辺機器との離隔</li>
<li>SOG制御装置との組み合わせ</li>
<li>SOG制御線の先端が端子上げ済みか</li>
<li>必要な圧着端子・絶縁キャップなどの端末処理材</li>
</ul>

同じ「PAS交換」でもメーカー変更によって現場条件が変わることがあるため、更新前にメーカー外形図と現物寸法を照合しておくと安心。<br>

<h2>注意点</h2>
「約1.5倍」は現場で見た機種同士の外観上の目安であり、すべての大垣電機製PASと戸上電機製PASに一律に当てはまる寸法比ではない。<br>
実際の更新・選定では、対象となる型式のメーカー仕様書・外形図で寸法を確認する。<br>
また、SOG制御線の端末処理についても、すべての機種で同じとは限らないため、対象型式のメーカー資料と現物を確認する。<br>

