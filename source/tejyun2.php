<h2>低圧ブレーカーを入れた状態でPASやVCBを投入する理由</h2>

低圧ブレーカー投入時、経年劣化で3線のうち2線が先に入ってしまう事故。<br>
<br>
・短時間の中性線欠損による高電圧（単相）<br>
・単相運転による過電流（3相）<br>
<br>
これで機器が故障する可能性がある。<br>
通電前に低圧ブレーカー入状態で高圧側を投入し復電する会社や個人が増えている。<br>
<br>
古いブレーカーで入切時に微妙な不揃いにより一瞬異常電圧が出るらしい。<br>
（昨今のブレーカーなら中相の接点が先に接触するらしい）<br>

