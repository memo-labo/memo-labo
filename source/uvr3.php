<h2>分散型電源とは？</h2>
電力供給の一形態<br>
小規模な発電装置を消費地近くに分散配置して、電力の供給を行うもの。<br>
コージェネレーションシステム（エネルギーの総合効率を高める）<br>
太陽光や風力発電（自然エネルギーを利用したもの）<br>

<h2>分散型電源のメリット</h2>
送電ロスが少ない<br>
送電設備を縮減<br>
災害時、電力が停止した場合でも、電源供給が期待<br>
冗長性が増すことで抗堪性が高まる<br>
コジェネレーションにおいて廃熱の利用が可能<br>

<h2>分散型電源のデメリット</h2>
送電系統と配電系統での逆潮流への対応が必要<br>
設備設計と日常的な制御が複雑<br>
系統連系するため電力の品質が低下<br>
設備に求められる余裕度が大きくなる<br>
大規模発電設備よりも発電効率が低い<br>
運転管理に手間がかかる<br>
必要な設備投資の合計額が大きくなるおそれ<br>
排煙処理などの確実性に疑問<br>

<h2>3相UVR 試験方法</h2>

試験機<br>
・コージェネレーション試験装置 CGRT-02K<br><br>

電圧出力コード<br>
P1、P2、P3<br><br>

CGRTの３相電圧はV結線で出力されている。<br>
P1-P2間⇒定格電圧AC110V入力<br>
P2-P3間⇒定格電圧AC110V入力<br>
P3-P1ツマミを回すことで位相角の調整を行う<br>
P3-P1ツマミだけでは電圧は出力されない<br><br>

