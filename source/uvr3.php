■不足電圧動作試験<br>
整定値の±5％<br>
試験電圧を定格値から徐々に下げる。<br>
継電器の各相毎の不足電圧検出表示 LED が点灯した時の電圧を読む。<br><br>

■動作時間試験<br>
整定値の±10％(最少誤差±50ms)<br>
①３相電圧定格状態をつくる<br>
②２相定格・１相だけ整定値の70％をつくる<br>
①から②へ切り替えと同時にカウンタスタート、動作時間を計測<br><br>

取説には定格110V⇒0%（0V）の動作時間は明記していなかった。<br>
定格110V⇒0%（0V）の試験をするかどうかは用途による。先方から指定される場合もある。<br>

