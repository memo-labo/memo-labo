<h2>三相UVR omron「K2ZC-K2VU-N」</h2>
分散型電源対応系統連系用複合継電器。<br>
１台で３相の不足電圧を検出することができる。<br>
３相各々の不足電圧検出をLED にて表示できる。<br>
<img src="images/uvr3-1.png" style="max-width:700px;" alt=""><br>
電源LED：正面左上に位置、端子（S1-S2）にDC24Vを印加すると緑色に点滅。<br>
不足電圧検出LED：正面右上、R・S・Tの３つ。オレンジ色。整定電圧以下になると点灯？<br><br>

動作表示LED<br>
正面右下、赤色。<br>
3相のいずれかが不足電圧となった状態で動作する3相のOR動作。<br>
不足電圧状態が整定時間以上継続した場合に接点動作＋LED点灯。<br>
動作して赤色点灯した場合、復帰ボタンを押さないと点灯を維持？（接点は自動復帰）<br>


<h2>三相UVRで電圧を監視する理由</h2>
電力系統側で短絡事故が起こると、受電端で各線間の電圧が低下する。<br>
また、系統側停電時においても、電圧が下がる。<br><br>

なので、受電端の電圧を監視することで、系統側事故を検出することができる。<br>
そして、発電機を系統から解列させることができる。<br><br>
２相短絡時にもUVRを動作させる必要がある。<br>
そのためUVRは３相検出用でなければならない。<br>

