<h2>電灯や動力のLBSがヒューズ溶断で開放されていた場合</h2>

高圧一括受電マンションで共用動力TrのLBSのPFが溶断で開放した場合。<br>
ヒューズ交換するために全館停電させる？それとも１次側充電状態で交換する？<br><br>

Xフォロワー様からの意見（電気管理技術者様）<br>
・電気主任技術者は、何をさておいても安全優先を基本とすべき。<br>
・LBSは古いと絶縁低下してる物もあり、開放されていても安全かどうかわからない。<br>
・無停電で交換しろと言われたら絶対に断る。<br>

