<h2>LBSがヒューズ切れにより開放されていた場合、どうする？</h2>

まずLBS１次側が充電状態でLBSのヒューズを交換してはいけない。<br>
充電部近接作業で感電の恐れがある。<br>

<h2>高圧コンデンサのLBSが切れていた場合</h2>
LBSヒューズが切れた原因を調査するため、コンデンサを調べる。<br>
コンデンサが相間短絡していた場合、ヒューズを替えても再度ヒューズ溶断する可能性。<br><br>

コンデンサの調べ方<br>
コンデンサの相間の静電容量をテスターを使ってRS、ST、TR間の３箇所を調べる。<br>
もし相間短絡していた場合、静電容量の値に違いが出るはず。<br><br>

