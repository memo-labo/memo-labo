<h2>電気工作物の区分</h2>

<img src="images/kubun.svg" style="max-width:600px;" alt="電気工作物の区分"><br>

<p><strong>現在の電気事業法では、電気工作物は大きく「一般用電気工作物」「小規模事業用電気工作物」「事業用電気工作物」に区分されます。</strong></p>

<ul>
  <li>一般用電気工作物：主に600V以下で受電する住宅・商店など</li>
  <li>小規模事業用電気工作物：10kW以上50kW未満の太陽電池発電設備、20kW未満の風力発電設備など</li>
  <li>事業用電気工作物：一般用・小規模事業用以外の電気工作物</li>
</ul>

<p>自家用電気工作物は、事業用電気工作物のうち、電気事業の用に供するもの以外の設備を指します。高圧で受電する工場・ビル・キュービクル設備などが代表例です。</p>

<h2>一般用電気工作物</h2>

<p>主に600V以下で受電し、一般家庭、商店、小規模事務所などで使用される電気設備です。</p>

<p>一般用電気工作物では、事業用電気工作物のような保安規程の届出や電気主任技術者の選任は通常求められません。</p>

<p>発電設備では、たとえば<strong>出力10kW未満の太陽電池発電設備</strong>など、一定の条件を満たす低出力設備が一般用電気工作物に該当します。</p>

<h2>小規模事業用電気工作物</h2>

<p>2023年3月から設けられた区分です。</p>

<ul>
  <li>太陽電池発電設備：出力10kW以上50kW未満</li>
  <li>風力発電設備：出力20kW未満</li>
</ul>

<p>小規模事業用電気工作物では、保安規程の届出や主任技術者の選任は不要ですが、対象設備では<strong>基礎情報の届出や使用前自己確認</strong>などが必要になります。</p>

<p>設備条件や運転開始時期によって扱いが変わるため、実際の手続きは経済産業省・所管の産業保安監督部の最新資料で確認します。</p>

<h2>自家用電気工作物</h2>

<p>一般用電気工作物・小規模事業用電気工作物や、電気事業の用に供する設備を除いた事業用電気工作物です。</p>

<p>代表例は次のとおりです。</p>

<ul>
  <li>600Vを超える電圧で受電する工場・ビル・店舗などの需要設備</li>
  <li>一定規模以上の自家用発電設備</li>
  <li>構外にわたる電線路を有する設備</li>
  <li>その他、法令上自家用電気工作物として扱われる設備</li>
</ul>

<p>高圧受電設備（6.6kV受電のキュービクルなど）は、一般的に自家用電気工作物に該当します。</p>

<h2>事業用電気工作物</h2>

<p>一般用電気工作物および小規模事業用電気工作物以外の電気工作物です。</p>

<p>自家用電気工作物のほか、発電所、変電所、送電線、配電線など、電気事業に使用される設備も含まれます。設備の種類に応じて、保安規程、主任技術者、工事計画、使用前自主検査などの保安規制が適用されます。</p>

<h2>太陽光発電の区分で間違えやすい点</h2>

<ul>
  <li>10kW未満：一定条件のもと一般用電気工作物</li>
  <li>10kW以上50kW未満：小規模事業用電気工作物</li>
  <li>50kW以上：原則として小規模事業用ではない事業用電気工作物</li>
</ul>

<p>以前は「50kW未満の太陽光＝一般用」と説明されることがありましたが、現在は10〜50kW未満に小規模事業用電気工作物の区分があります。</p>

