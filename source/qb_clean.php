<p>キュービクル（QB）内の清掃で、個人的にかなり使いやすいと感じているのが「サッサ」。</p>

<ul>
<li>ホコリが取れる</li>
<li>汚れも落ちる</li>
<li>表面がピカピカになる</li>
<li>清掃後はホコリが付きにくく感じる</li>
</ul>

<p>かなり汚れていたQB内をサッサでピカピカにしたことがある。翌年の点検で、モップで軽く拭いてからブロワーをかけたところ、すぐにピカピカの表面が出てきた。このときは清掃の効果にちょっと感動した。</p>

