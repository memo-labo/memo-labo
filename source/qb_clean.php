<h2>キュービクル内の清掃｜サッサでホコリ・汚れを落とす</h2>

<p>キュービクル（QB）内の清掃で、個人的にかなり使いやすいと感じているのが「サッサ」。盤面や金属面のホコリを取りやすく、軽い汚れも落としやすい。</p>

<ul>
<li>ホコリが取れる</li>
<li>軽い汚れも落としやすい</li>
<li>表面がピカピカになる</li>
<li>清掃後はホコリが付きにくく感じる</li>
</ul>

<p>かなり汚れていたQB内をサッサでピカピカにしたことがある。翌年の点検で、モップで軽く拭いてからブロワーをかけたところ、すぐにきれいな表面が出てきた。このときは清掃の効果をかなり実感した。</p>

