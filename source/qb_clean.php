<h2>キュービクル清掃で確認したい場所</h2>
<ul>
<li>盤面・機器表面のホコリや汚れ</li>
<li>床面の油漏れ・雨漏り跡</li>
<li>小動物や虫の侵入跡</li>
<li>がいし・高圧クリート周辺の汚損</li>
</ul>
<p>床をきれいにしておくと、新しい油染みや水跡などの変化にも気づきやすい。がいし周辺については<a href="gaishi.php">高圧クリート・がいしの清掃</a>も参照。</p>

<h2>清掃時の注意</h2>
<p>キュービクル内の清掃は、充電部への接触や水分の付着が事故につながるため、安全を確保した状態で行う。水や濡れたウエスを使用する場合は特に、充電部や機器内部へ水分が入らないよう注意する。</p>
<p>停電・検電・接地など必要な安全措置を行ったうえで作業し、ウエスは水が垂れない程度まで固く絞る。ブロワーもホコリを機器内部へ押し込まないよう、吹き出す方向に注意する。</p>

