<h2>零相電圧とは</h2>
三相交流回路の、中性点の対地電圧のこと。<br>
V0(ブイゼロ)とも呼ぶ。<br><br>

三相交流回路の各相の電圧は、同じ大きさで120度ずつの位相差を持っている。<br>
この各相の電圧の大きさや位相が不揃いになると、V0電圧が発生する。<br>
三相回路において地絡事故が発生した場合、三相が不平衡になることで発生する。<br><br>

