対称三相交流の場合、次の式が成立する。<br>
① V0 = (Va + Vb + Vc) / 3<br>
② Va + Vb + Vc = 0V<br>
③ V0 = 0V<br><br>

地絡などで三相の対地電圧が不平衡になると、Va + Vb + Vc が0ではなくなり、零相電圧V0が発生する。<br>

<h2>6.6kV系統で完全一線地絡するとV0が3810Vになる理由</h2>
6.6kV三相3線式では、健全時の相電圧は、<br>
6600V / √3 ≒ 3810V<br>
となる。<br><br>

A相が完全地絡した場合、地絡相の対地電圧Vaは0Vになる。<br>
その一方で健全なB相、C相の対地電圧は線間電圧相当の6600Vまで上昇する。<br>
このとき3相のベクトル和を求めると3V0は約11430Vとなり、<br>
V0 = 3V0 / 3 = 3810V<br>
となる。<br>
<img src="images/v0/6.png" alt="完全一線地絡時の零相電圧" style="max-width:500px;"><br>

<h2>地絡の大きさを％で表すときの基準</h2>
6.6kV系統では、完全一線地絡時のV0 = 3810Vを100%として扱う。<br>
そのため、<br>
5% = 190.5V<br>
10% = 381V<br>
となる。<br><br>

保護継電器の「零相電圧5%」「零相電圧10%」という整定値は、この完全地絡時のV0を基準とした割合。<br>

<h2>ZPDで零相電圧を検出する</h2>
高圧受電設備では、零相電圧をそのまま継電器へ入力するのではなく、ZPD（零相電圧検出装置）で検出して低い電圧に変換し、DGRやOVGRへ入力する。<br>
ZPDは各相と大地間の電圧をコンデンサで分圧し、地絡時に発生する零相電圧を検出する。<br><br>

継電器に入力される電圧は、実際の高圧側V0そのものではなく、ZPDで変換された二次側の信号電圧。<br>
試験時は、継電器の端子へ何Vを印加するかではなく、使用しているZPD・継電器の変換比やメーカー試験方法を確認する。<br>

<h2>DGRとOVGRでのV0の使い方</h2>
<h3>DGR（地絡方向継電器）</h3>
DGRは、ZPDで検出した零相電圧V0と、ZCTで検出した零相電流I0の位相関係を見て、地絡事故の方向を判定する。<br>
単純に地絡電流の大きさだけを見るのではなく、自回線事故か他回線事故かを判別できるのが特徴。<br><br>

<h3>OVGR（地絡過電圧継電器）</h3>
OVGRは零相電圧V0の大きさを監視し、設定値を超えたときに動作する。<br>
DGRのようなV0とI0の方向判定は行わない。<br><br>

※RPR（逆電力継電器）は逆電力を監視する継電器であり、零相電圧を検出する地絡保護継電器とは別の用途。<br>

<h2>SOG・DGRの零相電圧5%整定</h2>
PASやUGSに組み合わされるSOG制御装置やDGRでは、零相電圧要素を5%程度に整定する例がある。<br>
6.6kV系統で5%なら、一次側V0換算で、<br>
3810V × 5% = 190.5V<br>
となる。<br><br>

ただし、実際の整定値は設備仕様、継電器形式、電力会社との保護協調によって決まるため、一律に5%と考えないこと。<br>
現場では継電器の銘板・整定表・メーカー資料・電力会社との協議値を確認する。<br>

<h2>零相電圧を見るときの現場ポイント</h2>
・健全時はV0はほぼ0V<br>
・地絡で三相の対地電圧が崩れるとV0が発生する<br>
・6.6kV系統の完全一線地絡時はV0 = 3810V<br>
・3V0はV0の3倍で、完全地絡時は約11430V<br>
・高圧受電設備ではZPDでV0を検出して継電器へ入力する構成が一般的<br>
・DGRはV0とI0の位相関係、OVGRは主にV0の大きさを利用する<br>
・零相電圧5%などの整定値は、完全地絡時V0を100%とした割合<br>
・試験時はZPDと継電器の組み合わせ、変換比、メーカー試験方法を確認する<br>

