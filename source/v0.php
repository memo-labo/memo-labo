対称三相交流の場合、次の式が成立する。<br>
① V0=(Ea+Eb+Ec)/3<br>
② Ea+Eb+Ec=0(V)<br>
③ V0=0(V)<br>
※Ea、Eb、Ecは、各相の起電圧（対地電圧）のこと<br>

<h2>完全一線地絡時の零相電圧が3810Vの理由</h2>
3相のうち1線が完全地絡した場合、地絡相の対地電圧 Va はゼロになる。<br>
Vaがゼロになるので、健全２相の対地電圧、Vb、Vcは健全時の線間電圧まで上昇する（3810V ✕ √3 = 6600V）<br>
図より、Vb、Vcのベクトル和は（6600V × cos30°）× 2 = 11430V<br>
地絡時の零相電圧は各相の起電圧（対地電圧）の和なので、V0 = 11430V / 3 = 3810V<br>
