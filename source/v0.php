<h2>零相電圧 V0 とは</h2>
零相電圧（V0）は、三相各相の対地電圧をベクトル的に合成したときに現れる零相分の電圧。<br>
三相が平衡している健全時は各相のベクトル和が0になるため、V0もほぼ0Vとなる。<br>
一方、1線地絡などで三相の対地電圧が不平衡になるとV0が発生する。<br><br>

式で表すと、<br>
V0 = (Va + Vb + Vc) / 3<br>
となる。<br>
※Va、Vb、Vcは各相の対地電圧。<br><br>

<h2>V0と3V0の違い</h2>
現場では「V0」と「3V0」が混在するので注意。<br>
V0は各相対地電圧のベクトル和を3で割った零相電圧成分。<br>
3V0はその3倍で、<br>
3V0 = Va + Vb + Vc<br>
となる。<br><br>

6.6kV系統で完全一線地絡した場合、<br>
V0 = 3810V<br>
3V0 = 11430V<br>
となる。<br>
保護継電器や試験器の仕様では、どちらを基準に表しているか確認が必要。<br>

