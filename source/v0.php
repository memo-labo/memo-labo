<h2>UGSやPASのSOGの電圧整定値は5%</h2>
上位の電力会社の変電所と保護協調を取るため、電力会社から指定される。<br>
SOGの零相電圧の動作値は、5% = 190.5V にて動作する。<br>
100% = 3810V<br><br>

3810Vとは？<br>
完全一線地絡時の零相電圧<br>


