<h2>便利な工具「ワイヤーストリッパー」での失敗談</h2>


VVFケーブルを剥く、切る、曲げるが簡単に出来る、すごく便利な工具。<br>
特に第二種電気工事士試験の「実技」に最適。作業時間が短縮できてミスも減る。<br><br>

<img src="images/denki-1-1.jpg" style="max-width:250px;" alt=""><br>

しかし新人の電気工事士は、基本工具からスタートした方が絶対に良い。<br>
基本工具というのは、電工ナイフ、ペンチ、ニッパーなどのこと。<br><br>


現場では、ナイフ、ペンチ、ニッパーでしか対応できない場面が多数出てくる。<br>
例えば活線状態のVVFを断線する場合、途中で剥いて導線を１本ずつ切ってテープで絶縁しながら断線する。<br>
その際、VVFの中間に電工ナイフを刺して中間を広げるので、電工ナイフの使い方が必須。<br>
電工ナイフに慣れていないと、手を切ったり、導線を傷つけたり、時間がかかったりする。<br><br>

