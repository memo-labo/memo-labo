また、自分の工具を忘れて、先輩から借りる場合なんてこともある。<br>
そのとき「ナイフ使えませ～ん」なんて言ったら当然怒られる。<br><br>

また、太めのCVケーブルなど剥く時は、ナイフ、ペンチ、ニッパー等で行う。<br>
そうなると当然、VVFストリッパーは使えない。<br><br>

なのでナイフとペンチで対応できるように練習しておく必要がある。<br>
いざというとき、すごく苦戦するし、事故の元となる。<br><br>

基本工具の使い方に慣れた後で、便利な工具に手を出すのは良いと思う。<br><br>


