<h2>電気事業法施行規則　第三十八条</h2>

電圧及び周波数の値<br>
第三十八条　法第二十六条第一項の経済産業省令で定める電圧の値。<br><br>

標準電圧：維持すべき値<br>
百ボルト：百一ボルトの上下六ボルトを超えない値<br>
二百ボルト：二百二ボルトの上下二十ボルトを超えない値<br><br>

２ 法第二十六条第一項の経済産業省令で定める周波数の値は、その者が供給する電気の標準周波数に等しい値とする。<br><br>

まとめ<br>
101V ±6V (95～107V) が許容範囲<br>
202V ±20V (182～222V) が許容範囲<br><br>

高圧受電設備において低圧の電圧をテスターで測定。<br>
許容範囲を上回る、または下回ることが常態化している場合の対処法。<br>
