<h2>公称電圧・定格電圧・最高電圧・耐電圧の違い</h2>

似た言葉だが、見ている対象が異なる。<br><br>

<table>
<tr><th>用語</th><th>意味</th></tr>
<tr><td>標準電圧</td><td>電気事業者が供給する電圧の基準となる値</td></tr>
<tr><td>公称電圧</td><td>電路・系統を代表して呼ぶための電圧</td></tr>
<tr><td>定格電圧</td><td>機器を設計・使用するときの基準となる仕様上の電圧</td></tr>
<tr><td>最高電圧（最大使用電圧）</td><td>通常運転状態でその系統に現れる線間電圧の上限として定める値</td></tr>
<tr><td>耐電圧</td><td>規定された条件・時間で絶縁が耐えなければならない試験電圧</td></tr>
</table>
<br>

6.6kV系統を例にすると、<br>
公称電圧：6.6kV<br>
最高電圧：6.9kV<br>
となる。<br><br>

機器の「定格電圧」と、絶縁性能を確認する「耐電圧」は別物なので混同しない。<br>

<h2>電気事業法施行規則　第三十八条</h2>

電圧及び周波数の値<br>
第三十八条　法第二十六条第一項の経済産業省令で定める電圧の値。<br><br>

標準電圧：維持すべき値<br>
百ボルト：百一ボルトの上下六ボルトを超えない値<br>
二百ボルト：二百二ボルトの上下二十ボルトを超えない値<br><br>

２ 法第二十六条第一項の経済産業省令で定める周波数の値は、その者が供給する電気の標準周波数に等しい値とする。<br><br>

まとめ<br>
101V ±6V（95～107V）が範囲<br>
202V ±20V（182～222V）が範囲<br><br>

高圧受電設備において低圧側電圧をテスターで測定し、電圧の高い・低い状態が継続している場合は、負荷状況や一次側電圧なども確認したうえで変圧器タップの検討を行う。<br>
