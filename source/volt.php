<h2>定格電圧 Rated Voltage</h2>
定格電圧は、その機器を設計・使用するときの基準としてメーカーが定める仕様上の電圧。<br>
単純に「これ以上なら直ちに壊れる最大電圧」という意味ではない。<br><br>

機器を選定するときは、使用する電路の電圧と機器の定格電圧を照合し、メーカー仕様・規格で定められた条件内で使用する。<br>

<h2>耐電圧</h2>
耐電圧は、規定された試験条件で絶縁破壊やフラッシオーバなどを生じずに耐えることを確認するための電圧。<br>
定格電圧とは目的が異なる。<br><br>

高圧機器やケーブルでは、使用電圧に応じて絶縁耐力試験の試験電圧が定められている。<br>
⇒<a href="vtest2.php">絶縁耐力試験の試験電圧</a><br>

<h2>公称電圧（Nominal Voltage）</h2>
その電線路・系統を代表して呼ぶための電圧。<br>
例えば高圧受電で一般的な「6.6kV」は公称電圧。<br><br>

法令や規格では文脈によって「使用電圧」など別の表現が使われることもあるため、条文・規格での定義を確認する。<br>

<h2>最高電圧（最大使用電圧）</h2>
異常時のサージ電圧ではなく、通常の運転状態でその回路に加わる線間電圧の最大値として定める値。<br>
最大使用電圧は、JECで公称電圧との関係が定められている。<br><br>

①公称電圧が1,000V以下の電路：公称電圧の1.15倍<br>
②公称電圧が1,000Vを超え500kV未満の電路：公称電圧の（1.15 / 1.1）倍<br><br>

例えば公称電圧6.6kVの場合、<br>
6.6kV ×（1.15 ÷ 1.1）≒ 6.9kV<br>
となる。<br>

