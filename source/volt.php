<h2>定格電圧 Rated Voltage</h2>
電気機器を安全に使用するための最大電圧のこと。<br>
メーカーによって保証されている最大電圧である。<br><br>

定格電圧以上の電圧で電気機器を使用してはいけない。<br>
定格電圧以上の電圧で使用した場合、電気機器はすぐに壊れることはないが、安全性の保証はない。<br>

<h2>耐電圧</h2>
絶縁破壊が生じることなく印加できる電圧の最大値のこと。<br>
定格電圧と耐電圧は全く異なる。<br><br>

商用電源の電圧は常に一定ではなく、雷のサージ電圧などによって電圧が跳ね上がる事がある。<br>
商用電源に接続されている電気機器や部品は、この過渡の過電圧に耐える必要がある。<br>
そのため、定格電圧よりも耐電圧の方が高くなっている。<br><br>

定格電圧100Vの部品でも、耐電圧は1000Vなどの部品もある。<br>
これを使用する場合は100V以下で使用し、過渡的に生じる過電圧は1000Vまで耐えることができる。<br>
耐電圧は、絶縁耐力 (Dielectric Strength)とも呼ばれる。<br>

<h2>公称電圧(Nominal Voltage)</h2>
その電線路を代表する線間電圧のこと。<br>
電技では条文の中で公称電圧のことを使用電圧と呼んでいる。<br>

<h2>最高電圧（最大使用電圧）</h2>
異常電圧のことではなく、通常の運転状態でその回路に加わる線間電圧の最大値のこと。<br>
最大使用電圧は、JECにより以下のように定められている<br>
①公称電圧が1,000〔V〕以下の電路は、その電路の公称電圧の1.15 倍<br>
②公称電圧が1,000〔V〕を超え500〔kV〕未満の電路は、その電路の公称電圧の(1.15/1.1) 倍<br><br>

例えば公称電圧6.6kVの最高電圧は、6.6kV ✕（1.15 ÷ 1.1）= 6.9kV<br>
これは、最大使用電圧は受電端電圧の115%を見ておけばよいだろうという考え方によるもの。<br>
軽負荷運転または無負荷運転の場合の電圧変動を考慮に入れている。<br><br>

