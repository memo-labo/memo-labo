成極比による判定基準<br>
１以上：良<br>
0.5～１：要注意<br>
0.5以下：不良<br><br>

成極比とは？<br>
=電圧印加１分後の漏れ電流値÷電圧印加規定後の漏れ電流値<br>
=電圧印加規定後の絶縁抵抗値÷電圧印加１分後の絶縁抵抗値<br>


