<h2>直流耐電圧試験</h2>

電気設備の技術基準の解釈<br>
【高圧又は特別高圧の電路の絶縁性能】（省令第5条第2項）第15条<br><br>

高圧又は特別高圧の電路（第13条各号に掲げる部分、次条に規定するもの及び直流電車線を除く。）は、次の各号のいずれかに適合する絶縁性能を有すること。<br><br>

一 15-1表に規定する試験電圧を電路と大地との間（多心ケーブルにあっては、心線相互間及び心線と大地との間）に連続して10分間加えたとき、これに耐える性能を有すること。<br><br>

二 電線にケーブルを使用する交流の電路においては、<span style="color:red;">15-1表に規定する試験電圧の2倍の直流電圧を電路と大地との間（多心ケーブルにあっては、心線相互間及び心線と大地との間）に連続して10分間</span>加えたとき、これに耐える性能を有すること。<br>

