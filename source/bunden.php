<h2>分電盤のトラブル</h2>
分電盤の主幹ELBが、その下にある子ELBより先にトリップしてしまう。<br>
各子ELBでの漏洩電流値が小さくても、それが合計されることで主幹ELBがトリップ。<br>
この場合、どの回路も不具合はないのに主幹だけがトリップしてしまう現象が発生。<br>
または主幹トリップはしないが感度電流以上で警報が鳴るというトラブル。<br>
現場にかけつけても個別の各回路には異常がなく特定ができない。<br><br>

ELBがついてない分電盤<br>
ELBではなくMCCBなのでいくら漏電していてもトリップしない。<br>
そのため10Aを超える電流が漏れていたとしてもトリップせず流れっぱなし。<br>
人が触れれば感電、熱を持てば火災の危険性がある。<br>
せめて主幹ブレーカーだけはELBにすべき<br><br>

主幹ELBの下にある子ELBが動作緩慢<br>
そのため下流の子ELBが動作する前に主幹ELBがトリップ<br>
主な原因はELBの使用環境と年数経過による経年劣化<br>



