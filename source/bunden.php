分電盤のD種接地<br>
キュービクルや電気室の方からD種接地線がきていて、分電盤に接続されている。<br>
現場によっては構造体に接地されていたり直接地面に接地されている場合もある。<br><br>

キュービクルや電気室側の接地を接地端子盤にて切り離していた場合どうなる？<br>
⇒分電盤のアースがとれていない状態で絶縁抵抗測定するとすべて∞Ωとなる。<br><br>

分電盤でのメガーのゼロチェック<br>
キュービクルのトランス⇒キュービクルMCCB⇒分電盤の主幹MCCBと繋がっている。<br>
キュービクルMCCBを投入状態で、分電盤の接地端子と分電盤の主幹MCCB１次側でゼロチェックを行う。<br>
そうすると分電盤のD種接地とキュービクルのB種接地でゼロチェックを行うことができる。<br><br>

