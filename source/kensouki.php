<h2>正相と逆相</h2>
三相交流はR相、S相、T相で表し、各相の順番のことを、相回転あるいは相順と呼ぶ。<br>
R、S、Tの各相は、120度の位相差がある。<br>
R相を基準としたとき、S相は120度遅れ、T相はR相より240度遅れている。<br>
三相交流回路の相回転が逆になると、三相誘導電動機は逆回転になる。<br><br>

※三相交流回路とは？<br>
電流または電圧の位相を120°ずつずらした、３系統の単相交流を組み合わせた回路。<br>

<h2>モーターの回転方向</h2>
日本のJIS規格では「軸の反対方向から見て時計方向を正回転とする」とされている。<br>
