<h2>相順の接続間違い</h2>
・PAS交換工事（PAS２次側リード線⇔引き込み側CVケーブル）<br>
・VCT交換工事（ケーブルが固定されている場合、間違える可能性は低い）<br>
・引き込み、サブ変送りCVケーブル交換工事（見分け用の色テープ自体を貼り間違えた場合・夜間作業や色弱で繋ぎ間違い）<br><br>


注意<br>
トランス２次側で逆相でも、その下流で正相に直してるケースもある。<br>
例えば動力主幹MCCB２次側で検相をしたところ逆相。<br>
そして動力主幹MCCBより下段にある各動力MCCB１次側で検相したら正相、という場合も。<br>
また、最初から逆相の状態で運用してるなら相を変えると逆相運転の機器が壊れる場合も。<br>
正相機器を逆相でつないだ場合、機種によっては防止機構が働いて止まる。<br>
古い機器の場合、それがついてない可能性があり、故障する場合も。<br>

