<h2>逆相のデメリット</h2>
電動機を逆回転させることを想定していない設計の場合<br>
・大きな抵抗が発生する<br>
・冷却機能が損なわれる<br>
・異常加熱や焼損の原因となる<br>


<h2>逆相電流</h2>
発電機から不平衡負荷への電源供給を行うと、回転子磁界と逆方向に流れる電流のこと。<br />
逆相電流が過大になると、発電機が異常振動したり、固定子が発熱して故障する可能性。<br />
逆方向の電流によって有効なトルクが減少し、効率低下、出力低下につながる。<br />


<h2>逆相を防ぐ 逆相リレー</h2>
逆相結線によるモーターの逆回転を防止するため逆相リレー（逆転防止リレー）を設置。<br>
逆走状態での起動スイッチの動作を抑制する制御が必要となる。<br>
逆相状態では、MC（マグネットコンタクタ）が動作せず、モーターが始動できず、安全装置として機能する。<br>
３本の電源線の逆接続異常を検出し、コンタクタ投入を防止することで、モータの逆回転動作を防止する。<br>


<h2>電線の識別標識</h2>
電力会社側と需要家側で、R相、S相、T相の色順が違っていることがある。<br />
PAS交換工事などで接続を間違うと逆相となり電気機器の故障につながる。<br />
