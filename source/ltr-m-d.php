<h2>交換・更新時に確認すること</h2>

<ul>
  <li>PASと制御装置の組み合わせ適合</li>
  <li>制御ケーブルの端子番号</li>
  <li>接地方式</li>
  <li>警報接点・遠方監視回路</li>
  <li>試験方法と整定値</li>
</ul>

<p>後継機へ更新する場合も、端子番号や内部回路が完全互換とは限りません。既設配線を記録し、メーカーの更新資料・接続図を照合します。</p>

