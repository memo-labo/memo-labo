<h2>LTR-M-D（戸上電機）とは？</h2>

<p><strong>LTR-M-Dは、戸上電機製のSOG制御装置関連で見かける型式です。</strong><br>
PASと組み合わせて使用される制御装置は、地絡事故の検出やPASの引外し制御などを行います。</p>

<p>同じSOG制御装置でも製造年代・PAS形式・制御電源・方向性の有無などで仕様が異なるため、<strong>型式だけで配線や試験条件を決めず、銘板と取扱説明書を確認します。</strong></p>

<img src="images/ltr-m-d1.jpg" style="max-width:800px;" alt="戸上電機 LTR-M-D SOG制御装置"><br>

<h2>現場で最初に確認するところ</h2>

<ul>
  <li>制御装置の正確な型式</li>
  <li>組み合わせるPASの型式・製造年</li>
  <li>制御電源の定格</li>
  <li>P1・P2など電源端子の配線</li>
  <li>ZCT・零相電圧検出回路の接続</li>
  <li>トリップ出力・警報接点の端子</li>
  <li>試験端子・試験スイッチの有無</li>
</ul>

<h2>SOGボックス裏面の注意書き</h2>

<img src="images/ltr-m-d2.jpg" style="max-width:800px;" alt="LTR-M-D SOG制御装置の注意書き"><br>

<p>古いSOG制御装置では、本体やボックス裏面に試験・接地・配線上の注意事項が記載されていることがあります。</p>

<p><strong>現場試験では、この注意書きを写真で記録してから作業すると、配線復旧や試験電源の条件確認に役立ちます。</strong></p>

<h2>SOG試験時の重要ポイント</h2>

<p>SOG制御装置を試験するときは、既設の制御電源と試験器の補助電源を不用意に重ねて印加しないようにします。</p>

<p>特にPAS内蔵VTからP1・P2へ給電されている設備では、接続状態によっては試験電源がVT側へ回り込むおそれがあります。離線・絶縁の要否は対象機種の取扱説明書と現場回路を確認します。</p>

