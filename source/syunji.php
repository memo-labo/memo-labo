<h2>OCR瞬時要素の試験とは？</h2>

<p>OCR（過電流継電器）の瞬時要素は、短絡などの大電流を速く検出する要素です。試験では主に<strong>瞬時動作電流値</strong>と<strong>瞬時動作時間</strong>を確認します。</p>

<p>JIS C 4602:2017では、瞬時要素の動作値は整定値に対して<strong>±15%</strong>、瞬時動作時間は所定の試験条件で<strong>0.05秒以下</strong>とされています。</p>

<p>ただし、実際の試験条件・判定値は継電器の形式、メーカー仕様、取扱説明書、保安規程などを優先して確認します。</p>

<h2>瞬時要素の最小動作電流試験</h2>

<p>試験前に現在の整定値を必ず記録し、試験後に元へ戻します。</p>

<ol>
  <li>瞬時要素を試験する整定値へ合わせる。</li>
  <li>限時要素が先に動作しないよう、メーカー指定の方法で限時要素をロックする。</li>
  <li>試験電流を0Aから徐々に上げる。</li>
  <li>瞬時要素が動作した時点の電流値を読む。</li>
  <li>R相・T相など必要な各相で確認する。</li>
  <li>試験終了後、整定値・ロック状態・配線を元へ戻す。</li>
</ol>

<p>例として瞬時整定20Aなら、JISの±15%を基準とする場合の範囲は17〜23Aです。</p>

<p><strong>試験器の指針・メモリ・デジタル表示の読み方は機種によって違うため、試験器の取扱説明書に従います。</strong></p>

<h2>限時要素をロックする理由</h2>

<p>瞬時動作電流を確認する途中で限時要素が動作すると、瞬時要素だけの動作値を正しく確認できません。</p>

<p>静止形OCRではロック機能、誘導形OCRではメーカー指定の試験方法を使用します。誘導円盤を無理に固定するなど、取扱説明書にない方法は避けます。</p>

<h2>OCR瞬時要素の動作時間試験</h2>

<p>JIS C 4602の代表的な試験では、瞬時要素を最小動作電流整定値とし、その<strong>200%の電流を急激に印加</strong>して動作時間を測定します。</p>

<p>例：</p>
<ul>
  <li>瞬時要素整定：20A</li>
  <li>試験電流：40A（200%）</li>
  <li>瞬時要素動作時間：0.05秒以下</li>
</ul>

<p>ただし、旧形・特殊仕様・メーカー独自仕様では条件が異なることがあるため、銘板・取扱説明書・試験成績書を確認します。</p>

<h2>OCRとVCBの連動試験</h2>

<p>OCR単体が正常でも、トリップ回路、補助電源、接点、VCBの引き外しコイルなどに不具合があると遮断できません。</p>

<p>必要に応じて連動試験を行い、次を確認します。</p>

<ul>
  <li>OCR瞬時要素が動作するか</li>
  <li>動作表示・接点信号が出るか</li>
  <li>VCBが確実に開放するか</li>
  <li>試験後に整定・配線・表示を復帰したか</li>
</ul>

<p>限時要素ではVCBが開放するのに、瞬時要素だけで開放しない場合は、OCR瞬時要素だけでなく、瞬時要素の出力接点や連動回路も含めて切り分けます。</p>

<h2>試験時の注意</h2>

<ul>
  <li>試験前の整定値を記録する</li>
  <li>試験電流を長時間流さない</li>
  <li>CT二次回路を不用意に開放しない</li>
  <li>試験後に整定値・ロック・配線を確実に復帰する</li>
  <li>継電器・試験器の取扱説明書を優先する</li>
</ul>

