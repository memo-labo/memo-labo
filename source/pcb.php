<h2>PCBによる人体への影響</h2>
PCBは生体に一度取り込まれると、体内では分解されずに残ってしまうという特徴がある。<br>
体内に残存したまま食物連鎖で移動し続け、食物連鎖の上位にある人間や肉食動物ほどPCBの影響を受ける。<br>
大気や食事、水などを通じて世界中に広がっており、多くの野生動物も汚染されている。<br>
簡単には分解されないので、汚染された環境が改善されるまで長い年月を要してしまう。<br><br>

したがって、早期のPCBの流出阻止と廃棄などの対処が世界各国で急がれている。<br>
人間が大量のPCBを摂取した場合、発疹、色素沈着、肝機能障害、免疫機能低下などが起こる可能性。<br>
発がん性の疑い、慢性的な蓄積による影響、神経や免疫への影響から肺炎やウイルス性の病気にかかりやすくなる。<br>
PCBなどの有害物質は人のへその緒に残留、母親の体内にPCBが蓄積すると、へその緒から胎児に影響を及ぼす。<br>

<h2>JESCOとは？</h2>
中間貯蔵・環境安全事業（株）<br>
JAPAN ENVIRONMENTAL STORAGE & SAFETY CORPORATION<br>
環境省が所管する、日本環境安全事業株式会社法（現・中間貯蔵・環境安全事業株式会社法）によって設立された日本の特殊会社。<br>


<h2>PCBを処分しないとどうなる？</h2>
PCB特措法では、PCB廃棄物の保管事業者に対して、環境大臣または都道府県知事が、<br>
「現状で使用中の高濃度PCB使用製品を含め、原則として処分期間中に、遅くとも計画的処理完了期限までに処分を完了するように」<br>
という改善命令を出すことができる。<br><br>

この改善命令に従わなかった場合、3年以下の懲役もしくは1,000万円以下の罰金またはその併科が処せられる。<br><br>

JESCOの各エリアでの事業終了までに高濃度PCB廃棄物を処分できなかった場合<br>
①危険物としての厳重な保管責任をいつまでも負い続ける<br>
②排出事業者が自ら処分するために莫大な設備投資をして化学処理や高温焼却処分をする（実質的に無理）<br>


