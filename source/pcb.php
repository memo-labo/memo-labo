<h2>PCB（ポリ塩化ビフェニル）</h2>
「絶縁油に必要な特徴」が備わっており昔はよく使用されていた。<br>
発がん性等の有毒性が指摘され、近年は使用されることはない。<br>


<h2>低濃度PCB絶縁油とは？</h2>
PCBの製造は1974年に中止された。<br>
2002年、PCBを使用していないはずの電気機器の絶縁油に微量のPCBが含まれている事が判明した。<br>
混入の原因は、再生油や製造工程で混入したと考えられているが、解明は出来ていない。<br>
絶縁油の場合、非意図的にPCBが混入し、かつPCB濃度が5,000mg/kg以下のものを「低濃度PCB廃油」と呼ぶ。<br>

<h2>PCB含有と製品の年代</h2>
製造時点でPCBによる汚染の可能性がある電気機器の製造時期<br>
絶縁油交換が可能な機器（変圧器等）：1993年以前<br>
絶縁油封じ切り機器（コンデンサー、避雷器等）：1990年以前<br>


<h2>高濃度PCB絶縁油とは？</h2>
PCBを使用した電気機器廃棄物のこと。<br>
一般的にコンデンサはPCB濃度概ね100%<br>
一般的にトランスはPCB濃度概ね60%<br>


<h2>PCBの処分方法・処分期限</h2>
低濃度PCB廃棄物は、許可を持つJESCO以外の民間処理業者で処分ができる。<br>
高濃度PCB廃棄物は、JESCOの全国5か所のPCB廃棄物処理施設でしか処理ができない。<br><br>



