<h2>タイトランス（連絡用変圧器）とは？</h2>

<p>タイトランス（Tie Transformer）は、異なる母線・系統を変圧器を介して連絡するために使われる変圧器です。</p>

<p>「Tie」は「結ぶ・連絡する」という意味で、設備によっては<strong>連絡用変圧器</strong>と呼ばれます。</p>

<h2>どんなときに使う？</h2>

<p>代表的には、構内に異なる電圧階級の系統が残っている場合や、既設設備と新しい受電系統をつなぐ場合に使われます。</p>

<ul>
  <li>6.6kV系統から3.3kV系統へ給電する</li>
  <li>既設の3.3kV高圧モータを6.6kV受電設備から使用する</li>
  <li>工場・プラント内の異なる母線間を変圧器を介して連絡する</li>
  <li>設備更新時に既設電圧の機器を継続使用する</li>
</ul>

<p>単なる「同じ電圧同士をつなぐ変圧器」という意味ではなく、<strong>系統連絡の目的で設けられる変圧器</strong>と考えると分かりやすいです。</p>

<h2>6.6kV受電設備に3.3kV回路が残る理由</h2>

<p>古い工場や大規模プラントでは、3.3kV定格の高圧モータや既設設備が残っていることがあります。</p>

<p>受電系統を6.6kVへ更新しても、既設の3.3kV機器をすべて同時に更新するのは大きな費用がかかります。そのため、6.6kVから3.3kVへ変圧するタイトランスを設け、既設設備を継続使用する構成があります。</p>

<h2>3.3kV負荷の例</h2>

<p>設備によって異なりますが、3.3kV級の高圧電動機は大型工場・プラントなどで使われることがあります。</p>

<ul>
  <li>大型ポンプ</li>
  <li>コンプレッサー</li>
  <li>大型ファン・集じん設備</li>
  <li>冷凍機</li>
  <li>生産設備用の高圧モータ</li>
</ul>

<p>「3.3kV回路がある＝必ずタイトランスがある」わけではありません。上位の特別高圧から直接3.3kVへ変圧している設備もあります。</p>

<h2>単線結線図で見るポイント</h2>

<ul>
  <li>一次側・二次側の定格電圧</li>
  <li>どの母線同士を連絡しているか</li>
  <li>変圧器容量</li>
  <li>一次・二次側の遮断器や保護継電器</li>
  <li>中性点・接地方式</li>
  <li>並列運転の有無</li>
</ul>

<p>タイトランスという名称だけで役割を決めず、単線結線図上で<strong>「どの系統から、どの電圧へ、何を給電しているか」</strong>を見るのが確実です。</p>

