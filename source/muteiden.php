<h2>現場でのポイント</h2>
・年次点検は原則毎年1回<br>
・要件を満たせば停電点検を3年に1回以上にできる制度がある<br>
・2025年4月から一定条件で月次点検を3月に1回以上へ延伸可能<br>
・月次点検延伸と無停電年次点検は別々に要件を確認する<br>
・無停電診断だけで停電試験のすべてを代替できるわけではない<br>
・設備変更・経年で条件を外れたら点検計画を見直す<br>

