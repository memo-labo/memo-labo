<h2>年次点検とは？</h2>
保安管理業務を外部委託している自家用電気工作物では、年次点検は原則として毎年1回実施する。<br>
通常は設備を停止して、外観点検だけでは確認できない絶縁・接地・保護継電器などの測定・試験を行う。<br><br>

ただし、設備の信頼性が高く、停電点検と同等と認められる点検を毎年1回以上行うなど一定の要件を満たす場合は、<strong>停電による年次点検を3年に1回以上</strong>とすることができる。<br>

<h2>「無停電年次点検」とは？</h2>
停電を伴う点検を省略する年に、運転中の設備へ無停電診断・監視などを組み合わせて年次点検を行う方式。<br><br>

単に「停電しないで目視だけする」という意味ではない。<br>
停電点検を3年に1回以上へ延伸するには、対象設備が信頼性の高い設備であること、維持基準を満たすこと、毎年必要な点検・測定を行うことなどの条件がある。<br>

<h2>2025年4月から月次点検の延伸制度も拡大</h2>
令和7年（2025年）4月1日施行の告示改正により、一定の要件をすべて満たす外部委託事業場では、月次点検の頻度を<strong>3月に1回以上</strong>とすることが可能になった。<br><br>

これは年次点検の無停電化とは別の制度条件。<br>
「月次点検を3か月ごとにできる設備」だから自動的に「停電年次点検も3年に1回でよい」とは考えず、それぞれの要件を確認する。<br>

<h2>無停電年次点検を採用する設備の基本条件</h2>
対象設備は、告示・内規で定める「信頼性が高い設備」の条件を満たす必要がある。<br><br>

代表的な確認項目<br>
・責任分界点付近に適切な地絡保護装置があること<br>
・責任分界点から主遮断装置までの設備構成が所定条件に適合すること<br>
・柱上変圧器や可燃性絶縁油を使用した屋外高圧開閉器など、対象条件を外れる設備がないこと<br>
・PAS、UGS、引込ケーブルなどが定められた設備条件・更新計画に適合すること<br>
・停電年次点検の測定結果や経年評価から策定した維持基準に適合すること<br>
・塩害、高温多湿など保安機能へ支障を与える環境を考慮していること<br>
・リコール・注意喚起対象機器がないか確認していること<br>
・製造者の推奨更新時期や余寿命評価を考慮していること<br><br>

具体的な年数・設備条件は制度改正や機器構成によって変わり得るので、最新の告示・主任技術者制度の解釈及び運用・監督部資料を確認する。<br>

<h2>無停電点検で行う代表的な診断</h2>
<h3>放電・絶縁異常の診断</h3>
超音波・電磁波などを利用した部分放電探査機器を使い、運転中の異常放電兆候を確認する方法がある。<br><br>

ただし、無停電診断で異常が見つからないことと、絶縁性能を停電試験で直接確認することは同じではない。<br>
過去データ・設備年齢・環境条件と組み合わせて評価する。<br>

<h3>過熱診断</h3>
<a href="ondokei.php">放射温度計</a>や<a href="thermography.php">サーモグラフィ</a>で、端子・母線・開閉器・変圧器などの温度分布を確認する。<br><br>

温度は一律の閾値だけで良否判定せず、<br>
・周囲温度<br>
・負荷電流<br>
・左右相・同種機器との温度差<br>
・過去値との比較<br>
・メーカー許容温度<br>
を合わせて判断する。<br>

<h3>漏電・絶縁監視</h3>
<a href="kanshi.php">Ior絶縁監視装置</a>などで低圧電路の絶縁状態を常時監視する。<br>
月次点検頻度の延伸制度では、低圧電路の絶縁状態を適確に監視できる装置などが要件になる場合がある。<br>

<h3>負荷監視</h3>
2025年の月次点検頻度延伸要件では、負荷を適確に監視できる装置と監視体制も条件の一つ。<br>
デマンド・電流・電圧などの遠隔監視データを、現地点検の代わりに単に蓄積するだけでなく、異常を適確に把握できる運用が必要になる。<br>

<h2>停電年次点検を3年に1回へ延伸できなくなった場合</h2>
機器の経年、設備変更、環境悪化、更新計画からの逸脱などで要件を満たさなくなった場合は、従来の停電年次点検頻度へ戻す必要がある。<br><br>

設備を更新したときも、新機器が自動的に無停電点検対象になるとは限らない。<br>
保安規程、維持基準、設備台帳、点検計画を合わせて見直す。<br>

<h2>電気管理技術者と電気保安法人</h2>
無停電年次点検の制度要件は、外部委託承認制度の枠組みで適用される。<br>
申請・届出・運用上の取扱いは管轄の産業保安監督部によって確認が必要な事項もあるため、「地域によってこうらしい」という口コミだけで判断せず、管轄監督部へ確認する。<br><br>

