<h2>無停電点検の方法</h2>
■コロナ放電探査（絶縁診断）<br>
超音波式放電探知器により、機器の劣化診断を行う<br>
超音波式部分放電探知器、温湿度機能付きノイズレベル計、などを使用する。<br><br>

■過熱診断<br>

<a href="ondokei.php">放射温度計</a>や<a href="thermography.php">サーモグラフィ装置</a>により、機器の異常や過熱の有無を診断する<br><br>
高圧電線、低圧電線、MCCBは、60℃未満。<br>
断路器、遮断器、開閉器、ヒューズ、VCT、コンデンサ、リアクトルなどは、55℃未満。<br>
油入変圧器、モールド変圧器は、70℃未満。<br>
※周囲温度、負荷使用状況などを考慮して、総合的に判定する。<br><br>

■漏電監視<br>
<a href="kanshi.php">Ior絶縁監視装置</a>により、漏電の有無を24時間監視する<br><br>


