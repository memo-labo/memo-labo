<h2>誘導型OCRの試験中に円盤が回らなくなってしまった</h2>

事故例<br />
整定電流値付近では円盤は回ったが、200%、300%、瞬時等を試験しようとした際、<br />
継電器から何か切れるような音がして、その後、電流を与えても回らなくなった。<br /><br />

古い誘導型OCRを試験する時の注意点<br />
整定タップ値の倍数に対する動作時間を調べる際、計算式がない場合がある。<br />
その際、特性カーブより図から読み取るしか方法がない場合がある。<br /><br />

例：ICO1D-ATI、タイムダイヤル４だった場合<br />
・200%:2.8s<br />
・300%:2.0s<br />
・500%:1.4s<br /><br />

上記数値は、MOC-A1シリーズのように計算式で出てくる数値ではない。<br />
事前に取説で調べておくか、もしくは継電器に書かれている図から読み取る。<br />
試験前に、理論上の動作時間を把握していないと継電器を壊す危険性がある。<br />
例えば、明らかに動作時間を超えているのに電流を流し続けてしまうなど。<br /><br />

■OCR故障後の対処法<br />
CTの入力部が故障断線している可能性が考えられる。<br />
継電器の電流入力部C1,C2をテスターで導通確認してみる。導通がなければ断線故障の可能性。<br />
継電器C1,C2間が断線してオープン状態だと、CT二次側に高電圧が発生し危険。<br />
なので、CT２次側を短絡させて、故障したOCRに電流が流れないようにしておく。<br />
CTT試験端子を差し込み、CT側を短絡バーにて三相短絡させておけば良い？<br />



