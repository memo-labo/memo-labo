<h2>CTTの金属部分の接触不良でOCR動作遅れ</h2>
・CTTの金属部分に汚れやさびが付着<br>
・OCR試験クリップとの接触部分で抵抗増<br>
・流れる電流の量が減り動作が遅れる不具合<br>
・さびを落として再び試験すると問題なく動作<br>


<h2>CTが故障しているか調べる方法</h2>
CTが壊れてて不正確な値を示していても、電流計やOCR試験では気がつけない。<br><br>

予想<br>
・受電設備が短絡事故<br>
・CT不良のためOCR瞬時動作が許容範囲で動作せず<br>
・配電側VCBがトリップ⇒波及事故<br><br>

■CTTからOCRの試験は本当に正確か？<br>
試験時はCTT２次側から電流を流す。<br>
実際にはCT１次側に電流が流れる⇒鉄心が励磁されてCT２次側に電流が流れる⇒CTTを経由してOCRに流れる。<br>
CTT２次側からOCR試験が出来ても、本当に事故の時にOCRが許容値内で動作するかどうかはわからない。<br><br>

■CT２次側配線<br>
CT２次側の配線を引き回した結果、インピーダンスが上がる。<br>
OCRの瞬時動作試験時、回路抵抗が高く、電流が流れにくく、許容値に収まらない事例。<br><br>

■停電⇒CTTからOCR試験⇒受電⇒接触不良で電流流れず<br>
CTTの締め付けが悪かった、または金属部分が錆びていて接触不良<br>
MCCB投入後、電流計が振れることを確認する<br>
高インピーダンスだった場合、OCRが正常に動作しない可能性もある？<br>

<h2>地域停電発生時からの再送電でOCRの瞬時動作</h2>
停電点検後の復電時、VCB投入時に励磁突入電流でOCRの瞬時要素動作⇒VCB開放。<br>
もし仮にその地域で停電が発生した場合、再送電されたとき、どうなる？<br>
OCRの瞬時要素が動作してVCBが開放⇒担当者が駆けつけるまで復電ができない可能性。<br><br>

OCRの整定値は電力会社との協議で決まるのでこちらの都合で勝手に変更できない。<br>
仮に瞬時要素の整定値を低く変更した場合、配電側の方が先に動作し波及事故に。<br>

<h2>OCRの整定値つまみ</h2>
つまみを中間位置に整定してはならない（不定となる）<br>
稼動中の整定変更は、不要動作の恐れがあるので避ける。<br>
※やむを得ず変更する場合、表示復帰レバーを押し上げて動作ロック状態として行う。<br>

<h2>OCRの周波数設定（50Hz or 60Hz）</h2>

OCRの設定で周波数設定がある。<br>
ディップスイッチによる設定で小さく見えにくい場合が多い。<br>
これが間違っている場合があり、その場合、動作値が微妙にずれる。<br>
不良で報告をあげて、実は周波数設定が間違っていた、などならないように。<br>
これはOCRに限らずRPR、使用する発電機やバッテリーでも同じこと。<br>

<h2>警報接点不良でOCRの試験が出来ない（動作信号が拾えない）</h2>
a1-a2接点が故障し、OCRのターゲットは動作するけど接点信号が拾えない場合の対処法<br>
信号線をR相⇒T1R、T相⇒T1T、com相⇒C2T2R or C2T2T、接点⇔電圧は電圧モード、これで動作信号を拾えるはず。<br>
OCR動作でC1RとC2T2Rの間にある内部b接点が開き、電流の流れがT1R側に切り替わり、その瞬間に電圧変化が発生するため。<br>
※継電器本体の警報接点の内部不良であるため交換の指摘を推奨。<br><br>

電圧引き外しOCRの警報接点で信号がとれない場合<br>
トリップ用接点であるT1-T2間で試してみる。<br><br>

電圧引き外しOCRのトリップ用端子（T1-T2）の不良でVCBとの連動試験ができない場合<br>
T1T2を離線した後、T1T2に信号線をつけてOCR単体試験が出来なければT1T2の故障が確定。<br>
もしこれで単体試験が出来た場合には、OCR以外のシーケンス部分に原因がある。<br>
落下式故障表示器、UVR、52Rと52Fとの絡み、など。<br>


<h2>OCRの動作時間特性の試験、どこまでやる？</h2>

・200%（参考値）<br>
・300%（公称値）<br>
・500%（参考値）<br>
・700%（公称値）<br>
<br>
200%と500%は参考値。なのでここが許容値から外れても良否判定はできない。<br>
<br>
とある管理技術者の方によれば、200,300,500だけ試験して700はしない。<br>
700は過渡電流の要因が大きくなり、正確な動作時間が測れないとのこと。<br>
でもJISに従えば300%と700%だけ試験すれば良いのでは？<br>

<h2>Twitterの意見</h2>

会社によっては、200、300、500、1000をやる。<br>
これは機種の準拠している規格（JIS IEC JECなど）によって変わる。<br>
なので1000%をやる場合もある。<br><br>

機種の例：富士電機製、1000%が必要なものがある。<br>
規格の例JIS C 4602－1986⇒300%,700%<br><br>

