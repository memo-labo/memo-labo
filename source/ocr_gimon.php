注意が必要なのは、この状態であってもOCR単体試験も連動試験も問題なく出来てしまうところ。<br>
指摘事項であげた場合「いや、おたくの会社でやってもらったんだけど」と突っ込まれる可能性も。<br><br>

また更新を推奨するにしても、現状の何が問題か説明できなきゃダメ。<br>
「問題なく動作はするが、想定していない使い方だから」では説明になってない。<br>



<h2>CTTの試験クリップ</h2>
ＣＴＴに試験クリップを挟むとき、クリップの金属部分と他の相のビニル部分が触れていると、そこから電流が逃げて測定値が遅れる場合がある。<br>
