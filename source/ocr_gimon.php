<h2>電圧引き外しVCB + 電流引き外しOCRの組み合わせ</h2>

工事会社の発注ミス<br>
電圧引き外しVCB + 電流引き外しOCRの現場があった。<br><br>

C1R端子⇒配線あり<br>
C2T2R端子⇒配線無し<br>
T1R端子⇒配線あり<br><br>

C1T端子⇒配線あり<br>
C2T2T端子⇒配線無し<br>
T1T端子⇒配線あり<br><br>

a1,a2端子⇒配線あり（DC電源・引き外し用）<br><br>

C1R⇒T1Rには内部接点がないので、常時閉路。<br>
電流引き外し用OCRを、そのまま電圧引き外し用OCRとして使用していた。<br>
この問題点は、a1a2接点が、警報用接点という部分。<br>
引き外し用と警報用では、<a href="setten.php">接点容量</a>に違いがあり、溶着する可能性あり。<br>
またこれはメーカーが推奨する使用方法ではないので、改修・指摘事項に該当。<br>

<h2>電流引き外しOCR＋電圧引き外しVCB＋外部パワーリレー１個</h2>

以下のような現場があった。<br>
・組み合わせは電流引き外しOCR＋電圧引き外しVCB＋外部パワーリレー１個<br>
・電流引き外しOCRの警報接点a1-a2を経由して外部のパワーリレーを動作<br>
・パワーリレー動作により電圧引き外し用VCBのトリップ回路に電圧印加<br>


<h2>電流引き外し用OCRと電圧引き外しVCBを組み合わせて使用している現場</h2>

とある現場で以下のように配線されていた。<br><br>
