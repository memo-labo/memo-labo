CT２次側回路は常に閉路状態であり、OCRが動作してもCT２次側はオープン状態にはならない。<br><br>
<img src="images/20260316-2.png" style="max-width:600px;" alt=""><br><br>

問題はトリップ回路として警報接点のa1-a2を利用している部分。<br>
そのまま使用すると接点容量の関係で危険だがパワーリレーを１つ挟めば問題なさそう。<br><br>

