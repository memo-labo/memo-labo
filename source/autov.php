標準形VCBにOCRとCTを組み合わせたタイプ。<br>
CTとOCR内蔵で、主回路を接続するだけですぐに使用可能。<br>
従来のようなCTやOCRの据付、配線接続が不要となる。<br>
H6形の場合、制御電源不要。<br>
注油作業の軽減でメンテナンス工数を省力化。<br>

<h2>特徴・注意点</h2>
VCB２次側のR相とT相部分に小型の貫通型CTが固定されている。<br>
OCR試験を行う時は「一次電流整定値」を「テスト」にセットする。<br>
テスト以外で試験を行うと焼損する可能性がある。<br>
試験する際の電流入力は正面の端子から、接点はVCB主接点または補助開閉器a接点間に接続。<br>
CTの二次電流は5Aでなく0.1Aであることに注意する。<br>

<h2>メリット</h2>
CT取り付けが不要となり充電露出部が減るので事故の確率が減る。<br>
CTやOCRが不要となり配線の接続ミスが無くなる。<br>
取り付ける品が減るのでスペースが広くなる。<br>
新品に交換する際はOCR、CT、VCBを１回ですべて交換できるので管理が楽になる。<br>
CTの過電流耐量不足による破損や過電流定数不足など、選定ミスによる動作不良や事故の心配がない。<br><br>

OCR試験におけるメリット<br>
試験電流が小さくて済むのでDGR試験機でも試験できてしまう。<br>
わざわざ大きなOCR試験機を用意する必要がない。<br>

<h2>デメリット</h2>
CT、OCR、VCB、どれか１つに異常があった際、全て交換となるので費用がかかる。<br>
