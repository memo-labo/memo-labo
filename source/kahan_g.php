<h2>可搬型発電機の届出の問題</h2>
届け出のされていない可搬型・非常用発電設備が多いらしい。<br>
可搬型・非常用発電設備はそれ単体で動作できてしまうので、設置者の届出の認識が低い。<br>
工事現場でリースで使われ、使用期間も短い場合、届出をしないケースも。<br>
船上に設置され、船から船へ移動するケースもあるらしい。<br>


