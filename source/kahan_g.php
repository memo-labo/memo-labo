<h2>可搬形発電機とは？</h2>
主に「ダイレクトカップリング方式」を採用。<br>
発電機をエンジンフライホイール出力軸に直接カップリングする方式のこと。<br>
移動や運搬時に発電機とエンジンの軸心がずれないので移動が容易。<br>
発電機とエンジンのセットは防振ゴムを介してベースに取り付けられている。<br>

