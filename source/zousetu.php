<h2>設備容量の増設</h2>

受電設備の例<br>
PAS⇒VCB⇒<br>
⇒LBS1⇒Tr1<br>
⇒LBS2⇒Tr2<br>
ここに新たにTr3変圧器を増設したい場合。<br><br>

高圧用CTを交換してCT比を大きくする必要がある。<br>
するとOCRの電流整定値を変更する必要がある。<br>
同時に高圧側の電流計も変更する必要がある。<br><br>

増設する理由<br>
・建物を増改築したとき<br>
・工場などで新しい設備を導入したとき<br><br>

増設方法<br>
・変圧器を新たに１台追加する<br>
・古い変圧器を容量の大きいものに交換する<br>
　（古い変圧器は形が大きい、最近の新しい変圧器は形が小さい）<br>

