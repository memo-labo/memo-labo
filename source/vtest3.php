<h2>絶縁耐力試験（耐電圧試験）</h2>

高圧ケーブルや受電設備機器が、規定された直流もしくは交流電圧を印加したとき、絶縁破壊を起こすかどうかで絶縁強度を測定する試験のこと。


<h2>絶縁耐力試験の印加電圧</h2>
