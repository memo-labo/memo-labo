<h2>ステンレス製のSOG制御装置ボックスの接地</h2>
開閉器の接地方式が一点接地の場合、ステンレス製のSOG制御装置ボックスは、5.5㎟以上の接地線でＤ種接地。<br>
または、PAS筐体のA種接地と共用接地でも可。<br>


<h2>耐電圧試験中に試験機がストップ！「抜ける」とは？</h2>

１０分間の絶縁耐力試験中に、急に試験機がストップしてしまう現象。<br><br>

高圧CVケーブルなどに傷があり、被試験物に印加された高電圧が、その絶縁不良箇所から放電して大電流が流れることで、試験機の保護回路が働き、試験機がストップする。

