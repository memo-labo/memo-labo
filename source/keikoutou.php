<h2>蛍光灯</h2>

白熱電球⇒電流を流すだけで点灯する<br>
蛍光灯⇒放電現象を起こさないと点灯できない<br><br>

蛍光灯の仕組み<br>
ガラス管と両端に取り付けられた電極で構成。<br>
電極はコイル状のフィラメントにエミッターという電子放射性物質を塗布したもの。<br>
ガラス管内は大気圧よりも圧力が低く、アルゴンなどの不活性ガスと微量の水銀が入っている。<br>
フィラメントから電子が放射され、水銀蒸気の原子に衝突、紫外線を発生。<br>
この紫外線がガラス管内の内面に塗布した蛍光物質を励起（れいき）して発光。<br><br>

蛍光灯は放電開始する際、フィラメントのエミッターを消耗する。<br>
エミッターが減少すると放電が行なえない状態となる。<br>
蛍光管の寿命は点灯回数に大きな影響を受ける。<br><br>

放射ルミネセンスとは？<br>
紫外線やX線を蛍光物質に照射して発光するもの。<br><br>


