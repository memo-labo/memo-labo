蛍光灯の発光の流れ<br>
電源を入れるとグロー点灯管の電極間に電圧がかかり放電を始める。<br>
バイメタルが加熱され湾曲し電極が接触する。<br>
電流が安定器とフィラメントを流れフィラメントが加熱され電子を放射しやすい状態に。<br>
グロー管の電極は接触状態なのでバイメタルが徐々に冷えて接点が開放される。<br>
離れた瞬間、安定器から逆起電力が発生して高電圧が発生する。<br>
この電圧が両方のフィラメントにかかり、放電が始まる。<br>
フィラメントから電子が放射され、反対側のフィラメントに飛んでいく。<br>

<h2>インバーター照明の仕組み</h2>
インバーター照明には安定器が無いので重量が軽く、雑音が発生しない。<br>
またグロー点灯管も必要なくついていない。<br>
<img src="images/inv5.png" style="max-width:600px;" /><br>
電源を入れると約１秒間フィラメントを温めて電子が飛び出しやすい状態にする。<br>
そして電極間に高い電圧をかけて放電を開始する。<br>
インバータで約50kHzの高周波電流を作る。<br>
放電中は蛍光管の中を約50kHzの高周波電流が流れる。<br>
高い周波数の電流を流すと電子の放射回数が非常に多くなる。<br>
なので水銀元素と電子の衝突回数が増え、衝突で発生する紫外線も増える。<br>
蛍光灯内部の蛍光物質に当たる量も増え、可視光線が大幅に増加する。<br>

<h2>スマホで一般的な蛍光灯を撮影すると明るさがちらつく理由</h2>
一般的な蛍光灯は毎秒100～120回点滅（商用電源周波数 50Hz or 60Hz）<br>
交流電源は電流がゼロになる瞬間があり、その時は放電が止まり、ちらつきが発生。<br>


