<h2>保安業務従事者の番号とは？</h2>

F番⇒電気管理技術者の番号<br>
J番⇒保安業務従事者の番号<br><br>

H○○-J○○○○<br>
○の部分には数字が入る。<br><br>

前半のH○○は保安法人の整理番号。<br>
後半のJ○○○○は保安業務従事者の番号。<br><br>

会社が変わると前半のH○○の数字の部分が変更になるらしい。<br>
電気管理技術者になると、後半のJがFに変わるらしい。<br>
またF○○は番号も別の番号を振られるらしい。<br>
またFから法人に戻ると、J○○の番号は元の番号を振られるらしい。<br><br>

このJとかFとかは、関東のみらしいとの情報。<br>
関東以外の地域では番号がないことが多いらしい。<br><br>

