<h2>アンペアブレーカーとは？</h2>
<img src="images/ab1.jpg" style="max-width:250px;"><br />
電流制限器・アンペアブレーカー・リミッターとも呼ばれる。<br />
需要家が契約電流値を超えて電気を使用すると、自動的に電気を切り、料金契約を適正に行う目的で、電力会社が設置し所有、管理をするもの。<br /><br />

需要家が使用している負荷機器や屋内配線の故障によって異常な大電流が流れた場合、このアンペアブレーカーによって安全に遮断することができる。<br /><br />

関西電力など、いくつかの電力会社では、電気供給約款に「電流制限器」の定めがない。<br />
その場合、電力量計までが電力会社の所有となり、需要家の主幹ブレーカーである、漏電ブレーカーや安全ブレーカーなどにつなぎ込みが行われる。

