<h2>中性線は導通している</h2>
電力会社で使用してるリミッターは、中性線は欠相保護のためバーにて常に導通している。<br>
一般家庭の分電盤の対地間絶縁測定をする際、B種接地を利用して測定すると、リミッターを開放して測定しても中性線で導通するために0MΩになってしまう。<br>
なので測定する際は、リミッター２次側にある子ブレーカーを開放して測定する。<br>


<h2>契約アンペアが小さいとどうなる？</h2>
契約アンペアが少ない場合、例えばヒーター、暖房、電子レンジなど容量の多いものを同時に使用すると、アンペアブレーカーが落ちてしまい、家全体で停電が起きてしまう。<br /><br />
この場合、そのままアンペアブレーカーを入れてしまうと、また再びブレーカーが落ちてしまうことがあるので、使用していた電化製品のどれか一部をOFFにして使用する必要がある。<br /><br />
それぞれの電化製品の使用する時間帯をずらすなどで対応をする必要がある。

<h2>契約アンペアが大きいとどうなる？</h2>

契約アンペアが大きいと、一度に使える電気の量に余裕がでるが、基本料金が高くなる。<br />
