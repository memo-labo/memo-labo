<h2>欠相とは？</h2>

欠相の原因<br>
モータの電源線が断線、接続部のゆるみ、制御用開閉器の接触不良、モータ内部の断線などで起こる。<br />
三相電圧で運転されるべきモータが、単相で運転されている状態となる。<br />

<h2>欠相のデメリット</h2>
欠相状態でモーターを起動すると、起動電流がいつまでも流れ続けることになる。<br />
その結果、過電流により、モータ自身が焼損する。<br />
停止している誘導電動機は、単相では回転を始めない。<br />

運転中に欠相し、軽負荷でそのまま運転を続けると、少し負荷が増えたときに停止する可能性がある。<br />
また、接続のはずれた導線が外被に接触して感電事故、短絡事故につながる可能性もある。<br /><br />

過負荷要素だけで欠相を検出しようとすると、軽負荷時の場合には、非常に時間がかかる。<br />
この検出を早く行うためには、過負荷要素だけでなく、欠相要素を設けるのが一般的である。<br />


<h2>欠相リレーとは？</h2>
欠相状態でモーターを起動すると、モーターが焼損する。<br />
運転の途中で欠相し単相状態になった場合、軽負荷だと三相誘導電動機は単相誘導電動機として回転を継続する。<br />
その場合、欠相リレーの過負荷要素によって検出をして、モータ自身の焼損を防止する。<br /><br />

欠相時、過電流要素だけではモータの焼損を防止できない場合があり、欠相要素が必要。<br />
欠相の検出には、電流方式と電圧方式があるが、電流方式の方が有利。


