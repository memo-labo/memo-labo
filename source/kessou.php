<h2>スター結線モータの欠相</h2>

スター結線三相電動機の欠相について<br />

電動機に流れる電流をIa,Ib,Icとする。<br />
平常時はIa=Ib=Ic=I。<br /><br />

電動機の出力<br />
P=√3VI cosφ ①<br /><br />

C相断線した場合<br />
Ic=0で単相運転<br /><br />

電動機出力Pは変化しない<br />
P=VI'cosφ ②<br /><br />

①②式は等価なので<br />
I'=√3I<br /><br />

よって１相欠相により電流は√3倍になる。<br />


<h2>Δ結線モータの外部欠相</h2>
正常時 巻線電流 = I<br />
正常時 電源電流 = √3I<br />
正常時 巻線定格電流 = In<br />
正常時 電源定格電流 = √3In<br />
過負荷要素 ⇒ √3In < √3Iを監視する。<br /><br />

１相に断線発生⇒１相が欠相<br />
I＝Inのとき、電源線の電流 = 1In + 0.5In = 1.5In<br />
1.5In < √3In<br /><br />

この場合、巻線は過電流となっても電源線は定格電流以下であるため過負荷要素は動作せず、巻線が焼けてしまう可能性がある。<br />
モータの焼損を防止するためには、欠相を検出するリレーが必要となる。<br />

<h2>Δ結線モータの内部欠相</h2>
過負荷要素が検出してモーター焼損の心配はない。


