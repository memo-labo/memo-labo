<h2>SPD分離器とは？</h2>
SPDが短絡故障したとき、短絡電流を安全に遮断すること。<br>
万が一、SPDが短絡故障を起こしても、安全に回路から切り離すことができる。<br>
また、SPDの点検時には、SPDを回路から開放し、無電圧での作業が必要となる。<br>
しかし、SPDに点検用断路機能がある場合、主幹の配線用遮断器を切らず、負荷機器に通電したままSPDの点検ができる。<br>


<h2>SPDの絶縁抵抗測定</h2>
SPD（避雷器）は内部に電子部品を使用していて、一般的な耐電圧試験（商用周波耐電圧試験）をすると内部回路が損傷する。<br>
また、秒単位の高い電圧には耐えられないので、絶縁抵抗試験をする場合にはSPDを回路から切り離す。<br>
対策として、SPD（避雷器）の電源側に栓形ヒューズを設置することが推奨される。<br>
この栓形ヒューズは、SPDの過電流保護と試験時・取替え時の断路器の役目を果たす。<br>


