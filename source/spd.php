  <h2>SPDとは？</h2>
  SPDは英語で Surge Protective Device。<br>
低圧サージ防護デバイス。<br>
低圧回路の雷サージから機器や回路を保護するデバイス。<br>
雷などによる過渡的な過電圧で機器が故障しないようにサージ電流を分流して機器を保護する。<br>
<a href="la.php">LA（避雷器）</a>は、高圧・特別高圧電路の雷保護用機器の事を指す。<br>
