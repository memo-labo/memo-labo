<h2>SPDの種類</h2>
電源用SPD クラスⅠ<br>
直撃雷対応。<br>
電源や接地（アース）から侵入する雷サージから機器を保護。<br>
直撃雷の分流成分を処理し、配電盤や分電盤に取り付ける。<br><br>

電源用SPD クラスⅡ<br>
誘導雷対応。<br>
電源や接地（アース）から侵入する雷サージから機器を保護。<br>
スタンダードなSPDで、配電盤や分電盤に取り付ける。<br><br>

接地間用SPD<br>
接地間の電位差を等しくする（等電位化）<br>
接地間に接続することで電位差を解消し、内部の機器を保護する。<br><br>

信号回線用SPD<br>
信号回線から侵入する雷サージから機器を保護する。<br>
信号回線用、電話回線用、通信線用、シリアル信号用、計装回線用、制御電源用など、製品の種類が幅広い。<br>

<h2>SPD避雷器は雷サージの侵入で劣化する</h2>
一度の落雷による雷電流は30～40kA程度と言われているが、まれに200kA以上の雷電流が発生することがある。<br>
度重なる雷サージや過度の雷サージにより、SPDは劣化することがある。<br>
SPDは、想定以上の雷サージが侵入した場合、自身を犠牲にして、機器を保護する。<br>
この時、SPDは故障状態になり、安全に回路から切り離されるが、SPDが設置されていない状態となる。<br>
なので、雷サージが再度侵入した場合、機器は保護することができない。<br>


<h2>劣化接点出力端子（Sタイプに標準装備）</h2>
劣化接点出力端子に信号線を配線すると、警報や遠隔監視が可能。<br>
ただし、遠隔監視装置を信号線から侵入する雷サージから保護するため、監視装置直近に信号線の電圧に応じた信号回専用のSPDを設置しなければならない。
