×端子は故障の原因になるので接続できない。<br>
更新時、既設の継電器にアース接続がある場合、○端子を中継用として使用可能。<br><br>

RD形（ユニット引出形）<br>
裏面の外部配線を外さずにツマミやLEDランプがある正面部分だけを取り外すことができる。<br><br>
もしCT回路の分離を忘れてリレーユニットを引き抜いてしまっても、CT2次回路が開放しないように補助機能として、「ユニット引出し時の自動短絡片」を備えている。<br><br>

稼動中の整定変更<br>
稼動中の整定変更は、不要動作の恐れがあるので避けること。<br>
しかしやむを得ず変更する場合、CPUリセットボタンを押して動作ロック状態で行う。<br>
（動作ロック状態では、リレーは動作しない。）<br><br>

OCRの慣性特性<br>
①限時要素 ダイヤル 10<br>
②入力：整定値の 1000%<br>
③通電時間：動作時間の 90%<br>
上記条件にて不動作であることを確認<br>

