RUNランプ
正面中央上部にある。<br>
入力電流が1.5A以上で点灯する。<br>
実際の電流はツマミを電流計測に合わせてデジタル数値で見る。<br><br>

CPU リセットボタン<br>
正面右上の黒い四角のボタン。<br>
押している間はRUNランプが消灯し、リレー機能がロックされる。<br><br>

