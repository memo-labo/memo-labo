<h2>提案の具体的内容等</h2>

昭和六二年に行われた電気工事二法（電気工事士法及び電気工事業の業務の適正化に関する法律）の改正に際して、通商産業省資源エネルギー庁公益事業部技術課長は、全国電気管理技術者協会連合会会長に対し、昭和六二年八月四日、わが国の電気保安の確保が、長い電気保安行政の歴史のなかで確立した保・工分離の考え方を基本としており、電気工事を行う者が保守管理も行う、あるいはその逆のケースは到底許されるべきではなく、通商産業省としては電気工事二法の改正後においても保・工分離の原則を徹底してゆく考えであることを示す内容の「電気工事二法改正と保守管理業務の関係について」と題する文書を発したほか、資源エネルギー庁公益事業部長は、同年八月二〇日に開催された参議院商工委員会において、電気工事二法の改正後も保・工分離の原則を堅持してゆく考えであることを政府委員として発言した。<br><br>

上記のとおり保・工分離の原則が、電気保安行政において定着し、慣習とされており、電気主任技術者は、「保安管理の専業者であって、他の職業を有することは許されない」とされています。<br><br>

電気主任技術者も、電気工事士の資格を保有しているケースが多くありますが、営利目的で工事の仕事をおこなってはいけないといった慣習が存在します。<br><br>

保工分離制度は、設置者の利益を守るために定められている制度になりますが、電気技術者のレベルも向上する中、このような慣習はもはや古いものであり、撤廃もしくは見直しを考える時代に来ているのではないでしょうか？<br>

<h2>対応の概要</h2>

保工分離の原則は設置者の利益を守るために業界内でも定着化・慣習化されたものであり、現時点においても設置者保護の観点からその考え方は有効なものです。<br><br>

また、この原則の基本的部分は、医薬分業といった他業界においても採用されているものであり、電気保安と電気工事の業界においても、設置者に必要のない工事費用を負担させない等、設置者の利益を第一に考え、この考え方に則り自らを律していくことが必要であると考えられます。<br><br>

したがって、ご提案にある電気技術者のレベルが向上したとしても、保工分離の原則は維持されるべきものと考えております。<br>

<h2>保工分離のルーツとは？</h2>
保工分離のルーツは「医薬分業」から来ている。<br>
医薬分業とは、薬の処方と調剤を分離すること。<br>
薬の処方は医師、調剤は薬剤師、という専門家が分担して行う。<br>
ヨーロッパでは800年近い歴史がある。<br>
最初は王が毒殺を怖れ、主治医の処方した薬を別の者にチェックさせたのが始まり。<br>
医師が薬局をもつことを法律で禁じた。<br>
日本の医薬分業は明治時代から。<br>
医療なら患者、電気設備なら設置者が不利にならないようにすること。<br>
その流れが「保工分離」にも根付いている。<br>


