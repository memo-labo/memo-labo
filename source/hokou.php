<h2>停電点検中の不具合や誤配線を発見した場合</h2>

受電設備の停電点検中、保護継電器や警報装置の複数箇所で誤配線が確認された場合、どうする？<br><br>

①誤配線部分の写真を撮影し、担当した工事会社に提出し、工事会社に修正工事を依頼する。<br>
②停電点検を行った電気主任技術者が、その場で修理をする。<br><br>


①側の意見<br>
予定外作業は絶対に禁止。<br>
責任分界点が曖昧になる。<br>
公的施設や規模の大きいお客様なら予定外作業禁止。<br>
写真を撮影しておき、報告書に記載する。<br>
修正工事の見積もりを出し、実際に修理工事をするかどうかは顧客の判断。<br>
電気主任技術者や点検作業員が勝手に介入するべきではない。<br><br>

②側の意見<br>
選任されていれば、その場で配線の修正工事を行う。<br>
停電時間に余裕があり、民間で小規模のお客様の場合、その場で対応する。<br><br>

どちらでもない<br>
受電設備が、選任か、外部委託かで、対応が変わる。<br>
停電時間に時間的な余裕が無ければ臨機応変に検討する。<br>
公的施設や規模の大きいお客様か、民間のお客様かで対応が変わる。<br>
不具合の発見は竣工検査の際に念入りに行うべき。<br>



