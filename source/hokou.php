<h2>保工分離制度（ほこうぶんりせいど）</h2>

保工分離の原則<br>
顧客の利益を守るため、工事をおこなうものと工事を監督する物は別人でなければならない。<br><br>

電気主任技術者も、電気工事士の資格を保有しているケースが多くある。<br>
しかし営利目的で工事の仕事をしてはいけないといった規則が存在。<br><br>

保工分離制度は、お客の利益を守るために定められている制度。<br>
保安をする会社が、お客に必要のない工事を提案し行う詐欺から守るなど。<br>
意図的に利益を追求する行為を抑制するために制定された規則。<br><br>

保安管理と工事を分離して、お客に不利益が生じないようお客を守るためにつくられた制度。<br>
しかし現実、保安法人と同じグループ会社・子会社に電気工事を依頼しているケースもある。<br>

