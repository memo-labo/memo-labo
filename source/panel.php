■獣害<br>
カラスがパネルの上に石を落としてパネルを割る。<br>
鳥がパネルの上に糞を落とす。<br>
カラスがパネルのPVケーブル用パイプの入り口に詰めているネオシールをつまんで剥がす。<br>
鹿や猿が太陽光パネルの上に乗る。<br>
猪が交流CVケーブルやPVケーブルをかじる。<br><br>


■調整池とは？<br>
集中豪雨など局地的な出水で川の流下能力を超える可能性のある洪水を一時的に溜める池のこと。<br>
太陽光の開発行為を行う合計面積が１ha 以上の場合「重要調整池」の設置が必要。<br />
通常、草木が繁茂している状態であれば、植物の根と土が保水力を保ってくれる。<br />
開発した土地は草木が生えていないので雨水は表面の土砂を巻き込みながら流れてしまう。<br /><br />

