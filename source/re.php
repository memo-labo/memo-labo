<h2>リアクトルの注意点</h2>

理想的なリアクトルであれば、並列接続する事によって、どれだけでも容量を増やす事が出来る。<br>
しかし実際はリアクトル容量の１割程度は損失があるので並列接続の際は注意。<br>
耐圧試験の際はＬ端子とE端子は開放させておく。<br>

