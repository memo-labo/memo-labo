<h2>試験上の注意</h2>
LDG-73とLDG-71の制御電源の供給元が違う可能性がある。<br>
例として、73⇒受電盤VTから、71⇒き電盤VTから。<br>
71の試験をする際は、73の制御電源を入れて試験する。<br>
73からのVo動作信号が届かず71のVoが動作しない。<br><br>

マグサインの復帰<br>
制御電源が入った状態でないと復帰できない。<br>
試験終わりに制御電源を入れて復帰してから終わること。<br><br>

復帰方式<br>
自動と手動で切り替えることができる。<br>
「手動」だった場合、DGRの試験をする際、毎回復帰スイッチで復帰させる必要がある。<br>
もしくは制御電源を一旦OFFにして自己保持を開放してあげれば続けて試験ができる。<br><br>

富士電機のQHA-DG3とQHA-DG4も同じ感じ<br>
・QHA-DG3（受電用）<br>
・QHA-DG4（分岐用）<br>

