<h2>地絡抵抗とリレー整定</h2>

<p>人工地絡試験に関する資料では、一定の地絡抵抗を想定して地絡検出感度を評価する例があります。</p>

<p><strong>「6kΩなら必ずこの整定」という全国共通の固定ルールではありません。</strong>配電事業者の保護方式、系統条件、リレー形式、協議結果によって扱いが異なります。</p>

<h2>試験時に保護リレーをどう扱う？</h2>

<p>実系統で試験する場合、不要な遮断・広範囲停電を防止するために、保護リレーや遮断回路を所定の試験状態へ切り替えることがあります。</p>

<p>ただし、制御電源OFF、ロック端子、DI入力、トリップ回路切離しなどの方法は<strong>機種・回路ごとに異なります</strong>。誤ったロックは本来必要な保護まで無効化するため、メーカー資料・電力会社手順・保安規程に従います。</p>

<h2>現場で重要なこと</h2>

<ul>
  <li>試験責任者・系統運用者との事前協議</li>
  <li>対象系統・保護範囲・停電影響の確認</li>
  <li>試験中に無効化する保護と代替保護の確認</li>
  <li>試験終了後の整定・ロック・回路復帰確認</li>
  <li>電力会社・メーカー指定の試験要領を優先する</li>
</ul>

<h2>人工地絡を行わず確認する方法</h2>

<p>現在は、二次注入試験、リレー試験器、シミュレーション、事故記録解析などにより、実系統へ人工地絡を発生させず保護性能を検証する方法もあります。</p>

<p>設備・目的に応じて、実人工地絡が本当に必要かを事前に検討します。</p>

