<h2>人工地絡試験とは？</h2>

<p><strong>人工地絡試験は、配電系統に意図的な地絡条件を作り、零相電圧V0・零相電流I0や地絡保護リレーの検出特性を確認する試験です。</strong></p>

<p>配電線の対地静電容量、接地方式、地絡抵抗などによって事故時のV0・I0が変わるため、地絡保護方式の検証や整定検討に利用されることがあります。</p>

<p><strong>実系統へ人工的に地絡を発生させる試験は、高電圧・大電流・系統停電を伴う重大な危険があります。ここでは原理のみを扱い、具体的な地絡投入手順や活線操作手順は掲載しません。</strong></p>

<h2>何を確認する試験？</h2>

<ul>
  <li>地絡時に発生する零相電圧V0</li>
  <li>地絡時に流れる零相電流I0</li>
  <li>DGR・OVGRなど地絡保護リレーの検出特性</li>
  <li>系統の対地静電容量による影響</li>
  <li>保護協調・整定値の妥当性</li>
</ul>

<h2>V0は何で変わる？</h2>

<p>非接地系統の地絡時に現れるV0は、地絡抵抗だけでなく、配電線や機器の対地静電容量、地絡位置、系統構成などの影響を受けます。</p>

<p>そのため、同じ地絡抵抗でも系統条件が変われば検出されるV0・I0は同じとは限りません。</p>

