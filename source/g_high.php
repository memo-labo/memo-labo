S1にはリアクトルがあり、インピーダンス（リアクタンス＋レジスタンス）を増加させることで電流を制限する。<br>
電流引き外しタイプのVCBはトリップコイルがR相、T相の２相に用意されている。<br>
OCRのR相は、OCRが動作した時のみ利用する。<br>
OCRのT相は、GRの引き外しコイルと兼用する。<br><br>

OCRのT相が動作した時の電流の流れ<br>
CT（T相 k側）⇒C1T⇒T1T⇒o1（GR）⇒T1⇒TC2（VCB）⇒T2⇒o2⇒AS⇒CT（T相 l側）<br><br>

GRが動作した時の電流の流れ<br>
P1-P2にGR制御電源が印加された状態で、地絡電流を感知するとGR内部接点[x]が動作する。<br>
S1-S2に引き外し用電源としてVCBパレットスイッチを介してAC100Vを印加しておく。<br>
VCB引き外し電流の流れは、S1⇒T1⇒TC2⇒T2⇒S2。<br>

引き外し電源をVCBパレットスイッチを介する理由<br>
VCBが開放された状態においてはトリップコイルに電流を流さないようにするため。<br>
コイルに電流を流し続けるとトリップコイルが焼損してしまう。<br>

