<h2>GR 電流整定値</h2>
通常は0.2Aで整定。<br>
検出感度が良すぎて微弱電流で動作してしまう場合は0.4Aに整定。<br />
0.6A以上に整定する場合、配電用変電所の保護範囲と接近し保護協調がとれなくなる可能性がある。<br>
この場合には電力会社と相談する。<br /><br />

構内充電電流が50mA以下：200mA<br />
構内充電電流が50～100mA：400mA<br />
構内充電電流が100mAを超える：600mA<br /><br />

構内の高圧ケーブル（6kV CVT100sq）が124m以上の場合、Ig = 200mA以上となるので、もしGRの整定が200mA整定だった場合、電源側の地絡事故により、<a href="moraijiko.php">不必要動作（もらい事故）</a>をする可能性がある。


<h2>地絡継電器 動作時間の保護協調</h2>
受電設備の地絡継電器は、配電用変電所のGRと、保護協調をとる必要がある。<br />
整定電流値の130%<br />
動作時間：0.1s～0.3s<br />
整定電流値の400%<br />
動作時間：0.1s～0.2s<br />
構内の対地静電容量による充電電流が200mA以上になると、<br />
GR方式では電源側の地絡事故で、もらい動作する場合がある。<br /><br />

