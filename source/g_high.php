<h2>GR 地絡継電器</h2>
GR 記号<br>
<img src="images/gr10.png" style="max-width:200px;" alt="地絡継電器 記号"/><br>
地絡継電器の器具番号は51G<br>
地絡継電器は英語でGround relay<br>
受電設備内の対地静電容量が小さい場合に使用する。<br>
構内の高圧電力ケーブルの長さが短いと静電容量が小さい。<br>
構内の対地静電容量が大きいと、電源側で地絡事故が発生した場合、地絡電流の一部が大地を経由して、<br />
構内の対地静電容量に流入し、構内の母線内を通過し、ZCTを通り、構内から構外に流出し、不要動作する。<br />


