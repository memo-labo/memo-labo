<h2>充電電流による不必要動作を防止</h2>
充電電流 >= GR感度電流の1/2 の場合、方向性のDGRを選ぶ。<br />
充電電流が100mA以上（ケーブルだと約60m以上）の場合、GRではなくDGRを選ぶ。<br /><br />

■上記の計算式<br />
6kV-CVT100sq<br />
GR感度電流：200mA<br />
1線の対地静電容量：C[μF]<br />
1心の静電容量：0.45[μF/km]<br />
周波数：f = 50Hz<br />
Ig × 10^-3 = 2πf × 3C × 10^-6 × 6600÷√3<br />
C = 0.0557[μF]<br />
0.0557 / 0.45 = 0.124[km] = 124m<br />


<h2>使用しないGRを不動作にする方法</h2>
※必ず停電状態にて作業をすること。<br>
1.GR継電器のP1P2端子から配線を外して絶縁ビニルテープを巻いて絶縁処理する。<br>
2.GR継電器のZ1Z2端子から配線を外し、その配線同士を短絡させる（ZCT2次側のkとlを短絡状態にする）<br>
3.引き外し回路a端子とc端子の配線を外し、絶縁ビニルテープを巻いて絶縁処理する。<br><br>

上記のうち、3だけ行った場合、引き外し回路が切れるので、遮断器は引き外されることはない。<br>
1と3を行えば、わざわざ2を行う必要はないかも？Z1とZ2は継電器についたままでも問題ない。<br>


