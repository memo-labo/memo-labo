<h2>電解コンデンサ</h2>

<img src="images/denkai1.jpg" style="max-width:300px;" /><br>

アルミ電解コンデンサ<br>
アルミニウムの酸化皮膜を誘電体として用いるコンデンサのこと。<br>
平滑用、デカップリング用などとして使用される。<br>
足の長いほうが「リード線」で「プラス＋」<br><br>

<img src="svg/inv3.svg" style="max-width:600px;" /><br><br>

デカップリングとは？<br>
「直流成分+交流成分」から「直流成分」のみを取り出すこと。<br><br>

電解コンデンサの「圧力弁」とは？<br><br>

別名「防爆弁」<br>
電解コンデンサの頭部には十字形やK字形の印がある。<br>
電解コンデンサの爆発を防ぐ。<br><br>

爆発の原因<br>
・逆電圧<br>
・過電圧<br>
・リプル電圧<br>
・交流電圧<br>
・急激な充放電<br><br>

