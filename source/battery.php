メリット<br>
電圧も電流の向きが一定なのでコンデンサやコイルなどの挙動も一定。<br>
直流では回路に進みや遅れが発生しない。<br>
電流の向きが入れ替わらないので負荷と電源の間を往復するだけの無効電力が発生しない。<br>
効率よく電力を利用できる。<br>
バッテリーやコンデンサ等で蓄電できる。<br><br>

直流電源のデメリット<br>
交流に比べて電流の遮断が難しい<br>
直流は常に一定の電圧がかかっているため、遮断の瞬間にアークが発生する。<br>
交流の場合、電圧がプラスからマイナスへと切り替わりの際に瞬間的に電圧が0になる。<br>
なので電圧が低いときを狙えば、直流よりも安全に電流遮断ができる。<br><br>

直流は電圧変換（昇圧・降圧）にコストがかかる<br>
直流の電圧を変換するには、一度交流に変換し、再び直流に戻す必要がある。<br><br>

直流は電食作用が強い<br>
常に同じ方向に電気が流れ続けるため静電誘導や電食作用で送電機器の腐食が進む。<br>
そのため送電に必要な地下パイプやがいしの腐食が激しい。<br>


<h2>蓄電池の種類</h2>

<h3>鉛蓄電池</h3>
<ul>
  <li>鉛（Pb）二酸化鉛（PbO2）希硫酸（H2SO4）
  <li>一般的に広く使われている。
  <li>アルカリ蓄電池に比べ、安い。
</ul>

<h3>アルカリ蓄電池</h3>
<ul>
  <li>オキシ水酸化ニッケル（NiOOH）カドミウム（Cd）苛性カリ溶液（KOH）
  <li>機械的強度が高く、過放電にも耐え、放電特性も良く、長寿命だが、コストが高い。
</ul>

<h2>直流電源喪失した場合</h2>
<ul>
  <li>制御電源喪失による、継電器や遮断機の不動作。
  <li>それに伴う波及事故、停電後の復電操作不能、など。
</ul>

