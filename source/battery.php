<h2>非常照明が点灯しない</h2>

・非常照明が点灯しないという不具合<br>
・直流電源装置の直流電圧計では電圧が確認された<br>
・充電電圧は正常に見えても負荷をかけると電圧が落ちる<br><br>

よくある原因<br>
・液面低下で電解液が減少、極板が一部露出、内部抵抗が急上昇<br>
・バッテリー劣化で電解コンデンサ容量抜けが発生<br><br>

対応方法<br>
・電解液補水は応急処置、蓄電池交換が妥当<br>
・全体が古い場合は制御基板も劣化しているので電源装置丸ごと更新（目安は20年）<br>

<h2>負荷電圧補償装置とは？</h2>

蓄電池から供給される負荷には、停電時には蓄電池が放電して電圧が低下して、回復充電の時には電圧が上昇する。<br>
このような電圧変動を負荷の許容範囲内に保ち、機器の故障を防止するため使用する。<br><br>

シリコンドロッパー（ＳＩＤ）方式。<br>
負荷補償装置として最も一般的な方法。<br>
直流電圧を降下させ、蓄電池などを設置する場合に利用される。<br>
シリコンダイオードの順方向電圧降下を利用したもの。<br>
１個当たり約0.6Vの電圧降下があるので必要電圧分を直列に接続する。<br>
抵抗と違って電流の変化にかかわらず電圧降下がほぼ一定なのが特徴。<br>
UPSだけでは充電量によって供給電源電圧が負荷の許容電圧を超える場合がある。<br>
なのでシリコンドロッパを設けて電圧を調整する必要がある。<br>

<h2>蓋の構造による違い　ベント形（開放タイプ）</h2>
<ul>
  <li>水の電気分解や自然蒸発によって電解液中の水分が失われる。
  <li>電解液比重を測定して、補水を行う必要がある。
  <li>通常、蓄電池の液口栓に触媒栓を取り付け、補水間隔を延ばす。
  <li>触媒栓とは、蓄電池化から発生する酸素ガスと水素ガスを再結合させて水に戻す装置。
</ul>

<h2>蓋の構造による違い　シール形（密閉タイプ）</h2>
<p>
発生した酸素ガスを、陰極の鉛と反応させ、PbSO4とH2Oを生成させる。<br>
このため、補水が必要になる。
</p>

<h2>蓄電池の寿命</h2>
<ul>
  <li>蓄電池は温度環境に大きく影響を受ける。
  <li>25℃を基準として、10℃温度が上昇すると、期待寿命が半減する。
  <li>設置場所の換気、温度調整が重要。
</ul>


