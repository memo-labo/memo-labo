インターロックレバーを持ち上げるとインターロックピンが持ち上がりVCBを引き出せる。<br>
<img src="images/vcb_hi4.jpg" style="max-width:500px;" /><br><br>

インターロック装置のあるタイプ<br>
①VCB閉路状態ではVCBの移動（引き出し・投入）ができない。<br>
インターロックピンが操作機構とインターロックされておりインターロックレバーが持ち上がらない。<br>
なのでVCB閉路状態において、盤外⇒試験位置⇔接続位置⇔の移動ができない。<br><br>

②試験位置及び接続位置以外の不完全な挿入状態では閉路できない。<br>
遮断器のインターロックピンが固定のロック板上にあり入切レバーを押し下げることができない。<br>
なのでハンドル等による手動投入はできない。<br>
かつ電気的にも投入制御回路を遮断しており閉路できない。<br>
