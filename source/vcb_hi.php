<h2>引出形VCBとは？</h2>

<p><strong>引出形VCBは、VCBを開閉するだけでなく、遮断器本体を盤内の主回路接触部から機械的に切り離せる構造の真空遮断器です。</strong></p>

<p>点検・保守時に主回路との接続状態を明確に分けられるため、受電盤や母線連絡盤などで使用されます。</p>

<img src="images/vcb_hi2.jpg" style="max-width:550px;" alt="引出形VCB"><br>

<h2>接続位置・試験位置・断路位置</h2>

<p>引出形VCBでは、機種によって次のような位置があります。</p>

<ul>
  <li><strong>接続位置</strong>：主回路・制御回路とも接続された運転位置</li>
  <li><strong>試験位置</strong>：主回路は切り離し、制御回路のみ接続して開閉動作などを確認できる位置</li>
  <li><strong>断路・引出位置</strong>：主回路から遮断器本体を切り離した位置</li>
</ul>

<p>名称・位置関係はメーカーや盤構造によって異なるため、盤の表示と取扱説明書を確認します。</p>

<h2>なぜ引き出せるようになっている？</h2>

<ul>
  <li>VCB本体の点検・交換をしやすくする</li>
  <li>主回路から機械的に切り離した状態を作る</li>
  <li>試験位置で制御回路・投入開放動作を確認できる</li>
  <li>保守時の誤投入防止や作業区分を明確にする</li>
</ul>

<p><a href="vcb_b.php">母線連絡遮断器 52B</a>などに引出形が採用される例もあります。</p>

<h2>制御プラグ</h2>

<p>引出形VCBでは、主回路接触部とは別に制御回路用プラグ・コネクタを持つ機種があります。</p>

<img src="images/vcb_hi3.jpg" style="max-width:500px;" alt="引出形VCBの制御プラグ"><br>

<p>試験位置で制御プラグを接続したままにできる構造では、主回路を切り離した状態で投入・開放信号、補助接点、トリップコイルなどを確認できます。</p>

<h2>インターロックの役割</h2>

<img src="images/vcb_hi4.jpg" style="max-width:500px;" alt="引出形VCBのインターロック機構"><br>

<p>引出形VCBには、誤操作を防ぐための機械的・電気的インターロックが設けられています。</p>

<p>代表的な機能例：</p>
<ul>
  <li>VCBが「入」の状態では移動できない</li>
  <li>接続位置・試験位置など所定位置以外では投入できない</li>
  <li>不完全挿入状態で主回路を閉路できない</li>
</ul>

<p><strong>インターロックを解除・無効化して無理に操作しないことが重要です。</strong>動かない場合は、VCBの開閉状態、位置表示、ロック機構、制御プラグなどを確認します。</p>

<h2>交換時の注意</h2>

<p>引出形VCBは、外形が似ていても次の条件が合わないとそのまま交換できません。</p>

<ul>
  <li>定格電圧・定格電流・遮断容量</li>
  <li>主回路接触部の位置</li>
  <li>台車・レール寸法</li>
  <li>制御プラグ・端子配列</li>
  <li>投入・引外し電圧</li>
  <li>機械的・電気的インターロック</li>
</ul>

<p>「同じメーカーなら必ず互換」「数分で交換できる」とは限らないため、更新機種の互換表・改造要否をメーカーへ確認します。</p>

<h2>点検時の確認ポイント</h2>

<ul>
  <li>接続位置・試験位置の表示が正しいか</li>
  <li>引出機構がスムーズに動くか</li>
  <li>主回路接触子に変色・焼損・異常摩耗がないか</li>
  <li>制御プラグの接触不良がないか</li>
  <li>インターロックが正常に働くか</li>
  <li>所定位置以外で投入できないことを確認する</li>
</ul>

