<h2>周波数・回転数・出力の関係とは？</h2>

回転数が変化すると、摩擦負荷の場合、出力は回転数に比例する。<br>
ポンプやブロアのような流体機器の場合、出力は回転数の３乗に比例する。<br><br>

V = KnfΦ[V]<br><br>

V=電圧<br>
K=定数<br>
n=巻数<br>
f=周波数[Hz]<br>
Φ=磁束[Wb]<br><br>

電圧が一定の場合、周波数と磁束は反比例の関係にある。<br>
電圧一定で周波数が減少した場合、磁束は増加し、大きな励磁電流が流れる。<br>
励磁電流が増加すると、負荷力率が低下する。<br>
なので、50・60Hz共用の電動機は、供給電圧を変えて運用することが行われている。<br>

<h2>周波数が家電器具に与える影響とは？</h2>
電熱を利用したものは、周波数には関係なく使用することができる。<br>
電動力を利用したものは、回転数が変化するので、支障が出る場合がある。<br>


