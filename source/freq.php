50Hzと60Hz<br>
日本には「50Hz」と「60Hz」という2種類の周波数が存在している。<br>
おおまかに、東日本が50Hz、西日本が60Hz。<br>
静岡県の富士川と新潟県の糸魚川あたりが境目となっている。<br>
※一部には混在している地区もある。<br><br>

電動機、変圧器、コンデンサ、家電器具など。<br>
周波数が変動すると、機器に影響を与える。<br>


