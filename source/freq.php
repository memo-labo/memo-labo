<h2>３相誘導電動機の回転数</h2>
３相誘導電動機の回転数は周波数に比例する。<br><br>

N = (120f/P)*(1-s)[rpm]<br><br>

rpm = rotations per minute<br>
1分間での回転数<br>
N=回転数<br>
P=極数<br>
f=周波数[Hz]<br>
s=すべり<br>

<h2>すべりとは？</h2>
誘導電動機の同期速度(Ns)から実際の回転速度(N)を引いて、Nsで割ったもの。<br><br>

s=(Ns-N)/Ns<br><br>

Ns=誘導電動機の同期速度[min^-1]<br>
N =実際の回転速度[min^-1]<br>

