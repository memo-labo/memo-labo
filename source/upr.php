<h2>UPR 不足電力継電器（91L）の役割・目的</h2>

UPR = Under Power Relay<br>
電力系統側で短絡事故が起こると、受電端での供給電力が不足状態となる。<br>
電力系統側で地絡事故が起こると、配電用変電所のDGR動作で停電になるので、供給電力が断たれる。<br>
受電端で供給電力を監視し、系統側の事故（短絡、地絡、断線）を検出し、発電設備を系統から解列。<br><br>

※逆電力においても動作する。<br>
※動作逆電力は整定値の105%動作<br><br>

製品例：omron<br>
・K2ZC-K2WU-NA（P1-P2-P3 & C1S-C2S）<br>
・K2ZC-K2WU-NT（P1-P2-P3 & C1R-C2R,C1T-C2T）三相不平衡用<br>
・K2ZC-K2WU-NS（P1-P2 & C1-C2）単相<br>
