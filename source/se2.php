<h2>図面を読むときの注意</h2>

<ul>
  <li>接点は通常状態（無励磁状態）で描かれていることが多い</li>
  <li>同じリレー記号の接点が図面内の離れた場所にある</li>
  <li>端子番号と機器番号を混同しない</li>
  <li>図面改修後に現物配線が変更されていない場合がある</li>
  <li>現物・端子台・メーカー資料と照合する</li>
</ul>

