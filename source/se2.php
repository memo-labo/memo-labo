<h2>ダイオードが入っている理由</h2>

<img src="images/se2/1.png" alt="DC警報回路のダイオード例" style="max-width:400px;"><br>

<p>DC制御回路のダイオードは、逆流防止、回路間の分離、論理OR回路、コイルの逆起電力対策など、さまざまな目的で使われます。</p>

<p><strong>個数だけを見て「電圧を0.7Vずつ落としている」と判断することはできません。</strong>ダイオードの向きと接続先を追い、どの回路からどこへの電流を許可・阻止しているかを確認します。</p>

<h2>警報回路用変圧器・整流器</h2>

<img src="images/se2/2.png" alt="警報回路用変圧器" style="max-width:500px;"><br>

<p>制御回路では、AC100Vを低い交流電圧へ変換する変圧器や、一次側と二次側を絶縁する変圧器が使われることがあります。</p>

<img src="images/se2/4.png" alt="ブリッジ整流器" style="max-width:400px;"><br>

<p>ブリッジ整流器は交流を直流へ変換します。整流後に平滑コンデンサやバッテリーを組み合わせる制御電源もあります。</p>

<h2>カドニカなど制御用バッテリー</h2>

<img src="images/se2/3.png" alt="制御用バッテリー" style="max-width:500px;"><br>

<p>Ah（アンペア時）はバッテリー容量を表す単位です。ただし「1.2Ah/5HRなら0.24Aを必ず5時間使える」という単純な保証値ではなく、放電終止電圧・温度・劣化・放電率によって実容量は変化します。</p>

