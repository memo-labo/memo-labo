<h2>展開接続図（シーケンス図）とは？</h2>

<p><strong>シーケンス図は、機器の実際の配置よりも「どの接点が動くと、次に何が動作するか」を追いやすくした制御回路図です。</strong>展開接続図とも呼ばれます。</p>

<p>受変電設備では、VCBの投入・引外し、OCR警報、UVR、インターロック、故障表示などを読むときに使います。</p>

<h2>よく出てくる記号</h2>

<table>
<tr><th>記号</th><th>意味の例</th></tr>
<tr><td>27</td><td>不足電圧継電器（UVR）</td></tr>
<tr><td>51</td><td>過電流継電器（OCR）</td></tr>
<tr><td>52</td><td>交流遮断器（VCBなど）</td></tr>
<tr><td>84</td><td>電圧・操作関連リレーとして使われる例。図面凡例を確認</td></tr>
<tr><td>89</td><td>断路器・負荷開閉器など</td></tr>
<tr><td>43</td><td>切替スイッチ</td></tr>
<tr><td>C / CLOSE</td><td>投入指令を示す表記例</td></tr>
<tr><td>T / TRIP</td><td>引外し指令を示す表記例</td></tr>
<tr><td>X</td><td>補助リレーを示すことが多い</td></tr>
<tr><td>T</td><td>タイマを示すことがある</td></tr>
</table>

<p><strong>52、51、27などの機器番号は規格・慣例に基づくものがありますが、X、T、R、Fなどの補助記号は盤メーカーや図面ごとのルールが入ります。</strong>必ずその図面の凡例を確認します。</p>

