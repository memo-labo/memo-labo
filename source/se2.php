<img src="images/se2_1.jpg" alt="OCR警報回路シーケンス図" style="max-width:500px;"><br>

<p>OCRの警報a接点が閉じると警報リレーが動作し、自己保持によってOCRが復帰したあともランプを保持する回路例です。</p>

