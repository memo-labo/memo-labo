<h2>シーケンス図を読む順番</h2>

<ol>
  <li>制御電源の＋側・電源側を探す</li>
  <li>操作スイッチや保護継電器接点を追う</li>
  <li>最終的に励磁されるコイルを探す</li>
  <li>そのコイルのa接点・b接点を別の場所で探す</li>
  <li>自己保持・インターロックの条件を確認する</li>
</ol>

<h2>OCR警報と自己保持回路</h2>

<img src="images/se2_2.png" style="max-width:500px;" alt="OCR警報自己保持回路"><br>

<p>OCRが動作すると補助リレー51Xが励磁され、51X自身のa接点で自己保持する回路例です。</p>

<p>リセットスイッチのb接点を一時的に開くことで自己保持を解除し、51Xと警報表示を復帰させます。</p>

<h2>30X・89Xを使った投入インターロックの例</h2>

<img src="images/se2_3.png" style="max-width:700px;" alt="VCB投入インターロック回路例"><br>
<img src="images/se2_4.png" style="max-width:700px;" alt="30Xと89Xのシーケンス例"><br>

<p>故障表示・ロック用リレーが動作中はVCB投入回路を成立させない、DSが所定位置でなければVCBを投入できない、といったインターロックが組まれることがあります。</p>

<p><strong>「切操作は必ず制限なし」などと一律に考えず、対象盤の回路を追います。</strong></p>

<h2>EWD・CWDとは？</h2>

<p><strong>EWD（Elementary Wiring Diagram）</strong>は、機器の物理配置より動作関係を優先して展開した図面です。動作順序を理解しやすいのが利点です。</p>

<p><strong>CWD（Control Wiring Diagram）</strong>は、実際の端子・配線・機器間接続を確認するときに使われる図面表現です。</p>

<p>図面名称や表現方法はメーカー・設備設計ルールによって異なります。</p>

