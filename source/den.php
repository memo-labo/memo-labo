<h2>架空地線・高圧架空電線</h2>
高圧架空電線<br>
6.6kV線路の高圧配電線のこと（OC線、OE線、OP線）<br><br>

OE電線（屋外用ポリエチレン絶縁電線）<br>
高圧架空電線路に用いられている電線。絶縁体にポリエチレンを使用。<br>
着雪による断線事故防止で絶縁体表面にヒレをつけたSN-OE電線などもある。<br>
最大許容温度は75℃。<br><br>

架空地線<br>
送電、配電などのための架空線（電線）路を、主に雷から保護する装置。<br>
送電線への直撃雷を保護する避雷設備の役割を持つ。<br>
グラウンドワイヤ (Ground Wire) の頭文字をとってGWと称されることも多い。<br><br>

OPGW（optical ground wire）<br>
架空地線の内部に光ファイバーを実装したもの。<br>
既存のケーブルを利用して、大容量の通信回線を設置することが可能となる。<br>
光ファイバー複合架空地線。<br><br>


