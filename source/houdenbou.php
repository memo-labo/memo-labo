商品例<br>
篠原電機 HSB-50<br><br>

放電電流を制限する為の抵抗を内蔵。<br>
安全性を高め、接触部のダメージを抑える。<br><br>

高圧のコンデンサ等に接地棒が触れると、触れた瞬間にバチッと火花が飛ぶ。<br>
大容量のコンデンサを放電抵抗なしで接地すると大電流が流れて接触部がアーク溶着する可能性。<br>
数秒の時間をかけて電荷をゆっくり放電する必要がある。<br><br>

