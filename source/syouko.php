消弧剤の成分：ケイ砂（二酸化珪素 SiO₂）<br><br>
消弧までの流れ<br>
・ヒューズ素子がジュール熱で急速に溶断し、アークを発生<br>
・アーク熱で消弧剤が気化蒸発し、アークを冷却<br>
・冷却によりアーク抵抗が増加し電流が減少<br>
・気化した消弧剤が固化し、固化した消弧剤により絶縁が増加<br>
・遮断完了<br><br>

