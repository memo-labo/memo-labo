<h2>絶縁耐力試験の充電電流計算</h2>
交流耐圧試験では、被試験物の絶縁が正常でも静電容量による充電電流が流れる。<br>
試験器や発電機の容量を考えるときは、この充電電流を先に見積もる。<br><br>

