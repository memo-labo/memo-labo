<h2>基本式 I = 2πfCV</h2>
<strong>I = 2πfCV</strong><br><br>

I：充電電流[A]<br>
f：周波数[Hz]<br>
C：対地静電容量[F]<br>
V：試験電圧[V]<br><br>

6.6kV系統をAC10.35kVで試験する場合、CをμFで入れると、<br><br>
50Hz：<strong>I[A] ≒ 3.25 × C[μF]</strong><br>
60Hz：<strong>I[A] ≒ 3.90 × C[μF]</strong><br>

<h2>計算例：C = 0.032μF、50Hz、10.35kV</h2>
C = 0.032μF<br><br>
I = 2πfCV<br>
≒ 3.25 × 0.032<br>
≒ 0.104A<br><br>

したがって、充電電流は約<strong>104mA</strong>。<br><br>
60Hzなら、<br>
I ≒ 3.90 × 0.032 ≒ 0.125A<br>
となる。<br>

<h2>なぜ I = 2πfCV になる？</h2>
コンデンサの容量性リアクタンスは、<br>
XC = 1 / (2πfC)<br>
で表される。<br><br>

交流電流は I = V / XC なので、XCを代入すると、<br>
<strong>I = 2πfCV</strong><br>
となる。<br><br>

