<h2>試験器容量の目安</h2>
充電電流が分かれば、交流耐圧試験に必要な皮相電力の目安も計算できる。<br><br>
<strong>S ≒ V × I</strong><br><br>

例：10.35kV、充電電流104mAの場合<br>
10,350V × 0.104A ≒ 1,076VA<br><br>

約1.08kVAの容量性負荷になる。<br>
実際の試験器選定では、余裕、試験用変圧器の定格、連続使用時間、リアクトル使用条件なども確認する。<br>

<h2>高圧CVケーブルは充電電流が大きくなりやすい</h2>
高圧CV・CVTケーブルは長くなるほど対地静電容量が増え、交流耐圧試験の充電電流も大きくなる。<br>
長い引込ケーブルでは、試験前に試験用変圧器や発電機容量を確認する。<br><br>

試験機メーカー資料に記載される参考値の例（50Hz・所定試験条件）<br>
38sq：2.04mA/m<br>
60sq：2.46mA/m<br>
100sq：3.03mA/m<br>
150sq：3.60mA/m<br><br>

例：60sq、50m<br>
2.46mA/m × 50m = 123mA<br><br>

これらはケーブル種類・メーカー・構造・試験条件で変わる。可能なら静電容量の実測値やケーブル仕様を優先する。<br>

<h2>変圧器・コンデンサ・開閉器も静電容量を持つ</h2>
ケーブル以外の高圧機器にも対地静電容量がある。<br>
変圧器、進相コンデンサ、PAS、UGS、VCBなどを一括して試験する場合、それぞれの静電容量が合成される。<br><br>

機器単体では数mA程度でも、ケーブルを含めると数百mAになる場合がある。一律の目安値だけで試験器容量を決めず、試験範囲全体で考える。<br>

