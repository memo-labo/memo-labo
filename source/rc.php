<h2>高圧進相コンデンサの絶縁抵抗測定</h2>
放電抵抗によって各相がスター結線にて短絡されている。<br>
なので１相だけ絶縁抵抗測定を行えば、すべての相に対して測定したことになる。<br>
丁寧にやる場合は充電部３相それぞれに対し、DC1000Vメガーにて対地間絶縁抵抗測定を行う。<br>
指示値は100MΩ以上あることが望ましい。値が低い場合、ブッシングなど乾いた布で清掃する。<br>
絶縁測定終了後は感電の危険性があるのでメガーの放電機能を使用し確実に放電する。<br>


