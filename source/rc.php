<h2>注意点</h2>
コンデンサをLBS等で開放した後の注意点。<br>
残留電圧が充分放電しない状態で再投入すると高い過渡電圧が発生。<br>
高圧では開路後５分以内（低圧では３分以内）の再投入はしない。<br><br>

自動制御などで短時間に再投入される可能性がある場合、<a href="coil2.php">放電コイル</a>を使用。<br>
コンデンサの操作シーケンスは、瞬時にOFF－ON動作をさせないように注意。<br><br>

受電中、開放された進相コンデンサ[SC]のLBSを投入すると？<br>
SCの定格電流の数十倍の突入電流が流れる。<br>
変流器二次側に異常電圧が発生、層間短絡や火花放電等で損傷。<br>
サージ電圧により電圧継電器が誤動作、制御回路への悪影響。<br>
対策として、直列リアクトルを設置。<br>
突入電流をSC定格電流の５倍程度まで抑制。<br>

<h2>コンデンサ故障の原因</h2>
①外箱腐食による劣化<br>
・外箱腐食<br>
・内部の絶縁油漏れ<br>
・吸湿<br>
・内部で部分放電<br>
・ガス発生<br>
・絶縁耐力低下<br>
・内部フラッシオーバ<br>
・最悪の場合、爆発<br><br>

その他の要因<br>
・ガスケット（固定用シール材）弾力低下⇒漏油<br>
・がい管部分にクラック⇒漏油<br>
・接続端子の接触不良⇒加熱⇒がい管破損⇒地絡・短絡<br>

<h2>１つのLBSにコンデンサが２つ並列に接続されている</h2>

<img src="images/20260325-1.jpg" style="max-width:500px;"><br>

２つに分ける理由（メリット）<br>
	・大きな１台より小さな２台の方が搬入や設置が簡単になる<br>
	・大容量の特注品ではなく標準品２台として対応できる<br>
	・故障時のリスク分散（１台壊れても、もう１台で対応できる）<br>
	・将来への段階的な増設（最初は１台、時期を見てもう１台増設など）<br>
	・表面積が増えるので放熱効果が良くなる<br><br>

２つに分けるデメリット<br>
	・機器が２台分になり、端子・配線・支持材が増え、コスト増の可能性<br>
	・設置に必要なスペースが増える<br>
	・突入電流が増える（コンデンサ投入時は充電の瞬間なので、ほぼ「短絡に近い状態」になる。コンデンサを並列にすると静電容量は２倍、等価インピーダンスは1/2になる。よって電流は約２倍流れやすくなる）<br>


