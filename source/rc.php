<h2>6%、13%の意味</h2>

コンデンサの、交流に対する容量性リアクタンス = XC = 1/2πfC<br />
コイルの交流に対する誘導性リアクタンス = XL = 2πfL<br /><br />

CとLが直列の場合、XC＝XLに成った時、一番リアクタンスが小さくなり、直列共振状態になる。<br /><br />

容量性の場合、配電線の誘導性リアクタンスと、高調波の周波数で共振する条件に成った時は、大きな高調波電流が配電線に流れ出してしまう。<br /><br />

それを防ぐため、高調波の有る周波数では、誘導性にするために必要な量の直列リアクトルを入れておく。<br /><br />

通常は、５次高調波が対象なので、電源周波数の５倍の周波数より低い周波数で共振する様に、６％の直列リアクトルを入れる。<br /><br />

３次の高調波が多いところでは、直列リアクトルの量を１３％と増やして、電源周波数の３倍の周波数よりも低い周波数で共振するようにする。<br /><br />

電源周波数に対して何倍か、という定数を n とする。<br /><br />

(1/n) * XC = n * XL <br /><br />

n = ５、５次高調波の時、<br /><br />

XL<br />
= (1/n^2) * XC<br />
= (1/25) * XC<br />
= 0.04 * XC<br /><br />

XL = XC * 4% で共振状態になる。<br />
誘導性にするために、4%ではなく、6%にする。<br />
こうすることで、５次高調波に対応する。<br /><br />

n = ３、３次高調波の時、<br /><br />

XL<br />
= (1/n^2) * XC<br />
= (1/9) * XC<br />
= 0.111... * XC<br /><br />

XL = XC * 11% で共振状態になる。<br />
誘導性にするために、11%ではなく、13%にする。<br />
こうすることで、３次高調波に対応する。
