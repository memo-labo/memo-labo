<h2>NHコンデンサとは？</h2>
NH = Non Self Healing<br />
箔電極コンデンサ。電極が金属箔（アルミ箔）<br />
局部的な破壊が生じると、その部分は短絡状態となり、絶縁回復せず、自己遮断不可能。<br />
コンデンサ内部で絶縁破壊が発生すると大きな短絡電流が流れ、コンデンサ容器の破壊や噴油に至ることがある。<br>

<h2>SHコンデンサとは？</h2>
SH = Self Healing<br />
蒸着電極コンデンサ。<br />
プラスチックフィルムの表面に、金属を真空蒸着して、電極として使用。<br />
誘電体の一部が絶縁破壊すると、破壊部分の電極膜が瞬時に蒸発・消滅、絶縁が自己回復する。<br /><br />

フィルムと蒸着金属、両方が取り除かれる。<br />
自己回復作用により徐々に内部圧力が上昇し、破壊時に大きな短絡電流が流れない。<br>
コンデンサ容器の破壊や噴油の危険がない。<br>


<h2>高圧進相コンデンサの放電</h2>

放電抵抗<br />
JISで定められていて、進相用コンデンサに内臓されている。<br />
コンデンサの印加電圧(高圧受電なら6600V)を遮断後、5分後に50V以下になる。<br /><br />

高圧進相コンデンサの放電性<br />
放電装置として放電抵抗を内蔵したコンデンサの放電性は、放電性試験によって試験を行ったとき、残留電圧が5分間で50 V以下でなければならない。<br /><br />

放電コイル<br />
約５秒で５０V以下に放電する。<br />
複数のコンデンサを入り切りして自動力率調整する場合に必要になる。<br />
放電コイルは放電性能が極めてよいため、大変高価<br />
⇒<a href="coil2.php">放電コイルの詳細はこちら</a><br><br>

放電の原理<br />
コイルとコンデンサで電流(電荷)が行き来をし、回路内の抵抗分でエネルギーを消費。<br />

