<h2>高圧進相コンデンサの仕組み・メリット</h2>
SC = Static Capacitor<br>
モーターなど熱源が主目的ではない電気機器の場合、コイルに電気が流れることで無効電流が発生。<br>
コンデンサは、この無効電流と逆方向の電流を流すことで、無駄な電流を抑える。<br>
交流回路で発生する無効電流の割合を減らして力率を改善。<br><br>

高圧側にコンデンサを設置すると、電力会社との契約に対し、見かけの力率が改善される。<br>
そして基本料金の低減に大きな効果を発揮する。<br><br>

低圧側に進相コンデンサを分散して配置するよりもコストが低い。<br>
【疑問】⇒低圧の個別負荷に対する力率改善に効果は無い？<br>

