<h2>CHZ形 微地絡検出</h2>

<img src="images/chz1.jpg" style="max-width:400px;"><br>

<img src="images/chz2.jpg" style="max-width:800px;"><br>

ＳＯＧ制御装置がＧＲ動作に至る前の予兆である「微地絡」を検出。<br>
接点出力、微地絡検出、確定時の計測瞬時値、日時を本器に保存（微地絡ログ）<br>
本体にはUSBコネクタがありパソコンと接続しデータを回収できる。<br>
オプションでＥメール通報を行う拡張ユニットもある。<br><br>

デメリット<br>
微地絡ログが見れたとしても、微地絡が発生している箇所は特定できない。<br>
なので不良と判定もできないし、交換の指摘も出来ない。<br>

<h2>ソフト</h2>

USBケーブル「Type A-Type B」にてパソコン上でデータ観覧可能<br>
ログはcsv形式ファイルでダウンロード可能<br>

<img src="images/chz3.jpg" style="max-width:800px;"><br>
微地絡検出条件の変更（<a href="https://www.togami-elec.co.jp/product/sog_seigyo/product_201.php">動画</a>）<br>
・Menu / Escを押す<br>
・▽を押して「現在の微地絡条件」を表示<br>
・▷を押し、▽を押して変更する項目を探す<br>
・OKボタンで設定変更完了<br><br>

※I0、V0、動作時間も似たような操作で実現可能<br>

