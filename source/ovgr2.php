<h2>低圧OVGR</h2>

製品例<br>
<a href="https://www.hikari-gr.co.jp/dcms_media/other/M002_LVG-7S_ZPC-2C.pdf" target="_blank">光商工 LVG-7S（低圧電路用特注品）</a><br><br>

用途<br>
変圧器の二次側が非接地だった場合、低圧回路の地絡を低圧OVGRで保護する。<br>

<h2>太陽光発電の変圧器に非接地方式が採用される理由（予想）</h2>
落雷時の過電流でパワーコンディショナーが故障するのを守るため。<br>
一般にPCSの電力線はアース線を必要としない非接地方式を採用している。<br>
Tr～PCSまでの回路の地絡は低圧OVGRで検出する。<br>

<h2>変圧器の混触防止板</h2>
混触防止板を使用する理由<br>
・低圧電路に接地工事をすることで不都合を生じる場合<br>
・300Vを超える低圧電路に中性点が取れない場合<br><br>

高圧巻線と低圧巻線との間に金属製の板を設ける。<br>
混触防止板には専用接地端子が必要となる。<br><br>

内線規定（JEAC 1350-12）<br>
同じ個所に２種類以上の接地工事を施す場合、接地抵抗の低い方の接地工事で兼用できる。<br>
混触防止板とトランス外箱を共用接地でもとくに不都合がない。<br>
なので混触防止板の接地は変圧器の外箱の接地端子と兼用する。<br>
A種、B種、どちらかの低い接地抵抗で接地工事を行う。<br><br>

混触防止板は静電的なシールドの効果がある。<br>
高圧側より侵入するサージ電圧を小さくする効果がある。<br>
シールド変圧器として使用される場合もある。<br>

<h2>低圧OVGRの試験例</h2>
低圧OVGRのZPCは、低圧MCCB２次側に配置される。<br>
MCCBをOFF状態で試験しないと電圧が低圧電路に印加されTrで逆昇圧の危険がある。<br />

