<h2>低圧OVGR動作しパワコン停止、どうする？</h2>

調査<br>
・低圧OVGR動作⇒パワコン停止⇒パワコン～トランス間の絶縁測定<br>
・絶縁異常なし⇒パワコン内部で地絡発生した可能性あり<br>
・OVGRの単体試験実施⇒継電器本体が故障していないか調べる<br><br>

対処<br>
・低圧OVGRの電源をOFFにして不動作状態にしてからパワコン復帰？<br>
・原因が解明できるまでパワコン停止状態にしておく？<br>

考察<br>
・雨や湿度の高い時だけPCS内部の絶縁が悪くなる場合がある。<br>
・雨の朝に地絡発生⇒晴れた日に再起動したら復帰できる場合もある。<br>
・晴れた日に再度OVGR動作したらメーカー連絡する。<br>



