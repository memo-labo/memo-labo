<h2>変圧器内部のスラッジ（泥状物質）</h2>
絶縁油への水分含有や絶縁油の酸化が進行すると、絶縁油内部にスラッジが発生する。<br>
スラッジは、コイルや鉄心に付着し始める。<br>
スラッジは冷却効果を妨げ、熱による劣化を促進する。<br>
放置すると絶縁破壊につながるおそれがある。<br><br>

スラッジがコイル絶縁物、鉄心、放熱面に付着すると冷却効果が低下する。<br>
すると温度が上昇し、絶縁物の熱劣化が加速される。<br><br>

絶縁劣化した状態で運転を続けていると、過電圧などによって部分放電が発生する。<br>
また外部からのサージや外部短絡時の電気的または機械的ストレスで絶縁破壊に至ることがある。

