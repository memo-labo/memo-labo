<h2>超音波センサー・振動センサー</h2>

ピエゾとは？<br>
圧電素子（あつでんそし）<br>
圧電効果を利用した受動素子。<br>
「piezoelectric element」の読みからピエゾ素子ともいわれる。<br>
圧電体に加えられた力を電圧に変換する、あるいは電圧を力に変換する。<br>
アクチュエータ、センサ、アナログ電子回路における発振回路やフィルタ回路にも用いられている。<br><br>

