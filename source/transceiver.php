ミリ波<br>
28GHz帯を使った通信方法のこと。<br>
5Gの28GHz帯通信は約30GHzということでミリ波と呼ばれている。<br>
高速通信が可能だが通信可能範囲が狭く障害物の影響を受けやすい。<br>


<h2>携帯電話と無線機の違い</h2>
携帯電話<br>
全国ある基地局を経由して音声データを通信する。<br>
山間部、施設や建物内での通信が圏外となる可能性がある。<br>
周波数が高い。<br><br>

無線機<br>
本体同士で直接電波を送受信する。<br>
携帯電話の通信圏外でも通話ができる。<br>
周波数が低い。<br>

<h2>トランシーバーによる保護継電器の誤作動例</h2>
・道路近くにあるPASのSOGがトラック無線の影響で１年に１回程度GR誤作動⇒停電<br>
・GR（地絡継電器）の近くでトランシーバーを使用したことによりGR誤作動⇒停電<br>
・トラックの無線によりELBがトリップ<br><br>

無線機で保護継電器が誤作動する原理を予想<br>
トランシーバーの使用で送信アンテナから磁束が発せられる。<br>
継電器の中にはコイルがありそれがアンテナの代わりとなってしまう。<br>
トランシーバーからの磁束が継電器内のコイルを貫通し誘起電圧が生じる。<br>
その誘起電圧によって継電器が誤作動を起こす。<br><br>
