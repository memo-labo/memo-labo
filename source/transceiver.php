<h2>無線機（トランシーバー）</h2>
トランシーバー（特定小電力トランシーバー）<br>
出力が5W以下の簡易業務用無線機よりもさらに通信範囲の出力が低い。<br>
総務省に無線局免許状の申請をする必要がない。<br>
誰でも無免許ですぐに利用できる。<br>
最大でも300mしか通信できない。<br><br>

TX（送信）<br>
RX（受信）<br>

<h2>周波数とチャンネル</h2>

チャンネル<br>
決まった周波数を割り当てたもの。<br>
例：ラジオ放送「TOKYO FM」は周波数80.0MHz<br><br>

トランシーバーの周波数<br>
400MHz帯の電波を使用する。<br><br>

トランシーバーchの例<br>
ch01：422.0500MHz<br>
ch02：422.0625MHz<br>
ch03：422.0750MHz<br><br>

トランシーバー同士のメーカーが異なってもチャンネル数が同じだと通信できる。<br>

<h2>違法になる例</h2>
トランシーバーを改造して別の周波数帯の電波を送信できるようにした場合。<br>
海外の周波数帯に合わせて作られた製品を日本で使うと違法になる可能性。<br>
その他いろいろな無線機器で使用できる電波の周波数は法律で決められている。<br>


