<h2>84 電圧継電器とは？</h2>

<p>日本の発電設備・制御回路で使われる制御器具番号の資料では、<strong>84を「電圧継電器」</strong>として表す例があります。</p>

<p>非常用発電機では、発電機電圧が確立したことを検出し、その接点信号を電源切替回路へ渡す用途で使われます。</p>

<h2>非常用発電機での84の役割</h2>

<p>代表的な流れは次のようになります。</p>

<ol>
  <li>商用電源が停電する</li>
  <li>非常用発電機が始動する</li>
  <li>発電機の電圧が規定範囲まで確立する</li>
  <li>84の接点が切り替わる</li>
  <li>電源切替回路へ「発電機電圧確立」の信号を送る</li>
  <li>インターロック条件が成立するとDT・ATSなどが非常電源側へ切り替わる</li>
</ol>

<p>実際には単純なパワーリレー、電圧検出リレー、専用コントローラなどで構成される場合があります。</p>

<h2>27・59との違い</h2>

<ul>
  <li><strong>27 UVR</strong>：不足電圧を検出する保護・制御用継電器</li>
  <li><strong>59 OVR</strong>：過電圧を検出する保護継電器</li>
  <li><strong>84</strong>：図面上で発電機の電圧確立などを示す電圧継電器として使われる例がある</li>
</ul>

<p>同じ「電圧を見るリレー」でも、設備内での役割と接点の使われ方が異なります。</p>

<h2>番号体系の違いに注意</h2>

<p><strong>制御器具番号は、使用している規格・図面体系によって意味が異なる場合があります。</strong></p>

<p>日本の設備資料では84を電圧継電器とする例がありますが、ANSI/IEEE C37.2のデバイス番号では84は「Operating Mechanism」とされています。</p>

<p>海外設備、輸入機器、外資系工場などの図面を見る場合は、「84だから必ず電圧継電器」と判断せず、その図面の凡例・機器表・適用規格を確認します。</p>

<h2>点検時に確認するポイント</h2>

<ul>
  <li>発電機電圧が確立したときに84の接点が切り替わるか</li>
  <li>電源切替回路まで信号が届いているか</li>
  <li>商用・発電機の同時投入を防止するインターロックが成立しているか</li>
  <li>復電時に所定のシーケンスで商用側へ戻るか</li>
  <li>図面上の84が何を意味するか凡例で確認したか</li>
</ul>

