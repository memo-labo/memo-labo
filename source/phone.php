<h2>注意点</h2>

東電の電力メーターに付いている通信機器にリークホンを当てると反応することがあるらしい。<br>
ネット情報では、どうやら内部の電源に反応することがあるらしい。<br><br>

DC電源を生成する電源回路にチョッパ回路が含まれている。<br>
そのスイッチング周波数が約40kHZで反応するとのこと（コウモリにも反応）<br>
デジタルメーターや電源機器の一部でも反応することがあるらしい。<br>
実際に何件かやってみたら、いくつか鳴ったという例があるらしい。<br><br>

上記であるのに「高圧充電部の絶縁不良によりコロナ放電が発生しています」など書くと責任問題。<br>


