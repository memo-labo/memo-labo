<h2>リークホン</h2>

製品例<br>
LH-100（フィルタなし）68,000円<br>
LH-100F（フィルタつき）98,000円<br><br>

高圧機器等の接触不良・絶縁不良箇所からは「コロナ放電」が発生する。<br>
そのコロナ放電は、人間の耳には聞こえないような「超音波音」を発している。<br>
その超音波を受信する装置がリークホンである。<br><br>

コロナ放電<br>
送電線のがいし部分でコロナ放電のジージーという騒音がする場合がある。<br>
がいしが埃や塩分などで汚れて、雨により表面が濡れると、がいし表面に微弱な電流が流れる。<br>
気候の変化や微弱な電流が流れたことによる温度変化で表面が乾燥することで、放電音が発生。<br>
青白い光と独特なジージィーという音を放つ。<br>
⇒参考資料：<a href="https://www.energia.co.jp/eneso/kankoubutsu/review/no51/pdf/51_p10_11.pdf">汚損がいしのコロナ騒音低減対策について</a><br><br>

