<h2>配管のエア噛み</h2>
・ポンプ内に空気が発生しやすい、混入しやすいような状態になっている。<br>
・ポンプの設置状態や場所が不適切な状態になっている。<br>
・濾過槽の圧力が高くなり、混入した空気が抜けづらい状態になっている<br>
・流体に溶存していた気体が分離して気泡やエア溜まりが発生する。<br>


<h2>エアバージ（エア抜き）</h2>
エアコン取り付け後、運転前に配管内部と室内機配管内の空気を抜く作業のこと。<br>
エアバージをしないで運転すると、コンプレッサーでエアーも圧縮してしまう。<br>
すると正常な運転圧力を保つことができなくなり、冷えなくなる。<br>


<h2>エアコンのガス漏れ</h2>
エアコンの冷媒ガスは、内部の熱交換器や冷媒管の中に封入されている。<br>
冷媒ガスは本来は減少することはなく、気化と液化を繰り返すだけ。<br>
しかし、何らかの原因で冷媒ガスが外に漏れ出して減ってしまうことがある。<br>

<h2>室外機が爆発する原因とは？</h2>
冷媒管から冷媒ガスが徐々に漏れて吹き出した。<br>
真空である冷媒管に空気が徐々に入ってきた。<br>
室外機のコンプレッサーに空気が入り、空気が圧縮され、爆発した。<br>

