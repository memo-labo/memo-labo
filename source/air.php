<h2>圧縮機（コンプレッサー）</h2>

エアコンの冷房で「熱」を室外に放出するには、室外気温よりも冷媒を高温にする必要がある。<br>
室外気温より熱くなった冷媒は、室外に熱を放出する。<br>
圧縮機は２つの渦巻状の部品で構成され、１つは固定、１つは回転する。<br>
冷媒は２つの渦巻きの間に入り、片方の渦巻きが回転することで圧縮される。<br><br>

<h2>膨張弁と感温筒</h2>
普通は室外機の方についていて、蒸発器の手前側に配置される。<br>
液体の冷媒を狭い隙間に通すことで低温・低圧にして流量と温度を自動調整する。<br>
ある流体が高速に流れると、その高速箇所だけ低圧になる（ベルヌーイの定理）<br>
膨張弁の狭い孔を通ると、冷媒の流入量が減り、噴き出すようにして速度が増す。<br>
小さな孔を通過させ、冷媒の密度を下げ、気体を膨張させる。<br>
