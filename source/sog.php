<h2>PAS無停電状態でのSOG試験</h2>
PASは投入状態のまま、停電させずにSOG動作試験をする方法。<br>
トリップコイル引き外し端子、Va VcをSOG制御装置から外して触れない状態にする。<br>
この状態であればSOGが動作してもPASのTCへ電圧は印加されずSOG単体試験ができる。<br>
しかしPAS２次側で地絡、短絡事故が発生した場合、PASは開放されず波及事故に繋がる。<br>

<h2 id="rendou">SOG制御装置とPASの連動試験</h2>

※PAS連動試験の動作時間は地絡動作時間に0.1秒をプラスした時間（<a href="https://www.togami-elec.co.jp/product/product_030.php">戸上PAS取扱説明書より</a>）<br>

<ul>
  <li>試験機のP1、P2は、SOGには繋がない。</li>
  <li>試験機のkt、Ltを、SOGのkt、Ltにそれぞれ繋ぐ。</li>
  <li>試験機のV、Eを、SOGのT、Z2/Eにそれぞれ繋ぐ。</li>
  <li>試験機の信号線T1、T2は、SOGのP1P2につなぐ。</li>
  <li>試験機のカウンタストップを「電圧」に切り替える。</li>
  <li>試験機I0を、整定値の130%に整定する。</li>
  <li>試験機V0を、整定値の150%に整定する。</li>
  <li>PASを投入する（SOGのP1P2に電圧が出力される）</li>
  <li>試験機からSOGに電流と電圧を印加し、SOGを動作させ、PASを開放させる。</li>
  <li>PASが開放したことによりP1P2が無電圧となり、試験機のカウンタがストップする。</li>
</ul>


<h2>PAS無停電状態でのSOG試験</h2>
<ul>
  <li>①警報接点a1、a2、a3、acを外す
  <li>②制御線、Va、Vb、Vcを外す（他の端子に触れないように、絶縁テープで保護）
  <li>V、E、Kt、Lt、a1、acにDGR試験機から配線し、SOG動作試験を行う
  <li>GR・SOテストスイッチでランプとターゲットが表示される事を確認
  <li>②⇒①の順で配線を戻す
</ul>

<h2>無停電状態で試験する際の注意点</h2>
<ul>
  <li>DGR試験機の制御電源は別電源からとる。
  <li>SOGのP1P2からDGR試験機の制御電源をとると、PAS内蔵VTが焼損する。
  <li>無停電状態ではP1P2に105Vの電圧が印加されている。P1P2を短絡させるとVTが焼損する。
  <li>Va-Vc間に電圧が印加されるとPASがトリップする。
</ul>



<h2>短絡電流⇒SO動作⇒PAS開放までの流れ</h2>
<ol>
  <li>需要家内で短絡事故発生</li>

  <li>PAS内のR相・T相に設置されたOCRが動作（600A±100Aで動作）</li>

  <li>PAS内OCRが動作⇒PAS内の接点が閉じる⇒SOG内のVb-Vc間が導通</li>

  <li>Vb-Vc導通⇒PC2（フォトカプラ）に電流が流れる⇒信号がCPUに伝達</li>

  <li>需要家の短絡電流により電力側の電線用遮断器（FCB）が遮断⇒停電発生</li>

  <li>PAS内の負荷側に接続されたVTが無電圧⇒SOG制御装置P1P2が無電圧</li>

  <li>SOG内のP1P2が無電圧⇒その信号がSOGのCPUに送信される</li>

  <li>Vb-Vcの導通、P1P2の電源停止、この２条件にてRY2が動作</li>

  <li>常時は、Vcの先にある「トリップコンデンサ」は蓄電状態</li>

  <li>RY2が動作⇒Va-Vc回路が閉路⇒トリップコンデンサ～Va～トリップコイル～Vcへと電流が放電

  <li>PAS主回路が開放される

</ol>


