<h2>SOの疑似動作試験方法</h2>

<ol>
  <li>SOG制御装置、P1、P2配線を端子から外しそれぞれテープ絶縁</li>
  <li>PASを投入状態にする</li>
  <li>SOG制御装置のP1P2に電源を印加</li>
  <li>SOG制御装置のVb-Vc間をワニぐちクリップ等で一瞬短絡（PAS内OCRの疑似動作）</li>
  <li>短絡後の１秒以内にP1P2への電源供給を停止</li>
  <li>SOG内のコンデンサからVa-Vc間に電圧が印加され、PAS内トリップコイルでPASが開放される</li>
</ol>


<h2>SOGのZ2が接地されていなかった場合</h2>
SOGの地絡電流検出は、Z1-Z2間の電圧で測定する。<br>
SOGの零相電圧検出は、Y1-Z2間の電圧で測定する。<br>
故にZ2が接地されていない場合、継電器試験でV0が動作しない可能性がある。<br>
実際の運用でもZ2が接地されていない事によりノイズの影響を受け誤動作を起こす可能性がある。<br>
また、SOGのZ2が接地されていないという事は、PAS筐体も接地されていないことになる。<br>
PASが無接地の状態でPASに高電圧が発生した場合、SOG制御装置まで高電圧が印加される。<br>


<h2>SOG制御装置が残留電圧による影響で零相電圧が基準値外に</h2>
単相回路の接続や、高圧自動電圧昇圧器（ＳＶＲ）の設置により、配電線の対地静電容量や対地電圧が不平衡であった場合、地絡事故がなくても、零相電圧が常時発生する。これを「残留電圧」と呼ぶ。<br>
この状態でSOGへ試験電圧を加えると、残留電圧と試験電圧のベクトル和がＳＯＧ制御装置に印加される。<br>
その場合、残留電圧が大きいと、正常値で動作しない可能性がある。<br>
この場合、PASやUGSの開閉器を開放し、停電状態にして、残留電圧の影響をなくし、試験を実施する。<br>


