<h2 id="rendou">SOGとPASの連動試験</h2>
SOG動作からPAS開放までを確認する試験。<br>
PASの連動試験時間は、SOGの動作時間に開閉器の機械的動作時間を加えた値として確認する。<br><br>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：連動試験では不要な受電設備まで励磁しない</span>
PASまたはUGSを実際に投入してSOG連動試験を行う場合は、設備条件が許せば受電LBSを開放しておく。<br>
受電LBSが投入されたままだと、PAS・UGSを投入した瞬間に変圧器など受電設備まで一緒に励磁され、突入電流が流れる。<br>
突入電流の大きさや継続時間によっては、LBSの高圧限流ヒューズが溶断する可能性がある。<br><br>
停電点検中のSOG連動試験では、PAS・UGSの動作確認だけが目的なら、不要な受電設備まで繰り返し励磁しないよう系統を切り分けておくと安全。<br>
ただし、LBSの開放可否や試験手順は設備構成・保護協調・現場の作業手順によって異なるため、単線結線図と現場状態を確認して判断する。<br>
⇒<a href="lbs.php">LBS（高圧交流負荷開閉器）の基本と点検</a>
</div>

試験例<br>
<ul>
<li>試験機Kt・LtをSOG Kt・Ltへ接続</li>
<li>試験機V・EをSOG T・Z2/Eへ接続</li>
<li>カウンタ停止信号をPAS開放で無電圧となる回路から取る</li>
<li>I0、V0を所定倍率へ設定</li>
<li>PAS投入状態でSOGを動作させる</li>
<li>PAS開放までの時間を測定する</li>
</ul>

<div class="article-field-note">
<span class="article-field-note-title">現場メモ：PASトリップ時の振動をカウンタ停止信号に使う方法</span>
130%など所定の試験値でSOGを動作させ、PASがトリップするまでの時間を測定したい場合、振動センサーを電柱へ固定し、PAS開放時の機械的な振動を拾ってカウンタ停止信号として使える場合がある。<br><br>
PAS本体から直接接点信号を取りにくい現場では、動作時の振動を利用できると測定しやすい。<br>
同じ考え方で、OCRとVCBの連動試験でもVCB開放時の振動を検出してカウンタ停止に利用できる場合がある。<br><br>
ただし、振動の伝わり方は電柱・架台・機器の構造で変わり、周囲の衝撃や作業振動を拾う可能性もある。事前に確実に動作信号を取れることを確認し、正式な測定方法や判定条件は使用する試験器・センサー・メーカー手順に従う。
</div>

<h2>PAS無停電状態でのSOG単体試験</h2>
<div class="article-warning">
<span class="article-warning-title">⚠ 注意：試験中は保護機能を一時的に失う場合がある</span>
PASを投入したままSOG単体を試験する場合は、SOGが動作してもPASへトリップ信号が出ないよう、Va・Vcなどトリップ回路を確実に切り分ける。<br>
ただし、その間に構内地絡・短絡事故が発生してもPASが開放できない状態になるため、試験中の保護機能喪失を認識して作業する。
</div>

<h2>無停電試験時の注意点</h2>
<ul>
<li>試験機の制御電源は別電源から取る</li>
<li>SOGのP1・P2から試験機電源を取らない</li>
<li>P1・P2を短絡させない</li>
<li>Va-Vc間へ誤って電圧を印加しない</li>
<li>外した制御線は他端子へ触れないよう絶縁する</li>
<li>試験後は外した配線を確実に復旧する</li>
</ul>

<h2>SO動作からPAS開放までの流れ</h2>
<ol>
<li>需要家内で短絡事故が発生</li>
<li>PAS内の過電流要素が短絡電流を検出</li>
<li>SOGへ短絡事故信号が送られる</li>
<li>上位側遮断器の動作で系統が停電</li>
<li>PAS内蔵VTの電圧が消失し、SOGが停電を検出</li>
<li>短絡検出と停電検出の条件が成立</li>
<li>SOG内部の蓄勢回路からトリップ回路へ放電</li>
<li>PASが開放される</li>
</ol>

<h2>SOの疑似動作試験</h2>
SO疑似試験の方法は機種・メーカーで異なる。既設配線を扱う場合は、取扱説明書と試験要領に従い、制御回路への誤印加や復旧漏れを防ぐ。<br>

<h2>SOG制御線</h2>
制御線のシールドは開閉器本体側で接地されている構成がある。<br>
追加接地すると多点接地になる可能性があるため、メーカー配線図どおりに施工する。<br><br>

PASをメーカー変更して更新する場合は、SOG制御線の先端がY端子で処理済みか、施工側で端子上げが必要かも確認する。<br>
⇒<a href="pas_size.php">大垣電機と戸上電機のPASの違い｜SOG制御線・本体サイズ・更新時の注意</a><br>

<h2>Z2接地の確認</h2>
SOGはZ1-Z2間で零相電流信号、Y1-Z2間で零相電圧信号を扱う構成がある。<br>
Z2接地が不完全だと、試験時のV0不動作やノイズによる誤動作につながる可能性がある。PAS筐体の接地状態もあわせて確認する。<br>
⇒<a href="pasz2.php">PAS・SOGのZ2/E接地｜旧仕様・新仕様・多点接地の注意</a><br>

<h2>残留電圧の影響</h2>
単相負荷の偏りやSVRなどにより、地絡事故がなくても零相電圧が常時発生する場合がある。<br>
この残留電圧と試験電圧がベクトル合成され、試験結果が基準値から外れることがある。<br>
必要に応じてPAS・UGSを開放し、残留電圧の影響をなくして試験する。<br>
⇒<a href="v0.php">V0（零相電圧）の意味・3810V・5%整定</a><br>

