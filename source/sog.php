<h2>SOG試験前の重要確認</h2>
既設のP1・P2配線は切り離して試験する。<br>
T・E・Kt・Ltは、試験方式に応じて既設状態を確認したうえで使用する。<br>
Ba・Bcなど警報接点に既設配線がある場合は、回路への回り込みに注意する。<br><br>

<div class="article-warning">
<span class="article-warning-title">⚠ 注意：P1・P2へ試験電源を入れる前に切り分けを確認</span>
P1・P2を既設配線へ接続したまま試験機から補助電源を印加すると、PAS内蔵VTへ逆印加し、高圧側へ昇圧される危険がある。<br>
VT焼損や感電につながるため、必ず既設回路との切り分けを確認する。<br>
