SOGとは、英語で、Storage Over Current Ground<br />
日本語では「過電流蓄勢トリップ付地絡トリップ動作」と呼ぶ。<br />
Storage Over Current = 蓄勢 + 過電流 = 短絡電流<br><br>

PASやUGSなどの区分開閉器に設置され、開閉器以降の構内（需要家側）を保護する継電器。<br>
需要家で短絡・地絡事故が発生した場合、PASやUGSを開放して波及事故を防止。<br>

<h2>SOG制御装置の月次点検</h2>
電源ランプは点灯しているか<br>
自己診断表示ランプは点灯していないか<br>
V0、I0ランプは点灯していないか<br>
SOG制御装置の扉は閉めてあるか<br>
ブッシング部の亀裂、損傷、汚損の有無<br>
SOG制御装置の外箱の錆、損傷、汚損<br>
SOG制御装置の中に汚れ、水滴、虫などの有無<br>


<h2>SOG試験方法の注意事項</h2>
SOGに接続されている既設のP1、P2配線は離線する。<br>
T、E、Kt、Lt、は離線せず既設状態のまま。<br>
Ba、Bcは警報接点。配線がされていればBc（common側）だけ離線する。<br><br>


P1、P2の既設配線が接続された状態で試験機からP1P2補助電源を印加すると、PAS内蔵VT２次側に電圧印加、6600V/105Vで昇圧、PAS２次側に6600V印加、構内ケーブルに対地静電容量分の充電電流が流れ、PAS内蔵VT容量以上の電流が流れ、VTが焼損する。
また、キュービクル内の作業員が感電する可能性がある。<br><br>
⇒<a href="j1.php">PASのSOG試験、P1P2配線を外さず電源印加 VT焼損</a><br><br>

■最大感度角<br>
SOG試験を行う時、地絡方向継電器の動作範囲は、V₀を基準として、I₀の位相角で決定される。<br>
この時、位相は「最大感度角」で行う必要がある。<br><br>
位相0度でも試験は行えるが、動作時間測定にて測定時間が少し遅れるケースがある。<br>
※位相特性が遅れ45°～進み135°だった場合、最大感度角は進み45°に設定する。<br><br>

