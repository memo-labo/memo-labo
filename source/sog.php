<h2>SOG制御装置とは？</h2>
SOGはPASやUGSなどの区分開閉器と組み合わせ、需要家構内の地絡・短絡事故時に開閉器を開放して波及事故を防止する制御装置。<br>
SOGはStorage Over Current Groundの略で、地絡保護と短絡事故時のSO動作を扱う。<br><br>

