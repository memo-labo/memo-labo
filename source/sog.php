<h2>SOG制御装置の月次点検</h2>
・電源ランプは点灯しているか<br>
・自己診断表示ランプは点灯していないか<br>
・V0、I0ランプは点灯していないか<br>
・扉は確実に閉まっているか<br>
・ブッシング部に亀裂、損傷、汚損がないか<br>
・外箱に錆、損傷、汚損がないか<br>
・内部に水滴、虫、汚れがないか<br>

<h2>SOG試験前の重要確認</h2>
既設のP1・P2配線は切り離して試験する。<br>
T・E・Kt・Ltは、試験方式に応じて既設状態を確認したうえで使用する。<br>
Ba・Bcなど警報接点に既設配線がある場合は、回路への回り込みに注意する。<br><br>

P1・P2を既設配線へ接続したまま試験機から補助電源を印加すると、PAS内蔵VTへ逆印加し、高圧側へ昇圧される危険がある。<br>
VT焼損や感電につながるため、必ず切り分けを確認する。<br>
⇒<a href="j1.php">PASのSOG試験、P1P2配線を外さず電源印加 VT焼損</a><br>

<h2>DGR要素試験</h2>
SOGの地絡方向要素試験では、I0とV0の位相関係を確認する。<br>
最大感度角で試験することで、動作時間や最小動作値を安定して確認しやすい。<br><br>

試験例<br>
地絡電流 / Z1-Z2間電圧<br>
・0.2A / 20mV±2mV<br>
・0.4A / 40mV±4mV<br><br>

零相電圧 / Y1-Z2間電圧<br>
・190V 5% / 60mV±15mV<br>
・381V 10% / 120mV±30mV<br>

<h2 id="rendou">SOGとPASの連動試験</h2>
SOG動作からPAS開放までを確認する試験。<br>
PASの連動試験時間は、地絡動作時間に開閉器動作時間を加えた値で確認する。<br><br>

<strong>PASまたはUGSを実際に投入してSOG連動試験を行う場合は、可能であれば受電LBSを開放しておく。</strong><br>
受電LBSが投入されたままだと、PAS・UGSを投入した瞬間に変圧器など受電設備まで一緒に励磁され、突入電流が流れる。<br>
この突入電流の大きさや継続時間によっては、LBSの高圧限流ヒューズが溶断する可能性がある。<br><br>

停電点検中のSOG連動試験では、PAS・UGSの動作確認だけが目的なら、不要な受電設備まで繰り返し励磁しないよう系統を切り分けておくと安全。<br>
ただし、LBSの開放可否や試験手順は設備構成・保護協調・現場の作業手順によって異なるため、単線結線図と現場状態を確認して判断する。<br><br>

試験例<br>
<ul>
<li>試験機Kt・LtをSOG Kt・Ltへ接続</li>
<li>試験機V・EをSOG T・Z2/Eへ接続</li>
<li>カウンタ停止信号をPAS開放で無電圧となる回路から取る</li>
<li>I0、V0を所定倍率へ設定</li>
<li>PAS投入状態でSOGを動作させる</li>
<li>PAS開放までの時間を測定する</li>
</ul>

<h2>PAS無停電状態でのSOG単体試験</h2>
PASを投入したままSOG単体を試験する場合は、SOGが動作してもPASへトリップ信号が出ないよう、Va・Vcなどトリップ回路を確実に切り分ける。<br>
ただし、その間に構内地絡・短絡事故が発生してもPASが開放できない状態になるため、試験中の保護機能喪失を認識して作業する。<br>

<h2>無停電試験時の注意点</h2>
<ul>
<li>試験機の制御電源は別電源から取る</li>
<li>SOGのP1・P2から試験機電源を取らない</li>
<li>P1・P2を短絡させない</li>
<li>Va-Vc間へ誤って電圧を印加しない</li>
<li>外した制御線は他端子へ触れないよう絶縁する</li>
<li>試験後は外した配線を確実に復旧する</li>
</ul>

<h2>SO動作からPAS開放までの流れ</h2>
<ol>
<li>需要家内で短絡事故が発生</li>
<li>PAS内の過電流要素が短絡電流を検出</li>
<li>SOGへ短絡事故信号が送られる</li>
<li>上位側遮断器の動作で系統が停電</li>
<li>PAS内蔵VTの電圧が消失し、SOGが停電を検出</li>
<li>短絡検出と停電検出の条件が成立</li>
<li>SOG内部の蓄勢回路からトリップ回路へ放電</li>
<li>PASが開放される</li>
</ol>

<h2>SOの疑似動作試験</h2>
<ol>
<li>SOGの既設P1・P2を外して絶縁する</li>
<li>PASを投入状態にする</li>
<li>SOGへ試験用補助電源を供給する</li>
<li>Vb-Vc間を一瞬短絡して過電流要素動作を模擬する</li>
<li>所定時間内にP1・P2電源を停止する</li>
<li>蓄勢回路からトリップ信号が出てPASが開放することを確認する</li>
</ol>

<h2>SOG制御線</h2>
制御線のシールドは開閉器本体側で接地されている構成がある。<br>
追加接地すると多点接地になる可能性があるため、メーカー配線図どおりに施工する。<br>

<h2>Z2接地の確認</h2>
SOGはZ1-Z2間で零相電流信号、Y1-Z2間で零相電圧信号を扱う構成がある。<br>
Z2接地が不完全だと、試験時のV0不動作やノイズによる誤動作につながる可能性がある。<br>
PAS筐体の接地状態もあわせて確認する。<br>

<h2>残留電圧の影響</h2>
単相負荷の偏りやSVRなどにより、地絡事故がなくても零相電圧が常時発生する場合がある。<br>
この残留電圧と試験電圧がベクトル合成され、試験結果が基準値から外れることがある。<br>
必要に応じてPAS・UGSを開放し、残留電圧の影響をなくして試験する。<br>

