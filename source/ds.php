<h2>DS（断路器・89）とは？</h2>

<p>DSは Disconnecting Switch / Disconnector と呼ばれる断路器です。日本の制御器具番号では89として表されることがあります。</p>

<p>主な役割は、<strong>停電した電路を目で確認できる形で電気的に切り離し、点検・保守時の隔離を確保すること</strong>です。</p>

<p>VCBやLBSのように負荷電流・短絡電流を遮断するための機器ではありません。</p>

<h2>VCBとの違い</h2>

<table>
  <tr><th>機器</th><th>主な役割</th></tr>
  <tr><td>VCB</td><td>負荷電流・事故電流を遮断する</td></tr>
  <tr><td>DS</td><td>無負荷状態の電路を断路し、明確な絶縁距離を確保する</td></tr>
</table>

<p>そのため、一般的な受電設備ではVCBなどの遮断器で電流を遮断したうえで、DSを隔離用として使用します。</p>

<h2>DSを負荷電流の開閉に使わない</h2>

<p>断路器には、通常の負荷電流や短絡電流を安全に遮断するための消弧能力がありません。</p>

<p>負荷電流が流れている状態で開放すると、接点間にアークが継続し、相間短絡・地絡・火傷など重大事故につながるおそれがあります。</p>

<p><strong>DS操作の可否は「電流が小さそう」では判断せず、設備の正式な操作手順、インターロック、機器仕様を確認します。</strong></p>

<h2>微小電流の開閉性能について</h2>

<p>断路器には、母線・ブッシング・ケーブルなどの充電電流といった微小電流について、規格・メーカー仕様上の開閉性能が示される場合があります。</p>

<p>ただし、その値は機種・規格によって異なります。<strong>「DSなら1A以下は開閉してよい」と現場操作の一般ルールにしない</strong>ようにします。</p>

<h2>断路器の定格</h2>

<p>6.6kV設備用では、定格電圧7.2kV、定格電流200A・400A・600Aなどの製品があります。定格短時間耐電流も機種ごとに定められています。</p>

<p>定格短時間耐電流は、事故時などに所定時間流れる大電流に対して、断路器が熱的・機械的に耐えられる能力を示す値です。遮断できる電流値を示すものではありません。</p>

