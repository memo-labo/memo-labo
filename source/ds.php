  <h2>DS 89 断路器</h2>
DS（disconnect switch）<br />
日本名は断路器。ジスコンとも呼ばれる。番号は89。<br />
電流が流れていない電路を開閉するための装置。<br />
短絡電流や負荷電流を遮断する能力はない。<br />
遠隔での動作はない。<br /><br />

VCBの１次側に取り付け、断路器を開放することで完全に回路を断路する。<br /><br />

断路器は、わずかな隙間状態が継続すると、アーク（気体放電、高温で強い光を発する）の原因となるため、フック棒を勢いよく操作するのが原則。<br /><br />

⇒<a href="ark.php">アークとは？</a><br /><br />

飛散したアークが極間や大地に渡ると、アークを通じて、短絡事故や地絡事故につながるため大変危険。<br /><br />

「負荷電流が発生している状態で断路器を開放する」といったようなヒューマンエラーを避けるため、断路器と遮断器でインターロックを組み、「遮断器が投入状態の時は断路器は投入状態で固定」という機械的な保護機構を備えるのが望ましい。<br /><br />

<h2>断路器の定格</h2>
定格電圧：7.2kV<br>
定格電流：200A・400A・600A<br>
定格短時間耐電流：8kA・12.5kA<br><br>

定格短時間耐電流とは？<br>
規定の時間（１秒以上）その断路器に通じても異常が認められない電流の限度のこと。


<h2>ジスコンの電流開閉性能</h2>
メーカーHPより<br>
断路器の電流開閉性能は1A以下であれば開閉可能。<br>
断路器は電流開閉をたてまえとしない機器。<br>
しかし充電された電路、ブッシング、母線、接続線、CVケーブルの充電電流のような微小電流は流れている。<br>
これらの微小電流を1A以下と考え、断路器でこの電流を開閉する性能があることを確認している。<br>

