<h2>インターロックの役割</h2>

<p>遮断器が投入されたままDSを操作する誤操作を防ぐため、VCBとDSの間に機械的・電気的インターロックが設けられる設備があります。</p>

<p>ただし、すべての設備に同じインターロックがあるとは限りません。古い設備では操作手順に依存している場合もあるため、単線結線図・展開接続図・現物を確認します。</p>

<h2>停電・復電操作で重要なこと</h2>

<p>DS、VCB、PAS、UGS、MDS、PDSなどの操作順序は、設備構成・責任分界点・インターロック・電力会社との取り決めによって異なります。</p>

<p><strong>Web上の一般例をそのまま現場の停復電操作手順として使用しません。</strong>各事業場で承認された停復電手順書、単線結線図、保安規程、メーカー資料に従います。</p>

<p>特に復電前は、短絡接地器具、工具、作業者、盤内異物、保護継電器のロック・試験配線などが完全に復旧していることを確認します。</p>

<h2>点検時の確認ポイント</h2>

<ul>
  <li>接点・ブレードに変色、過熱、腐食がないか</li>
  <li>碍子に亀裂・汚損・トラッキング跡がないか</li>
  <li>操作機構が固着していないか</li>
  <li>投入位置・開放位置が明確か</li>
  <li>ロック・インターロックが正常に機能するか</li>
  <li>定格が設備の電圧・電流・短絡条件に適合しているか</li>
</ul>

