<h2>断路器の開閉操作の注意</h2>
断路器を開く時は、必ずVCBを切ってから。<br>
断路器を入れる時は、必ずVCBが切れた状態で。<br>
アークによる負傷を防ぐため。<br><br>

断路器の事故例<br>
・PAS入、VCB入、MCCB入状態で、充電状態にも関わらず断路器を先に開放してしまい、アークを顔面に浴び、火傷を負った。<br />
・停電点検後、断路器１次側に<a href="tanraku.php">短絡接地器具（アースフック）</a>をとりつけたままPAS投入、短絡事故。<br />

<h2>DS生切りの威力（例）</h2>

復電する際、PAS入、DS切、VCB入、MCCB切状態であった。<br>
その状態で、DSの１相を入れた瞬間、激しい音と光と熱が発生し、焦げ臭い匂いと煙が周囲に漂った。<br>
低圧MCCBすべて開放状態だったので、変圧器の励磁電流（突入電流を含む）だけでこの威力である。<br>
もし受電中で負荷電流が流れている中でいきなりDSを切ったら、どれほど恐ろしいことになるか想像は容易い。<br>


<h2>停電・復電時のジスコン操作</h2>

MDSの場合<br>
停電：DS入状態⇒MDS切<br>
復電：DS入状態⇒MDS入<br>
<br>
PDSの場合<br>
停電：DS切状態⇒PDS切<br>
復電：DS切状態⇒MDS入⇒DS入<br>
<br>
PAS or UGSの場合<br>
停電：DS入状態⇒PAS切<br>
復電：DS入状態⇒PAS入<br>
<br>
理由<br>
操作時の危険度がPDS > DS > MDSだから。<br>
<br>
DS<br>
錆びてて固くて最後まで投入しにくい状態のもあるので充電状態で投入するのは危険。<br>
<br>
PDS<br>
絶縁体の陶器と刃が近接しており操作時には充電部に近接するので一番危険。アーク発生が最小限になるような状態で操作。<br>
<br>
MDS<br>
コップ状の陶器＋操作ハンドルで絶縁が確保されているのでPDSより安全。<br>
