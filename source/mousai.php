<h2>毛細管現象</h2>

水中に細い管を立てると毛細管現象で水位が上昇する。<br>
<img src="images/mousai1.jpg" style="max-width:400px;" /><br>

液体中に細い管を入れると、液の種類によっては管内の液面が外部の自由表面より上または下に移動する現象。
吸取り紙は毛管現象を応用したもので、植物の茎が水分を吸上げるのもこの現象に基づく。<br><br>


毛細管現象が電気設備に与える事故例<br>
接地線は銅線を撚り合わせた構造。接地線であるIVの撚り線は地中に埋まっており、地中には水分がある。
「毛細管現象」により地中から接地線導体と被覆の間を水が伝わっていく。そして接地線を伝わり建物内に水が侵入するおそれがある。<br>
