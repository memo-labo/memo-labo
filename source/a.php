<h2>A種の接地側と機器側</h2>

接地端子盤で切り離しA種の機器側と接地極側を測定。<br>
A種の機器側で接地抵抗値が低い場合⇒変圧器の筐体などがコンクリ床にボルト止めされており接地が効いている。<br>
トランスが防振ゴムなどで絶縁されている場合、機器側を測定しても振り切れる（1000Ω以上）<br><br>

機器側が10Ω以下であった場合、どちらが機器側か、接地極側か、判別ができない。<br>
その場合、トランス筐体やケーブルシースアースの接地抵抗を測定してみれば判別できる。<br>

