<h2>A種接地とは？</h2>
高圧の電気設備で感電した場合、わずかな漏電による感電でも致命傷となる。
なので、キュービクル躯体、PAS躯体、避雷器、Tr躯体、VCB躯体、LBS躯体などにA種接地をする。
接地抵抗値は10Ω以下を確保するように接地極を埋設する。
接地抵抗が小さければ、感電した際の人体に分流する電流が小さくなり、被害が低減。

<h2>A種接地の接地線太さ（銅線）</h2>
【一般】直径2.6mm（5.5sq）<br>
【避雷器用】14mm2（14sq）<br>
⇒<a href="la.php">PAS筐体のA種接地がLA内蔵タイプか外付けLAかで太さが変わる理由</a><br>



<h2>A種接地の施工方法</h2>
接地極（接地棒の上端）は地上より75cm以上の深さに埋設する。<br>
接地線を鉄柱や金属体に沿って施設する場合、接地極を地中でその金属体から1m以上離す。<br>
接地線の地下75㎝から地表上2mは、合成樹脂管の「絶縁効力及び強さのあるもの」で覆う。<br>
ただし厚さ2㎜未満の合成樹脂管及びCD管は除く。<br>
避雷器の接地線を防護する場合、金属製の管以外の管に収めて施設する。<br><br>

A種接地埋設に使用される配管<br>
硬質ビニル電線管（VE管）を電柱に固定して一緒に埋設。<br>
