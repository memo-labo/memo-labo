<h2>波及事故が発生した場合のAS開放</h2>
受電設備で地絡や短絡事故が発生し、電力側の遮断器が開放され、最閉路も失敗した場合。<br>
ASを開放して事故点を切り離し、他の需要家に電力を供給しなければならない。<br>
その際、電力側はどのような手順でASを開放するのだろうか？<br>
確かネットで見た情報では、約１時間以内で現地に到着して開放しているらしい。<br>


