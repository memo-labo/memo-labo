<h2>波及事故が発生した場合のAS開放</h2>
需要家設備で地絡・短絡事故が発生し、上位側の保護装置が動作した場合、事故区間を切り離して健全区間への送電を復旧する必要がある。<br><br>

実際にどの開閉器を操作するか、誰が操作するか、復旧までの手順は設備構成や送配電会社の運用によって異なる。<br>
事故時は需要家側の判断で電力側設備を操作せず、送配電会社と連絡を取りながら対応する。<br>

<h2>ASを見るときのポイント</h2>
・ASとPASの位置関係を単線結線図で確認する<br>
・責任分界点と設備の所有区分を確認する<br>
・操作が必要な工事は早めに送配電会社へ相談する<br>
・事故時の操作・復旧手順は送配電会社の指示に従う<br>

