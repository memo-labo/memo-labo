<h2>AS操作の申込み・費用</h2>
ASの操作を送配電会社へ依頼する場合、申込み期限・費用・必要な手続きは地域や工事内容によって異なる。<br>
停電工事の日程を決める前に、管轄する一般送配電事業者へ確認しておく。<br><br>

