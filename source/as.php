<h2>AS（電力側の開閉器）とは？</h2>
ASは、需要家の高圧受電設備より電源側に設置される開閉器として現場で呼ばれているもの。<br>
設備によって構成は異なるが、配電線側の事故区間切り離しや工事・保守時の開放などに使用される。<br><br>

受電設備を追うと、構成例として、<br>
配電線 ⇒ AS ⇒ PAS ⇒ 高圧受電設備<br>
のように見える場合がある。<br><br>

ASとPASは設置者・役割・責任分界点との関係が異なるため、同じ開閉器として扱わず、現場の単線結線図や送配電会社の設備区分を確認する。<br>

