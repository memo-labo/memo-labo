<h2>ASの呼び方</h2>
現場では、<br>
・AS（エーエス）<br>
・電力側の開閉器<br>
などと呼ばれる。<br><br>

電力側の開閉器には、キャビネット内にモールド形の開閉器が設置される構成もある。<br>
名称や形式だけで判断せず、設備図面と送配電会社の管理範囲を確認する。<br>

