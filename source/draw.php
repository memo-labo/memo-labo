<h2>web上で図面作成できるソフト「draw.io」</h2>

「draw.io」<br>
保護継電器やシーケンス図を書く時に便利なフリーソフト。<br>
webサービスなのでパソコンにソフトをインストールする必要がない。<br>
ネットに繋がっていてブラウザが開ければどこでも使うことができる。<br>
動作が軽いのでスペックの低いパソコンでも動きが重くならない。<br>
図形や線を書く時の「自動調整機能」が豊富。<br><br>

