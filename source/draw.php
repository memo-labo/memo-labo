<h2>フローチャート図を作成</h2>

フローチャートは、業務のプロセス、システム、コンピューターアルゴリズムを示す流れ図のこと。<br>
複雑化しやすいプロセスの記録、学習、計画、改善、伝達を明確かつ分かりやすい方法で実現するためのツールとして利用される。<br><br>

無料ソフト draw.io というソフトを使うと簡単にできる。<br>
作成した図は、xml、png、svg、htmlなど様々な保存形式にて保存可能。<br><br>
