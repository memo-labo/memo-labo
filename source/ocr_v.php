<h2>UVRとOCRの組み合わせ盤でOCR連動試験が出来ない</h2>

電圧引き外しOCRの連動試験をしようとしたところ、VCB連動試験ができない。<br>
CTDのAC側に補助電源を入れてVCBをハンドルで投入しても、すぐに開放されてしまう。<br>
理由はUVRが動作時（b接点閉路時）はUVRを介してVCBのトリップコイルに電圧が印加されるから<br><br>

UVRとOCRの配線図<br>
<img src="images/uvr-ocr1.svg" style="max-width:700px;" /><br>

この例ではVCBの切回路は３つ並列で存在する。<br>
①手動⇔自動モードを手動にした状態でハンドルで切る<br>
②OCR(51)が動作するとVCBのTCに電圧が印加されVCB開放<br>
③UVR(27)が動作するとVCBのTCに電圧が印加されVCB開放<br>
<br>
停電時には③が動作状態なのでハンドルでVCBを入れてもすぐ開放されてしまう。<br><br>

対策<br>
UVR裏面のトリップ回路配線を本体から離線しておく（だいたいb1-C1）<br>
この状態であればUVRによってVCBが開放されることがないので連動試験が行える<br>

<h2>受電盤52Rが投入状態かつUVRを離線してないと52F1が入らない</h2>

受電盤にOCRとUVR、き電盤にOCRが付いている現場でたまにある現象。<br>
受電盤52Rが投入状態でないと、き電盤が入らないシーケンスが組まれている。<br>
かつ受電盤UVRのトリップ回路を離線しておかないと、き電盤VCBが入らない仕組み。<br><br>

UVRのトリップ回路を離線し、かつ52Rを投入状態で52F1の連動試験が行える。<br>
こういった現場は、本来は担当者が試験方法を記録しておき、試験者に詳細を伝えるべき。<br>

<h2>OCRの連動試験がT1-T2間の接点動作不良により実施できない</h2>

警報接点のa1-a2の動作は問題なかった。<br>
連動試験の際、OCRが動作してもVCBが動作しなかった。<br>
調べると、引き外し接点「T1-T2」の動作不良であった。<br>
<br>
調べ方<br>
T1-T2の配線を外し、OCR単体動作をT1-T2に信号線をつけて試験してみる。<br>
OCRが動作してもカウンタがストップしなければT1-T2の動作不良。<br>
<br>
応急処置<br>
T1-T2を警報接点のa1-a2に接続する。<br>
これでOCRが動作した場合、VCBのTCに電圧が印加され引き外しは可能。<br>
しかしこれは本来の繋ぎ方ではない。<a href="setten.php">接点容量の問題</a>もある。<br>
指摘事項に「動作不良・交換推奨」としてあげるべき。<br>


