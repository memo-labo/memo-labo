OCR電圧引き外しタイプ<br>
別名「常時開路式」<br>
名前の由来「内部の接点構造」<br><br>

メリット</h2>
電圧引き外しは、引き外し用電源が常に安定的に供給される仕組み。<br>
電流引き外しは、事故電流からCT２次側電流を利用することで引き外す。<br>
CT２次側の配線状況や接点抵抗で電流値が変化するので電圧引き外しの方が信頼性が高い。<br><br>

電流回路<br>
CTTのR相⇒C1R⇒C2R⇒AS⇒A⇒CTTのcom相<br>
CTTのT相⇒C1T⇒C2T⇒AS⇒A⇒CTTのcom相<br>
電圧引き外しは電流引き外しのように電流回路に開路される接点はない。<br><br>

VCBトリップ回路<br>
OCRが動作すると、継電器内部にあるa接点、T1-T2間とa1-a2間が同時に閉路。<br>
制御電源⇒T2⇒T1⇒52aパレットスイッチ⇒トリップコイル⇒制御電源。<br>
上記回路によりVCBトリップコイルに電圧が印加されVCBが開放。<br><br>

「52a」とは？<br>
VCB内部にあるパレットスイッチ。<br>
遮断器の開閉状態に連動して動作するスイッチのこと。<br>
VCBのトリップコイルに電圧を励磁し続けないようにするための装置。<br>
VCBが開放状態で52aも開放、VCBが投入状態で52aも投入状態となる。<br>
また遮断器の開閉状態を外部に送るためのもの。<br><br>

