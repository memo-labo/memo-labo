<h2>トリップ用電源</h2>

①<a href="ctd.php">CTD（コンデンサ引き外し電源装置）</a><br>
常時は商用電源からCTDにAC100Ｖで充電され、直流電圧を出力し、VCBを遮断させる。<br />
コンデンサが内蔵されているので、停電しても動作することができる。<br />
CTDの入力側AC100Vの供給源は、VT2次側または低圧電灯盤のMCCBから供給されていることが多い。<br />
CTDの容量は少ないので、停電状態においては１回程度の引き外ししかできない。<br><br>

②直流電源盤<br>
電圧引き外し用OCRがついてるのにCTDが見当たらない場合はだいたい直流電源盤から電源をとっている。<br>
キュービクル内ではなく少し離れて独立した小屋または盤に収納されているケースが多い。<br>

<h2>電圧引き外しVCB</h2>
VCBトリップ回路<br>
VCB上面の5番・6番端子がトリップ回路の端子。<br>
CTDのDC出力側が開放されていればトリップコイルの抵抗値と絶縁抵抗が測定可能。<br><br>

VCB電動ばね操作型<br>
手動タイプと同じく端子番号⑤⑥がトリップ回路。<br>
端子番号①②が蓄勢回路、③④が投入指令回路。<br>
蓄勢や投入指令の電圧はACまたはDCの２タイプがある。<br>
VCBトリップの電圧にACはなく、DC100/110V、DC24V、DC48Vなどの直流電圧。<br>


<h2>電圧引き外しOCRのトラブル</h2>

逆昇圧<br>
VCBとの連動試験を行う際、CTDのAC側に電圧を印加しなければならない。<br>
その際、高圧VTとの回路をVTT試験端子やヒューズを抜く等により切り分け出来ていないまま電圧を印加した場合、VT２次側から１次側へ逆昇圧し高圧母線等に高電圧が印加され他の作業員への感電事故に繋がる。<br>
<img src="svg/vt_jiko2.svg" style="max-width:700px;"><br><br>

CTDのDC側にACを入力し破損<br>
CTDのAC側に入力された配線がどこから来ているかわからないので直接CTD裏面に配線し電圧を印加。<br>
それがAC側ではなくDC側であったため、DC端子にACを入力し、CTDの内部基盤が焼損。<br>
新しい製品は４端子あり、裏面にAC・DCの表記があるが、古いのはその表記がない場合がある。<br>
例えば３端子しかなく、５：直流（＋）７：直流（ー）と交流（～）の共通端子、９：交流（～）というケースも。<br>
対策としては、端子への直接入力は極力避け、ちゃんとその上流から印加する。<br>
迷いやすいのはこれ。VTTだけでは上下の切り分けが出来ず、筒ヒューズがあるタイプ。<br>
