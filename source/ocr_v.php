電圧引き外しOCRには、引き外し用接点がT1-T2の１つしかない。<br>
これは遮断器のトリップコイルが１つしかない事を意味する（電流引き外しVCBは２つある）<br>
電圧引き外しOCRは、R相動作時もT相動作時も、同じ１つのトリップコイルを使用してVCBを遮断する。<br><br>

