LBS開放状態の場合、引外し回路スイッチも開放されるので、トリップコイルは励磁されず焼損しない。<br>
フック棒で本体を投入側に押えたまま切指令が継続すると開路せず連続通電となりコイルが焼損する。<br>
LBSが投入状態で安全ピンがついたままの状態でトリップコイルが励磁されるとコイルが焼損する。<br>
リミットスイッチがついていないLBSもあり、その場合にGR試験を行う際、GR継電器が自己保持タイプの場合、コイルに電圧が印加され続ける可能性がある。<br><br>

