<h2>LBS＋GRのリレー試験でトリップコイルへの配線を外す必要があるか</h2>
LBS＋GRのリレー試験を行う際、トリップコイルへの配線を外して試験するケースがある。<br>
しかし、次のどちらかに該当する場合は、基本的にトリップコイルへの配線を外す必要はない。<br><br>

<strong>① LBSにパレットスイッチがある場合</strong><br>
LBSが開放するとパレットスイッチ（引外し回路用のリミットスイッチ）も開放され、トリップコイルへの通電が切れる。<br><br>

<strong>② GRが自己保持ではない場合</strong><br>
GRの動作出力が自己保持されないため、トリップコイルへ電圧が印加され続ける状態にならない。<br><br>

つまり、<strong>「LBSにパレットスイッチがある」または「GRが自己保持ではない」場合は、トリップコイルへの配線を外さなくてもよい。</strong><br>
逆に、パレットスイッチがなく、GRが自己保持する回路では、LBS開放後もトリップコイルへの通電が継続する可能性があるため注意する。<br><br>

※実際の試験では、LBS・GRの機種、接点構成、制御回路、メーカー資料を確認し、現物の回路に合わせて判断する。<br>


