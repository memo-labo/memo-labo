<h2>LBSの補助スイッチ・トリップコイルとは？</h2>

<p><strong>LBSのトリップコイルは、GRなどの保護継電器から引外し指令を受けてLBSを開放させるための電磁コイルです。</strong></p>

<p>コイルが励磁されると機構部が動き、ラッチが外れてLBSが開放します。</p>
<img src="images/lbs9.jpg" style="max-width:400px;" alt="LBSトリップコイル"><br>

<h2>GR試験でトリップコイル配線を外す必要はある？</h2>

<p><strong>一律に「外す」「外さない」と決めず、LBS・GR・補助スイッチ・自己保持回路を含む実際の引外し回路を確認して判断します。</strong></p>

<p>確認するポイント：</p>
<ul>
  <li>LBS開放時にトリップコイル回路を切る補助スイッチがあるか</li>
  <li>GRの出力が自己保持する回路か</li>
  <li>トリップコイルの定格が連続定格か短時間定格か</li>
  <li>試験中に切指令が保持される可能性があるか</li>
  <li>メーカーの試験手順で離線指定があるか</li>
</ul>

<p>短時間定格のトリップコイルへ通電が継続すると、過熱・焼損の原因になります。</p>

<h2>補助スイッチがある場合</h2>

<p>LBS開放に連動して補助スイッチが開き、トリップコイル回路を遮断する構成があります。</p>

<p>この場合はLBSが正常に開放すればコイルへの通電も切れますが、<strong>補助スイッチの故障・調整不良・機構拘束があれば通電が続く可能性</strong>があります。</p>

<h2>GRが自己保持する場合</h2>

<p>GRの出力接点または外部リレーで自己保持している回路では、LBSが開放しても引外し指令が残る構成があります。</p>

<p>補助スイッチでトリップコイル回路を確実に切れるか、復帰操作で自己保持が解除されるかを回路図で確認します。</p>

<h2>LBSのトリップ用リミットスイッチ</h2>

<img src="images/20211105-1.png" style="max-width:400px;" alt="LBS補助スイッチ"><br>
<img src="images/lbs_s1.jpg" style="max-width:300px;" alt="LBSトリップ用リミットスイッチ"><br>

<p>Auxは auxiliary（補助）の意味です。</p>

<p>補助スイッチは、LBSの開閉状態に連動して接点を切り替え、表示・インターロック・トリップコイル回路などに使われます。</p>

<h2>トリップコイルが焼損しやすいケース</h2>

<ul>
  <li>LBSが機械的に開放できない状態で切指令が継続した</li>
  <li>安全ピン・機構ロックなどで開放できないままコイルを励磁した</li>
  <li>補助スイッチが動作せずコイル回路が切れなかった</li>
  <li>自己保持回路により切指令が残り続けた</li>
  <li>誤配線でトリップコイルへ常時電圧が加わった</li>
</ul>

