<h2>連動試験前の確認手順</h2>

<ol>
  <li>LBS・GRの形式と制御電圧を確認する</li>
  <li>回路図でトリップコイルへの電源経路を追う</li>
  <li>補助スイッチの有無と接点状態を確認する</li>
  <li>GR出力の自己保持有無を確認する</li>
  <li>メーカー手順で離線指定がある場合は従う</li>
  <li>試験後に配線・復帰状態を確認する</li>
</ol>

<p><strong>「前の現場では外さなかった」ではなく、その現場の回路で判断するのが安全です。</strong></p>

