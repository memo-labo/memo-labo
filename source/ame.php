<h2>ブルーシートを固定する道具</h2>

ひも<br>
値段が安い<br>
縛るのが面倒<br>
固結びしてしまうとほどくのに苦労する<br>
寒い日や雨の日は手がかじかんでつらい<br><br>

磁石<br>
値段が高い（１個５００円くらい？）<br>
とりつけ、取り外しが簡単<br>
だけどすぐ無くなる（気がついたら個数が減ってる）<br>
強風にあおられてブルーシートが外れてその勢いで磁石が飛んでしまう場合がある<br><br>

インシュロック（何度も使えるタイプ）<br>
値段が安い<br>
切れにくい<br>
縛るのも、ほどくのも簡単にできる<br><br>

フックのついたゴム<br>
ひものように縛る必要がなくなるので楽に固定できる。<br>


