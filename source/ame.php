<h2>ブルーシートでキュービクルの雨の養生</h2>

薄手タイプ<br>
軽くて扱いやすい。<br>
折りたたんでしまうのも簡単。<br>
サイズ3.6m✕5.4mで値段は500円前後と安い。<br>
キュービクルのドアを開けた時にひっかかって破れやすい。<br>
薄くて軽いので強風にバタバタと煽られる。<br>
その結果、ハトメが簡単に破れてしまう。<br><br>

厚手タイプ<br>
重くて持ち運びが大変でしまうのも大変。<br>
値段が高い（#3000 / 3.6×5.4m / 2300円程度）<br>
厚みがあって丈夫で破れにくい。<br>
重みがあるので強風が吹いても煽られにくい。<br>
ドアを開けた時にひっかかっても破られにくい。<br>
使ってて安心感・安定感がある<br>
