<h2>ELBは逆接続できる？</h2>
「ELBはすべて逆接続禁止」と一律には言えない。<br>
機種によって電源側・負荷側が指定されているもの、逆接続に対応するもの、メグ測定スイッチなど所定の仕様が必要なものがある。<br><br>

逆接続不可の機種を逆に使用すると、OFF・トリップ後も内部の漏電検出回路や引き外しコイルへ電圧が残るなど、故障につながる場合がある。<br>
必ず本体表示とメーカー仕様を確認する。<br>

<h2>漏電遮断器のテストボタン</h2>
テストボタンは、漏電発生時にELBが電気的にトリップするか確認するためのもの。<br>
メーカー資料では、漏電遮断器本体に所定の電圧が印加されていないとテスト動作しない機種がある。<br><br>

テストボタンで確認できるのは、主にELB内部の漏電検出・引き外し機構。<br>
機器の接地抵抗、接地線の断線、実際の地絡経路まで一括して確認できる試験ではない。<br><br>

テストでトリップしたあと投入できない、レバーが正常にリセットできないなどの異常が出た場合は、無理に叩いたり繰り返し投入したりせず、原因確認と交換を検討する。<br>
古い機器では内部機構の劣化・固着が表面化することもある。<br>

<h2>接地線の緑・黄／緑色</h2>
保護導体・接地線には、規格や設備ルールに従った識別色を使用する。<br>
緑色や緑／黄色の組み合わせが使われるが、既設設備では施工年代・規格によって表示が異なる場合もある。<br><br>

色だけで接地系統を判断せず、接地端子、図面、導通、接地極との接続を確認する。<br>

<h2>ELB点検時の確認ポイント</h2>
・定格電流、定格感度電流、動作時間の種類<br>
・電源側／負荷側の指定と逆接続可否<br>
・テストボタンで正常にトリップするか<br>
・トリップ後に正常にリセット・再投入できるか<br>
・接地線の断線、緩み、腐食がないか<br>
・ELBで保護される範囲と接地系統が一致しているか<br>
・単相3線式では中性線欠相保護の有無も確認する<br>

