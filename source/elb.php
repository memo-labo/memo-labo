</table>

<h2>ELBが漏電を検出する仕組み</h2>
正常時は、電源から負荷へ流れる電流と負荷から戻る電流がほぼ同じなので、ZCTで見た電流の合計はほぼ0になる。<br><br>

漏電すると一部の電流が大地側へ流れ、往路と復路の電流に差が生じる。<br>
ELBはこの不平衡電流を検出してトリップする。<br>

<h2>感度電流と動作時間</h2>
漏電遮断器には、定格感度電流と漏電引き外し特性が定められている。<br>
高速形・時延形・反限時形などがあり、具体的な動作時間は機種・規格・設定によって異なるため、銘板・仕様書・メーカーの特性曲線で確認する。<br><br>

定格不動作電流 IΔno は、定格感度電流 IΔn との関係が規格で定められている機種がある。<br>
試験時は「感度電流だけ」ではなく、適用規格とメーカーが示す許容範囲を確認する。<br>

<h2>ELBと接地工事の関係</h2>
ELBと機器接地は、どちらか一方だけでよいというものではなく、感電・地絡保護のために組み合わせて考える。<br><br>

機器の金属製外箱などにD種接地工事を行うことで、絶縁故障時の接触電圧を抑え、地絡電流の経路を確保する。<br>
一方、ELBはZCTを通過する電流の不平衡を検出して電路を遮断する。<br><br>

変圧器二次側が非接地のままなど、地絡電流の帰路が成立しない回路では、漏電検出が期待どおり行えない構成がある。<br>
高圧受電設備の低圧側では、B種接地・機器側のC種/D種接地・ELBの組み合わせを設備全体で確認する。<br>

