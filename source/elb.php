<h2>ELB（漏電遮断器）とは？</h2>
ELBは、電路から大地へ漏れる電流を検出し、設定された条件を超えると回路を自動的に遮断する装置。<br>
ELB（Earth Leakage Breaker）、ELCB（Earth Leakage Circuit Breaker）などの呼び方が使われる。<br><br>

内部のZCT（零相変流器）で往路と復路の電流差を監視し、漏電によって差電流が生じると漏電引き外し機構が動作する。<br><br>

