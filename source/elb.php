<h2>漏電ブレーカーとは？</h2>
漏電ブレーカーの英語表記<br>
ELB = Earth Leakage Breaker<br>
ELCB = Earth Leakage Circuit Breaker<br>
２種類の表現があるが、どちらも同じ「漏電ブレーカ」<br>
漏電を検知するとブレーカーが落ちる。<br />
人が復旧させなければならない。<br />

<h2>感度電流と動作時間</h2>

グラフ：漏電引きはずし特性曲線<br>
横軸：地絡電流（定格感度電流に対する％）<br>
縦軸：動作時間<br><br>

定格不動作電流<br>
地絡電流や漏洩電流があっても漏電トリップしない電流値のこと。<br>
漏電遮断器（ＪＩＳ Ｃ ８２０１-２-２）<br>
定格漏電不動作電流Ｉ△ｎｏとして規定され、定格感度電流Ｉ△ｎの５０％の値。<br><br>

高速形の場合<br>
地絡電流が100%：0.1sで動作<br>
地絡電流が500%以上：0.04sで動作<br>

<h2>漏電引きはずし特性の種類</h2>
・高速形<br>
・時延形<br>
・反限時形<br>

<h2>ELBは逆接続してはならない</h2>
電源側と負荷側を逆に接続してはならない。<br>
電源側と負荷側を表示しているNVは、内部の電磁装置が短時間定格。<br>
電源側と負荷側を逆に接続すると、トリップしても電圧印加が継続。<br>
電磁装置が焼損する可能性。<br>

<h2>漏電遮断器のD種接地工事</h2>
<img src="images/elb6.png" alt="" style="width:600px;"><br>
漏電遮断器を動作させるためには、漏電電流を接地に流さなければならない。<br>
接地があることで、漏電遮断器が正常に動作し、感電事故を未然に防ぐことができる。<br>
漏電遮断器と接地、両方が健全であることで、初めて安全が保たれる。<br>


<h2>ELBのD種接地はMCCBと共通にしてはならない</h2>
<a href="setti.php">D種接地工事</a>は、漏電遮断器で保護されている回路と、保護されていない回路を、同一系統にしてはならない。<br>
漏電遮断器で保護されていない回路にて漏電が発生すると、漏洩電流が接地線を伝わり、漏電遮断器で保護されていない回路すべての機器のフレームの電位を上昇させる。<br>
この時、事故電流は漏電遮断器を経由しないため、漏洩状態が継続したまま遮断されることがない。<br><br>

