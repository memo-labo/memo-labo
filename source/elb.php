<h2>ELB保護回路と非保護回路の接地線を共用するときの注意</h2>
漏電遮断器で保護されている電路と、漏電遮断器で保護されていない電路の機器接地を無条件に共用すると、非保護回路の地絡時に共通接地線を通じて他の機器外箱の電位が上昇するおそれがある。<br><br>

内線規程を引用したメーカー技術資料では、ELB保護回路と非保護回路の接地線・接地極は共用しないことを推奨し、低抵抗の接地極を用いる場合の例外も示されている。<br>
現場では接地系統図、接地抵抗値、ELBの保護範囲を確認して判断する。<br><br>

