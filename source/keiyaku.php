<h2>高圧の契約電力はどう決まる？</h2>
高圧需要家の契約電力は、単純に「変圧器容量＝契約電力」ではない。<br>
実際の最大需要電力（デマンド）や契約種別、受電設備・負荷設備の内容などによって決まる。<br><br>

東京電力エリアの一般的な高圧契約では、<br>
・契約電力500kW未満：実量制<br>
・契約電力500kW以上：需要家と小売電気事業者との協議<br>
という区分が案内されている。<br><br>

ただし、契約メニュー・小売電気事業者・一般送配電事業者・予備電力や自家発補給電力などの付帯契約によって扱いが異なる。<br>
実際の契約変更では現在の契約約款・料金メニューを確認する。<br>

<h2>500kW未満の実量制</h2>
実量制では、30分ごとの使用電力からその月の最大需要電力（最大デマンド）を求める。<br><br>

東京電力の案内では、当月を含む過去1年間の各月の最大需要電力のうち、最も大きい値が契約電力となる。<br><br>

つまり、ある月に一度だけ大きなデマンドを出すと、その値がその後の契約電力・基本料金に影響する。<br>
デマンド監視装置や負荷制御を使ってピークを抑える意味はここにある。<br>

<h2>500kW以上の協議契約</h2>
契約電力500kW以上では、負荷設備・受電設備・同業種の負荷率・過去の使用実績などを踏まえて協議により契約電力を決める方式がある。<br><br>

設備を増設したから機械的に「変圧器容量分だけ契約電力が増える」とは限らない。<br>
逆に、契約受電設備や負荷設備を大きく変更する場合は、契約変更の申込み・協議が必要になることがある。<br>

<h2>設備容量と契約電力の違い</h2>
<table>
<tr><th>項目</th><th>意味</th></tr>
<tr><td>設備容量</td><td>変圧器や負荷設備など、設置されている設備の容量</td></tr>
<tr><td>最大需要電力</td><td>一定時間ごとの平均需要電力のうち最大となった値。高圧では30分デマンドが一般的</td></tr>
<tr><td>契約電力</td><td>基本料金等の基準となる契約上の電力</td></tr>
</table>
<br>

例えば変圧器が300kVAあっても、実際の最大需要が100kW前後なら、必ず契約電力が300kWになるわけではない。<br>

<h2>「設備容量×0.8、0.7…」の計算は何？</h2>
設備容量を段階的な需要率で換算する計算方法が、契約設備電力や申込時の契約電力相当値などを求める場面で使われることがある。<br><br>

例として、過去に使われてきた段階式では、<br>
・最初の50kVA部分：80%<br>
・次の50kVA部分：70%<br>
・次の200kVA部分：60%<br>
・次の300kVA部分：50%<br>
・600kVAを超える部分：40%<br>
のように換算する考え方がある。<br><br>

ただし、<strong>この式を現在のすべての高圧契約へ一律に適用できるわけではない。</strong><br>
新設・増設・契約変更の計算では、管轄する一般送配電事業者や小売電気事業者が示す最新の算定方法を確認する。<br>

<h2>段階式の計算例</h2>
仮に設備容量400kVAを上記の段階式で換算する場合、<br><br>

50 × 0.8 = 40<br>
50 × 0.7 = 35<br>
200 × 0.6 = 120<br>
100 × 0.5 = 50<br><br>

合計<br>
40 + 35 + 120 + 50 = <strong>245kW相当</strong><br><br>

これはあくまで、その算定方式を適用する場面での設備容量換算例。<br>
実量制の既設需要家なら、実際の契約電力は最大需要電力の実績で決まる場合がある。<br>

<h2>デマンドを下げる方法</h2>
契約電力500kW未満の実量制では、ピークデマンドを抑えることが基本料金対策につながる。<br><br>

代表例<br>
・空調・ヒーターなど大きな負荷を同時起動しない<br>
・デマンド監視装置で警報を出す<br>
・デマンドコントローラで優先度の低い負荷を一時停止する<br>
・蓄電池や蓄熱設備でピーク時間帯の負荷をずらす<br>
・設備更新時に高効率機器へ変更する<br>

<h2>変圧器を増設・交換するとき</h2>
変圧器の容量変更は、契約受電設備の変更申込みが必要になる場合がある。<br>
東京電力の実量制Q&Aでも、契約受電設備（変圧器）を取り替える場合は、増減や同容量交換を含め申込みが必要と案内されている。<br><br>

設備工事だけ終わらせて契約手続きを忘れないよう、工事会社・電気主任技術者・小売電気事業者・一般送配電事業者で事前に確認する。<br>

