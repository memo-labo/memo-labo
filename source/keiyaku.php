<h2>現場でのポイント</h2>
・設備容量と契約電力は別物<br>
・500kW未満では最大デマンドの管理が重要な契約が多い<br>
・一度高いデマンドを出すと、その後の契約電力へ影響する場合がある<br>
・変圧器増設・交換時は契約変更手続きも確認する<br>
・古い設備容量換算式を現在の契約へそのまま当てはめない<br>

