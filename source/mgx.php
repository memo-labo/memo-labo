<h2>電流引き外し用補助継電器</h2>
製品例<br>
・三菱 MGX-1形電流トリップ補助箱<br>
・光商工 CF-15A<br>
・omron AOF-1N<br><br>

GRやDGRなど地絡継電器と組み合わせて使用される。<br>
電流引き外しタイプのOCRとDGRを同じVCBで併用する場合に使用される。<br>
電圧を電流引き外し方式へ変換し、電流引き外しタイプのVCBを引き外すための補助継電器。<br>
<a href="ldg-23.php">光商工LDG-23K</a>は補助ボックス機能をDGR本体に内蔵しているので不要。<br>

<h2>特徴</h2>
電源の供給用端子がS1、S2とあり、S1の先にはリアクタンスがある。<br>
AC100Vを電流引き外し用電流値の3A～4A程度に抑える。<br>
S1の先にあるリアクタンスを使用する事で4A程度に下げる。<br>
電流引き外し用VCBのトリップコイル抵抗はメーカーにより差がある。<br>
ここに100Vで直接励磁すると電流が流れすぎてトリップコイルが焼損する。<br>

