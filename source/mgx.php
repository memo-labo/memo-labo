<h2>動作原理と試験方法</h2>
・P1P2はVT２次側⇒VTT⇒AC100Vで制御電源を供給<br>
・S1S2は電灯トランス⇒MCCBよりトリップ用電源を供給<br><br>

試験方法<br>
・Kt、Ltに電流を流す<br>
・P1、P2に電圧を印加（VTへ印加させないように）<br>
・S1、S2に電圧を印加（S1S2⇒ブレーカー側⇒トランスへ印加させないように）<br><br>

接点<br>
DGR本体に警報用a接点があるタイプがほとんどなのでそこへ、なければ以下を使用<br>
・a接点：S1-T1、または、T2-S2<br>
・b接点：o1-T1、または、T2-o2<br>

<h2>注意点</h2>

電流引き外しVCBは、引き外し回路に52a接点を介さない場合が多い。<br>
DGRにはメーカーによって出力接点に自己保持を持つものがある（光商工など）<br>
DGR動作後、S1S2に「引き外し用電源」が印加され続けるような状態の場合、VCBトリップコイルに電流が流れ続け、焼損の可能性。<br><br>

継電器の制御電源とトリップ用電源は、VCBより上流のVTからなのか、VCBの下流である変圧器２次側からなのか、注意する。<br>
DGR電源は、多くの場合、制御電源P1P2はVT２次側から、引き外し用電源S1S2は変圧器２次側から。<br><br>

VCBとの連動試験<br>
DGRのP1P2、S1S2を離線し、端子に直接AC100Vを印加してVCBとの連動試験しようとしたらできなかった。<br>
これはP1P2と並列に電圧が供給されてる箇所があり、それはDGRのa接点を通り補助BOXのリレーを動作させるようになってるので、VTT２次側から供給しないとダメ。<br>
このタイプのDGRは試験する際、離線ではなく、VTT２次側から供給＋トリップ電源はMCCB２次側から供給と、本元から電源入力した方が良い。<br>
