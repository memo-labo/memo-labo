<h2>MC 電磁開閉器 特徴</h2>
電磁開閉器。MCやマグネットとも呼ばれる。<br>
操作コイルへの電源の入切をキッカケとして、主接点が入切される。<br>
モーターのような大電流が流れる機器の接点として使用できる「主接点」<br>
電磁リレーのように小電流が流れる制御回路で使用する「補助接点」<br>
MCCBの入切ではなく制御電源の入切をキッカケに動作させることができる。<br>

