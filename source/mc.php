<h2>MCの用途例</h2>
店舗の照明。照明負荷が十数直列の場合、スイッチの開閉容量をオーバーする。<br>
スイッチの入切でMCの開閉を操作し、MCの主回路にて照明に電源を供給する。<br>
サーマルリレーなどの過負荷制御。<br>
表示灯回路のランプの点灯。<br>
自己保持回路の作成、タイマー時間制御、満水 or 渇水などのポンプ制御。<br>
加電圧 or 無電圧の非常用発電制御など。<br>
中央監視からの運転指令で動作。<br>
サーモがついてて設定温度以上になるとファンが運転。<br>


