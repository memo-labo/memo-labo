<h2>モールドジスコンだった場合のケーブルシースアースとZCT</h2>

設備例<br>
モールドジスコン＋VCB＋GRの物件<br><br>

ZCTのシース線のくぐらせ方の予想<br>
L⇒Kに１回くぐらせる<br><br>

理由<br>
他需要家で発生した地絡事故による地絡電流を相殺するため。<br><br>

デメリット<br>
引込ケーブルの絶縁不良で発生した地絡電流もZCTで相殺されGR動作しない<br>
（そもそもMDSでは引込ケーブル地絡は保護できない）<br><br>

くぐらせ方パターン<br>
①ZCTにくぐっていない<br>
②kからLへ１回<br>
③LからKへ１回<br><br>

もらい事故でGR動作する確率<br>
②＞①＞③<br><br>

結論<br>
③にすべき<br><br>

