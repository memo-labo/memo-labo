<h2>吸気口から排気口への空気の流れ</h2>

キュービクルには吸気口を設ける（吸気口がないキュービクルもある？）<br>
ファン排気口・ファン吸気口付近に障害物がある場合、風量低下や騒音の原因となる。<br>
仕切板を設けて通風路を設定することで局部的に温度が高い箇所（熱だまり）を防ぐ。<br>

<h2>換気扇交換の際の注意</h2>
キュービクル上面にはホコリが溜まっているのでブロワーとモップで清掃する。<br>
手動⇔切⇔自動の切替スイッチがついていた場合、手動に切替えて現在の動作状態を確認する。<br>
手動に切り替えても動作しない場合、<a href="pt.php">設定温度つまみ（パネルサーモ）</a>で温度設定を低くして動作させる。<br>
換気扇を動かしてみて、羽根の近くに紙を近づければ吸気か排気か確認できる。<br><br>

吸気タイプと排気タイプを間違えると、屋外の空気をキュービクル内に送ってしまう事になる。<br>
羽根はキュービクル内に向かって取り付いており、吸気タイプであるケースが多い。<br>


