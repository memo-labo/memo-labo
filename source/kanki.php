<h2>キュービクルの換気・排気</h2>

キュービクルの場合、ファンは基本的にキュービクル内の温度が上昇した時のみ動作。<br>
キュービクル内温度監視は<a href="pt.php">パネルサーモ 盤用温度調節器</a>を使用。<br><br>

天井換気扇は雨水が入りやすい傾向がある。<br>
