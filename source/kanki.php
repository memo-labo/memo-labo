変圧器上にシミ？<br>
屋外キュービクルの天井に換気扇があり、その真下に変圧器がある場合、変圧器の上にボタボタと黒いシミがあることがある。<br>
これは換気扇からの汚れた結露水。換気扇の羽根やシャッターに付着した粉じん・油分が、結露水と一緒に落ちて黒いシミになる。<br>

