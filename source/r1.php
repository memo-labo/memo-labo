<h2>スコットトランスとは？</h2>

スコットさんと言う人が発明したトランス。<br />
三相電源から、単相電源 × ２ を取得することができる。<br /><br />

三相から単相を取るとき、三相の片相だけから取った場合、三相のバランスが崩れてしまう。<br />
なので、スコットトランスを使う。<br /><br />

スコット結線変圧器の二次電圧は、位相が９０度異なった２つの単相回路が得られる。<br />
２つの単相負荷が等しいとき、一次側は平衡三相電流となるため、電源側の三相発電機に悪影響を与えることなく、ビル・工場などの非常用電源として使用することができる。<br /><br />

１次側<br />
M座トランス<br />
T座トランス<br /><br />

２次側<br />
M座トランス L1-L2（単相出力）<br />
T座トランス L3-L4（単相出力）<br /><br />

電源S相 ⇒ M座Tr V ⇒ M座Tr O  ⇒ M座Tr W ⇒ 電源T相<br />
電源R相 ⇒ T座Tr U ⇒ M座Tr O<br />

