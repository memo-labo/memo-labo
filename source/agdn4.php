オムロンの「一級漏電火災警報器」<br>

漏電が発生した場合<br>
ブザーが鳴り表示灯（赤）が点灯する。<br><br>

自動モード<br>
・漏電が動作値に達するとブザーが鳴り表示灯が点灯する<br>
・動作値以下になるとブザーが鳴り止み表示灯が消灯する<br><br>

手動モード<br>
・警報が維持される<br>
・手動⇒自動に変更することでリセットされる（接点復帰・警報停止・消灯）<br><br>

制御電源<br>
AC100VとAC200V、両方使える。<br>
P0-P1：AC100V<br>
P0-P2：AC200V<br><br>

