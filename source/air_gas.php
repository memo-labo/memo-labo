<h2>エアコンの配管</h2>
エアコンの配管の太さは、２分３分（にぶさんぶ）と２分４分（にぶよんぶ）の２種類がある。<br>
これは、メーカー、機種、容量によって配管の太さが決められている。<br><br>

細い管は「液管」で、冷房時には冷媒（液体）は室外機から室内機へ向かう。<br>
太い管は「ガス管」で、冷房時には冷媒（気体）は室内機から室外機へ向かう。<br><br>

なぜ液管は細くて、ガス管は太いのか？その理由は？<br>
冷媒の液体は密度が高いので体積が小さく、気体は密度が低いので体積が大きい。<br>
なのでガス管（気体）の方を太くさせると冷媒の通過や抵抗などを考えると効率が良い。<br>

<h2>エアコンのガス漏れ・ガス抜けの確認方法</h2>

エアコンを冷房にして15分ほど運転させる。<br>
調査する際の冷房運転は「強制冷房運転」にて行う（操作方法は取扱説明書を確認）<br><br>

ガスが一定量減ると、冷房運転時に室外機配管接続部分や熱交換器に霜が発生する。<br>
室外機から出てる細いパイプに、白い霜があるかどうかを確認する。<br>
水分が付着していれば正常、もし霜がついていたらガス漏れの可能性がある。<br>

