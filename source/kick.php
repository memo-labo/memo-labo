<h2>CTの極性をキック試験で確認する考え方</h2>
CT一次側へ小さな直流を瞬間的に流し、二次側に接続した両振れ直流計器の初期振れ方向から極性を確認する。<br><br>

配線例<br>
<img src="images/kick1.jpg" alt="CT極性キック試験の配線例" style="max-width:550px;"><br>

回路図<br>
<img src="images/kick2.png" alt="CTキック試験の回路図" style="max-width:800px;"><br>

例として、<br>
CT一次側K：電池＋側<br>
CT一次側L：電池－側<br>
CT二次側k：両振れ直流計器＋側<br>
CT二次側l：両振れ直流計器－側<br>
のように基準を決める。<br><br>

押しボタンで直流を接続した瞬間と、開放した瞬間では二次側の誘起電圧の向きが反転するため、計器の振れも反対方向になる。<br>

<h2>CTキック試験の注意点</h2>
・対象CTを運転回路から確実に切り離す<br>
・CT二次回路に接続された電子機器・継電器への影響を確認する<br>
・使用する直流電源を長時間つなぎっぱなしにしない<br>
・試験後はCT二次回路の短絡・開放状態を正しく復旧する<br>
・極性表示が不明な場合は一度の振れだけで判断せず、結線図と照合する<br>

CTは通常運転中に二次側を開放すると危険なので、運転回路での切替・離線はCTTなど所定の試験端子を使用する。<br>
⇒<a href="ctt.php">CTT 電流試験端子</a><br>

<h2>VTの極性をキック試験で確認する考え方</h2>
VTも一次側へ瞬間的に直流を加え、二次側の初期振れ方向を見ることで端子の対応を確認できる。<br><br>

計器用変圧器の極性試験例<br>
<img src="images/202206241.svg" style="max-width:600px;" alt="VT極性キック試験の配線例"><br>

端子名の例<br>
VT一次側：U・V<br>
VT二次側：u・v<br><br>

ただし、VT・計器用変成器の内部構成や接続先によって試験方法が異なるため、メーカー資料・試験要領を優先する。<br>

<h2>キック試験で分かること・分からないこと</h2>
<strong>分かること</strong><br>
・一次／二次端子の極性関係<br>
・配線方向の取り違え<br>
・計器までの導通・極性の一部確認<br><br>

<strong>キック試験だけでは分からないこと</strong><br>
・CT比、VT比の精度<br>
・負担VAの適否<br>
・絶縁性能<br>
・CTの励磁特性<br>
・継電器の動作特性<br><br>

極性確認と、変成比・絶縁・継電器試験は別の試験として考える。<br>

