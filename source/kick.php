<h2>キック試験とは？</h2>
キック試験とは、VTと電圧計、CTと電流計の配線方法が、減極性か加極性かを調べる試験。<br>
極性の間違い、配線ミスなどを発見することができる。<br>

<h2>変圧器の極性とは？</h2>
一次・二次の両端子間の起電力の位相関係のこと。<br>
両端子間の起電力が同相であるか，180度の位相差があるかどうかということ。<br>
変圧器を単独で使用するときは問題ないが、並行運転や何台かを組み合わせて結線する場合に必要となる。<br>

<h2>減極性・加極性とは？</h2>
一次、二次両端子間の起電力の位相関係のこと。<br>
U と u が同じ側にあるものを減極性、対角線上にあるものを加極性という。<br>
日本においては、減極性を標準としている。<br>

<h2>減極性とは？</h2>
<img src="images/kick4.png" alt="" style="max-width:500px;"><br>
減極性は、Uとu が同じ側にあるものを言う。<br>
両巻線間に誘起される電圧の方向は、減極性は同一方向となる。<br>
日本においては、減極性を標準としている。<br>

<h2>加極性とは？</h2>
<img src="images/kick3.png" alt="" style="max-width:500px;"><br>
加極性は、Uとu、Vとvが対角線上にある。<br>
両巻線間に誘起される電圧の方向は、加極性の場合、逆方向となる。<br>
加極性は、日本においては使用されていない。<br>


