<h2>CTのキック試験の実施方法</h2>
ボタンを押してDC電圧を印加する。<br>
するとCT２次のkからlにDC電圧が現れる。<br>
CT２次のkとlに接続した両振れ電圧計がプラス側に振れれば正しい配線。<br>
ボタンを離してDC電圧を開放する。<br>
CT２次のkとlに接続した両振れ電圧計がマイナス側に振れれば正しい配線。<br>

