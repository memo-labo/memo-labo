<h2>キック試験とは？</h2>
キック試験は、乾電池などの直流電源を瞬間的に接続・開放し、そのとき二次側計器がどちらへ振れるかを見て、CT・VTなどの極性や配線方向を確認する試験。<br><br>

主に、<br>
・CTのK-Lとk-lの対応<br>
・VTのU-Vとu-vの対応<br>
・計器までの配線極性
を確認するときに使われる。<br><br>

<strong>試験は対象回路を停電・無電圧とし、他回路から切り離した状態で行う。</strong><br>
CT・VTの定格や接続先を確認し、継電器・電子計器へ不用意に直流を印加しない。<br>

<h2>極性とは？</h2>
計器用変成器の極性は、一次側と二次側の対応する端子で電圧・電流の瞬時方向がどの関係になるかを表す。<br><br>

CTではK-Lとk-l、VTではU-Vとu-vなどの極性表示を使い、計器・電力量計・保護継電器の結線を正しく合わせる。<br>
極性を間違えると、電力・力率・方向要素などの測定値や継電器判定が正しくならない場合がある。<br>

<h2>減極性・加極性とは？</h2>
変圧器の極性表示には減極性・加極性という表現がある。<br>
一次・二次の対応端子位置と、直列に接続したときの電圧が差し引かれるか加算されるかで区別する。<br><br>

一般的な国内の計器用変成器では減極性の機器を多く見かけるが、<strong>「日本では加極性は存在しない」と一律には判断せず、銘板・端子記号・メーカー仕様で確認する。</strong><br>

