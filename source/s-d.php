<h2>スターデルタ始動方式（Y-Δ始動方式）</h2>
・三相誘導電動機（モーター）の始動電流を小さくするための始動方法<br>
・始動時と通常運転時で、モーターの巻線の接続方法を切り替える<br>
<br>
始動時：スター（Y）結線<br>
・各巻線にかかる電圧が通常の約58％（1/√3）になる<br>
・その結果、始動電流は直入れ始動（全電圧始動）の約1/3に抑えられる<br>
・電源への負担や電圧降下を小さくできる<br>
<br>
加速後：デルタ（Δ）結線<br>
・モーターがある程度回転速度に達したら、デルタ結線へ切り替える<br>
・定格電圧で通常運転を行う<br>

