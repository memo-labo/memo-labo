<h2>動作の流れ</h2>
① 運転ボタン（ON）を押す<br>
      ↓<br>
② 主電磁接触器（MC）ON<br>
   ＋ スター用MC（Y）ON<br>
   ＋ タイマー作動開始<br>
      ↓<br>
③ モーターはスター（Y）結線で始動<br>
   ・始動電流：約1/3<br>
   ・始動トルク：約1/3<br>
      ↓<br>
④ タイマー設定時間（例：5～10秒）経過<br>
      ↓<br>
⑤ タイマーの接点が切り替わる<br>
      ↓<br>
⑥ スター用MC（Y）OFF<br>
   （数十ms程度の切替時間）<br>
      ↓<br>
⑦ デルタ用MC（Δ）ON<br>
      ↓<br>
⑧ モーターはデルタ（Δ）結線となり<br>
   定格電圧で通常運転<br>


<h2>スターデルタ結線のインターロック</h2>

運転SW ON<br>
│<br>
主MC ON<br>
│<br>
├─ TM ON（時間経過）<br>
│<br>
├─ TM(b)⇒Δ-MC(b)⇒Y-MC<br>
│<br>
└─ TM(a)⇒Y-MC(b)⇒Δ-MC<br><br>

タイマーのa接点・b接点でスター（Y）からデルタ（Δ）への切り替えを行い、さらにY-MCとΔ-MCのb接点による相互インターロックで、両方の接触器が同時にONにならないようにしている。<br>


<h2><a href="inv.php">インバータ</a>との違い</h2>
<li>設備費が安くできる
<li>MCとタイマーが主な構成で故障箇所が少ない
<li>ポンプやファンなど一定速度でしか使わず、回転数を変える必要がない
<li>高調波を発生する機器（インバータ、UPS、サイリスタ整流器など）を一定規模以上設置する場合、高調波流出計算が必要になることがある。<br>
<li>その点、スターデルタ始動はインバータを使用しないため、高調波発生が少なく、高調波流出計算の対象となる高調波発生機器には通常該当しない。

