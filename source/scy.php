<h2>高圧進相コンデンサの容量の決め方・求め方</h2>

進相コンデンサは、負荷設備の種類、稼働率、補正負荷容量に対して選定する。<br>
またインバータ機器を用いた場合には、補正負荷容量から除く。<br>
過度の進み力率とならないような定格設備容量とする。<br><br>

補正負荷容量とは？<br>
電灯や動力負荷に適切な需要率を見込んだ補正係数を乗じた上で合計した負荷容量のこと。<br><br>

インバータ回路の負荷<br>
力率をほぼ１とみなすことができる。<br>
なので力率改善を考慮する補正負荷容量から除いている。<br><br>

従来から広く用いられてきた選定基準「三相変圧器容量の3分の1程度」<br>
これは前提条件が現状とは合っておらず、結果として過剰なSC容量が選定されてしまう。<br>
現在はそのような基準ではコンデンサ容量は選定しない。<br>

SC容量は、負荷の無効電力を想定したうえで選定する。<br>
無効電力を想定してSC容量を選定する際、改善前の力率が不明な場合、負荷力率の平均値表を用いる。<br><br>

