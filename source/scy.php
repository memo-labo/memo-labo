進相コンデンサの容量計算方法<br>
コンデンサ容量（kvar）＝ 負荷容量（kW）× 設置容量係数 kθ（表）<br><br>


負荷が500kWの場合<br>
例：改善前の力率cosθ1=0.75とする。<br>
これをcosθ2=0.95に改善したい場合、kθは表から「55」となる。<br>
すると必要なコンデンサ容量 = 500kW × 0.55 = 275kvarとなる。<br><br>

負荷がkVAで表されている場合<br>
まずはkW = kVA × cosθ1 からkWを求める。<br>
その後は上段と同じように計算する。<br><br>

