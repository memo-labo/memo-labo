<h2>B種接地の機器側の絶縁抵抗が低いケース</h2>
上記のB種機器側の絶縁抵抗測定にて値が低いケース。<br>
変圧器２次側端子と接地端子盤の間には中継点で端子台やエポキシ樹脂がいしが用いられる。<br>
<img src="images/gaishi6.jpg" style="max-width:500px;" alt=""><br>
碍子本体の裏側はキュービクル筐体の金属部分に触れておりA種接地と繋がっている。<br>
この碍子に汚れが溜まると絶縁が悪くなりB種機器側の絶縁を測定した時、値が低く出てしまう。<br><br>

B種接地線の被覆が金属ボルトやアンカーボルトに食い込んでいたり、鉄板床などに挟まれていることで絶縁不良を発生しそこから漏洩電流発生⇒加熱⇒被覆焼損などの事例がある。<br><br>

