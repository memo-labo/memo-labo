<h2>B種接地線を外さずクランプテスターで測定する方法</h2>
停電点検時に変圧器二次側のMCCBを全て開放する。<br>
この状態でB種接地線の漏えい電流を<a href="clamp.php">クランプメーター</a>にて測定する。<br>
これでトランス２次側～MCCB１次側までの間の漏洩電流値を測定できる。<br>
この値が1mA以下であれば100V回路で0.1MΩ以上、200V回路で0.2MΩ以上の絶縁があると判断できる。<br>



