<h2>B種接地抵抗のトランス側の絶縁測定</h2>

S-E間（セカンダリ・アース間）と呼んだりもするらしい。<br>
変圧器２次側～MCCB１次側の絶縁抵抗測定はする？しない？<br>
この部分の絶縁が悪くなって事故が起こった例ってある？<br><br>

低圧のMCCB１次側は地絡保護が効かず、短絡電流も大きくなる区間である。<br>
接地切り離し可能ならば、保安規定で低圧電路の絶縁抵抗測定を謳っているので必須。<br><br>

事故の予想<br>
絶縁低下したケーブルやブスバーがキュービクル筐体に触れて地絡電流⇒焼損事故<br>
（ただし、この区間の事故事例としては少ないらしい）<br><br>

MCCB本体が経年劣化で絶縁不良<br>
この場合、MCCB１次側の対地絶縁抵抗が低下している可能性あり<br>

<h2>B種機器側の測定方法</h2>
すべての低圧MCCBを開放する。<br>
接地端子盤にてB種接地の機器側と接地極側を切り離す。<br>
B種接地の機器側に対して絶縁測定を行う。<br>
するとそこに繋がったすべての変圧器２次側のB種接地線に電圧が印加される。<br>
変圧器２次側内部コイルにてR相T相にも繋がり、電灯、動力、各MCCB１次側まで電圧印加。<br>

<h2>B種機器側から低圧絶縁抵抗測定の裏技</h2>
・低圧MCCBは開放せずに全館停電<br>
・B種接地線を極側と機器側に切り分ける<br>
・B種のトランス側に対してメガーを当てる<br>
・するとB種接地線⇒トランス２次側⇒MCCB⇒低圧負荷まで絶縁測定できる<br>
　（※ただし正確な測定方法はMCCB開放⇒MCCB２次側を１個ずつ測定）<br>
