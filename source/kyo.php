<h2>灯動共用変圧器のデメリット</h2>
<ul>
<li>各巻線の負荷力率が異なるため<a href="drop.php">電圧降下</a>に差異を生じ線間電圧に不平衡が生じる
<li>動力負荷が急激に変動すると、それに引っ張られて照明側の電圧も変動し、ちらつき（フリッカ）が発生する可能性
<li>停電時などに非常用照明を優先的に動かしたい場合でも、共用だと分離して運用するのが困難
<li>突然「機械増やす」とか言い出す可能性がある工場などでは難しい（店舗やビルならあり）
</ul>

<h2>灯動共用変圧器の注意点</h2>
通常だと、変圧器の二次側接地は、単相側中性点に施す。<br />
しかし、単相側中性点を接地した場合には、三相側の接地はできない。<br />
この変圧器を、三相二次側ー端接地を施している設備に使用する場合は、接地回路の見直しが必要。
