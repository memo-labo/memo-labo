<h2>灯動共用変圧器とは？</h2>
１台の変圧器で、動力負荷と電灯負荷に供給ができる変圧器。<br />
変圧器の小型化・省スペース化が可能。<br />
コンビニなどに設置されている「小型キュービクル」に設置可能。<br />

