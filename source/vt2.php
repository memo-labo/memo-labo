<h2>非接地形 操作用電源変圧器とは？</h2>

見た目は通常のVT（計器用変圧器）と似ている。<br>
VTではなくPTと呼ばれることもある。<br><br>

遮断器や開閉器の動作は、瞬時に大容量の電力を必要とする。<br>
操作用電源変圧器は、この電力を確実に供給できるような仕様となっている。<br><br>

開閉動作の際、瞬時に大容量を必要とする。<br>
PTには、一時的な過電流に耐えうる仕様が求められる。<br><br>

２次側の接地<br>
通常、VTの２次側のV相（中相）はD種接地をする。<br>
PTの場合、非接地形という製品があり、この場合には２次側は接地しなくても良いらしい。<br>
現場によっては「PT」２次側のV相（中相）にB種接地がされている場合もある。<br><br>

また、VTやCTの二次側は、B種でなくてD種で良い。<br>
負荷が全てキュービクル等の中で使用されるため（電技解釈の解説）<br>
その理屈を準用してPTも基本はD種で問題ない、らしい。<br>

