<h2>特徴</h2>
電圧降下率を小さく設計し、遮断器投入電源などの瞬時に大容量が必要な場合でも確実に供給できる。<br>
巻線をエポキシ樹脂で真空注型する方法で絶縁しているため、絶縁強度と機械的強度が高い。<br>


<h2>VTの制限負荷とLBS引き外し電源</h2>
