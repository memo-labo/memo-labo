<h2>ブレーカーの内部付属装置</h2>

AL：警報スイッチ<br>
ブレーカのトリップ状態を電気的に表示するスイッチ。<br><br>

AX：補助スイッチ<br>
ブレーカのＯＮ、ＯＦＦ状態を電気的に表示するスイッチ。<br><br>

SHT：電圧引外し装置<br>
ブレーカを遠方から電気的にトリップさせる装置。<br><br>

UVR：不足電圧引外し装置<br>
回路電圧が低下した場合、ブレーカをトリップさせる装置。<br>
ブレーカを遠方からトリップさせる事もできる。<br><br>

TL：テストリード<br>
漏電遮断器のテストボタンでの漏電トリップ動作を遠方から行う装置。<br><br>

Mg：メガテストスイッチ<br>
ハンドルをOFFまたはトリップ状態で漏電遮断器の負荷側の相間メグ測定を可能にする装置。<br>

