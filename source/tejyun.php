<h2>MCCBは動力、電灯、どちらを先に切る？</h2>

停電の際、動力から切る理由<br>
・モーターと制御が別電源の現場で、電灯を先にきったら警報が出た。<br>
・動力のエレベーターやモーターが動いている状態で先に照明が消えると危険。<br>
・電灯から切ると暗闇で動力の機器に巻き込まれたりして危険。<br>

<h2>高圧受電設備の停電操作手順</h2>
低圧MCCBから順番に開放して最後に高圧側の遮断器を開放、と書かれたテキストもある。<br>
低圧MCCBを開放する前に、高圧VCB開放⇒PAS開放という手順という意見もある。<br>
停電・復電操作の手順については、会社によってルールが多少違うらしい。<br>


<h2>停電操作の順番</h2>
「高圧・特別高圧電気取扱特別教育」テキストは、下流から上流に向けての順番で書いてある。<br>

停電の順番<br>
・低圧MCCBを開放<br>
・LBS or VCBを開放<br>
・DS（ジスコン）開放<br>
・主開閉器開放（PAS・UGS・モールドジスコン・ピラージスコン）<br><br>

個人的な感想<br>
・VCBがある場合、それより下流のLBSは開放せずに上流のVCBで一発開放。<br>
・PASやUGSがある場合、ジスコンは開放せず、PASやUGSで開放。<br>
・断路器は遮断性能がないため充電状態だとアークが発生して危険な場合がある。<br>
・また誤認識によりVCBやMCCBが入った状態でDSを開くとアークが発生して危険。<br>
・PASやUGSではなくモールドやピラージスコンであった場合、ジスコンを先に開く。<br><br>

■ジスコンの注意点<br>
DS（ジスコン）は無負荷・無電圧状態にて開閉操作をすること。<br>
LBSはジスコンと違ってアークシュートがあるので充電状態でも開放できる。<br>
しかしジスコンと同じように、無負荷・無電圧状態で開閉した方がより安全。<br>
受電状態で最初にジスコンを開放するとアークにより負傷する危険性。<br>
