<h2>異種金属接触腐食</h2>

発生場所の例<br>
・太陽光パネル枠を繋ぐアース線<br>
・パネル架台と固定金具<br><br>

原理<br>
電解液のような腐食環境下（雨とか？）で異なる種類の金属が接触して電子電導すると片方の金属の腐食が促進される現象。<br>
２種の金属と環境の間で腐食電池が形成されることで生じる。<br><br>

自然電位が低い方の金属で腐食が加速される。<br>
自然電位が高い方の金属では腐食が抑制される。<br><br>

防ぎ方<br>
・ゴムや樹脂などの絶縁材を挟む。<br>
・２種の金属の自然電位の差を小さくする。<br>
・自然電位が高い方の金属の表面積を低い方よりも相対的に小さくする。<br>


<h2>太陽光パネルの不具合</h2>
パネルは直列接続のため、１枚だけが不具合の場合でも、電流の流れが妨げられ、発電量が大幅に低下することがある。<br>

