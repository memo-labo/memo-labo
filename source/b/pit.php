<h2>事前確認</h2>

酸素欠乏危険場所の事前確認<br>
タンク、マンホール、ピット、槽、井戸、たて坑など。<br>
内部が酸素欠乏危険場所に該当するか、作業中に酸素欠乏空気及び、<br>
硫化水素の発生・漏洩・流入等のおそれはないか、事前に確認。<br>

