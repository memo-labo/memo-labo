<h2>水撃（ウォーターハンマー）の実験</h2>
空のビンに、水を８割程度入れる。<br>
ビンのフタを締め、ビンのフタ側を手で強く叩く。<br>
ビンだけが下がり、水はその場に留まるので、ビンの底に隙間ができる。<br>
この隙間は「真空状態」であり、水がその真空状態の位置へ戻ろうとする。<br>
水がビンの底にぶつかる衝撃で、ビンの底が割れる。<br>

