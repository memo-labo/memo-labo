<h2>台所の配管の詰まり・原因</h2>
腐食により穴が開く。<br>
鉄が水に触れることで酸化して錆びる。<br>
排水管内に滞留するガスによる腐食で穴が空く。<br>
排水管を腐食しづらい樹脂系の材質に取替えると漏水の心配がなくなる。<br><br>

食べ物、油、樹脂の詰まり<br>
油、食べ物が堆積して排水管の口径が狭くなる。<br>
樹脂製であっても樹脂の排水管にも油等は付着する。<br>
また錆びコブに堆積物が固着してせき止められる。<br>
錆びコブによる詰まりは、樹脂系の排水管に取替工事で解消できる。<br>
排水管のニオイの原因は、縦パイプに溜まったヘドロに雑菌が繁殖するから。<br>
パイプの汚れを放置すると、次第にパイプ内を塞ぎ、詰まりの原因になることも。<br><br>

解消方法<br>
パイプマン（パイプユニッシュ）を利用する。<br>
キッチン、お風呂、洗面所のぬめり、臭い、詰まりを解消する。<br>
髪の毛、ヘドロ、油汚れを強力に溶かす。<br>
