成分の「水酸化ナトリウム」とは？<br>
化学式：NaOH<br>
強いアルカリ性の化合物。<br>
ナトリウムの水酸化物。<br>
常温常圧では無色無臭。<br>
ナトリウムイオンと水酸化物イオンからなるイオン結晶（白い米粒状の固体）<br>
吸湿性が高い。<br>
タンパク質を激しく分解する。油汚れも落ちる。<br><br>

使い方<br>
目皿などのゴミは取り除く。<br>
透明のキャップを開け、排水口やそのまわりに液をかける。<br>
15〜30分程度、放置する。<br>
十分な水で流す。<br><br>

注意事項<br>
窓を開ける、換気扇を回す等、必ず換気する。<br>
液が目に入らないように注意する。<br>
必ず単独で使用する。他の洗剤や調味料などと混ぜない。<br>
酸性、食酢、アルコール等と混ざると有毒な塩素ガスが発生して危険。<br>
熱湯で流さない。<br>

