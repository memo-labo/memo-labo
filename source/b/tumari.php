<h2>トイレの詰まり</h2>
詰まる原因<br>
大量のトイレットペーパーの流し過ぎ。<br>
尿石、髪の毛、陰毛、糸くず、ほこり、皮脂。<br>
またトイレットペーパーは水に溶け、ティッシュは水に溶けない。<br>
なのでトイレにティッシュを流してはいけない。詰まる原因になる。<br>
それらが絡み合って固着して堆積物となる。<br><br>

特にS字の部分（S字トラップ）で詰まりを起こしやすい。<br>
トイレと同様、台所や洗面所などでも同じ。<br>

