<h2>建築物衛生法の事業登録とは？</h2>

建築物の衛生的環境を確保するためには、建築物の環境衛生上の維持管理を行う事業者が、適切にその業務を遂行するように資質の向上を図ることが重要。<br><br>

昭和５５年の法改正で、建築物の環境衛生上の維持管理を行う事業者は、物的・人的基準を満たしている場合、都道府県知事の登録を受けることができるという制度が設けられた。<br><br>

※なお、事業登録制度は、登録を受けない事業者が建築物の維持管理に関する業務を行うことについては何ら制限を加えるものではない。<br><br>

