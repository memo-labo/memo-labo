<h2>クロスコネクションとは？</h2>
<img src="images/closs1.png" style="max-width:500px;"><br>

水道管（給水装置）とその他の目的の管とが直接連結されていること。<br>
水道水と井戸水等を必要に応じてバルブで切り替えて使用することも同様。<br><br>

「その他の目的の管」とは？<br>
井戸水、工業用水道、農業用水道、温泉、雨水等の貯留水、貯水槽以下の配管など<br>

<h2>クロスコネクションが禁止されている理由</h2>
バルブの故障や操作不良等が発生すると、井戸水などが水道本管へ逆流してしまう。<br>
逆流した水が汚染されていた場合、周辺のご家庭の水道水に流れてしまう。<br>
最悪の場合、水道水の水質が汚染され、広範囲で健康被害が発生してしまう危険性がある。<br>
水道水の安全性を確保する公衆衛生上の観点から、水道法により「禁止」されている。<br>


