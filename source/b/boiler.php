<h2>油焚きボイラとガス焚きボイラの違い</h2>
ガスは油に比べて燃焼効率が高く高効率な運転ができる。<br>
油だきはススが発生し、ススは熱伝導率が小さく、水への伝熱量は大幅低下。<br>
ガスは低温腐食の原因となる硫黄をほとんど含まないのでエコノマイザでの十分な排熱回収が可能。<br>
ガスは管理面においても効率化を図っており燃料貯蔵スペースの有効利用も可能。<br>

