<h2>小型貫流ボイラー</h2>
管によって構成される。<br>
管の一方から水を送り込み、もう一方から蒸気を取り出す。<br>
保有水量が少なく、早く蒸気を発生させることができる。<br>
コンパクトでボイラの設置スペースが少なくて済む。<br>

