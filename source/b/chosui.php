<h2>貯水槽とは？</h2>
貯水槽とは、水を貯める施設・設備のこと。<br>
上水道用水のほか、工業用水、防火用水などの用途がある。<br>
貯水槽は、受水槽、高置水槽、圧力水槽に大別される。<br>

<h2>貯水槽の清掃義務</h2>
10ｍ3を超える受水槽を備えた給水設備は、簡易専用水道として、水道法で１年以内ごとに１回、<br>
水槽の清掃や厚生労働大臣の指定する検査機関等による定期検査などを行うことが義務づけられている。

<h2>受水槽とは？</h2>
ビルやマンション等など多量の水を使用する建物などで、<br>
水道局から水道管を通って送られてきた水を、いったん貯めておく容器のこと。<br>


<h2>直結直圧式（直結式）</h2>
水道本管の圧力によって直接供給するもの。<br>
２階建て以下（地域によっては５階程度）の建築物に用いられる。<br>
管理の手間が少ない。<br>
一般的に戸建住宅ではこの方式が用いられている。<br>

<h2>直結増圧式（直結式）</h2>
水道本管から引き込まれた給水管に指定された増圧ポンプを直結して給水管内の水圧を増圧して供給する。<br>
水槽がなく、管理の手間が少なく、衛生面でもメリットが大きい。<br>
水道管の強度など、インフラが整っていない地域では使用することができない。<br>
近年、受水槽方式に変わり、多くの地域で普及が推進されている。<br>
停電時には増圧給水装置が稼働できなくなり、増圧によって給水している上層階は、断水する。<br>


<h2>高置水槽とは？</h2>
