高置水槽方式は、必要とされる圧力を得るため、給水の箇所よりも高い位置の水槽にポンプで揚水し、重力で給水するものである。
<h2>高置水槽のメリット</h2>
断水や停電時でも、タンクに貯めた水を利用できる。<br>
災害対応のため、配管破損時用の緊急遮断弁の設置が推奨されている。<br>
必要な動力が少なく、省エネルギーである。<br>
ポンプの発停回数が少なく、長寿命である。<br>
圧力変動が小さい。<br>
大便器の洗浄に、フラッシュバルブ（※１）が使用できる。<br>

<h2>高置水槽のデメリット</h2>
定期的な水槽清掃と水質検査が必要。<br>
設置面積が大きく、高所に重量物を設置するための構造上の配慮が必要。<br>

<h2>※１ フラッシュバルブ式とは？</h2>
フラッシュバルブ式のトイレは、学校や駅など不特定多数の人が連続して使用する公共施設で多く使用されている。<br>
水道管に直接取り付けられており、レバーペダルや人感センサーで起動させることで強力な水流で便器を洗浄する。<br>
タンク式のように水を貯めておく必要がなく、時間をおかずに連続して使用することができる。<br>
タンクを設置するスペースが必要ないため、省スペースが可能。

