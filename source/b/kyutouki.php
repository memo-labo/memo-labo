<h2>給湯器の温度を42度以下に設定していると故障する？</h2>

42度以下にしていると、お風呂のサーモ水栓の寿命が半分になるらしい。<br>
しかも、早いと5年で壊れるらしい。<br><br>

<img src="images/kyutouki1.jpg" style="max-width:400px;" alt=""><br><br>

その壊れ方は「水しか出なくなる」という壊れ方。<br><br>

せっかくガス代節約したのに、壊れてしまったら意味がない。<br>
温度の調節は、蛇口の方で調節をする。<br>

<h2>給湯器が故障する理由</h2>
例えば給湯器の設定が39度（42度以下）で考えてみる。<br>
すると、蛇口は40度を出したいのに給湯器の方で39度で、誤差となり、温度を感知する金属が馬鹿になる。<br>
すると、混合比率がおかしくなり、水が多く混じって、お湯がぬるくなってしまう。<br><br>

給湯器で設定した温度が40度でも、蛇口まで行き着くまでに冷める可能性もあるので、バグることがある。<br>


<h2>サーモスタット混合栓とは？</h2>
自動温度調節機能が付いた水栓のこと。<br>
片側にはシャワーかカラン（蛇口）のどちらから湯を出すか切り替えるハンドルがある。<br>
もう片側には湯の温度を設定するハンドルが付いている。<br>
