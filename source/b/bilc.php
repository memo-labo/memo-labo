<h2>ビルクリーニング技能検定とは？</h2>

ビルにおける環境衛生維持管理業務のうち、ビルの所有者から委託を受けて行うビルクリーニング作業について必要な技能を認定する国家資格。<br><br>

昭和57年5月職業能力促進法（旧・職業訓練法）に基づき、技能検定の職種としてビルクリーニングが加えられた。<br><br>

平成28年度からは、単一等級から複数等級（1級・2級・3級・基礎級）試験として実施されている。<br>

<h2>１級ビルクリーニング技能士のメリット</h2>
「建築物衛生法」の事業登録に必要な人的要件の一つの「清掃作業監督者」になるための必要資格。<br>

