排水管をＵ字に曲げることでその部分に水が溜まり蓋の代わりになる。<br>
ここに溜まっている水のことを「封水（ほうすい）」と呼ぶ。<br><br>

<img src="images/trap4.jpg" style="max-width:300px;" alt=""><br>

封水でネズミや害虫の侵入を防ぐことができる。<br>
また下水管からの悪臭を防ぐことができる（防臭弁）<br><br>


