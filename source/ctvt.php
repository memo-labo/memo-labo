<h2>変圧器のブーンという音</h2>

トランスのハム、変圧器のハミング音。<br>
変圧器の鉄心、電流の流れに応じて微妙に伸縮を繰り返す。<br>
1秒間に50Hz（または60Hz）の振動を生み出し「ブーン」という低音が発生。<br>
50Hz地域、60Hz地域で音が異なる。<br>
特に第3高調波である150Hzや180Hzの成分が多く感じられる。<br><br>

電磁力による振動<br>
コイルに流れる電流の変化で鉄心や巻線に微小な振動が発生。<br><br>

取り付け状態や経年劣化<br>
変圧器の固定が不十分だと共振して音が大きくなる場合も。<br><br>

劣化で絶縁材が緩む。<br><br>

変圧器の音は、お客様からの心配やクレームにつながる場合が。<br><br>

JEC-2200<br>
トランスからの騒音について記載。<br>
1m離れた地点で60dB以下となっている。<br>
音が異常に高い場合、鉄心の刺し方に不具合の可能性。<br>

