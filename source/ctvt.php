<h2>デルタスター結線 Δ−Y</h2>
接続記号：Dy11<br />
２次巻線を増やすことなく昇圧可能<br />
6.6kv/415Vの設備用変圧器として使用<br />
第３高調波の環流回路があり、ひずみ波が発生しにくい。<br /><br />

デルタ：線間電圧 = 相電圧<br />
スター：線間電圧 = √3相電圧<br /><br />

二次側（負荷側）がスターで中性線があるので接地が可能<br />
二次側の対地電圧が1/√3 = 415v/1.73=231V < 300V以下<br />
位相：２次巻線は１次巻線より30度進む<br />

<h2>スタースター結線 Y－Y</h2>
<ul>
  <li>スタースター結線は電源側（1次側）と負荷側（2次側）の両方に中性点を持つ。
  <li>どちらでも接地が可能なため、回路の保守と保護が容易。
  <li>第3高調波の環流回路がなく吸収ができないため、誘導起電力に第３高調波が生じ、ひずみ波が発生することがある。
  <li>容量の小さな変圧器に使われることがあるが、通常はあまり使われない。
</ul>

<h2>漏れリアクタンス</h2>
変圧器の一次巻線を貫く磁束は、全部二次巻線を貫くわけではない。<br />
実際には、途中で漏れてしまう磁束がある。<br />
また、二次負荷電流によってできる磁束も、全てが一次巻線を貫くわけではない。<br />
一次巻線と二次巻線の間で漏れる磁束のことを「漏れ磁束」という。<br />
この漏れ磁束は、リアクタンスの電圧降下と同じ影響を与える。<br />
なので等価的に漏れリアクタンスとして表している。

