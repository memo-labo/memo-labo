<h2>油入自冷式</h2>
配電用変圧器で最も一般的に用いられる冷却方式。<br>
タンク内の鉄心と巻線を絶縁油に浸してタンク外側を空気で自然冷却する。<br>
冷却面積を大きくするためにタンク外側に波形フィン、ラジエータ、冷却パイプを付ける。<br>
<img src="images/tr1.jpg" style="max-width:500px;" alt=""><br>

<h2>乾式自冷式</h2>
絶縁油を使わず、鉄心および巻線を直接空気により冷却。<br>
油入変圧器に比べて冷却効果が低い。<br>
耐熱性の良い耐熱クラスB以上の絶縁物が使用。<br>

<h2>絶縁種別</h2>
