<h2>停電・復電で機器トラブルを起こさないために</h2>

<p><strong>停電点検では、停電そのものだけでなく、復電時の突入電流・瞬時的な電圧変動・通信機器の再起動などでトラブルが表面化することがあります。</strong></p>

<p>エアコン、サーバー、通信機器、制御装置、タイマー、冷蔵・冷凍設備など、停電の影響を受ける機器を事前に洗い出しておくことが重要です。</p>

<h2>停電前に利用者へ伝える内容</h2>

<ul>
  <li>停電予定日時と復電予定時間</li>
  <li>停電対象範囲</li>
  <li>PC・サーバー・通信機器などの正常終了</li>
  <li>必要に応じて機器の電源OFF・プラグ抜去を行うこと</li>
  <li>冷蔵・冷凍設備、警備設備、電話設備などへの影響</li>
  <li>復電後に手動再起動・時刻再設定が必要な機器</li>
  <li>非常用電源・UPSで継続する設備の確認</li>
  <li>トラブル発生時の連絡先</li>
</ul>

<h2>「停電のお知らせ」は免責だけを書くものではない</h2>

<p>事前通知に「故障しても一切対応しない」とだけ記載しても、設備管理上の責任関係が自動的に決まるわけではありません。</p>

<p>停電通知の目的は、利用者に必要な準備をしてもらい、作業範囲・影響・連絡方法を共有してトラブルを予防することです。</p>

<p>契約上の責任や補償範囲について明示する必要がある場合は、施設管理者・契約書・保険条件などを確認して文面を決めます。</p>

<h2>停電前に止めておきたい機器</h2>

<p>設備条件によりますが、復電時の一斉起動を避けたい機器は事前に停止しておくとトラブル低減につながります。</p>

<ul>
  <li>大型空調・ヒータ</li>
  <li>モータ・ポンプ</li>
  <li>コンプレッサ</li>
  <li>サーバー・NAS・ネットワーク機器</li>
  <li>生産設備・制御盤</li>
  <li>電子レンジ・IHなど大容量負荷</li>
</ul>

<p>復電後は、設備の優先順位に従って段階的に起動すると、突入電流やデマンドの急上昇を抑えやすくなります。</p>

<h2>復電時に確認すること</h2>

<ul>
  <li>高圧・低圧電圧に異常がないか</li>
  <li>欠相・逆相・異常警報が出ていないか</li>
  <li>変圧器・開閉器から異音・異臭がないか</li>
  <li>主幹MCCB・分岐ブレーカが正常か</li>
  <li>非常用発電機・UPSが商用へ正常復帰したか</li>
  <li>空調・ポンプ・通信設備が正常再起動したか</li>
</ul>

<h2>復電直後に機器が故障した場合</h2>

<p>「停電前は動いていた」という事実だけで、停電作業が直接原因とは限りません。経年劣化した電源部が再起動時に故障するケースや、機器内部のバックアップ電池切れ、設定消失などもあります。</p>

<p>次を記録して原因を切り分けます。</p>

<ul>
  <li>故障した機器と症状</li>
  <li>停電・復電時刻</li>
  <li>復電時の電圧・異常警報</li>
  <li>同系統の他機器に異常があるか</li>
  <li>機器メーカーの診断結果</li>
</ul>

<h2>サージアブソーバについて</h2>

<p>開閉サージ対策としてサージアブソーバ等が使用される場合がありますが、<strong>停電・復電時のあらゆる機器故障を防止できるものではありません。</strong></p>

<p>設置位置・適用電圧・対象負荷を確認し、メーカー指定の用途で使用します。</p>

<p>参考：<a href="https://www.chubuseiki.co.jp/products/general/surgeabsorber/sh-g/" rel="noopener">中部精機 サージアブソーバ</a></p>

<h2>分電盤の主幹MCCBを切る場合</h2>

<p>需要家側で主幹MCCBを開放しておくと、復電時に負荷が一斉に立ち上がることを避けられる場合があります。</p>

<p>一方で、停電点検でどこまで絶縁測定・動作確認を行うかによっては、主幹や分岐回路の状態が点検内容へ影響します。作業者と施設管理者で事前に停電操作範囲を決めておきます。</p>

<h2>停電前チェックリスト</h2>

<ul>
  <li>重要負荷を一覧化した</li>
  <li>UPS・発電機の対象負荷を確認した</li>
  <li>利用者へ停電日時を通知した</li>
  <li>復電後に手動再起動する機器を確認した</li>
  <li>メーカー・保守会社の連絡先を確認した</li>
  <li>復電順序を決めた</li>
</ul>

