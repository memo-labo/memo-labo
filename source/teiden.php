<h2>停電・復電でお客様のエアコンや通信機器が故障！</h2>

停電点検でエアコンや通信機器が故障する例が多発<br>
お客様「停電前は壊れてなかった！弁償しろ！」のクレーム<br><br>

対応策<br>
停電前に「停電のお知らせ」という用紙を配布する。<br><br>

明記する内容<br>
・停電、復電作業で機器が故障する場合がある。<br>
・故障を防ぐために停電前に電子機器をコンセントから抜いてください。<br>
・停電・復電に伴う電子機器の故障やトラブル対応には応じられません。<br>
・停電で冷蔵庫が止まるので中身の処置（処分等）をお願いします。<br>
・停電に伴う機器の設定、トラブル等はメーカーにお願いします。<br><br>

<h2>停電点検は「停電OK」の合図だけで切らない</h2>
管理会社が立会いなどで間に入っている場合は、現場で定められた指揮命令系統と手順に従う。<br><br>
設置者側の社員から「停電OK」の合図が出ても、管理会社側で弱電設備やサーバーなどの停電前処理をしている可能性がある。関係者間の確認が完了する前に停電操作へ進まない。<br><br>
停電立会いに不慣れな担当者が対応する場合にも注意する。各所への連絡や停電前処理が完了しているかを確認する。<br><br>
<strong>停電操作前に確認する例</strong><br>
・他業者の作業有無<br>
・エレベーターや機械式駐車場などで人が取り残される可能性がないか<br>
・関係者への連絡が完了しているか<br>
・サーバー、弱電設備、機械設備などの停電前処理が完了しているか<br>
・誰の最終指示で停電操作を行うか<br><br>
現場ごとの責任分界・指揮命令系統・停電手順を事前に確認する。<br><br>

