<h2>再閉路とは？</h2>
送電線や配電線に落雷などの事故が発生すると、配電側（電力会社側）の保護リレーが動作する。<br>
そして配電側の遮断器が開放され、ある一定の地域が停電状態となる。<br>
そして一定の時間で自動的に遮断器が再投入され、切り離された送電線を再び閉じる。<br>
これを再閉路と呼ぶ<br><br>

■再閉路の時間<br>
高速再閉路方式：１秒程度以内で再閉路<br>
中速再閉路方式：1～15秒程度で再閉路<br>
低速再閉路方式：１分程度で再閉路<br><br>

■最閉路失敗と波及事故<br>
最閉路した時、事故原因が取り除かれておらず、再び地絡または短絡により配電側の保護継電器が動作し遮断器が開放されてしまった場合、波及事故となる。<br>

