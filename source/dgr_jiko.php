<h2>DGRが不必要動作する主な原因</h2>

<p><strong>DGR（地絡方向継電器）が動作したからといって、必ず構内地絡が発生したとは限りません。</strong>雷サージ、残留零相電圧、配線異常、試験条件などでも動作条件に近づくことがあります。</p>

<p>まず「本当に構内事故か」「外部系統の影響か」「試験・配線上の問題か」を切り分けます。</p>

<h2>雷による動作</h2>

<p>雷サージや誘導雷によって、瞬間的な零相電圧・零相電流が発生し、地絡保護リレーが動作することがあります。</p>

<p>この場合も「雷だからリレー故障ではない」と即断せず、次を確認します。</p>

<ul>
  <li>事故時刻と落雷・系統停電の時刻が一致するか</li>
  <li>リレーの動作表示・事故記録</li>
  <li>PAS・ケーブル・キュービクルの絶縁状態</li>
  <li>LA（避雷器）の異常</li>
  <li>ZCT・ZPD・制御ケーブルの異常</li>
</ul>

<h2>残留零相電圧の影響</h2>

<p>高圧配電系統では、各相の対地静電容量や対地電圧が完全に均衡していないため、地絡事故がなくても零相電圧が残ることがあります。</p>

<p>これを残留零相電圧として扱います。配電線構成や単相負荷、SVRなどの影響で値が変化する場合があります。</p>

<p>受電中にDGR・SOGへ試験電圧を加えると、実系統に存在する残留成分と試験器の信号がベクトル的に重なり、単体試験時と異なる結果になることがあります。</p>

<p><strong>受電状態での試験可否・補正方法は、対象機種とメーカー試験要領を確認します。</strong>試験値がずれたからといって、すぐにリレー不良と判定しません。</p>

<h2>DGR試験端子の注意</h2>

<p>Z1・Z2、Y1・Y2、M・Nなどの端子名はメーカー・機種によって役割が異なります。</p>

<p><strong>端子名だけを見て試験器を直接接続しないことが重要です。</strong>試験電圧・試験電流を入力する場所、試験端子、短絡片、試験プラグなどは取扱説明書の試験回路図に従います。</p>

<p>誤った端子へ試験信号を加えると、入力回路・変換器・継電器を損傷するおそれがあります。</p>

<h2>不必要動作を調べる順番</h2>

<ol>
  <li>リレーの動作表示・履歴を確認する</li>
  <li>構内に実地絡・絶縁低下がないか確認する</li>
  <li>ZCT・ZPD・制御線の接続状態を確認する</li>
  <li>残留V0・I0の有無を確認する</li>
  <li>雷・配電線事故など構外要因を確認する</li>
  <li>最後にリレー単体試験で動作値・位相特性を確認する</li>
</ol>

<h2>GR・DGRの不必要動作要因</h2>

<ul>
  <li>ケーブルシース接地・ZCT貫通方法の不適切</li>
  <li>ZCT二次配線の極性・接続異常</li>
  <li>残留零相電圧・零相電流</li>
  <li>構外地絡による系統V0の上昇</li>
  <li>雷サージ・開閉サージ</li>
  <li>継電器整定値の誤り</li>
  <li>制御電源・入力回路の異常</li>
  <li>継電器本体の経年劣化・故障</li>
</ul>

