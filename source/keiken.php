直近の解決策<br>
選任であれば、経済産業省のデータベースにその記録が残っているはず。<br>
介護福祉士試験で、実務経験証明書が得られない場合、「給与明細書、雇用契約書、介護サービスの提供に係る記録書類等により、業務従事期間等を証明することで差し支えない」とする記事あり（⇒<a href="http://sakuragaoka-lo.cocolog-nifty.com/blog/2014/01/post-f926.html">ブログはこちら</a>
