<h2>保安法人</h2>
保安協会より保安法人の方が数が多いし未経験を採用してる会社もたくさん存在する。<br>
また、関東東北産業保安監督部が「電気保安法人」の一覧をPDFにて公開している。<br>
⇒<a href="https://www.safety-kanto.meti.go.jp/denki/jikayou/data/PDF/02-1.pdf">電気保安法人一覧（関東東北産業保安監督部）</a><br>
この一覧から会社名をネットで調べて、求人募集を行っているかどうか調べる。<br><br>

最初から断られることは想定して、ダメ元で連絡をしてみるもの手。<br>
もしかしたら未経験でも面接⇒採用まで行けるかもしれない。<br>
実際にそうやって未経験３種持ちが保安法人に入社できた事例を知っている。<br><br>

保安法人は「外部委託」が専門なので様々な受電設備の点検業務の経験や知識が手に入る。<br>
「電気主任技術者の選任」は１物件でフルの月21件が取得できる。<br>
しかし外部委託の場合、１つ１つが別の契約の受電設備となり、選任に比べると手続きが難しい。<br><br>

保安法人の年収はネット上の口コミ情報によると、<br>
未経験で年収300～400万程度。<br>
実務経験を積み外部委託の資格が得られると500万～700万程度。<br>
未経験を採用できる会社というのは比較的規模が大きく体力がある会社という印象。<br><br>

