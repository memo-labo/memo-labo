<h2>相手方の会社の押印が貰えなかった例</h2>
自社が相手方社長の押印の依頼をするのを躊躇して、頼んで貰えなかった。<br>
自社の上司からの嫌がらせ、個人的な判断で、押印してもらえなかった。<br>
会社自体が廃業し、押印がもらえなかった。<br>
M&A（合併買収）されて、押印がもらえなかった。<br>
３年間の実務経験はあったが、途中で退職したため雇用関係のない第三者となってしまい、相手方の契約書や押印が貰えなかった。<br><br>


途中退職した場合でも押印が貰えた例<br>
退職した会社が保有する受電設備の電気主任技術者であった。<br>
退職後、元会社に連絡をしたら、印鑑をいただけることになった。<br>
