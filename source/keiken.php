<h2>「電験三種合格・未経験」の主な就職先（※個人調べ）</h2>

・保安協会（狭き門）<br>
・保安法人（未経験でも採用してくれる会社あり）<br>
・病院や工場の選任<br>
・普通のビルメン<br>
・再エネ（太陽光発電の設備管理・点検）<br>


<h2>工場勤務（未選任）</h2>
・工場勤務だが受電設備の選任にはなっていない。<br>
・高圧受電設備を選任者と一緒に日々点検をしている。<br>
・この場合、点検をした日が実務経験としてカウントされる。<br><br>
上記条件で電験三種を持っていなかった場合<br>
その場合でも、その期間は1/2として実務経験をカウントしてもらえるらしい。<br>


<h2>ビルメン（他社保有ビルの管理・選任なし）</h2>
他社ビルを管理しているビルメン会社で働いている場合。<br>
これは実務経験の押印は、そのビルオーナーの社長の印鑑が必要。<br>
「お客様であるビルオーナー社長の印鑑をもらうのは難しい」と言われ実務経験が貰えない事例も。<br>
その場合、実務経験を目的にして何年も働いていた分がすべて水の泡になることも。<br>

<h2>ビルメン（他社保有ビル管理・選任）</h2>
「電気主任技術者の選任」で働かせてもらえるケースが一番良い。<br>
それはビルを管理するビルメン会社に限らず、商業施設、病院、工場、浄水場、ゴミ処理施設など様々。<br>
「電気主任技術者 選任 求人」で検索すると、特に都市部では「未経験」でも求人が多い。<br>
しかし地方では、そもそも高圧受電設備自体の数が少ないので未経験の求人が非常に少ない。<br>
地元の県から引っ越しを覚悟すれば、求人数は増えるし会社も見つかると思う。<br>


<h2>選任したのに実務経験の押印が経営者判断でもらえなかった事案</h2>
