<h2>電気管理技術者の下で、個人請負（一人親方）として働く</h2>
非常に珍しいケースだが、親族や知人に電気管理技術者がいた場合、あり得る。<br>
実際の例では、知り合いの電気管理技術者と繋がり、個人請負の形で手伝いをした。<br>
管技のための実務経験を積むにあたり、保安監督部の承認を得る際に、報酬の発生が必要であった。<br>
なので毎月一定の報酬をいただき、知り合いの監理技術者の手伝いをして実務経験を積んだ。<br><br>

このケースが安全で最強。<br>
いろいろな現場に参加できるし、点検業務や試験機材も使用できる。<br>
実務経験の押印も、親族であれば「嫌がらせで押印が貰えない」なんてことも無いだろう。<br>
ただ親族ゆえに仕事のトラブルや不適格と判断されて解雇された場合、関係に大きく亀裂が入る。<br>


<h2>一番最悪なパターン「紹介料がGET出来れば後は何でも良い」</h2>
身近な電気管理技術者に相談しようと思い、やっと出会えたのが高齢管技。<br>
ビルメン会社、選任なし、仕事内容は電気と関係なく空調、水回り、雑務のみ。<br>
給与は手取り20万円以下、宿直ありの長時間拘束。<br>
その長老管技は「職業紹介料として私に○○万円を支払ってください。業界の常識です。」と指示。<br>
管技に言われた通り紹介料を管技に支払い、就職したが、最終的に実務経験の押印貰えず。<br>

