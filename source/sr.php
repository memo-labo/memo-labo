<h2>旧JISと現JIS品の混在使用はNG</h2>
1990年版以前の規格に準ずる製品（旧JIS）と、1998年版以降の規格に準ずる製品（現JIS）を組み合わせると、規格改正前後で機器の定格が異なるため、インピーダンスのマッチングが変化してしまう。<br />
混在使用すると、リアクトルの誘導性リアクタンスが６％にならず、コンデンサが絶縁破壊や過電流による焼損などの問題を生じる可能性がある。<br />
爆発することもあるらしい（絶縁不良⇒短絡⇒加熱⇒絶縁油が熱で膨張⇒容器破裂？）<br><br>

注意ポイント<br>
ニチコンのコンデンサをPCB等で更新する際、選定に注意。（メーカー確認）<br>
リアクトルが同じ6%でも第三高調波の許容値が違うので加熱した例もあるらしい。<br>
キュービクル一括異常⇒ELRと予想⇒SR過熱だった例もあるらしい。<br>


<h2>直列リアクトルが不要な場合</h2>
小規模設備で高圧コンデンサが常時電路につながっている。<br>
自動力率調整装置等でコンデンサの入切を頻繁に行わない。<br>
電源側や負荷側からの高調波流入による影響が少ない。<br>


