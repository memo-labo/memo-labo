<h2>直列リアクトル</h2>
SR = Series Reactor<br>
進相コンデンサに直列に接続される。<br>
JISや高圧受電設備規程で、原則設置となっている。

<h2>直列リアクトルを設置する意味とは？</h2>

■高調波電流の流出抑制<br>
負荷設備による高調波が存在しており、進相コンデンサに直列リアクトルが設置されていない場合、
電源側の誘導性リアクタンスと進相コンデンサとが並列に接続されていることになり、
並列共振作用によって電源側への高調波流出電流が増加する。<br>
進相コンデンサに直列リアクトルを挿入し、合成リアクタンスを誘導性にしている。<br><br>

■高調波による進相コンデンサの焼損を防止<br>
リアクトルが過熱した場合は警報発砲、及びLBSやVMCにて開路する。<br>
※2004年のJIS C4620「ｷｭｰﾋﾞｸﾙ式高圧受電設備」改正により直列リアクトルの取付が義務付けされたらしい。<br><br>

■進相コンデンサ投入時の突入電流の抑制<br>
コンデンサの開閉により、過渡的に発生する過大な電流・電圧などの特異現象による弊害を防止する。<br>
リアクトルを接続すると、コンデンサの端子電圧は上昇するので、それに対応した定格電圧のコンデンサを使用する必要がある。<br>
既設のコンデンサにリアクトルを追加で接続すると危険。<br>


