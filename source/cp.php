<h2>サーキットプロテクタ CP</h2>
回路の過負荷保護、短絡保護ができる。<br>
定格電流：0.1A～30Aなど、小さい電流から大きな電流まで遮断可能な製品が用意されている。<br>
MCCBでは保護できないような低容量の制御回路、電子回路などによく利用されている。<br>
VTとマルチメーターの間の配線にも存在する場合がある。<br>
