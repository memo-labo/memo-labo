<h2>トラッキング現象とは？</h2>

<p><strong>トラッキング現象は、絶縁物の表面に汚れ・塩分・ほこり・水分などが付着し、微小な漏れ電流や放電を繰り返すことで表面が炭化し、導電路が形成される現象です。</strong></p>

<p>進行すると地絡・相間短絡・発煙・発火などにつながるおそれがあります。</p>

