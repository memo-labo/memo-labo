<h2>高圧受電設備で見つかりやすい場所</h2>

<ul>
  <li>VCB・VCS・VMCなどの絶縁部</li>
  <li>高圧母線の支持がいし表面</li>
  <li>LBS・PCなどの樹脂絶縁部</li>
  <li>PAS・開閉器のブッシング部</li>
  <li>端子部周辺の樹脂・モールド部</li>
</ul>

<h2>見た目の特徴</h2>

<p>次のような跡がある場合はトラッキングや沿面放電を疑います。</p>

<ul>
  <li>絶縁物表面に黒い筋・炭化した線がある</li>
  <li>枝分かれしたような放電跡がある</li>
  <li>表面の一部だけ色が変わっている</li>
  <li>煤・焦げ・変色がある</li>
  <li>異臭や放電音を伴う</li>
</ul>

<p>ただし、単なる汚れ・成形跡・擦り傷などと見分けにくい場合もあるため、清掃前後の状態や絶縁測定結果も合わせて判断します。</p>

<h2>なぜ発生する？</h2>

<ol>
  <li>絶縁物表面へほこり・塩分・粉じんなどが付着する</li>
  <li>湿気・結露・水分を吸って表面抵抗が低下する</li>
  <li>漏れ電流が流れ、局部的な発熱・乾燥が起こる</li>
  <li>微小放電・沿面放電を繰り返す</li>
  <li>表面が炭化して導電路（トラック）が形成される</li>
  <li>地絡・短絡へ進展することがある</li>
</ol>

<h2>起こりやすい環境</h2>

<ul>
  <li>高温多湿</li>
  <li>塩害地域</li>
  <li>粉じん・油煙が多い場所</li>
  <li>換気が悪く結露しやすいキュービクル</li>
  <li>清掃されず汚損が蓄積した設備</li>
</ul>

<h2>点検で見つけたら？</h2>

<p><strong>炭化跡を見つけた場合、表面を拭くだけで「復旧」と判断しないことが重要です。</strong></p>

<ul>
  <li>停電・安全措置を行ったうえで汚損状態を確認する</li>
  <li>絶縁物のひび、炭化、侵食、変形を確認する</li>
  <li>絶縁抵抗測定やメーカー指定の点検を行う</li>
  <li>炭化が絶縁物内部まで進行している場合は交換を検討する</li>
  <li>結露・粉じん・塩害など根本原因も改善する</li>
</ul>

<p>炭化した部分は導電性を持つため、清掃だけで完全に絶縁性能が戻るとは限りません。</p>

<h2>予防方法</h2>

<ul>
  <li>定期的に絶縁物表面を清掃する</li>
  <li>キュービクル内の結露・湿気対策を行う</li>
  <li>換気口・フィルタの汚れを確認する</li>
  <li>塩害・粉じん環境では点検周期を見直す</li>
  <li>放電音・異臭・変色を月次点検で確認する</li>
</ul>

<h2>家庭用コンセントでも同じ現象が起こる</h2>

<p>家庭では、コンセントとプラグの間にほこりと湿気がたまり、火花放電を繰り返して炭化・発火する「トラッキング火災」が知られています。</p>

<p>高圧設備と電圧・構造は違いますが、<strong>汚損＋水分＋表面放電＋炭化導電路</strong>という基本的な進行イメージは共通しています。</p>

