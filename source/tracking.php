発生場所<br>
VCBやVCSの筐体表面やプラスチックカバー部分、高圧母線がいし表面、LBSの茶色絶縁部分など。VSCやVMCのプラスチック部分やVCBの筐体部分に枝葉のような後やスーッと１本色違いの部分が見られたらそれはトラッキング跡の可能性が高い。<br><br>

発生原因<br>
絶縁物に汚れ、粉塵、埃が付着し、また高温多湿の環境で長期使用すると、埃や粉塵が湿気を吸って、そこが局部的に高電界にさらされ、さらに微小放電が生じ、これが長期間にわたって絶縁物表面を劣化させて、劣化の際に遊離炭素を生成、いわゆるトラッキング（炭化導電路）が形成されて地絡や相間短絡事故に至る。<br><br>

