MCコネクタの接続を外す前の注意点<br>
パネルから直流電流が流れているかどうか直流クランプにて確認する。<br><br>

製品例<br>
STRAIGHT/ストレート<br>
AC/DCデジタルクランプメーター 15-147<br>
価格：約１万円<br><br>

発電状態でコネクタ抜いたり接触不良があると直流電流のアークで焼損する。<br>
パワコンのモニターで発電状況を確認するだけでは危険。クランプで測定する。<br>
⇒<a href="https://twitter.com/tanaka7kanata/status/1600843643501543425" target="_blank">パネルケーブルMCコネクタの事故例（twitter）</a><br><br>

