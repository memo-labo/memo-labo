<h2>RPR 整定値の考え方</h2>
系統連系保護では、発電機単機容量の10％前後の逆電力を検出する設定例がある。<br><br>

<strong>動作時間整定</strong><br>
・発電機を並列投入した際の電力動揺（パワースイング）でRPRが不要動作しない時間を確保する。<br>
・系統側停電後の逆潮流による充電などを考慮し、1秒以下とする例がある。<br>

<h2>RPR 整定値の計算例</h2>
■初期条件<br>
V = 一次電圧 = 6600V<br>
I = CT一次側定格電流 = 100A<br>
P = 発電機容量 = 500kW<br>
Pr = 検出逆電力<br>
逆電力整定値 = 10%<br><br>

■検出逆電力<br>
Pr = P × 10%<br>
= 500 × 10³ × 0.1<br>
= 50 × 10³W<br><br>

Pr = √3 × V × I × TAP(%)<br>
50 × 10³ = √3 × 6600 × 100 × TAP(%)<br>
TAP(%) = 4.4%<br><br>

したがって、整定値をTAP = 4%とする例。<br><br>

P0 = 動作逆電力<br>
P0 = √3 × V × I × TAP(%) × 0.95<br>
TAPに4%を代入すると、P0 = 43.4 × 10³W<br>
（※動作値を整定値の95%として計算した例）<br><br>

低圧側（RPR継電器入力側）の電力は、<br>
P0 = √3 × 110 × 5 × 0.04 × 0.95<br>
= 36.2W<br><br>

入力電圧を110V一定とした場合、<br>
動作電流 I = 5A × 0.04 × 0.95 = 190mA<br>

<h2>RPR試験方法</h2>
<strong>電流要素</strong><br>
CTTを切り分けたうえで、二次側より試験電流を流す。<br><br>

<strong>電圧要素</strong><br>
VTTを切り分けたうえで、二次側より電圧を印加する。VTへの逆昇圧に注意する。<br><br>

<strong>制御電源</strong><br>
DC24Vの場合、AC110Vからブロック電源を介してDC24Vへ変換されている構成がある。<br>
大元のAC110V電源を確認して供給する。<br><br>

<strong>信号接点</strong><br>
本体接点、警報用パワーリレーのコイル、PCS信号線へつながる端子台など、どこで動作確認するかを事前に確認する。<br>

<h2>RPRの制御電源</h2>
連系用保護継電器は、電源の供給信頼性を確保するため、専用の直流回路で供給する構成がある。<br>
VT二次側のみから制御電源を取ると、系統側の短絡事故や断線時に電源が失われる場合がある。<br>
⇒<a href="ovgr_pw.php">OVGRのバックアップ電源（ブロック電源）</a><br>

<h2>RPRの誤動作</h2>
構内の変圧器を無負荷で投入すると、過渡的な励磁突入電流によって電流位相が大きく遅れ、逆電力として検出する場合がある。<br>
励磁突入電流の影響が想定される場合には、時間整定を設けて誤動作を避ける。<br>
また、CTやVTの極性・配線方向を誤ると、正常時の電力を逆潮流として判定する場合がある。<br>

<h2>RPR 単相用</h2>
単相用RPRは、単相PCSの逆潮流防止のため、単相変圧器の直下に設置する構成がある。<br>
継電器の接点出力を使って、単相PCSの発電を停止させる。<br><br>

<strong>ゲートブロック（GB）</strong><br>
PCSを半導体スイッチで系統から切り離す（解列する）こと。<br><br>

<strong>解列</strong><br>
太陽光PCSの系統連系リレーをオフし、電力系統から切り離された状態。<br>

<h2>休日に起こる逆潮流とPCS停止</h2>
発電電力が構内の消費電力を上回ると、余剰電力が電力会社側へ流れる逆潮流が発生する。<br>
完全自家消費・逆潮流なしの契約では、逆潮流を検出したRPRによってPCSを停止させる構成がある。<br><br>

工場では平日に問題なくても、祝日や連休で負荷が大きく下がると、太陽光発電量が消費電力を上回ることがある。<br>
その場合、RPRが動作してPCSが停止する。<br>
太陽光発電設備容量が工場の最小消費電力に対して大きい場合は、逆潮流が発生しやすい。<br>

<h2>試験・点検時の注意点</h2>
RPR専用のCT・VTを、既設の計測用CT・VTとは別に増設している場合がある。<br>
RPR専用CT・VTを使用している場合、既存のCTT・VTTから試験できないことがある。<br>
その場合は、RPR本体の入力端子へ直接、電流・電圧を入力して試験する。<br>

