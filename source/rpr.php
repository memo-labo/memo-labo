<h2>RPRの誤動作</h2>
構内の変圧器を無負荷で投入すると、過渡的な大きな励磁突入電流により、電流位相が極端に遅れ、逆電力として検出してしまう場合がある。<br />
なので励磁突入電流の影響が想定される場合には、RPRを0.5秒以上の時間整定にして、誤動作を避ける必要がある。<br />
また、正常時でも電流は流れている為、継電器の配線の向きを反対に接続してしまうと、逆潮流と判断される場合がある。<br />

<h2>RPR 単相用</h2>
単相用RPRは、単相PCSの逆潮防止のため、単相トランスの直下に設置する。<br>
継電器の接点出力を使って、単相PCSの発電を停止させる。<br><br>

ゲートブロック GB <br>
PCSを半導体スイッチで系統から切り離す（解列する）こと。<br><br>

解列（かいれつ）<br>
太陽光PCSの系統連系リレーをオフしている状態を指す。<br>
電力会社の、発電・変電・送電・配電設備に接続される系統から、物理的に切り離された状態のこと。<br>


<h2>注意点</h2>
RPR専用のCT、VTを、既設のものとは別に増設する場合がある。<br>
RPR専用CT、VTを利用している場合、既存のCTT、VTTは利用できないことがある。<br>
その際はRPR継電器本体に直接電流・電圧を入力し試験を行う。<br>


<h2>休日に起こる逆潮流とPCS停止</h2>
逆潮流は、発電電力が消費電力を上回り電力会社に流れること。<br>
電力会社との契約上、逆潮流が許可されない場合、逆電力継電器の設置が義務付けられる。<br>
これは、逆潮流発生時、PCSを停止して、発電を強制停止させる機能を持つ。<br>
工場の消費電力に対して太陽光発電システム容量が大きい場合、頻繁にPCSが停止する。<br>
逆潮流を防止するには、工場での最小消費電力に合わせ、パネル設置容量を制限する必要がある。<br><br>

■自家消費型太陽光がついた工場</h2>
自家消費型の太陽光発電設備がある工場は、通常、電力は自社で消費され系統側へ流れることはない。<br>
しかし祝日や連休で自社の電力消費量が減ると、発電した電力が系統へ流れ込む逆潮流が発生。<br>
この逆潮流を防ぐためにRPRを設置。<br>
しかし逆潮流が発生してRPRが動作するとPCSが停止して発電がストップ。<br>

