<h2>逆電力継電器 RPRとは？</h2>
RPR（Reverse Power Relay：逆電力継電器）は、受電端で逆潮流を検出し、発電設備やPCSを系統から解列するための保護継電器。<br>
系統側で短絡事故や断線などが発生し、発電設備が単独運転状態になった場合などに、発電電力が系統側へ流出するのを防ぐために使用する。<br><br>

<h2>逆潮流なし・逆潮流あり</h2>
<strong>逆潮流なし</strong><br>
自家消費型の太陽光発電設備などで、発電した電力を電力会社へ売電せず、構内で消費する運用。<br>
工場などでは、太陽光発電によって電力会社から購入する電力量を減らす。<br>
逆潮流なしで契約する場合には、RPRを設置する構成がある（省略条件あり）。<br><br>

<strong>逆潮流あり</strong><br>
電力会社と買取契約を結び、発電電力を系統側へ流す運用。<br>
この場合は、逆潮流を禁止する目的でのRPRは不要となる。<br><br>

<h2>RPRを省略できる場合</h2>
太陽光発電設備容量が契約電力の5％程度以下の場合や、PCSの単独運転検出機能で単独運転を確実に検出できる場合には、OVGRとRPRを省略できる場合がある。<br>
