<h2>逆電力継電器 RPRとは？</h2>

系統側で短絡事故や断線が発生すると、発電機が単独運転状態になる。<br>
すると発電機の電力が系統側に流出してしまう。<br>
受電端にて逆潮流を検出して発電機を系統から解列する。<br><br>

逆潮流なし<br>
自家消費型の太陽光発電設備のこと。<br>
太陽光で発電した電気を電力会社に売電しない形式。<br>
工場などで自家消費して、電力会社から購入する電気量を減らす。<br>
太陽光発電で「逆潮流なし」で契約する場合には<a href="rpr.php">RPR 逆電力継電器</a>の設置が必要（省略条件あり）<br><br>

逆潮流あり<br>
電力会社と買取契約をしている場合の契約。<br>
この場合、RPRの設置は不要。<br><br>

RPRが省略できる条件<br>
太陽光発電設備容量が契約電力の5％程度以下の場合。<br>
パワコンの単独運転検出機能で単独運転を確実に検出出来る場合、OVGRとRPRの省略が可能。<br>
⇒<a href="https://naigai-e.co.jp/pdf/120710qp_leaflet.pdf">参考資料「内外電機 PDF」</a><br>


