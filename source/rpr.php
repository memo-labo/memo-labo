<h2>RPR 整定値 計算方法</h2>

系統連系保護では発電機単機容量の10％前後の逆電力を検出することが多い。<br><br>

動作時間整定<br>
・発電機を並列投入した際の電力動揺（パワースィング）でRPRが不必要動作しない時間。<br>
・系統側停電後、逆潮流があり充電による危険性を考えた場合は１秒以下が望まれる。<br><br>

■初期条件<br>
V = 一次電圧 = 6600V<br>
I = CT一次側定格電流 = 100A<br>
P  = 発電機容量 = 500kw<br>
Pr = 検出逆電力<br>
逆電力整定値 = 10%<br><br>

■計算式<br>
Pr = P * 10%<br>
= 500 * 10^3 * 0.1<br>
= 50 * 10^3[w]<br><br>

Pr = √3 * V * I * TAP(%)（代入）<br>
50 * 10^ = √3 * 6600 * 100 * TAP(%)<br>
TAP(%) = 4.4(%)<br><br>

したがって、整定値はTAP = 4(%)に設定する。<br><br>

P0 = 動作逆電力<br>
P0 = √3 * V * I * TAP(%) * 0.95<br>
TAPに4%代入すると、P0 = 43.4 * 10^3[w]<br>
（※RPRの動作電力値は、整定値の95%らしい）<br><br>

低圧側（RPR継電器入力側）の電力P0は、<br>
P0 = √3 * V * I * TAP(%) * 0.95<br>
= √3 * 110 * 5 * 0.04 * 0.95<br>
= 36.2[w]<br><br>

RPRの試験を行うとき、入力電圧を110V一定とすると、電流を変化させた場合、<br>
動作電流I = 5[A] * 0.04 * 0.95 = 190mAでRPRが動作する。<br>

<h2>RPR試験方法</h2>

電流要素<br>
CTTを切り分けた上で2次側より試験電流を流す<br><br>

電圧要素<br>
VTTを切り分けた上で2次側より電圧を印加する。ただしVTへの逆昇圧には要注意。<br><br>

制御電源<br>
DC24Vの場合、AC110V⇒ブロック電源⇒DC24Vに変換され供給されている。<br>
なので大元のAV110Vを探しそこから供給する方法が間違いない。<br><br>

信号接点<br>
本体に直接、警報用パワーリレーのコイル部、パワコンの信号線へと繋がる盤の端子台どれか。<br>

<h2>RPRの制御電源</h2>
連系用保護継電器は、電源の供給信頼性を確保するため、専用の直流回路で供給する。<br>
仮にVTの２次側から制御電源をとった場合、系統側の短絡事故や断線した際に、電源が供給されなくなってしまう。<br>
