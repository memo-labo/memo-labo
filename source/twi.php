<h2>単相三線式の配線間違いによる事故</h2>
変圧器の交換工事や新設工事の誤配線による事故。<br>
事故を防ぐ方法としては、受電時、低圧ブレーカーを入れる前の電圧確認。<br>
<img src="images/t3_1.png" style="max-width:250px;" /><br />


ただし負荷手前の中継端子台で配線を間違えた場合、MCCB側では確認できない。<br>
<img src="images/33_1.jpg" style="max-width:400px;"><br>

三相三線の動力回路で配線間違えた場合、逆相になるだけで運が良ければ故障しない。<br>
しかし単相三線の電灯回路の場合、誤配線をすると本来100V回路に200V回路を印加。<br>
ほとんどの電気器具が内部基盤で絶縁破壊を起こして焼損、故障。<br>


