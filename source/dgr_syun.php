<h2>竣工検査で電気主任技術者が「止める」役割</h2>
<p>工事会社によって施工品質にはかなり差があり、現場によっては「本当にこの状態で引き渡すのか」と驚くような施工に出会うことがある。</p>

<p>そういう場面で改めて感じるのが、電気主任技術者の役割。単に試験値を記録して終わるのではなく、設備の安全性や保安上の問題を確認し、不備があれば工事を止めたり、是正を求めたりするところまで含めて仕事だと思う。</p>

<div class="article-point">
<strong>ポイント</strong><br>
「施工会社に気を使って言えない」では、保安を担う立場として不十分。<br>
危険や不適切な施工を見つけたときに、根拠を持ってはっきり指摘し、必要なら是正が終わるまで受電・復電・引渡しを進めない判断が必要になる。
</div>

<p>もちろん、見た目が気に入らないという話ではなく、図面・仕様書・メーカー施工要領・法令・社内基準・現場条件など、確認できる根拠に基づいて判断する。</p>

<p>竣工検査は「試験を実施した」という形式を整えるためのものではなく、実際に安全に使用できる設備になっているかを確認する最後の防波堤でもある。</p>

