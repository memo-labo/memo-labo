<h2>竣工検査で電気主任技術者が「止める」役割</h2>
<p>工事会社によって施工品質にはかなり差があり、現場によっては「本当にこの状態で引き渡すのか」と驚くような施工に出会うことがある。</p>

<p>そういう場面で改めて感じるのが、電気主任技術者の役割。単に試験値を記録して終わるのではなく、設備の安全性や保安上の問題を確認し、不備があれば工事を止めたり、是正を求めたりするところまで含めて仕事だと思う。</p>

<div class="article-point">
<strong>ポイント</strong><br>
「施工会社に気を使って言えない」では、保安を担う立場として不十分。<br>
危険や不適切な施工を見つけたときに、根拠を持ってはっきり指摘し、必要なら是正が終わるまで受電・復電・引渡しを進めない判断が必要になる。
</div>

<h3>実際に見た施工不良の例</h3>
<ul>
  <li><strong>高圧引込ケーブルの立ち上がり部で、ブラケットのスペーサーがずれていた。</strong><br>ケーブル支持部は、ケーブルに無理な力がかかっていないか、所定の位置で確実に保持されているかまで確認する。</li>
  <li><strong>ケーブルシースの引出し線に取り付けた圧着端子のサイズが合っておらず、軽く引っ張っただけで抜けた。</strong><br>端子と導体サイズが合っていないことによる圧着不足で、見た目だけでは見逃す可能性がある。圧着部は使用端子・導体サイズ・圧着状態を確認し、必要に応じて軽く引張って確実に保持されているか確認する。</li>
  <li><strong>主変から二変へ送る回路で、主変側のLBS＋GRに組み合わせたZCTに対し、送りケーブルのシースアースのくぐらせ方が誤っていた。</strong><br>このような誤施工では、送りケーブルや二変側で地絡が発生した際に、シース側を流れる電流がZCT内で打ち消される方向に作用し、送り用GRが本来検出すべき零相電流を正しく検出できず、不動作となるおそれがある。ケーブルシースアースは「接地されていればよい」のではなく、ZCTとの位置関係・通し方・接地点を含めて保護範囲が成立しているか確認する。</li>
  <li><strong>マンションの高圧受電設備で、共用部の電力量計用CT・VTの二次側配線が間違っており、正しく計量できなかった。</strong><br>実際にこの例では、受電後に計量不良が判明し、再び停電して工事をやり直すことになった。竣工時はCT二次側・VT二次側の配線を施工図や結線図と照合し、電力量計まで正しく接続されているか確認する。</li>
</ul>

<div class="article-warning">
<strong>⚠ 注意</strong><br>
高圧ケーブルのシース接地や引出し線の接続不良は、接地機能の不確実化や異常時の保護上の問題につながる可能性がある。竣工時は「端子が付いているからOK」「アースにつながっているからOK」ではなく、サイズ適合・圧着状態・導通・接地経路に加え、ZCTを含む保護回路として正しく構成されているかまで確認する。<br><br>
また、CT・VTを用いた計量回路は、通電できているだけでは正常とは限らない。CT二次側・VT二次側の配線を誤ると正しく計量できないため、受電前に結線図と現物を照合する。
</div>

<p>特に送り回路のGRは、試験器からリレー単体へ電流を入れて動作することだけを確認しても、実際のZCT・ケーブル・シース接地の施工が間違っていれば保護が成立しない。竣工時はリレー単体試験だけでなく、実設備の配線・ZCTの向き・シースアースの経路まで現物で確認することが重要。</p>

<p>同じように、計量回路も電力量計の表示が出ているだけで正常とは限らない。CT二次側・VT二次側から電力量計までの配線を、施工図・結線図と現物で照合しておくことで、受電後の再停電・再工事を防ぎやすくなる。</p>

<p>もちろん、見た目が気に入らないという話ではなく、図面・仕様書・メーカー施工要領・法令・社内基準・現場条件など、確認できる根拠に基づいて判断する。</p>

<p>竣工検査は「試験を実施した」という形式を整えるためのものではなく、実際に安全に使用できる設備になっているかを確認する最後の防波堤でもある。</p>

