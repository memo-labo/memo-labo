<h2>EVTの役割</h2>
配電用変電所など、同一母線から多回線用に引き出される地絡故障を判別するために使用される。<br>
地絡の判別には零相電圧要素で検出し、そのために接地電圧変成器が使われる。<br><br>

EVTの一次側はスター結線で中性点に接地がされている。<br>
EVTの二次側は開放デルタ結線（オープンデルタ結線）となっている。<br>
開放デルタ端には地絡故障時に電圧が発生するので、これを継電器へと取り込む。<br>
ここで検出される電圧というのは、完全地絡の場合、零相電圧の3倍となる。<br>
このEVTで得られた零相電圧V0は、地絡方向継電器DGRや過電圧地絡継電器OVGRにて使用される。<br>


<h2>EVTと漏電継電器を使った低圧非接地回路の地絡保護</h2>
非接地回路は地絡電流を少なく抑えるので化学工場や停電できない工場などで採用される。<br>
一線が完全地絡しても地絡電流はほとんど流れず、漏電継電器で地絡を検出することができない。<br>
漏電継電器の定格感度電流は数100mA～数A程度なので完全地絡時に数A程度の地絡電流が流れる必要がある。<br><br>

なのでEVT方式では非接地回路用絶縁トランスの二次側にEVTとその三次巻線に制限抵抗器(CLR)を接続する。<br>
地絡電流はCLRを１次換算した等価中性点抵抗で制限され、漏電継電器で検出できる地絡電流を流すことができる。<br><br>

配線図<br>
高圧KIPケーブルU、V、W<br>
EVTのU、V、W、O（１次 スター）<br>
EVTのu、v、w、o（２次 スター）<br>
EVTのa、b、c、f（３次 オープンデルタ）<br>
a-f間にはCLR（制限抵抗器）がある<br>
O、o、fは接地され、接地線にはZCTが設置されている<br><br>
