<h2>CLR（制限抵抗器）の役割</h2>
CLRは、EVTを使った接地・地絡検出回路で零相回路の電流を適切な範囲に制限し、回路を安定させるために使用される抵抗器。<br><br>

役割は設備方式によって異なるが、地絡時に継電器が判定に利用できる有効分を確保したり、EVTと対地静電容量による零相回路の共振・不安定現象を抑制したりする目的で組み合わされる。<br>

<h2>EVTと耐圧試験の注意</h2>
EVTを接続したまま主回路へ高い試験電圧を印加すると、EVTの巻線へ通常運転とは異なる電圧が加わり、過励磁や絶縁ストレスにつながる可能性がある。<br><br>

耐圧試験では「EVTだから必ずこの方法」と決めつけず、単線結線図・試験範囲・EVTメーカーの試験要領を確認し、必要に応じて切り離す。<br><br>

