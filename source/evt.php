<h2>CLR（制限抵抗器）とは？</h2>

非接地方式の電路で地絡方向継電器を動作させるには零相電圧が必要。<br>
この場合、接地変圧器 (EVT or GPT) を設置し、一時側中性点を接地し、二次側オープンデルタ部に制限（限流）抵抗CLRを挿入。<br>
これで、あたかも一時側中性点を高抵抗で接地したような「抵抗接地式配電線」とみなすことができる。<br>
CLRによりEVTリアクタンスと線路の対地静電容量による中性点不安定現象を抑制する。<br>
また地絡発生時にリレーにある程度の有効分電流を流し、リレー動作を容易にする。<br>
