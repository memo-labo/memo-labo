<h2>EVTで3V0を検出する考え方</h2>
零相電圧は、<br>
V0 = (Va + Vb + Vc) / 3<br>
で表される。<br><br>

したがって、三相対地電圧のベクトル和は、<br>
Va + Vb + Vc = 3V0<br>
となる。<br><br>

EVTの開放デルタ回路では、この零相成分に対応する電圧を取り出して継電器へ入力する。<br>
実際の端子電圧はEVTの変成比によって低い値へ変換されるので、「一次側の3V0そのもの」と「継電器へ入力される電圧」を混同しない。<br>

<h2>EVTの設置位置</h2>
EVTは系統の零相回路・接地方式に関係するため、どこへ接続するかは保護方式と設備構成で決まる。<br><br>

同一母線へ複数の接地用変成器や接地回路を接続すると、零相インピーダンスや地絡電流の分担が変わることがある。<br>
追加・更新するときは既設EVT、ZPD、発電機、ZCT、DGR・OVGRとの関係を単線結線図で確認する。<br><br>

高圧非常用発電機にEVTを使用する場合も、商用系統と発電機系統の切替方式・接地方式に応じて接続状態を設計する。<br>

<h2>EVTとDGR・OVGR</h2>
EVTから得た零相電圧は、地絡保護継電器の入力として利用される。<br><br>

・<a href="dgr.php">DGR</a>：V0とI0の位相関係を利用して地絡方向を判定<br>
・<a href="ovgr.php">OVGR</a>：零相電圧の大きさを監視<br><br>

DGRで方向判定を行う場合は、EVT側の極性・ZCT極性・位相設定を合わせて確認する。<br>

<h2>低圧非接地回路でEVTを使用する構成</h2>
非接地方式では、一線地絡時の地絡電流が小さく、通常の過電流保護だけでは地絡を検出しにくい。<br>
設備によってはEVTとCLR（制限抵抗器）、ZCT、地絡継電器を組み合わせて地絡を検出する方式が使われる。<br><br>

代表的な構成では、EVTの開放デルタ巻線側にCLRを接続し、系統の零相回路へ所定の抵抗分を与える。<br>
具体的な抵抗値・端子接続・継電器整定はEVTメーカーの資料と設備設計によって決める。<br><br>

