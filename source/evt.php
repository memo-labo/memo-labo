EVTは英語でEarthing Voltage Transformer<br>
非接地系の零相電圧を計測する。<br>
主に配電用変電所の母線に接続する変圧器。<br>
以前はGPTと呼ばれていた。<br>
GPTは英語でGrounding Potential Transformer<br>

<h2>EVTの取り付け位置</h2>
取扱説明書によれば、ジスコンの１次側（電源側）<br>
EVTを複数台設置すると、地絡電流が分流して検出に支障が出てしまう。<br>
よって高圧需要家ではエポキシ樹脂コンデンサタイプのZPDが設置される。<br>
高圧の需要家でEVTを設置するのは、高圧の非常用発電機がある場合。<br>
高圧発電機用にEVTを設置する場合、商用受電時は商用回路に接続してはならない。<br>
高圧発電機による送電時のみEVTが回路に接続されるようにする。<br>

<h2>EVTの外観</h2>
EVTは１つの変圧器が３つセットに連なったもの。<br>
変圧器の高圧側端子はUとV（Vは接地側）の１つ。<br>
変圧器の低圧側端子はu-v、a-b、２つ。<br>
高圧KIPケーブルからのU、V、Wは、EVTの高圧側端子Uに接続される。<br>


