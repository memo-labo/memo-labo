<h2>接地変圧器EVTの特徴</h2>
高価である。<br>
抵抗方式に比べ、地絡継続中にだけ電力を消費するので、発熱が少ない。<br>
コンデンサ方式に比べ、経年変化が少なく、高調波電流が流れにくい。<br>
対地静電容量と地絡電流の周波数によっては共振を起こすことがある。<br>
直流電流が重畳すると地絡電流が多く流れることがある。<br>


<h2>EVTの注意</h2>
耐圧試験時はEVTを除外する<br><br>

一次側を回路につないだまま耐圧<br>
⇒鉄心の磁束が過励磁で焼損<br><br>

二次側だけ外して浮かせた状態で耐圧<br>
⇒一次と二次の巻線間絶縁の設計を超える異常な電圧ストレスが加わる可能性<br><br>

<img src="images/20260727-1.jpg"><br><br>

高圧非常用発電機⇒EVT⇒VCB(52G)⇒という構成の場合、52G開放状態であればEVTに試験電圧はかからない。<br><br>

EVTまたはGTの設置位置<br>
ZCTの負荷側にEVTまたはGTが設置してあると不要動作することがある。<br>
EVTの設置位置はZCTの上流側に設置する。<br>

