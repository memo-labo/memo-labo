<h2>EVTの構造と結線</h2>
EVTは三相分の変圧器要素を組み合わせて構成される。<br>
機種によって端子構成は異なるが、一次側をスター結線として中性点を接地し、零相電圧を取り出すための開放デルタ巻線を持つ構成が代表的。<br><br>

地絡がない平衡状態では開放デルタ端の電圧は小さい。<br>
一線地絡などで三相対地電圧が不平衡になると零相電圧が発生し、開放デルタ端に零相分に対応する電圧が現れる。<br>

