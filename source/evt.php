<h2>EVT（接地形計器用変圧器）とは？</h2>
EVT（Earthing Voltage Transformer）は、非接地系統などで零相電圧を取り出し、地絡保護・監視に利用する接地形計器用変圧器。<br>
旧称としてGPT（Grounding Potential Transformer）が使われることもある。<br><br>

主な役割は、地絡時に発生する零相電圧を継電器で扱える電圧へ変成すること。<br>
DGR（地絡方向継電器）やOVGR（地絡過電圧継電器）などの零相電圧要素に利用される。<br><br>

