<h2>位相の式</h2>
位相表示は「余弦波形」を基準とする。<br><br>

y(t) = A cos(ωt + φ) <br><br>

A:振幅（Amplitude）<br>
φ:位相（ファイ）
ω:角周波数（オメガ）<br>
(ωt + φ)：位相角<br><br>

φ = 0 を基準として、φ が正であれば位相進み、負であれば位相遅れとなる。<br>
t = 0 における位相 φ を「初期位相」と呼ぶ。<br>
このときの φ を「位相」と呼ぶ。<br><br>

位相差とは？<br>
２つの波形の時間的なズレの差のこと。<br>
位相差は角度で表わされる。<br>
位相には、波形のズレ方によって同位相、遅れ位相、進み位相がある。<br><br>

遅れ位相・進み位相とは？<br>
AとBの２つの波があり、BがAより右にずれている場合「BはAに対して遅れ位相」となる。<br>
逆にBを基準とした時、AはBより左にずれているので「AはBに対して進み位相」となる。<br>

<h2>力率と位相</h2>
力率は、電圧と電流の位相差 θ の cos（余弦）をとったもの。<br>
電圧ベクトルと電流ベクトルのなす角が0°の場合、位相差は0°、力率は１となる。<br>
抵抗だけの回路の場合、電圧ベクトル V→ と 電流ベクトル I→ の向きにズレがないので力率は１。<br><br>

力率を電力で表わすと次の式になる。<br><br>

力率 = 有効電力 ÷ 皮相電力<br>
皮相電力 = √（有効電力^2 + 無効電力^2）<br><br>

力率：cosθ<br>
有効電力：P<br>
無効電力：Q<br>
皮相電力：S<br><br>

cosθ = P ÷ S = P ÷ √（P^2 + Q^2）<br><br>

力率 = 皮相電力と有効電力のなす角 θ の cos（余弦）をとったもの<br>

