対称三相交流とは？<br>
・三相の起電力の大きさと周波数が等しい。<br>
・電流または電圧の位相を互いにずらした３系統の単相交流を組み合わせた交流。<br>
・三相それぞれの位相が（2π/3）[rad] = 120度ずつずれている。<br><br>

電圧と電流の波形がずれ、位相差が生じた際、その位相差の余弦を力率という。<br>
