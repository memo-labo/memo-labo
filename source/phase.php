<h2>位相とは？</h2>
位相は英語でphase（フェーズ）<br><br>
三相３線式を「3P3W」と表現する理由は以下<br>
P：phase（位相）<br>
W：電線数（W=Wire）<br><br>

位相とは、繰り返される現象の一周期のうち、ある特定の局面のこと。<br>
周期的に変動する波の位置情報を意味する。<br>
通常は角度（単位は「度」または「ラジアン」）で表される。<br><br>

