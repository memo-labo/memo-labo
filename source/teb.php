端子a点、端子b点の間にある抵抗R[Ω]に流れる電流I[A]を求めたいとする。<br><br>

抵抗Rを取り外した状態での端子ab間に現れる電圧（開放電圧）をV0[V]とする。<br>
抵抗Rを取り外した状態での端子ab間の合成抵抗をR0[Ω]とする。<br><br>

※端子a-b間の合成抵抗R0を求めるときは、電圧源は短絡、電流源は開放する。<br><br>

端子a-bより左側の回路は、起電力V0、内部抵抗R0の電圧源に置き換え可能（等価変換）<br>

