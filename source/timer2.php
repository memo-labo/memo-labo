<h2>トラブル・故障</h2>

■停電点検時のトラブル<br><br>
停電点検開始<br>
↓<br>
復電<br>
↓<br>
後日電話でクレーム<br>
↓<br>
「いつも夕方５時でつくはずの外灯がつかないんだけど！」<br>
↓<br>
停電点検中、タイムスイッチが動作せず、数時間遅れたため<br>
↓<br>
タイマー調整して復旧<br><br>

■経年劣化<br>
・停電保証用の電池が経年劣化により故障。<br>
・電池だけの交換が出来ず本体ごと交換するしかない。<br>
・電池がダメになるより先に機械接点の方が壊れやすいらしい。<br>

