<h2>低圧・高圧・特別高圧の違い</h2>

<p>電気設備の技術基準では、電圧区分は<strong>電圧そのもの</strong>で決まります。契約電力や設備容量で低圧・高圧・特別高圧が決まるわけではありません。</p>

