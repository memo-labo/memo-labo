<h2>低圧</h2>

<p>一般住宅や小規模店舗などで使われる100V・200Vは低圧です。一般送配電事業者の柱上変圧器などで高圧から100V・200Vへ変圧して供給されるのが一般的です。</p>

<p>「50kW未満なら低圧受電」と説明されることがありますが、これは電力会社の供給条件・契約区分で使われる目安であり、法令上の電圧区分そのものとは別です。</p>

<h2>高圧</h2>

<p>6.6kV（6,600V）受電は高圧に該当します。工場、ビル、商業施設、マンションの一括受電設備などで多く使われます。</p>

<p>高圧受電では需要家側に変圧器、開閉器、保護継電器などの受変電設備を設けます。設備形態としてキュービクルが多く使われますが、<strong>「高圧＝必ずキュービクル」ではありません。</strong></p>

<h2>特別高圧</h2>

<p>7,000Vを超える電圧は特別高圧です。大規模工場、鉄道、データセンター、大規模ビルなどで22kV・33kV・66kV等を受電する例があります。</p>

<p>特別高圧設備では電圧が高いため、接近限界、保護具、活線・停電作業の方法などを設備電圧と作業条件に応じて厳格に管理します。</p>

<p><strong>「電線から2m以内なら近づくだけで感電する」といった一律の説明はできません。</strong>必要な離隔距離は電圧、設備構造、作業内容などで異なります。</p>

<h2>6.6kVがよく使われる理由</h2>

<p>日本の高圧配電では、標準的な公称電圧として6.6kVが広く使われています。</p>

<p>「高圧の上限が7kVだから6.6kVになった」「電圧降下10%を見込んで6,000Vを6,600Vにした」と単純に説明されることがありますが、6.6kVの成立経緯をその理由だけで断定するのは適切ではありません。</p>

<p>現在の実務では、<strong>6.6kVは国内の標準的な高圧配電電圧</strong>として覚えておくのが分かりやすいです。</p>

