<h2>等価回路からIgを計算する</h2>
V、Z、R(B)で等価回路をつくり、Igを求める。<br><br>
<img src="images/b/6.png" style="max-width:500px;"><br />

Ig = (6600/√3) ÷ {(1/j3ωc) + R(B)}<br />
(1/j3ωc) = 一般的に数千Ω<br />
R(B) = 一般的に数十Ω<br />
Ig ≒ 6600√3ωc[A] = 数アンペア<br />
Vg = Ig × R(B)<br>

