<h2>B種接地抵抗とは？</h2>

B種接地が必要な理由<br>
変圧器の低圧側と高圧側の電路が混触したとき、低圧側電路の電圧を上昇させないため。<br><br>

もしB種接地がないとどうなる？<br>
変圧器の故障で低圧と高圧が混触した時、低圧回路に高圧の電圧が印加される。<br>
低圧回路の機器が過電圧により絶縁破壊、焼損による機器故障やアークや感電による人身事故。<br>
その場合、２次側の対地電圧は6600V / √3 = 3810V。<br><br>

２次側にB種接地をした場合</h2>
高圧と低圧が混触した場合、２次側の対地電圧を、数十ボルトに抑えることができる。<br />

<h2>B種接地抵抗の値は何で決まる？</h2>

E(B) = 150/Ig [Ω]（技術基準の解釈）<br><br>

Igとは「１線地絡電流」のこと。<br>
これは変圧器の高圧と低圧が混触したとき、B種接地線に流れる地絡電流のこと。<br>
これは、電力会社の配電線が持っている対地静電容量から算出するもの。<br>
この値は公開されておらず、電力会社に問い合わせるしかない。<br><br>


Ｂ種接地抵抗値は、低ければ良いというものではない。<br>
その理由は「１線地絡電流値の大きさ」に関係がある。<br><br>

B種接地抵抗が小さい場合<br>
機器のD種接地、C種接地が施された機器が漏電した場合、これらの接地抵抗にはＢ種接地工事の抵抗と直列に接続されて、対地電圧がかかる状態となり、機器にかかるその分圧は、Ｂ種接地抵抗が小さいほど大きくなる。<br><br>

B種接地抵抗が大きい場合<br>
高圧と低圧が混触した時、低圧側での感電の危険性が上がる。<br><br>

キュービクルの設備容量が変化するとB種接地抵抗は変化する？<br>
B種接地抵抗はIg（1線地絡電流）から算出され、それは系統側の静電容量で決まるので変化しないらしい。<br>

<h2>B種接地が共用接地か単独接地か</h2>
B種接地が共用だと漏電発生した際の対地電圧変動が他バンクにも影響する。<br>
信頼性が求められるような場合は単独接地にすることが多いらしい。<br>


