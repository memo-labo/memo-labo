<h2>母線連絡遮断器</h2>
大規模の設備では、停電範囲を限定したい場合、母線連絡遮断器で停電範囲を限定させて点検を行う。<br />
母線連絡遮断器１台ではVCB本体の点検に全停電が必要なので、VCB２台を直列で設ける必要がある。<br />
保全上有利な方式だが、VCBの数が増えるのでコストアップになる（VCBは高価）<br />
母線連絡遮断器VCBの表記は「52B」と表記される。<br /><br />

また、小規模の場合には商用電源利用の変圧器と非常電源利用の変圧器の系統を分離することができる。<br />
※商用電源利用の際には通常負荷と非常負荷、非常電源利用の際には非常負荷のみ給電。<br />

