<h2>VCBの清掃点検</h2>
エチルアルコールと水道水を１：１で混ぜたものをウエスに染み込ませて拭く。<br>
VCB絶縁フレーム表面は、相間、極間の電路を断つ様に平面を直線的に拭き取る。<br>
絶縁フレームの凹部など細かい部分は割りばしにウエスを巻き付けアルコール水溶液を滲み込ませて清掃する。<br>
真空バルブ外面（絶縁筒）や絶縁ロッドもウエスで拭き取る。<br><br>

<h2>VCBのトラッキング</h2>
VCBの絶縁部に炭化導電路（トラッキング）が見られた場合、取り替え、更新が推奨される。<br>
長い期間清掃されず、塵埃・結露により部分放電を繰返し、トラッキングが伸長、短絡事故に至る場合も。<br>
VCB絶縁部にトラッキング発見、清掃終了後、絶縁抵抗測定値が50MΩ未満だった場合、VCBの交換が必要。<br>



<h2>VCBが投入できない不具合</h2>
・ばね蓄勢の途中でモーターが止まってしまい、投入することができなくなった。<br />
・手動でVCBを投入すると、投入したような音はするが、表示が入状態にならない。<br /><br />

オイルミストによるＶＣＢ蓄勢モータの焼損<br />
⇒製造ラインと電気室を仕切るなどの対策。<br /><br />

グリース固化による操作機構の固渋<br />
・トリップコイル焼損<br />
・投入がされない<br />
・遮断しても自動的に投入される<br />


