APFC = automatic power factor controller<br>
電力用コンデンサの投入を自動的に制御して力率の調整を行う。<br>
力率割引による電気料金の低減、電力損失の軽減、進みすぎによる電圧上昇防止。<br>
高圧受変電設備の系統に設置して力率を監視、コンデンサを自動投入・切り離しを行う。<br><br>

力率料金制度<br>
力率は85％を基準とし、85%より1%上回ると電力の基本料金が1%割引される。<br>
逆に85%より1%下回ると電力の基本料金が1%割増される。<br>
力率が100%より進みすぎても電力料金の割引は100%と同じらしい。<br><br>



進相コンデンサーは、交流回路において発生する「無効電流」の割合を減らし、力率の改善ができる。<br>
モーターなど熱源となることを目的としない負荷の場合、コイルに電気が流れ無効電流が発生する。<br>
進相コンデンサは、無効電流と逆方向の電流を流すことで、無駄な電流を省く役割がある。<br><br>

従来では早朝にコンデンサを手動投入、業務終了時に開放が手作業にて行われていた。<br>
ただこの方法では、操作者の技量により安全性・信頼性が大きく変動する。<br>
この作業を自動化し、安全性と効率を高めるため、APFCを設置する。<br>
VCSやVMC（高圧接触器MC）をSCの１次側に設置、信号によって操作、MCの入切を行う。<br>

