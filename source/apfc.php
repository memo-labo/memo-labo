接点信号<br>
端子端子はC1～C6の６個とCOM1×4個 <br>
接点は無電圧1a接点を各バンク毎に出力する常時励磁式。<br>
コンデンサ制御信号として投入時連続ON、遮断時連続OFFする。<br>
出力信号C1～C6の片側は共通端子（COM1）<br>
VMCやVCSとAPFCの信号線を接続する際は必ず補助リレーを使用する（C1X～C6X）<br>

<h2>自動力率調整器のメリット</h2>
<ul>
    <li>力率料金制度（力率85％基準）により、電気料金が低減できる。
    <li>力率改善で負荷電流が減少し変圧器や配電線による電力損失が軽減され省エネに。
    <li>夜間の軽負荷時に力率の進みすぎによる電圧上昇、機器寿命低下への影響を防止する。
    <li>自動でコンデンサ投入、遮断が可能となり、人手を省き、かつ正確な力率調整を実行できる。
</ul>

<h2>VCSの頻繁な開閉防止措置</h2>
コンデンサの一次側に設置されている電磁接触器を開閉し、力率を調整する。<br>
力率の変動に対して頻繁なオンオフが発生しないように、タイマーによる制限を設ける。<br>


<h2>自動力率調整器のデメリット・事故事例</h2>
接点不良？APFC故障？APFC内部接点が投入-開放を短時間で高頻度に繰り返した。<br>
その結果、VMCが開放、投入を繰り返し、リアクトルとコンデンサに負担を与えた。<br>
APFCの故障内容により、VMC、リアクトル、コンデンサにダメージを与える可能性。<br>



