<h2>絶縁油劣化試験</h2>

絶縁油が劣化する原因<br />
・油と接触する空気が油中に溶け込んで、空気に含まれる酸素による酸化が起こる。<br />
・この酸化反応は、変圧器の運転による温度上昇によって促進される。<br /><br />

絶縁油試験方法<br />
・絶縁破壊電圧試験<br />
・全酸価試験<br /><br />

絶縁油不良の場合の対応方法<br />
・ろ過<br />
・浄油<br />
・取替<br /><br />

劣化の色の変化<br />
無色透明⇒薄い茶色⇒黒茶

