<h2>スコットトランスとは？</h2>
スコットトランスは、三相三線210Vなどの三相電源から、位相が90度異なる2組の単相回路を取り出す変圧器。<br>
ビル・工場などで、商用受電時だけでなく非常用発電機運転時にも、単相負荷へ給電する用途で使われる。<br><br>

