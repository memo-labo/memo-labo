<h2>スコット結線の特徴</h2>
二次側には、位相が90度異なる2つの単相回路がある。<br>
2つの単相負荷が等しければ、一次側は平衡した三相電流となる。<br>
三相電源の1相だけから単相負荷を取る場合に比べて、三相側の不平衡を抑えやすい。<br>

<h2>二次側の結線</h2>
・単二専用：1Φ2W 105V × 2（u-ou、ov-v）<br>
・単三専用：1Φ3W 105-105-210V × 2（u1-u2-ou、ov-v2-v1）<br>
・単二単三共用：1Φ3W 105-105-210V × 2（u1-u2-ou1-ou2、ov2-ov1-v2-v1）<br>

<h2>一次側の構成</h2>
<strong>T変圧器・T座トランス</strong><br>
単相変圧器2台のうち1台から、一次巻線中央50%位置にタップを出す。<br><br>

<strong>M変圧器・M座トランス</strong><br>
もう1台は、一次巻線の√3/2＝86.6%位置にタップを出す。<br>

<h2>容量の考え方</h2>
標準容量として10、20、30、50、75kVAなどがある。<br>
20～30kVA程度の設備を見ることが多い。<br><br>

50kVAのスコット変圧器であれば、二次側の2回路または4分割した回路を合計して、全体で50kVAの範囲で使用する。<br>

<h2>負荷不平衡</h2>
スコット結線の二次側2回路には、それぞれ独立した単相負荷を接続する。<br>
二次側2回路を並列接続して1回路にまとめることはできない。<br><br>

一次側の三相電流を平衡させるには、二次側の単相負荷AとBをできるだけ同程度にする。<br>
AとBの負荷が異なると、一次側R-S-Tの三相電流も不平衡になる。<br>
不平衡が大きいと、電流不平衡、温度上昇、効率低下、振動・騒音の増加などにつながる。<br>

<h2>スコットトランスの接地</h2>
スコットトランスの二次側接地は、一次側電圧・二次側回路の用途・保護方式によって確認する。<br><br>

一次側が高圧または特別高圧の変圧器ではB種接地が関係するが、一次側が低圧のスコットトランスでは、二次側中性線の接地を一律にB種接地として扱うものではない。<br>
二次側電路を接地する場合は、機器仕様や回路方式に従って中性点を接地する。<br><br>

医療用IT系統や特殊な絶縁系統などでは、意図的に非接地とする構成もある。<br>
その場合は、1線地絡時の継続運転や絶縁監視を含めた専用設計となる。<br>

<h2>接地に関する不具合例</h2>
中性線の接地が取れていなかった設備で、二次側単相3線100/200V回路の対中性線電圧が、R相120V・T相80Vのように不平衡となった例。<br>
中性点の接地を確認・復旧したところ、電圧不平衡が解消した。<br>

<h2>現場で確認するポイント</h2>
・M座、T座の二次負荷が大きく偏っていないか<br>
・二次側2回路を誤って並列接続していないか<br>
・中性点接地の有無と回路方式が設計どおりか<br>
・非常用発電機運転時も同じ負荷構成になるか<br>
・各回路の合計負荷が変圧器容量を超えていないか<br>

