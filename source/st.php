三相三線210Vの動力回路を1Φ2W、1Φ3W等の電灯回路に変換できる。<br>
スコットトランスの二次電圧は、位相が９０度異なった、２つの単相回路となる。<br />
商用受電時でも、停電時の非常用発電機からの受電でも、両方とも1Φ3Wの電灯回路に給電可能。<br><br>

２つの単相負荷が等しければ、一次側は平衡三相電流となる。<br>
電源側の三相発電機に悪影響を与えず、ビル・工場などの非常用電源として使用することができる。<br><br>

２次側結線<br>
・単二専用：1Φ2w 105V ✕ 2（u-ou,ov-v）<br>
・単三専用：1Φ3w 105-105-210V ✕ 2（u1-u2-ou,ov-v2-v1）<br>
・単二単三共用：1Φ3w 105-105-210V ✕ 2（u1-u2-ou1-ou2,ov2-ov1-v2-v1）<br><br>

