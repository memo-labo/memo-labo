<h2>接地極を等電位化した場合</h2>
<img src="images/bonding2.png" style="max-width:500px;"><br />

建物の構造体接地極等を電気的に接続し、水道管や窓枠金属など、系統外導電性部分も含め、<br />
人が触れる可能性がある全ての導電性部分を、共用の接地極に接続して等電位化する。<br /><br />

すると、金属部分から伝わってきたサージはすべて大地に放流される。<br />
接地と同電位（等電位）となり、火花放電や絶縁破壊の発生はなくなる。<br /><br />

また、電源線や通信線は、接地極や金属導体に直接接続できないので、<a href="spd.php">SPD（避雷器）</a>を用いて接続する。<br />

