<h2>等電位ボンディングとは？</h2>

雷サージとは？<br />
落雷で電源線、電話線、水道管、ガス管等に発生する、大きな過電圧のこと。<br />
その大きさは、数kVから十数kVに達する。<br /><br />

これらの電圧が電線や管を伝わり室内に侵入すると、火花放電による火事を発生させる。<br />
また、電気機器を絶縁破壊により破損させたりもする。<br />
この対策として「等電位ボンディング」がある。<br />

