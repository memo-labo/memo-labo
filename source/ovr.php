<h2>試験方法</h2>
■配線方法<br>
OVRのP1P2端子の配線を外し、試験機の電圧線を取り付ける。<br>
①a11端子とa12端子、②a21端子とa22端子、①か②、配線されていない方に、試験機の信号線を取り付ける。<br>
①と②、両方とも何らかの配線がされているようであれば、①と②、どちらか一方の配線を外す。<br><br>

■動作時間<br>
電圧を0V→整定値の120％の電圧に急変させ、何秒で動作するかを測定する。<br>
その時、整定時間の±10％以内に収まっていれば良い（詳細は各製品の取説参照）<br><br>

■動作値・復帰値<br>
OVR継電器の「動作時間」を最小値に設定。<br>
試験機の信号線カウンター機能をOFF状態。<br>
カウンタOFFは、OVR継電器の接点が動作しても、試験機からの電圧供給を停止させないため。<br>
P1P2に電圧を印加し徐々に上げていく。<br>
あるタイミングでOVRの接点が動作し試験機のカウンターランプが点滅。<br>
OVRの接点が閉じた時の電圧が動作値（過電圧）、接点が開いた時の電圧が復帰値（通常電圧）となる。<br>
動作値の許容範囲は、整定値の±5％以内。<br>
120V整定であれば、114V～126Vで動作した場合、正常。<br>

