OVRの主な設置場所「高圧の非常用予備発電装置の盤」<br>
過電圧が発生する原因は、非常用発電機の故障による電圧の急上昇など。<br>
高圧交流回路の電圧変動に応じ、電圧が整定値に達した際、過電圧を検出して接点動作する。<br>
OVRが接点動作を行うことで、警報発砲またはVCB（遮断器）引きはずし動作を行う。<br> 

<h2>単独運転の防止機能として</h2>
単独運転とは、発電設備と連系している系統が、事故などで電力会社の電源から切り離されているとき、<br>
太陽光発電設備や自家用発電設備から、電力会社側に向かって電力供給が行われている状態のこと。<br><br>

電力会社が管理している系統に事故が発生した場合、安全のため事故点を発電設備から切り離し、点検をする。<br>
もしその時、需要家側から電源が供給されていた場合、保守員に対して感電の危険が及ぶ。<br><br>

なので、単独運転防止のため、OVR、UVR、OFR、UFR、この4要素を安全装置として使用する。<br>
太陽光発電設備の場合、パワーコンディショナーに内蔵されている場合が多い。<br>

