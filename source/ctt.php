電路の試験測定を行うための端子。<br>
日本配電盤工業会規格「キュービクル式高圧受電設備通則（JSIA 200）」<br>
キュービクル外箱の作業しやすい位置に試験用端子を設置するよう規定している。<br><br>

JIS C 4620「キュービクル式高圧受電設備」より抜粋<br>
外箱正面の内部で作業のしやすい位置に、高圧回路に用いる変流器、計器用変圧器、零相変流器などの試験用端子を設ける。<br>
ただし、専用の電気室に設置する屋内用の場合には、試験用端子は外箱の扉に設けてもよい。<br>

<h2>差し込みプラグ型</h2>
３相同時に操作（開路・相間短絡・閉路）することができる。<br>
