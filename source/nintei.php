<h2>高圧の電気工事ができる資格</h2>

■最大電力500kW以上の自家用電気工作物の電気工事<br>
・選任されている電気主任技術者の指揮のもとで行われる。<br>
・法令上規定してないので作業員は無資格でも作業可能。<br><br>

■最大電力500kW未満の自家用電気工作物の電気工事<br>
・高圧部分⇒第一種電気工事士免状保有者<br>
・低圧部分（電圧600V以下）⇒認定電気工事従事者、第一種電気工事士免状保有者<br>

<h2>認定電気工事従事者</h2>
経済産業大臣により認定される。<br>
交付・事務取扱は出先機関の産業保安監督部長。<br>
自家用電気工作物の電気工事に従事できる資格。<br><br>

工場やビルなどの自家用電気工作物のうち、<br>
簡易電気工事（電圧600V以下で使用、最大電力500kW未満の自家用電気工作物）を行える。<br><br>

第一種電気工事士のうちの、低圧自家用工作物限定免許。<br><br>

