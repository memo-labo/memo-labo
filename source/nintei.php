■開業に必要な電気工事業登録<br>
認定電気工事従事者と第二種電気工事士の資格があれば、<br>
自家用・一般用で登録を行うことが出来る。<br>
（低圧限定だが登録の際、高圧回路用計測器の常備は必要）<br><br>

■資格認定条件の一例<br><br>

第一種電気工事士試験に合格した者<br>
（免状取得には実務経験が必要だが、認定電気工事従事者の資格を得れば一定範囲の実務従事は可能）<br><br>

第二種電気工事士免状の交付を受けた後に「認定電気工事従事者認定講習」の課程を修了した者。<br><br>

■認定電気工事従事者の認定<br>
上記の資格認定条件を満たし、住所地を管轄する各産業保安監督部長に申請することで認定。<br>

