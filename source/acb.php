<h2>ACB 気中遮断器</h2>
ACB：Air-Circuit-Breaker<br>
低圧回路の電路保護が目的。<br>
MCCBやELBと同様に空気中で電流を遮断する遮断器。<br>
圧縮空気によって大きな遮断音を発生する。<br><br>

主に大電流を遮断するための遮断器。<br>
開閉耐久に優れている。<br>
引出式タイプはメンテナンス性が高い。<br>

