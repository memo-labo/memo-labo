<h2>ACB 気中遮断器</h2>
<p>ACB：Air-Circuit-Breaker</p>
<p>
低圧回路の電路保護が目的。<br>
MCCBやELBと同様に空気中で電流を遮断する遮断器。<br>
圧縮空気によって大きな遮断音を発生する。</p>

<h3>ACBの主な特徴</h3>
<ul>
<li>主に大電流を遮断するための遮断器。</li>
<li>開閉耐久に優れている。</li>
<li>引出式タイプはメンテナンス性が高い。</li>
</ul>

