<h2>MCCBとの違い</h2>
<ul>
    <li>大容量の電流（6300Aなど）が遮断可能。
    <li>ACBを引出式にすることで本体を引き出してメンテナンスが可能。
    <li>MCCBに比べて機械的開閉回数が大幅増。
    <li>MCCBと比べて豊富な付属装置（オプション）取り付け可能。
    <li>引きはずしリレー（ETR）と組み合わせて短絡、漏電、地絡などの保護が可能。
    <li>引きはずしコイル・投入コイル・電動チャージを本体に内蔵することができる。
</ul>


