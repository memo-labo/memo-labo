<h2>UVR試験方法</h2>
<p><img src="images/20261009-1.png" alt="UVR 試験例"></p>

UVR単体試験では、P1-P2配線を切り分けて継電器端子へ直接試験電圧を印加する方法がある。<br>
VTT二次側から印加すると、同じ回路につながる警報リレーなどにも電圧が印加される場合があるため注意する。<br><br>

P1またはP2の片側だけを外して試験すると、予期しない回り込みや不動作につながる可能性があるため、試験回路を明確に切り分ける。<br>

<h2>UVR試験時の接点確認</h2>
UVRには、トリップ用・警報用など複数の接点がある。<br>
空き接点がある場合は、既設配線を外さずに接点動作を確認できることがある。<br>
既設配線を外す場合は、戻し忘れ・戻し間違いに注意する。<br>

<h2>点検・試験中のトラブル</h2>
<h3>OCR＋UVR連動試験</h3>
UVR接点がVCBトリップ回路に入っている場合、試験中にUVRがVCBを開放しないよう、回路を切り分ける必要がある場合がある。<br><br>

<h3>配線の戻し忘れ</h3>
UVR接点は停電・復電シーケンスに使われるため、戻し忘れるとVCBの自動投入・自動開放が正常に動かなくなる。<br><br>

<h3>VT二次ヒューズ切れ</h3>
系統が停電していなくても、UVR電源系のヒューズ切れによってUVRが不足電圧を検出し、VCBが開放する場合がある。<br>

