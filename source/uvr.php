<h2>UVR 不足電圧継電器とは？</h2>
UVR（Under Voltage Relay：不足電圧継電器）は、電圧が設定値より低下したことを検出する保護・制御用継電器。<br>
「停電かどうか」そのものを判定するのではなく、入力電圧が不足しているかを監視する。<br><br>

<img src="images/uvr2.png" alt="UVR 不足電圧継電器 図記号" style="max-width:150px;"><br>

<h2>UVRの主な役割</h2>
<ul>
<li>停電／復電時に非常用発電機へ運転・停止信号を送る</li>
<li>停電時に非常用照明を点灯させる</li>
<li>電源切替器を非常系へ切り替える</li>
<li>停電／復電シーケンスでVCBを自動開閉する</li>
<li>警報を出す</li>
</ul>

設備によってはUVRが設置されていても、警報表示だけに使用している場合や、接点が未使用の場合もある。<br>
非常用発電機とダブルスローの切替回路では、27（UVR）の停電・復電検出が切替条件に使われる構成がある。<br>
