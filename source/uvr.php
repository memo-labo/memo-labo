<h2>UVR継電器の点検・試験中の事故やトラブル</h2>
OCR + UVRでOCR電圧引き外しの連動試験ができない<br>
静止型UVRの場合、UVRの引き外し用配線（c1 or c2）だけを外す。<br>
UVRの動作接点はVCBの引き外し回路、または投入用回路になっている。<br>
UVRのVCB開路線を常にオープンにしておくことでVCBがUVRによって開路されない。<br><br>

UVRの配線戻し忘れ、戻し間違い<br>
期待していたVCBのシーケンス動作にならない。<br>
UVRの役割は停電警報表示やVCBの自動投入・自動開放を制御する。<br>
そのため停電・復電操作をVCB手動モードで行うと制御が正常かどうかの確認ができない。<br><br>

誘導型のOCR+UVRの場合<br />
停電中はUVR接点が閉なのでVCBを投入してもTCで引き外されて入らないことがある。<br />
その場合、UVRのb接点を外すか円板を動作状態に固定してあげてテープで止めた状態にしておく。<br><br>

UVR、P1P2上流（VT下流）にあるヒューズが切れてUVR動作⇒VCB開放。<br>
停電していないのにヒューズ切れだけでUVR動作して予期せぬ全館停電。<br>
自動シーケンスで制御するメリットのない設備は自動⇔手動を手動にしておいた方が良い。<br><br>
