<h2>UVRの電源</h2>
P1-P2はVT二次側から供給される構成が多い。<br>
VCB負荷側VTからUVR電源を取る場合は、VCB投入直後のシーケンスに注意する。<br>
UVR復帰までの時間を確保するため、タイマーリレーを組み合わせる場合がある。<br><br>

