<h2>不足電圧時に起こりやすいトラブル</h2>
<ul>
<li>モータの過電流・焼損</li>
<li>接触器のチャタリング</li>
<li>電圧低下に伴う電流増大でOCRが動作</li>
<li>インバータ停止</li>
<li>制御回路のリセット</li>
</ul>

<h2>UVRの整定値</h2>
<h3>動作電圧</h3>
80～90V程度の整定例がある。<br><br>

<h3>動作時間</h3>
1～2秒程度の整定例がある。<br>
動作時間を短くしすぎると、瞬時電圧低下で不要動作する可能性がある。<br>

<h2>UVRと瞬時電圧低下</h2>
落雷などによる系統事故では、短時間だけ電圧が低下して復帰することがある。<br>
UVRの動作時間を設定する際は、このような瞬時電圧低下で不要動作しないようにする。<br>

<h2>再閉路とUVR</h2>
送配電線で事故が発生すると、保護継電器で事故区間を遮断した後、一定時間後に遮断器を自動投入する再閉路が行われる場合がある。<br><br>

再閉路の時間例<br>
<ul>
<li>高速再閉路：1秒程度以内</li>
<li>中速再閉路：1～15秒程度</li>
<li>低速再閉路：1分程度</li>
</ul>

UVRの動作時間は、系統の瞬低や再閉路条件も考慮して決める。<br>

<h2>UVRの接点とシーケンス</h2>
UVRには、a接点・b接点を使ってVCBの投入・開放や警報を制御する構成がある。<br><br>

<h3>受電時：27復帰</h3>
<ul>
<li>b1-c1：開路</li>
<li>a2-c2：閉路</li>
</ul>

<h3>停電時：27動作</h3>
<ul>
<li>b1-c1：閉路</li>
<li>a2-c2：開路</li>
</ul>

