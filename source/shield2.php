<h2>高圧CVTケーブルの遮蔽銅テープ（シールド）が断線する原因</h2>

通電ヒートサイクル（負荷変動）等によるケーブルの熱膨張。<br>
CVTケーブルのシース部分の劣化や損傷により水分が侵入し遮へい銅テープが腐食。<br>
CVTケーブルのシース部分に熱収縮が発生。<br>
銅テープに固定された「すずメッキ軟銅線」と銅テープの接触面に引張応力が発生し銅テープ破断。<br><br>

遮へい銅テープが破断した場合<br>
破断部分に充電電流が流れて発熱⇒絶縁劣化⇒発火<br>
破断による外導テープ侵食⇒アーク放電の進展（トラッキング現象）<br>

