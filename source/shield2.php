<h2>遮蔽銅テープ（シールド）の絶縁不良の例</h2>
<img src="images/20220526_1.png" style="max-width:500px;" /><br>
高圧ケーブルシースアースの絶縁抵抗測定の値が低いケース。<br>
PASやUGS側のシースアースは接地されておらず、テープ等で絶縁されている。<br>
その部分のテーピングや絶縁処置に問題がある、または金属箱に触れていた場合、
受電盤側から絶縁抵抗測定をしたとき、値が低くでることがあるので注意。<br>
※PAS側は高い位置にあるので確認は難しい？<br>

<h2>遮蔽銅テープ（シールド）の破断調査方法</h2>

PASやUGS側ではシールドアースは接地されておらず、絶縁テープで絶縁されているのが通常。<br>
遮へい銅テープは受電盤の引き込み側にて接地されている。<br>
３相は１つの裸圧着丸端子で一括で端子上げされている。<br>
もしくは３相とも３つそれぞれ端子あげされている場合もある。<br><br>

<img src="images/shield21.png" style="max-width:500px;" alt=""><br>

上記画像のように、区分開閉器側では３相が一括で絶縁処理されており、<br>
かつ受電盤側では３相がそれぞれ３つとも端子あげされているような場合<br>
テスターを用いることで相間の導通や抵抗値を測定することができる。<br>
もし仮に抵抗値が異常に高かった場合、断線の可能性がある。<br>

<img src="images/shield22.png" style="max-width:500px;" alt=""><br>
上記画像のように区分開閉器側で絶縁されているシールドのテープを外してテスターで抵抗値測定。<br>
すると、R相とS相の抵抗値が測定できる。同様に、S-T間、T-R間を測定する。<br>


