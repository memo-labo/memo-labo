三相3線 + N相（中性線）<br>
三相回路＋中性線を一括で遮断できる。<br>
主に三相4線式の配電回路に使用。<br><br>

動力トランスの容量が少ない場合、動力トランスの設置が省略できる。<br>
代わりに電灯トランス１台使用し、V結線し、動力負荷と電灯負荷の１部を負担。<br>
電灯トランス１台、動力トランス１台の時より配電盤までの配線が細く出来る。<br>
またメインの電灯トランス１台の容量も減らせる。<br>
小規模施設や、動力負荷が軽微なケースならコスト・配線効率の面で有効な手法。<br>

