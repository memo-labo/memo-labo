<h2>許容電流とは？</h2>
許容電流の種類<br>
許容電流（常時許容電流）：連続して流すことの出来る電流<br>
短時間許容電流：短絡電流等短い時間のみ流すことができる電流<br><br>

許容電流の変化<br>
絶縁体の種類（絶縁被覆の許容温度が絶縁体によって異なるため）<br>
電線の布設方法（地中埋設布設方法により、熱拡散のし易さが異なるため）<br>
周囲温度（周囲温度が低いと、絶縁被覆の許容温度に達するまでの電流が多くなる）<br><br>

布設の種類<br>
気中式：ケーブルが宙に浮いている（熱が逃げやすい）<br>
管路式：地中の管内に布設する<br>
暗渠（あんきょ）式：ケーブルに直接日光が当たらない<br>
直接埋設式：ケーブルを地中に埋める<br>

