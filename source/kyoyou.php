<h2>許容電流の低減率</h2>
ケーブルラックで配線するとケーブルどうしが密に接触する。<br>
なので放熱性能が低下することにより許容電流が低下する。<br>
ケーブルラックに１段で敷き詰めて幹線を敷設した場合の低減率は0.7<br>
幹線ケーブルを多段積みで乗せた場合、さらに低減率は大きくなる。<br>

<h2>基底温度</h2>
ケーブルが敷設されている場所の周囲温度のこと。<br>
幹線で使用するCV、CVTケーブルは周囲温度40℃で許容電流が算出される。<br>

<h2>許容電流に関する事故</h2>

事故例１<br>
ドラムリールに電線を巻き付けたまま使用した。<br>
電線が重なった部分の放熱性能が著しく悪化して熱を持った。<br>
その状態で負荷の大きな電気器具を利用したため異常発熱によって発火した。<br><br>

事故例２<br>
電源コードをインシュロックやビニタイなどで小さく束ねたまま使用した。<br>
電熱器具など消費電力が大きい製品の場合、束ねたコード部分が発熱した。<br>


