協約型ブレーカー<br>
JIS C 8370による協約寸法を持つブレーカー。<br>
ブレーカーはメーカーによって外径寸法が異なる場合がある。<br>
しかし協約形ブレーカーは同一寸法となっている。<br><br>

漏電遮断機（ELB）<br>
地絡による感電を防止する目的で回路に設けられる。<br>
ほとんどの製品で「過電流遮断機能」も付いている。<br>
