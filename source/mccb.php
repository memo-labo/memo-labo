<h2>周囲温度上昇（40°以上）によるブレーカーの誤作動</h2>

ブレーカの定格電流は基準周囲温度 40℃で調整されている。<br>
盤内は通常、周囲温度より10℃～20℃高くなる。<br>
<img src="images/mccb4.png" alt="" style="max-width:350px;"><br><br>

定格電流補正率<br>
盤内温度が40℃を超える高温状態では、ブレーカの定格電流の低減率を考慮する必要がある。<br>
JIS C 8480｢キャビネット形分電盤｣では安全に連続通電できる負荷電流を「ブレーカの定格電流の80％以下」と規定している。<br>
例：主幹ブレーカの定格電流が100Aの場合、その分電盤の定格は80A。<br>
周囲温度が40°以上の場合、定格電流補正率が加わり、ブレーカーの定格電流は下がる。<br><br>

温度補正曲線<br>
横軸：周囲温度（℃）<br>
縦軸：動作時間変化率（％）<br>
周囲温度が40°の時、動作時間変化率は100％<br>
周囲温度が60°の時、動作時間変化率は約70％<br>
周囲温度が高くなると、ブレーカーがより早く動作してしまう（誤作動の原因）<br><br>

