<h2>コールドスタート・ホットスタート</h2>
コールドスタート<br>
ＮＦＢに電流を負担していない（室温に冷却された）状態から通電を開始した場合の動作時間を表す。<br><br>

ホットスタート<br>
遮断器にある程度の電流を負担している状態から所定の過負荷電流の通電を開始した場合の動作を表す。<br>
動作時間はコールドスタートに比べて短くなる。<br><br>

通常、過負荷は始動電流を対象として考えるので、コールドスタートの特性を検討すれば十分。<br>
抵抗溶接機や間欠運転（機械の稼働と停止を繰り返す）などの場合は、遮断器が十分に冷却されていない状態から過負荷が起こるので、ホットスタートの動作特性が必要。<br>



<h2>動力負荷のMCCBを入れてもすぐ切れる現象</h2>
負荷が冷蔵庫や冷凍庫などの圧縮機（コンプレッサー）の場合<br>
始動電流が大きく起動時に定格電流の5～8倍もの大きな突入電流が発生<br>
この突入電流でMCCB投入直後に遮断される場合も<br><br>

瞬時トリップ値を適切なものに設定（許容範囲内で調整可能なMCCBの場合）<br>
インバーターやソフトスターターを使用し、突入電流を抑える<br>
始動時の負荷を分散させる（複数の冷蔵庫がある場合は順次投入する）<br><br>

コンプレッサーの異常（高負荷・ロックローター）<br>
回転せずに過大電流が流れ、MCCBが即座に遮断する場合も<br><br>

対策<br>
動力MCCBを次々と投入せず、少し時間をおきながら入れる。<br>
コンプレッサーが動くか確認（手で回す・テスト運転）<br>
電源を切ってしばらく放置し、圧力バランスを整えてから再投入<br>
サーマルリレーや過電流保護リレーが動作していないか確認する<br>
圧縮機が故障していないか点検する（メーカー対応）<br><br>

