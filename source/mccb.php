<h2>ブレーカーの事故と予防</h2>
<img src="images/mccb1.jpg" alt="" style="max-width:550px;"><br>
ブレーカーに関する事故は「接続部の緩み」が原因であることが多い。<br>
容量の小さい子ブレーカーと呼ばれるものは、銅線をそのまま挟み込むタイプ。<br>
容量が大きくサイズも大きいブレーカーは丸端子をつけてネジで留めるタイプ。<br>
どちらも圧着面積が狭い、圧着力が弱い等が原因で、抵抗が上がり、発熱する。<br><br>

対策方法<br>
・目視点検で焦げつきや色の変化が起きていないか確認<br>
・ブレーカーの増し締め<br>
・日常点検や月次点検での温度測定<br>

<h2>安全ブレーカーを固定する方法</h2>

マグネット、皿ネジ、ナット、これで穴を開けずに盤に固定可能。<br>
安全ブレーカーと磁石を、ネジとボルトを使って固定し、磁石の力で盤にくっつける。<br><br>
