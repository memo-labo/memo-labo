<h2>MCCB 配線用遮断機</h2>
<img src="images/mccb1.jpg" alt="" style="max-width:550px;"><br>
MCCB = Molded Case Circuit Breaker<br>
NFB（ノーヒューズブレーカー）とも呼ばれる<br>
過電流遮断器の一種。<br>
回路内の電流が設定された値より高いことを感知すると回路を遮断。<br><br>

MCBとは？<br>
Miniature Circuit Breaker（ミニアチュア サーキット ブレーカ）<br>
家庭用に使われている小形の遮断器に限定して使用を推奨<br>

<h2>MCCBの種類（用途別）</h2>
安全ブレーカー<br>
小型のブレーカー<br>
家庭用の分電盤内、分岐ブレーカーなど<br><br>

モーターブレーカー<br>
モーターは回り始めが一番電力を消費<br>
それにあわせて始動電流で動作しない設計<br><br>

単３中性線欠相保護付ブレ－カー<br>
単相３線式は、一般家庭で一番普及している配線方式。<br>
中性線(N相)が欠相すると、単相200Vの直列回路となり、負荷機器の抵抗による分圧で100Vを超える電圧が100V負荷機器に加わり、損傷・焼損するおそれがある。<br>
中性線が欠相したときの電圧の変化を検知し、瞬間的に電気を遮断できるブレーカー。<br>
家庭のみならず100V、200Vの異なる電圧の機械を同時に使う際に用いられる。<br>
