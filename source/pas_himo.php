<h2>PAS紐を固定するときの注意</h2>
地上側の紐は、風で暴れたり車両・人に引っ掛かったりしないよう整理して固定する。<br>
ただし、PASの機構によってはトリップ時に操作ハンドルやロープ側が動く形式もある。<br><br>

ロープを強く張って固定することでPASの正常な開放動作を妨げないか、使用機種の構造・取扱説明書を確認する。<br>
「入紐・切紐を必ずこの順で張る」といった現場ルールだけで判断しない。<br>

<h2>停電点検前に確認しておくと安心なこと</h2>
・PAS操作紐にほつれ・硬化・細りがないか<br>
・操作紐が十分な長さか<br>
・入／切の表示が分かるか<br>
・足場ボルトや腕金に絡みそうな経路になっていないか<br>
・結び目が緩んでいないか<br>
・操作が異常に重くないか<br>
・予備ロープまたは交換手配先があるか<br>
・切断時の連絡先・復旧体制を決めているか<br>

