<h2>PAS紐の縛り方</h2>
電柱の足（飛び出たボルト部分）に巻きつけるようにして、最後に縛って固定する。<br>
ピンと張り、ぐるぐる巻いて、最後に輪っかを作って棒に引っ掛けて縛る。<br>
皆同じような巻き方で。特殊な方法だと解くのに時間がかかるから。<br>
入れたときは入紐（赤）を先に、切ったときは切紐（緑）を先に縛る。<br>
こうすることでPASの入切ハンドルが現状でしっかりと固定される。<br><br>

