<h2>PASメーカーの結び方を優先する</h2>
操作紐の結び方・固定位置は、PASメーカーが取扱説明書で例を示している場合がある。<br>
更新・交換時は現場独自の結び方より、使用しているPASの取扱説明書を優先する。<br><br>

