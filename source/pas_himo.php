<h2>PAS紐が切れた場合</h2>

トラブル例<br>
停電点検が終了し、復電のためPASを投入しようとしたところ、PAS紐が上部で切れてしまった。<br>
PASは開放状態のまま。さてどうする？<br><br>

①PAS操作ハンドル付近まで登って紐を直接交換する<br>
②紐が切れた部分まで登って新しい紐で延長する<br>
③工事会社に依頼して高所作業車で対応してもらう<br>
④PAS付近まで登ってジスコン棒を使って手動で投入する<br>

<h2>PASの操作紐をつなぎ合わせて延長したい場合</h2>

・二重テグス結び<br>
・紐を切った端部はほつれないようにライターで炙る<br>
・端部はインシュロックで固定するとなお良い<br><br>

本番でいきなり実践せず、地上でロープ２本で色々と試しておく。<br>
