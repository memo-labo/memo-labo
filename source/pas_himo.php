<h2>PAS紐が絡まって投入できない</h2>

PASの入と切の紐は、２つとも手に持った状態で操作。<br>
片方を離し、片方の紐だけ引くと、もう片方が勢いよく上に引っ張られ、PASに絡まる。<br>
絡まる部分は電柱の足場ボルトやPAS入切の金具部など。<br>
こうなると紐を引っ張っても操作できず、電柱に登って紐をほどかなければならない。<br>
PASの位置まで登るのは通信線や腕金などの障害物があり非常に危険。<br><br>

固くて片手では引っ張れない場合どうする？<br>
操作しない方の紐を緩めて手首に巻き付けて、もう片方を両手で持って引っ張る。<br>
PAS紐を延長し、脚立上ではなく地上から操作できる程度まで延ばす。<br>

<h2>PASの操作紐</h2>

PAS操作紐の種類<br>
①サランロープ（ポリエチレンロープ）<br>
②エスロンロープ<br><br>

サランロープ（ポリエチレンロープ）とは？<br>
従来のPAS紐。経年劣化でほつれて紐が切れやすくなる。<br>
新品の場合、紐を引っ張ると少し伸びてPAS開放・投入操作がしにくい。<br><br>

エスロンロープとは？<br>
ポリ塩化ビニル製、芯材はガラス繊維。<br>
耐久性、耐候性に優れ、断線しにくい。表面に光沢がある。<br><br>
