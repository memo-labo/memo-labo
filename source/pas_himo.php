<h2>PASの紐が切れた！どうする？</h2>

PAS紐の予備もない場合の緊急復電方法<br>
・PASが開放された状態で紐が切れてしまった場合<br>
・ロープを肩にかついで電柱に昇りPASの近くまでいく。<br>
・そこからロープを降ろし、下でジスコンを縛って、引き上げる。<br>
・ジスコンを使ってPASを投入する。<br><br>


