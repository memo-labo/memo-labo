<h2>PASの操作紐トラブルで一番避けたいこと</h2>
PASの操作紐が絡む・切れると、停電点検後にPASを投入できず復電できないことがある。<br>
トラブルが起きてから高所で応急処置するより、点検前にロープの劣化・長さ・固定状態を確認しておく方が安全で確実。<br><br>

<strong>PAS付近までの昇柱や高所での操作が必要になった場合は、適切な高所作業設備・保護具・作業体制を確保し、無理な応急操作をしない。</strong><br>

<h2>PAS紐が絡まって投入できない原因</h2>
入・切の2本の操作紐は、操作中に一方が大きく跳ね上がると、足場ボルト・腕金・PASの操作金具などへ絡むことがある。<br><br>

絡み防止のポイント<br>
・2本の紐の位置を確認してから操作する<br>
・余長が多すぎて風で振られないようにする<br>
・足場ボルトや突起部へ引っ掛かる経路になっていないか確認する<br>
・地上から安全に操作できる長さ・取り回しにする<br>
・劣化、ほつれ、結び目の緩みを停電点検前に確認する<br><br>

操作力が異常に重い場合は、紐だけの問題とは限らない。<br>
無理に強く引かず、PASの操作機構、ロープ経路、固着などを確認する。<br>

<h2>PAS操作紐の種類</h2>
PASの操作紐には、ポリエチレン系ロープや耐候性を考慮した専用ロープなどが使用される。<br>
製品・施工仕様によって材質は異なるため、交換時はPASメーカーや施工仕様に適合するロープを選ぶ。<br><br>

従来のロープでは、長期の紫外線・風雨で表面が毛羽立つ、硬化する、細くなるなどの劣化が見られることがある。<br>
見た目に問題がなくても、結び目付近や金具との接触部は局部的に傷みやすい。<br><br>

