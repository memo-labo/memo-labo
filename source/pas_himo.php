<h2>PAS紐が切れた場合</h2>
PASが開放状態のまま操作紐が切れると、通常の地上操作では投入できない。<br><br>

この場合は、まず、<br>
・PASが確実に開放状態か<br>
・切れた位置はどこか<br>
・高所作業車など安全な作業手段を確保できるか<br>
・工事会社・送配電会社との調整が必要か<br>
を確認する。<br><br>

高所でのロープ交換やPAS操作部への直接アクセスは、墜落・感電・近接充電部への接近リスクがある。<br>
復電を急ぐ状況でも、通信線や腕金を避けながら無理に昇柱して応急投入する方法は採らず、資格・設備・作業手順を整えて対応する。<br>

<h2>PAS紐を延長・交換するとき</h2>
ロープを途中で継ぐ方法もあるが、結び目は操作時の引張力を受け、経年で緩み・摩耗が発生する。<br>
可能なら、適切な長さのロープへ一体で交換する方が管理しやすい。<br><br>

途中接続が必要な場合は、<br>
・使用ロープに適した結び方・端末処理を採用する<br>
・結び目が足場ボルトや操作金具に引っ掛からない位置にする<br>
・地上で十分に引張確認してから使用する<br>
・熱処理が適さない材質もあるため、端末を火で炙る方法を一律に使わない<br>
・金属カラビナ等を使用する場合は、メーカー・施工仕様、近接充電部との離隔を確認する<br>

