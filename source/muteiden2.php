<h2>無停電（活線状態）での保護継電器試験</h2>

<p><strong>受電を継続したまま保護継電器を試験する場合、誤トリップによる全館停電と、CT二次回路の開放による高電圧発生を防ぐことが最重要です。</strong></p>

<p>工場・病院・ビルなど、停電が難しい設備で無停電点検が検討されることがあります。<br>
⇒<a href="muteiden.php">無停電の年次点検ができる条件</a></p>

<p>ただし、活線状態での試験可否は設備構成・保安規程・メーカー手順によって異なります。ここでは考え方を整理し、具体的な活線操作手順は対象設備の手順書を優先します。</p>

<h2>無停電試験で確認できる範囲</h2>

<p>無停電状態では、設備条件が整っていればOCR・DGRなどの<strong>継電器単体の動作値・動作時間</strong>を確認できる場合があります。</p>

<p>一方、継電器を実際に動作させてVCB・LBSまで開放させる連動トリップ試験は、受電継続中には通常実施できません。</p>

<h2>誤トリップ防止が最優先</h2>

<p>単体試験を行うには、試験による継電器出力が実際の遮断器へ伝わらない状態を確実に作る必要があります。</p>

<p>設備によっては、トリップロック用試験端子、テストスイッチ、専用プラグ、制御回路の試験位置などが用意されています。</p>

<img src="images/muteiden2-1.png" style="max-width:500px;" alt="OCRトリップロック回路の例"><br>

<p><strong>図は一例です。端子を抜く・差す、配線を離線する、といった操作を他設備へそのまま適用しません。</strong></p>

<h2>試験前に確認すること</h2>

<ul>
  <li>対象継電器と遮断器の回路図</li>
  <li>トリップロック機構の有無と正常動作</li>
  <li>継電器出力がどの遮断器・開閉器へ接続されているか</li>
  <li>試験端子・CTT・TCTTの形式</li>
  <li>CT二次回路を短絡した状態で切替できる構造か</li>
  <li>試験中に失われる保護機能と代替保護</li>
  <li>誤停電した場合の影響と復旧手順</li>
</ul>

<h2>CT二次回路の注意</h2>

<p><strong>CT一次側に電流が流れている状態で、CT二次側を開放してはいけません。</strong>二次側に高電圧が発生し、感電・絶縁破壊・CT損傷につながるおそれがあります。</p>

<p>試験端子を使用する設備では、CT二次側を安全に短絡してから継電器側を切り離せる構造になっているものがあります。</p>

<p>具体的な短絡・切替順序はCTTの形式によって異なるため、<strong>「素早く抜き差しすればよい」と考えず、メーカー指定の手順と専用治具を使用します。</strong></p>

<p>⇒<a href="ctt.php">CTT（電流試験端子）の構造と注意点</a></p>

<h2>トリップロック後も確認が必要</h2>

<p>ロック端子や試験プラグを使用した場合でも、試験開始前に「継電器を動作させても実遮断器へ引外し信号が届かない」ことを、設備の試験要領に従って確認します。</p>

<p>補助リレーや自己保持回路を介している設備では、想定外の経路でトリップ信号が成立することがあります。</p>

<h2>無停電試験では確認できないこと</h2>

<ul>
  <li>遮断器が実際に開放するまでの連動動作</li>
  <li>トリップコイル・機械機構を含む一連の遮断性能</li>
  <li>停電状態でしか確認できない絶縁・接触・機械点検の一部</li>
</ul>

<p>無停電で単体試験が正常でも、保護回路全体が正常とは限りません。停電点検時には連動試験を含めた確認が必要です。</p>

<h2>試験終了後の復帰確認</h2>

<ul>
  <li>トリップロックを解除したか</li>
  <li>試験端子・プラグを運転位置へ戻したか</li>
  <li>CT二次回路が正常接続されているか</li>
  <li>継電器整定値を元へ戻したか</li>
  <li>警報・表示・遠方監視に異常がないか</li>
  <li>本来の保護機能が復帰したことを確認したか</li>
</ul>

<p><strong>活線試験は、設備を止めずに済む代わりに誤操作時の影響が大きい作業です。現場固有の試験要領・メーカー資料・保安規程を優先します。</strong></p>

