<h2>インダクタンス</h2>

導体に電気を流した時の磁場の起こりやすさを示した値のこと。<br>
コイルなどにおいて電流の変化割合が誘導起電力となって現れる性質のこと。<br />
この比例定数をインダクタンスあるいは誘導係数という。<br /><br />

コイルに流れる電流が変化すると、電流の変化が磁束の変化となり、コイルに起電力を誘起する。<br />
この作用のことを自己誘導作用と呼び、この起電力を自己誘導起電力と呼ぶ。<br /><br />

1A/1Sの割合で電流が変化するとき、1ボルトの起電力を生ずるインダクタンスが1ヘンリー（H）<br />
自己インダクタンスの記号はL、相互インダクタンスの記号はMで表す。<br><br>

自己誘導作用による自己誘導起電力eは、電流の変化の割合（電流の変化率 = ΔI/Δt）に比例する。<br><br>

VL = L ✕ (di÷dt)<br>
VL：誘導起電力（起電圧）<br>
L：インダクタンス<br>
di：電流の変化量<br>
dt：時間<br>

