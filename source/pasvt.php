<h2>PAS内蔵VTと計器用変圧器VTの違い</h2>

計器用変圧器PD-50HF（ヒューズ付き）<br>
二次電圧：110V<br>
定格負担：50VA<br><br>

VT内蔵PAS<br>
二次電圧：105V<br>
定格負担：25VA<br><br>

２つを比べると、二次電圧に5Vの差がある。<br>
計器用変圧器VTは、精度が重要なので変圧比を単純にしている。<br>
PAS内VTはSOG制御電源專用で、外部電源の105Vでも動作できるようになっている。<br>
105Vと110Vの差は大きく、110Vを100V定格の機器に突っ込むと壊れやすい。<br><br>

SOG制御装置の定格制御電圧<br>
１回路用：AC100/110V(変動範囲85～120V)<br>
多回路用：AC100V<br><br>

