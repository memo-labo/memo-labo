<h2>注意</h2>

刃が浮いて押し込みきれていない場合がある。<br>
金属の接続面積が減り、抵抗が増え、発熱、焼損。<br>
停電点検や新築の竣工検査の際、高圧カットアウトを手で押し込み確認。<br>
⇒<a href="https://twitter.com/MK_0721/status/1656964275339161601">カットアウト押し込み不足による焼損事故例</a>

<h2>LBSと比較した場合のPCのメリット</h2>
本体価格が安く施工が簡単。<br>
PCは充電部が陶器で蓋されてる。<br>
充電部が空気中に触れていない。<br>
ほこりや湿気が内部に付着しないので絶縁劣化しにくい。<br>
充電部露出していないため相間短絡が起こりにくい。<br>



<h2>PC（高圧カットアウト）での事故例</h2>

刃が浮いて押し込みきれていない場合がある。<br>
その場合、金属の接続面積が減り、抵抗が増え、発熱、焼損にいたる例もある。<br>
停電点検や新築の竣工検査のときは、高圧カットアウトを手でぐっと押し込んで確認する。<br>
⇒<a href="https://twitter.com/MK_0721/status/1656964275339161601">カットアウト押し込み不足による焼損事故例（Twitter）</a><br><br>

製造年月が古いタイプのカットアウト<br>
古かった場合、開けただけで壊れてしまうことがある。<br>
1980年代くらいから危ない。古いものは開けないのが一番。<br><br>

壊れた例<br>
ヒューズホルダーの刃の受けの部分のプラスチック。<br>
PCの蓋をあけた時、刃の受け部分が付け根から割れた。<br>


