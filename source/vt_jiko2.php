<h2>誤って印加した可能性がある場合</h2>

<p>異常に気付いたら、ヒューズが切れたかどうかだけで安全と判断せず、外部電源を停止し、回路を安全な状態にしてから高圧側・低圧側双方の状態を確認します。</p>

<p><strong>「高圧側は停電中のはず」という前提ではなく、検電・接地・回路確認など所定の安全手順で無電圧を確認します。</strong></p>

