<h2>VT二次側からの逆昇圧とは？</h2>

<p><strong>VTの二次側へ外部電源を誤って印加すると、変圧器作用によって一次側に高電圧が発生するおそれがあります。</strong></p>

<img src="svg/vt_jiko2.svg" style="max-width:700px;" alt="VT二次側から一次側へ逆昇圧するイメージ"><br>

<p>たとえば6600/110VのVTは、本来6600Vを110Vへ変成する機器ですが、一次側が回路につながった状態で二次側へ外部電源を与えると、一次側へ高電圧が現れる可能性があります。</p>

<h2>なぜ危険？</h2>

<ul>
  <li>停電していると思っている高圧母線が充電されるおそれがある</li>
  <li>高圧機器・変圧器・ケーブルへ意図しない電圧が加わる</li>
  <li>接地作業中の回路へ逆送電する危険がある</li>
  <li>VT、試験器、ヒューズなどを損傷する可能性がある</li>
  <li>感電・アーク事故につながる</li>
</ul>

<p><strong>低圧側だから安全、という考え方はできません。</strong>VT・PT・操作用変圧器など、変圧器を介して高圧側へ電圧が現れる経路がないかを確認します。</p>

<h2>事故例から分かること</h2>

<p>停電中のキュービクルで低圧電源を利用しようとした際、変圧器を介した逆送電によって高圧側が充電され、感電事故に至る事例があります。</p>

<p>参考：<a href="https://www.tokyotsa.com/file/58_saigai.pdf" rel="noopener">キュービクル式受変電設備内の照明利用時の感電災害事例</a></p>

<h2>ヒューズを入れれば防げる？</h2>

<p><strong>小容量ヒューズを入れることを逆昇圧防止策の代わりにしてはいけません。</strong></p>

<p>ヒューズが溶断するまでの間にも高圧側に危険な電圧が現れる可能性があり、負荷条件によってはヒューズが想定どおり切れる保証もありません。</p>

<p>逆昇圧事故の基本対策は、過電流保護に頼るのではなく、<strong>外部電源を印加する回路とVT二次回路を確実に分離し、逆送電経路そのものを作らないこと</strong>です。</p>

<h2>試験電源・仮設電源を使う前の確認</h2>

<ul>
  <li>電源を入れる端子がVT二次回路とつながっていないか</li>
  <li>既設電源と試験電源が並列・逆送電状態にならないか</li>
  <li>VT一次側が高圧母線へ接続されたままではないか</li>
  <li>回路図と現物端子番号が一致しているか</li>
  <li>必要な切離し・ロックアウトが完了しているか</li>
</ul>

<h2>SOG・継電器試験でも同じ注意が必要</h2>

<p>PAS内蔵VTなどから制御電源を受けている回路へ、試験器の補助電源を外部から印加する場合も、接続状態によってはVT側へ逆送電する危険があります。</p>

