<h2>火花放電（フラッシオーバ）</h2>
電極間に高電圧が加わると、高電圧によって加速された電子が気体分子と衝突して電離をする。<br>
そこで生成された正イオンが負極に衝突する際、二次電子放出が起こる。<br>
負極から電子が電極間の空間に供給されて、火花が観察される。<br>
これは不連続な過渡的現象である。<br><br>

