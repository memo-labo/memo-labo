<h2>安定器とは？</h2>
蛍光ランプやHIDランプなどの放電ランプは、放電現象を利用した光源である。<br>
放電現象は不安定で電源に直接つなぐと電流が急激に増え瞬間的にランプの電極やシール部(封止部)が壊れてしまう。<br><br>

放電ランプは負特性のため、直接電源に接続し、いったんランプ電流が流れ始めると急激に電流が増大して瞬時にランプの電極やシール部が破損してしまう。<br><br>

なので電源とランプの間に抵抗を入れて、電流を一定の値に安定させる必要がある。<br>
この抵抗のことを「安定器」と呼ぶ。<br><br>

