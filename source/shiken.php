  <h2>非常用発電機の起動試験 手順</h2>

<ul>
  <li>非常用回路を開放。
  <li>制御盤「商用」ランプが消灯。
  <li>エンジンが起動。
  <li>発電検出まで回転数が上がる。
  <li>電圧が確立される。
  <li>制御盤「発電」ランプが点灯。
  <li>発電ランプ点灯後、２秒で負荷切替。
  <li>制御盤「負荷商用」ランプが消灯。
  <li>制御盤「負荷発電」ランプが点灯。
  <li>操作選択ボタンで試験に切り替える。
  <li>停止ボタンを押して発電機を停止させる。
  <li>試験モードになっていることを確認し、発電機内ブレーカーを開放し、点検作業に入る。
</ul>

<h2>非常用発電機の停止試験 手順</h2>

<ul>
  <li>非常用発電機からの送電用ブレーカーを投入状態にする。
  <li>発電機の制御盤の操作選択ボタンにて試験⇒自動へ切り替える。
  <li>非常用発電機が起動し、電圧確立し「負荷発電」ランプが点灯する。
  <li>高圧受電設備の高圧側を受電状態にする。
  <li>低圧の非常用回路MCCBを投入（もしくはVCBを投入）
  <li>制御盤「商用」ランプが点灯する。
  <li>60秒後に負荷切替。
  <li>制御盤「負荷発電」ランプ消灯。
  <li>制御盤「負荷商用」ランプ点灯。
  <li>120秒後にエンジンが停止。
  <li>制御盤「発電」ランプ消灯。
  <li>停止ソレノイドが開放。
</ul>

<h2>非常用発電機の起動・停止試験の注意点</h2>

非常用発電機の起動・停止試験<br>
ダブルスローが切り替わり、非常系負荷に電力が供給されることを確認する。<br>
ダブルスロー本体の故障、ダブルスローに繋がっているパワーリレーの故障もあり得る。<br>
ダブルスローは27X、84X、タイマーリレーといった名称のリレーを組み合わせてる場合が多い。<br>
もしこのリレーひとつが接点動作不良を起こしていた場合、ダブルスローは動かない。<br>

<h2>非常用自家発電設備の種類</h2>

防災用専用機<br>
停電時の電源として、法令（消防法、建築基準法）に基づく防災負荷（消防用設備、建築設備）のみを対象に設置されたもの。<br><br>

保安用専用機<br>
停電時の電源として、設置者が自主的に設けた保安負荷のみを対象に設置されたもの。<br><br>

防災用・保安用共用機<br>
停電時の電源として、防災負荷とそれ以外の設置者が自主的に設けた保安負荷（一般照明、医療機器、コンピュータ等のバックアップ用）の両方を対象に設置されたもの。<br><br>

防災用負荷の運転が優先され、そのための燃料を確保することが優先される。<br>
そのため火災時には保安負荷を火災検知＋マグネットで回路を切り離し、防災負荷のみに長時間供給されるように設計する場合がある。<br>

<h2>消防法により規定される仕様</h2>

自家発電設備は消防法で「自家発電設備およびバッテリ設備は消防庁長官が定める基準に適合するものとする」と規定されている。<br>
消防庁告示第1号「自家発電設備の基準」<br>
（1）常用電源が停電した場合は自動始動し，40秒以内に電圧を確立し供給できること。<br>
（2）発電用火力設備技術基準によるほか下記の計測装置を設けること。<br>
● 電圧計・電流計・周波数計またはエンジンの回転速度計<br>
● エンジン潤滑油の温度計および圧力計<br>
● エンジンの冷却水温度計<br>
（3）定格負荷で1時間以上連続して運転できること。<br>
（4）セルモータのピニオンギアとエンジンのリンクギアとの自動かみ合せ装置を設けること。<br>
（5）セルモータに使用するバッテリおよび充電器は告示2号によるほかバッテリは高率放電用のものを用いること。<br>
（自動車用バッテリは不可）<br>
（6）燃料タンク容量は2時間以上運転できること。<br>
（7）燃料系統の配管は金属管または、これと同等以上のものを用いること。<br>
（8）発電機の絶縁種別はB種以上とすること。<br>
（9）次の保安装置を設けること。<br>
●出力過電流　●エンジン過速度<br>
