<h2>設置基準（設置場所や施工上の注意）</h2>

自家発電設備は、運転中の騒音、振動、排気、引火の危険性がある燃料を使用することなどから、その設置場所について、施工規則第12条において定めがある（一部抜粋）<br><br>

・点検に便利で、火災等の災害による被害を受けるおそれが少ない箇所。<br>
・不燃材料で造られた壁、柱、床及び天井で区画され、窓及び出入口に防火戸を設けた専用の室に設けること。<br>
・ただし、キュービクル式自家発電設備で、不燃材料で区画された変電設備室、発電設備室、機械室、ポンプ室、その他これらに類する室又は屋外若しくは屋上に設ける場合は、この限りではない。<br><br>

<h2>言葉の意味</h2>

買電＝商用電源<br>
一般的に、買電の上流にはMCCBがあり、屋外型キュービクルの動力盤に設置されている。<br>
そのブレーカーは、他の一般負荷と区別するため、赤枠や赤い箱状のものに囲まれている。<br><br>

83Rと83Gは接触器<br>
商用受電時 ⇒ 83Rは閉、83Gは開<br>
商用停電時 AND 発電機起動後の電圧確立 ⇒ 83Rは閉、83Gは開<br><br>

G回路とは？<br>
災害や事故による停電で電力会社から商用電源が供給不可となった場合、非常用発電機から電源を供給する回路。<br><br>

緊急性が高く、停電すると困る負荷とは？<br>
避難用誘導照明、非常用照明、消火設備ポンプ、防犯設備、非常用エレベーターなど。<br>
（接続される機器の容量に制限あり）<br><br>

継電器での電力監視<br>
非常用発電機から負荷へ送り出す間には、様々な継電器が電力を監視している。<br>
51G（過電流）27G（不足電圧）59G（過電圧）95G（周波数）<br><br>

計器<br>
交流電流計、交流電圧計、周波数計、電力計、力率計、直流電圧計、直流電流計<br><br>

<h2>ラジエーターとは？</h2>

エンジンが高温になるのを防ぐパーツのこと。中には冷却水が入っている。<br>
冷却水の量を確認、必要に応じて補充など、定期的なメンテナンスが必要となる。<br><br>

よくある故障として「ラジエーター本体から水漏れ」がある。<br>
ラジエーター内部の腐食が進行し水圧の掛かる弱い箇所から水漏れが発生する。<br>
古い機種でラジエーター本体が生産終了している場合、修理不可能？<br><br>

運転時、水圧で漏れがひどく、待機中も該当箇所から冷却水は少しづつ漏れていく。<br>
冷却水の水量が足りない、または補充しても水漏れしている場合、災害時に始動しても、水温異常による緊急停止が起こる。<br>
または、センサーや制御が故障していた場合、最悪はオーバーヒートを招く。<br>


