<h2>サージアブソーバ ZNR</h2>

ZNRとは英語でZinc-Oxide Non-liner Resistor<br>
日本語訳で「酸化亜鉛非直線抵抗器」<br>
バリスタ（variable resistor）とも呼ばれる。<br>
