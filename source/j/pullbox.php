プルボックス<br>
ケーブルの分岐部分に使用される箱のこと。<br>
電線やケーブルの引き入れ、引き出しが容易にできる。<br>
また配線を延長や分岐する際、このプルボックスがあれば作業が容易に行える。<br>
ステンレス、鋼板製、高耐食性メッキ鋼板製、FRP樹脂製など、いろいろある。<br><br>

形としては、何方向にケーブルの出口があるか、という違いがある。<br>
一方出、二方出、三方出、四方出、など。<br>
配線が下から入ってきて右から出る場合、二方出となる。<br><br>

設置場所<br>
建物の天井、天井裏、電気室の壁、建物の各階をまたぐ縦穴など。<br>
屋外の場合、耐候性に優れた素材が必要。<br><br>

ボックスとコネクタ部分。<br>
ボンド線が接地用端子にネジ止めされておりボックスの中へ。<br>
