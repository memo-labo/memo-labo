<h2>ジプトーンとは？</h2>
ジプトーンとは、トラバーチン模様の洋風天井用化粧石膏ボードのこと。<br>
トラバーチンとは天然で採掘される無機質石灰岩の一種。分類としては大理石。<br>
ジプトーンという名称は某会社の化粧石膏ボードの商品名。<br>
<img src="images/jip3.jpg" style="max-width:700px;" alt=""><br>

ジプトーンの特徴
・値段がそこそこ安い。<br>
・下地の上に貼るだけなので簡単。<br>
・サイズが決まってるので交換が簡単。<br>
・事務所や店舗建築、オフィスなどで広く普及している。<br><br>

ジプトーンのメリット<br>
施工の際に使用するビスが目立たない。<br>
表面の模様の穴で天井の表面積が広がり、吸音性能が高くなり、室内の反響音が抑えられる。<br><br>

ジプトーンのデメリット<br>
昔からよく見かけるデザインで、少し古臭い。<br>
ぶつぶつの穴の模様が怖いと感じる人もいる。<br>

