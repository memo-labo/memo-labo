吸音天井ボード<br>
・模様が統一されている。<br>
・人の話し声（低・中音域での周波数）の吸音性能に優れている。<br>
・非吸音タイプと組み合わせて学校や会議室などで最適な音響設計ができる。<br>
・学校の教室や音楽室で吸音、反射を組み合わせて効果的に使用するらしい。<br>
・凹み部に専用ビス留めが出来て、ビスが目立たない。<br>
・目地処理や塗装仕上げが不要で工数を減らせる。<br>
・不燃材料であり内装制限を受けない。<br>
・ホルムアルデヒド吸収分解性能がある。<br>
・シックスクール・シックハウス対策が出来ている。<br>


