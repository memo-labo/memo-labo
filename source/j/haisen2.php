<h2>白線、黒線の配線方法</h2>

非接地側（黒線）<br>
接地側（白線）<br><br>

正しい配線<br>
電源（黒線）⇒スイッチ⇒電灯⇒電源（白線）<br>
スイッチを切ると電灯につながっているのは電源（白線）だけ。<br>
電源（白線）は接地されており対地電圧ゼロなので器具交換の際に感電しない。<br><br>

誤った配線<br>
電源（黒線）⇒スイッチ⇒電灯⇒電源（白線）<br>
スイッチを切ると電灯につながっているのは電源（黒線）だけ。<br>
電源（黒線）は対地電圧が100V印加されており器具交換の際に感電する。<br>
またスイッチを切っても電灯に常に対地電圧が印加されている状態。<br>

<h2>コンセント</h2>
穴が縦に長いほうが接地側（白）<br>
穴が縦に短いほうが非接地側（黒）<br>

