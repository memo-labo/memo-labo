<h2>ナイフスイッチ</h2>
<img src="images/knife1.jpg" style="max-width:400px;" alt=""><br><br>

CKS（たぶん Cover Knife Switchの略）<br>
カバー付ナイフスイッチの取付方向<br>
上が電源側（1次側）上に倒すとON状態<br>
下が負荷側（2次側）下に倒すとOFF状態<br><br>

自重や振動によってスイッチが勝手にON状態とならないようにするため。<br><br>

銅合金で作製された刃の形状をした電極。<br>
同じく銅合金で作製された電極（刃受け）<br>
刃を刃受けに差し込むことで、導通状態とする仕組み。<br>
刃切開閉器と呼ばれることもある。<br>

<h2>ナイフスイッチの構造</h2>
<img src="images/knife2.svg" style="max-width:700px;" alt=""><br><br>

ナイフスイッチの中央⇔下側には爪ヒューズが使われているものがある。<br>
定格以上の電流が流れた場合に「可溶体」の部分が溶断する。<br>
可溶体部分の材質は、鉛、スズ、亜鉛の合金。<br>


