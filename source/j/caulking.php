<h2>コーキングの種類と用途</h2>

シリコン系<br>
・シリコン樹脂が原料<br>
・お風呂やキッチンなどの水回りとして。<br>
・耐久性、耐候性、耐熱性、撥水性に優れている。<br><br>

変成シリコン系<br>
・ポリエーテル樹脂が原料<br>
・湿気硬化型タイプの接着剤で空気中の水分と触媒により硬化する。<br>
・硬化後は優れた弾力性を保ち、衝撃や振動に強い。<br>
・被着体同士の膨張、収縮の応力を吸収し、耐久性に優れる。<br>
・建築物などに多く用いられている。<br>
・上から塗装が可能である。<br><br>

ウレタン系コーキング材<br>
・主にコンクリートのひび割れの補修や木材に使用。<br>
・密着性に優れ、硬化すると弾力性のある仕上がり。<br>
・紫外線に弱く上からの塗装が必要となる。<br>

