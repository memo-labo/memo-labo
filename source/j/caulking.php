<h2>シーリングとコーキングの違い</h2>

【JIS K6800:1985「接着剤・接着用語」】<br><br>

〇シーリング材<br>
構造体の目地、間げき（隙）部分に充てん（填）して防水性、気密性などの機能を発揮させる材料<br><br>

〇油性コーキング剤<br>
ペースト状のシーリング材。<br>
展色材（天然樹脂、合成樹脂、アルキド樹脂など）と鉱物質充てん剤（炭酸カルシウムなど）を混合。<br>
相対変位の小さな目地のシールに使用される。<br>
鉱物質充てん剤として、石綿は、現在使用が禁止されている。<br><br>

シーリングとコーキングに大きな違いはない。<br>
呼び方が違うだけでどちらも同じものとして扱われているらしい。<br>
厳密に言えば、コーキングはシーリングの一部。<br>

<h2>コーキング</h2>
チューブ容器に入っていて専用の押出し機であるコーキングガンを使用する。<br>
樹脂性の物をコーキング剤（コーキング）という事が多いらしい。<br><br>

