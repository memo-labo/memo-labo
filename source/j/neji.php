<h2>ネジがナメてしまう理由</h2>
<img src="images/neji/1.jpg" style="width:200px;" alt=""><br>
<ul>
    <li>ドライバーを押し込む力が弱い状態で、ドライバーを回転させてしまった。
    <li>ネジ頭に対してドライバーを垂直にせず、斜めの状態で回転させた。
    <li>ネジ穴に合わないドライバーのサイズを使用した。
    <li>下穴の径が小さすぎたり、角度が斜めで噛み合っていない状態でネジが進まなくなることがある。
    <li>その状態でインパクトドライバーや電動ドライバーを使うと、ネジ頭だけに力を加わり、ねじ切れたりナメたりすることがある。
</ul>

<h2>高圧ケーブルのシールドアース接地部のネジ</h2>
高圧ケーブルのシールドアースを接地に落とす部分では、現場によって真鍮製のプラス3号ネジが使われていることがある。<br><br>
これをプラス2号のドライバーや電動ドライバーで無理に緩めると、ネジ頭をナメてしまう場合がある。<br>
<strong>ネジ頭に合ったドライバーを使い、特に固いネジを緩めるときはネジ頭を傷めないよう注意する。</strong><br><br>
ネジの材質・サイズは設備によって異なるため、実物を確認して適合する工具を使用する。<br>

<h2>ネジを潰さない（ナメない）ようにする方法</h2>
<ul>
    <li>ネジのサイズにあったドライバーを使う。
    <li>ネジ頭に対して垂直にドライバーを使う。
    <li>インパクトドライバーが打ち込んだ時（トルクが働いたとき）は、無理に回さない。
    <li>ネジが噛み合ってなくて途中で入らなくなった時は、一度緩めて、やり直す。
    <li>緩める、締めるときの最初と最後は、手回しで手動ドライバーを使用する。
</ul>

