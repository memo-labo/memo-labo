<h2>リモコントランスとは？</h2>
<img src="images/remote2.jpg" style="max-width:500px;" alt=""><br>
小型リモコントランス(F型/分電盤用) <br>
20Aフルパワーリモコンリレーを駆動するための電源として使用する。<br>
リモコンリレー用として使用する場合、盤内に１台取り付ける。<br>

