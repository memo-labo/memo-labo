支線ワイヤーに張力を加える部品<br><br>
<img src="images/shisen3.jpg" style="width:400px;"><br>
<img src="images/shisen4.jpg" style="width:400px;"><br>

ロープやワイヤーやタイロッドなどの張力を調節する。<br>
金属製の胴の両端にネジ山が切られていて、一方は右ネジ、もう一方は左ネジ（逆ネジ）になっている。<br>
胴の部分を回転させると両端に取り付けられたボルトが締まったり緩んだりして張力の調節ができる。<br><br>


