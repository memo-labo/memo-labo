<h2>VE管とは？</h2>
<img src="images/ve1.jpg" style="max-width:300px;"><br>
VEは英語でVinyl electric（ビニール エレクトリック）<br>
日本語では硬質ビニル電線管。J管とも呼ばれる。<br><br>

耐水、耐油、耐候性があり太陽の紫外線や腐食に強い。<br>
金属の電線管と比べて安い、軽い、扱いやすい。<br>
金属と比べて衝撃に対する耐久性はない（踏んだら割れる？）<br>
VE管はPF管と違って可とう性がなく曲げられない。<br><br>

値段の比較<br>
メートル単価はVE管よりPF管のほうが安い。<br><br>

VE管はカラーバリエーションが豊富<br>
