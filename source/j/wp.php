<h2>注意点</h2>
<img src="https://blog.memo-labo.com/wp-content/uploads/2022/03/image-16.png" style="max-width:700px;"><br>
ペンチやプライヤーだと握る＝挟む力が加わり、表面がギザギザしている。<br>
モンキーの場合、握る＝挟む力は固定で、かつ挟む表面部分がつるつると平ら。<br>
なので掴む対象が傷つかない。<br>


