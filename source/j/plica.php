<h2>プリカチューブ</h2>

標準プリカ<br>
外層に亜鉛めっき鋼帯、中間層に鋼帯、内層に耐水紙を用いた管にひだ付けした構造<br><br>

<img src="images/plica2.jpg" style="width:400px;" alt=""><br><br>

<img src="images/plica1.jpg" style="width:700px;" alt=""><br>

特定電気用品以外の電気用品である。<br>
コンクリート埋設や、特殊場所を除いた乾燥した場所の低圧屋内配線に鋼製電線管と同様に施設できる。<br>
電線はＩＶ電線／ケーブル等が使用できる。<br>
PF管・CD管に比べて使用温度範囲が広く、耐候性が高い。<br>
PF管・CD管に比べて値段が高い。<br>
金属だけどナイフ（プリカナイフ）で切れる。<br><br>


<h2>プリカチューブの切断</h2>

プリカナイフ<br>
プリカチューブの切断は、プリカナイフ使用する。<br><br>

電工ナイフとプリカナイフの違い<br>
プリカナイフは刃が長く刃がギザギザしている。<br><br>

プリカカッター/フレキシブルカッター<br>
ハサミのような工具で握ることで刃で管を切断する。<br><br>


