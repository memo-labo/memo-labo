<h2>VCTF</h2>

VCTF<br>
ビニルキャブタイヤ丸形コード<br><br>

内線規程<br>
「コードは電球線及び移動電線として仕様する場合に限るものとし、固定した配線として使用しないこと」<br>
ケーブルではなく「コード及び移動電線」に分類される。<br><br>

ケーブルラック、鉄骨、間仕切りなどに VCTFを固定してはいけない。<br>
ステップル等を使用し、柱やボードに固定することも禁止。<br><br>

コードとは？<br>
原則として小型可搬用電気機器に電源を供給するための電線。<br>
支持固定をして恒久的な電源供給を行うように製作されていない。<br><br>

コードは、許容電流が小さく構造的にも弱い。<br>
支持に固定をすると被覆や心線を傷つけてしまい、異常加熱や発火の原因となる。<br>

