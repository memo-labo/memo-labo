<h2>ダクターチャンネル</h2>

ダクターチャンネルの素材<br>
鉄、溶融亜鉛メッキ、ステンレスの３種類がある。<br>
鉄：水気に弱い、さびやすい、屋内の湿気が少ない場所で使用。<br>
溶融亜鉛メッキ：屋内・屋外で使用。<br>
ステンレス：水気に強い、屋外など錆の可能性がある場所で使用。<br>

