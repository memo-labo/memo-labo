<h2>ローバル（亜鉛塗料）</h2>
錆止め（防錆）のために使われる亜鉛リッチペイント（高濃度亜鉛塗料）<br>
主成分は高純度の亜鉛粉末（95%近い含有率）<br>
ドブでも端部と穴抜いたとこはただの鉄。<br>
鉄やドブのダクター端部に吹き付ける。<br>

