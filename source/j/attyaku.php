<h2>圧着工具の値段による違い</h2>

官庁工事でしっかり品質管理しているところはJISマークの工具を使用を必須にしている現場がある。<br>
摩耗で圧着ダイス痕が判別できなくなる状態になるのが早い（圧着不足）<br><br>

JISマーク適合工具は、圧着する時、ハンドルが軽く、ガチッ！と決まる感じがする。<br>
汎用品は、ハンドルが固く、握力が必要。ガチッと決まる感じが薄い。<br><br>


汎用品タイプのクチコミ<br>
ダイスの噛み合わせが悪く、ずれている。<br>
特に1.25sqと2sqは、圧着端子の中心がずれてしまうため、仕上がった圧着端子が曲がってしまう。<br>
かしめが中央ではなく端に寄ってしまい、端子が歪み、かしめも甘くなってしまう。<br><br>


