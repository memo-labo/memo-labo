<h2>活線状態のVVFケーブルを電工ナイフで切断する方法</h2>

※電気工事会社の先輩に教えてもらった方法。<br>
本来はブレーカー落として無電圧で作業しなければ危険。<br><br>

まずVVFケーブルの中央に電工ナイフで穴を空ける。<br>
刃が向こう側に飛び出たらそのまま電工ナイフで10cmくらい切り込みを入れる。<br>
<img src="../images/denki-1-2.jpg" style="max-width:250px;" alt=""><br>
<img src="../images/denki-1-3.jpg" style="max-width:250px;" alt=""><br><br>

ペンチやニッパーを使って片方ずつ銅線を切断する。<br>
こうすることで短絡させず活線状態で切断することができる。<br>
