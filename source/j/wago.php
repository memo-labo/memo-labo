<h2>電気工事士の意見</h2>
過去の事故事例を教訓に、会社自体でワゴの使用を禁止している場合もある。<br>
また、現場によってはワゴの使用を禁止している現場もある。<br>
「屋内に限り使用、熟練度に差が出ないのでワゴの方が良い」という意見も電気工事士もいる。<br>
ワゴで接続した後で、テーブでグルグル巻にしているケースもある。<br>

