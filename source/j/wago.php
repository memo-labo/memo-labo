ＱＬＳＱ・ＱＬＭＣシリーズ<br>
一度接続した電線を抜いた場合、コネクタの再接続はできない。<br>
これは知らずにやりがち。このせいで接触が甘くなり火災事故に繋がるのかも？<br>
