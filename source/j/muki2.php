<h2>活線状態のCVケーブルを電工ナイフで切断する方法</h2>

※電気工事会社の先輩に教えてもらった方法。<br>
本来はブレーカー落として無電圧で作業しなければ危険。<br><br>

まずCVケーブルの被覆を電工ナイフで削る。<br>
中の芯線に傷をつけないように慎重に。<br>

