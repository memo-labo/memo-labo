アース線の取り付けの悪い例<br>
アース端子がドリルビスで鋼管に打たれていた。<br>
ドリルビスが管の中に飛び出しCVケーブルの被覆を傷つける可能性。<br>
空けた穴が錆びて広がり中に雨などが侵入し絶縁不良⇒地絡につながる恐れ。<br><br>

鋼管の被覆を剥いてラジアスクランプなどでボンド線を固定する。<br>
そして専用の補修塗料や防食テープ等で被覆をはがした部分の防食処理を行う。<br>
