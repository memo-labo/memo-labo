<h2>厚鋼電線管と薄鋼電線管の違い</h2>

厚鋼電線管（G管）<br>
電線管の肉厚は2.3mm～3.5mmまである。<br>
管の内外面に溶融亜鉛メッキが施されている。<br>
低圧電線だけでなく高圧や特別高圧の電線路にも適用可能。<br><br>

薄鋼電線管（C管）<br>
電線管の肉厚は1.6mm～2.0mmまである。<br>
厚鋼に比べて肉厚が薄く、耐候性が劣る。<br>
基本的に屋内で使用する。<br>
電線管の呼び径は19、25など奇数値で規定されている。<br>

<h2>ポリエチライニング鋼管</h2>
ケーブル保護用合成樹脂被覆鋼管。<br>
湿気、水気に強く錆びにくい。<br>
腐食性に強い。<br>
化学薬品に強い。<br>
一般的にポリエチレンは紫外線に弱い。<br>
