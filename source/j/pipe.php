水道管、ガス管、単管パイプなどの丸いパイプをつかんで回すためのレンチ。<br>
パイプは丸い形状なので、スパナやモンキーレンチでは回せない。<br>
パイプレンチは上あごと植歯（うえば）がパイプに食い込むので丸いパイプを回せる。<br>
調整丸ナットを指で回して上あごと植歯（うえば）をパイプに接触させる。<br>
ハンドルを押して回すことで更に締め付けが加わる構造となっている。<br>
回転方向と逆方向に軽く本体を持ち上げれば食い込みが緩む。<br>
逆方向の回転を得たい場合には、パイプレンチを逆向きに取り付ける必要がある。<br>


<h2>モンキーレンチとパイプレンチの違い</h2>
パイプレンチはパイプに食い込ませるギザギザのあごがある。<br>
モンキーレンチは締め具の平面に傷をつけないようにあごが滑らか。<br>
パイプレンチのあご同士は平行ではない。<br>
モンキーレンチのあごは互いに平行。<br><br>

