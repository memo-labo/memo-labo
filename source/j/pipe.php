<h2>パイプレンチの特殊な用途例</h2>
ユンボで土に埋め込まれた単管パイプは土との摩擦があり抜けない。<br>
パイプレンチで単管パイプを回すと土と金属パイプの縁が切れて抜けやすい。<br>
土に穴があくので、そこにアース棒を放り込んで接地工事として活用する。<br>


