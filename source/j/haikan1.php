耐候性とは？<br>
太陽光、温度、湿度、雨等の屋外の自然環境に耐えうる性質のこと。<br><br>

自己消火性とは？<br>
大気中で熱源が無くなった際に自ら消化する性質のこと。<br>
火源があると燃え続けるが、火源が無くなると燃焼が止まる。<br>
燃焼の基準となるのは、材料の燃えやすさを表す酸素指数。<br>
酸素指数とは、プラスチックが燃焼し続けるために最低限必要な酸素濃度のこと。<br>

<h2>PF管とは？</h2>
<img src="images/haikan1/2.jpg" style="max-width:400px;"><br>
<img src="images/haikan1/3.jpg" style="max-width:400px;"><br>
耐候性がある。<br>
自己消化性がある（不燃ではない）<br>
露出配管も隠蔽配管にも使用可能。<br>
PF管は、様々なカラーがあり、露出配管に最適。<br>
CD管に比べて高い。<br>
PF管でも日の当たる屋外で使うと劣化してひび割れてしまう。<br>
⇒<a href="https://twitter.com/DIYyuzo/status/1602857713679364096">劣化したPF管の画像例（Twitter）</a><br>


<h2>PFD管とは？</h2>
単層構造はPFS、複層構造はPFDと呼ぶ。<br>
高耐候２層管のPFDは、太陽光発電の引込など、直射日光が長時間当たる場所で使う。<br>
