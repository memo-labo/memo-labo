<h2>非常用照明とは？</h2>
主に天井についている。<br>
電池によって一定時間は照度が確保できる照明器具のこと。<br><br>

火災などで停電が起きた時、真っ暗の中では避難することができない。<br>
商用電源（コンセントからの電源）が失われている時は、電池を搭載した「非常用照明」で避難が可能になる。<br><br>

建築基準法施行例により、不特定多数の人々が利用する特殊建築物及び一定規模以上の建築物の住居等に設置が義務付けられている。

