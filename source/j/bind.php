注意点（ネット情報）<br>
耐圧試験の際、ケーブル同士の離隔をとるためにクレモナを使用。<br>
羽子板端子の穴の部分に紐を通して縛って離隔をとった。<br>
すると絶縁が少し悪くなったので、穴ではなく絶縁テープ部分で縛った。<br>
絶縁テープ部分で縛って離隔をとり、メガーを当てると絶縁が良くなった。<br>
