<h2>銅バインド線・鉄ソフトバインド線</h2>
太陽光パネルのPVケーブルが垂れ下がってコネクタ部分が折板屋根につかないように固定。<br>
太陽光パネルの枠アルミ部分には一定間隔で穴が空いており、そこを利用してバインド線で固定。<br>
太陽光パネルのフェンスに看板を固定するのにも、このバインド線が使える。<br>
芯線0.9mm ✕ 300m で約2400円。<br><br>

鉄バインド線は錆びてすぐ切れてしまってダメ、という意見もある。<br>
銅バインド線だったら鉄のように錆びて切れることが少ない、とのこと。<br>
銅バインド線の値段は 芯線0.9mm ✕ 300m で約6800円で鉄の約３倍。高い。<br>
