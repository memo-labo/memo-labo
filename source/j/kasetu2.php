<h2>仮設電気工事の電力契約</h2>
臨時電灯<br>
主に道路工事現場や建設工事現場などの電灯機器で電気を使用するお客さま向けのプラン。<br>
契約使用期間は１年未満。<br>
毎年一定期間を限り、繰り返し使用する場合には契約できない。<br><br>

臨時電灯A：電気機器の総容量が3kVA以下<br>
臨時電灯B：契約電流は40A、50A、60Aの中から選択可能<br>
臨時電灯C：契約容量が6kVA以上から50kVA未満まで<br><br>

※上記情報は東北電力HPより引用。

