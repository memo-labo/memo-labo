<h2>仮設ポールの建て方</h2>

穴を掘る。<br>
穴の入り口は少し大きめに。その方が穴が掘りやすい。<br>
ポールを入れる穴のへりを、斜めに切り下げて入れやすいようにしておく。<br><br>

建柱<br>
１人は穴にスコップを当てて、もう１人は柱を持ち上げる。<br>
スコップではなく木板（幅100mm、長さ500mm程度）を使うほうがいいらしい。<br>
