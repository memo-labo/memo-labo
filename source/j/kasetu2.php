<h2>仮設ポールの抜き方</h2>
まずポールを引き抜いて横に倒す方向を決める。<br>
ポールを前後左右に揺すって穴を広げる。<br>
土とポールにある程度の隙間ができたら地面に近いところにロープや帯を回して固定する。<br>
そのロープを上に引っ張りつつ、ポールをゆっくり倒していく。<br>
ポールを倒す際にも根元のほうから手で支えつつゆっくり倒していく。<br>
支えていないと最後の方でポールの底が土を押し上げ、ポールが跳ねるので危険。<br>

