<h2>給水の制御とは？</h2>
ビルや集合住宅は、いったん受水槽で給水を受けた後、屋上に設置した「高架水槽」へ水を送り、各階に配給する方式をとっている。<br>
高架水槽は、水の消費により水槽内の水位が下がると、ポンプを回して受水槽から水を補給する。<br>
また、ある水位まで水が貯まるとポンプを停止する。<br>
高架水槽では、上限と下限の間に水位を保つよう、水位の制御を行う。<br>

<h2>レベル機器とは？</h2>
電気的に液位を検出する検出器を「電極式レベルスイッチ」と呼ぶ。<br>
ビル、集合住宅の上下水道、工場、浄水場など、液面制御のために幅広く使用されている。<br>
電極に液体が接触すると、液体を通して閉回路（電気が流れる道）ができる。<br>
そこに電流が流れ、水位のレベルを検知する。<br>
液体の電極間抵抗を直接検出して、設定した抵抗値より大きいか小さいかで液面の有無を判断する。<br>
