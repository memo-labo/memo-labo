61F（フロートなしスイッチ）<br>
動作状態がひとめでわかるLED動作表示<br>
内部リレーの信頼性向上（微小負荷DC5V 1mA）によりPLC入力が可能<br>
電極側端子とその他の配線端子が分離されており配線作業が容易<br><br>

61F 使用上の注意<br>
大きな振動、衝撃がかからないように。チャタリング誤動作などの原因となる。<br>
動作時に衝撃が発生する大容量コンタクタとならべて使用しない。<br>
絶縁抵抗を測定する際、電極端子相互間のメガテストは絶対にしない。<br>
コンタクタ開閉を制御する場合、必ず自己保持電極（E2）を使用する。<br>
E1だけで制御すると、液面の波立ちによってコンタクタがバタツキ、接点が焼損する。<br>

