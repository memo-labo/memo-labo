<h2>フル2線式リモコンの負荷アドレスとは？</h2>
<img src="images/full2/5.jpg" alt="" style="width:280px;"><br>
フル2線式リモコンは、あらかじめスイッチに負荷アドレスを書き込んでおく。<br>
負荷アドレスとは、文字通りその照明回路の住所のこと。<br>
負荷アドレスとは、負荷チャンネル（丁目）と負荷ナンバー（番地）の２つで出来ている。<br>
負荷アドレスの例は、15-1、15-2、など。15の部分がチャンネルで、後ろの1、2の部分がナンバー。<br>
スイッチを押せば、決められたアドレスに信号を送り、該当する照明をON/OFFする。<br>

<h2>リレー制御盤内</h2>

<img src="images/202207061.png" style="max-width:900px;"><br>

伝送ユニット<br>
スイッチからの信号をフル２線信号線で受け取る。<br>
信号をT/U（負荷チャンネル）に送る。<br>
１台で256回路まで制御可能。<br><br>

T/U（負荷チャンネル）<br>
負荷チャンネル（丁目）が設定されている。<br>
他の負荷チャンネルにフル２線信号線で接続され、15丁目、14丁目と、丁目が振られる。<br>
各負荷チャンネルは、各リモコンリレーに対して、AC24V配線で接続される。<br><br>

<img src="images/tu1.jpg" style="max-width:300px;"><br><br>
<img src="images/tu2.jpg" style="max-width:500px;"><br><br>

リモコンリレー<br>
負荷ナンバー（番地）が割り付けられている。<br>
ON/OFF動作を実行する。<br>
照明などの負荷に接続される。<br><br>

<h2>グループ制御</h2>
任意の負荷アドレスに対してグループ分けが出来る。<br>
またそのグループに対して一括ON・OFF制御が可能。<br><br>

グループ制御の例<br>
・１フロアすべての照明２０個をすべて点灯<br>
・１フロアすべての照明２０個をすべて消灯<br>
・１フロアの左半分の照明１０個をすべて点灯<br>

<h2>パターン制御</h2>
パターン制御の例<br>
パターン名：P-1<br>
負荷アドレス 1-1 調光100%<br>
負荷アドレス 1-2 調光70%<br>
負荷アドレス 2-1 調光30%<br>


<h2>フル2線式リモコンスイッチの全体構成</h2>
負荷アドレス（スイッチ部）⇒ 伝送ユニット ⇒ T/U ⇒ リモコンリレー ⇒ 照明負荷<br>

