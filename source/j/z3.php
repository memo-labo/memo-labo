<h2>ステンレス（SUS / ステン）</h2>
<p><img src="images/z3/3.jpg" class="img-fluid" alt=""></p>
ステンレス=Stain lessSteeI（さびない鉄）<br>
磁石にくっつかない。<br>
鉄やユニクロと比べて値段が高い。<br>
電位が高く、接触している他の金属を錆びさせる働きが強い。<br>
水タンクに鉄とステンレスを混在させると、あっという間に鉄部分が電気作用で腐食する。<br>
この場合、鉄単独の方が持ちが良い。<br>
