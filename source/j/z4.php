<h2>パイラック活用法</h2>
L型アングルにパイラックを固定。<br>
パイラックの穴を利用してＢ種接地線をインシュロックで固定。<br>
<img src="images/pl1.jpg" style="max-width:400px;" alt=""><br><br>

ハゼ式折板屋根にパイラックを数個固定。<br>
そのパイラックに針金を用いてテントのようにしてアンテナを固定。<br>

