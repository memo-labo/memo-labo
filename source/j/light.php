<ul>
    <li>三相交流電源により3灯を各相で点灯する<br>
    <li>放電灯に電球を混光して照明する<br>
    <li>2灯用フリッカレス安定器で点灯する<br>
    <li>高周波点灯回路もしくは直流点灯回路を用いる<br>
</ul>

