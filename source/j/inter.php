<h2>ネット通信</h2>
配線：親機LAN端子⇒ルーター（有線/無線）⇒センサーカメラ<br>
無線ルーターの場合､ドアホン親機との間を無線LANで接続することもできる。<br>
ルーターはグローバルIPアドレスが付与され、UPnP対応のものが必要。<br><br>

UPnP=Universal Plug and Play（ユニバーサル・プラグ・アンド・プレイ）の略<br>
同じネットワーク上にあるデバイス同士の接続を簡単に行うためのツール。<br>
ネットワークがハッキングされる恐れもある。<br>

