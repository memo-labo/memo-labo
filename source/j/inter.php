<h2>弱電配線工事の注意点</h2>

ドアホンへの配線材を分岐して使用してはいけない。<br>
複数台のモニター（ドアホン親機、増設モニター）接続時は、２芯線を使用してそれぞれ配線する。<br>
４芯線などを使用してまとめて配線しない。誤作動の原因となる。<br><br>


