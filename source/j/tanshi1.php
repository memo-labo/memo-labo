<h2>丸端子の材質</h2>
材質はJST独特の無酸素銅。<br>
導電率・ネバりの点で優れている。<br>
電気的、機械的にも優れている。<br>
JSTの標準品種は「防蝕性のよい電気すずめっき」されている。<br>
めっきの定着性が良く、電気抵抗が低く、防蝕性能が改善される。<br><br>

真鍮（黄銅）<br>
銅と亜鉛の合金で、特に亜鉛が20%以上のもの。<br>
最も一般的な黄銅は、銅65%、亜鉛35%。<br>
銅と亜鉛の割合によって物性が変化する。<br>
<a href="https://memo-labo.com/shield.php">ケーブルシースアース</a>のブラケットのネジ止めに使われる。<br>
身近なものでは、五円硬貨の材質として使用されている。<br>

