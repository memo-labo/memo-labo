ボルトを締めることでボルト本体には引張力が働く。<br>
部材には圧縮力が働く。<br>
この２つの力で摩擦抵抗が生まれる。<br>
ボルトの締め付けによって発生する力をボルトの「軸力」と呼ぶ。<br><br>

<h2>締めたボルトが緩む原因</h2>

振動や衝撃によってボルトが徐々に回転して緩む。<br><br>

ゆるみ実験の結果<br>
・皿ばね座金⇒効果あり<br>
・食い違い型ばね座金⇒効果なし<br><br>

