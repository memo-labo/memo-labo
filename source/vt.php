<h2>VTと電力用変圧器との違い</h2>
１．測定誤差を小さくするために巻線の電気抵抗や磁束の漏れを小さくしている<br />
２．二次側に電流をあまり流す必要がないので小容量<br />

<h2>VTの注意点</h2>
VTは、計器用変圧器(VT)の二次側を短絡させてはいけない。<br />
VT二次側を短絡させると、VT二次巻線に過大電流が流れ、VT二次巻線が焼損する可能性がある。<br />
すると、VT一次巻線と二次巻線の間で絶縁破壊を起こし、VTを介して高圧地絡や相間短絡に至る場合がある。<br />

<h2>VTの接地工事</h2>
VT本体の接地：A種接地<br>
VT２次側の接地：D種接地<br>
低圧用VT：接地工事不要（詳細は電気設備技術基準の解釈第13条参照）<br>

<h2>継電器の制御用電源として使用</h2>
VT２次側電圧の利用例<br>
・UVR（不足電圧継電器）の電源回路P1P2端子へ<br>
・GRの制御電源P1P2端子へ<br>
VTの容量は50VA～200VAと小さいが、UVRやGRなどの継電器の制御電源は2VA～10VAとさらに小さいので対応が可能。<br>

<h2>VT１次側（高圧側）のヒューズ</h2>
通常は定格電流1A・遮断電流40kA程度。<br>
過負荷による焼損防止が目的ではない。<br>
計器用変圧器の絶縁破壊や端子短絡時に計器用変圧器を主回路から切り離す事が目的。<br>

<h2>VT２次側（低圧側）のヒューズ</h2>
通常はガラス管ヒューズが使用される。<br>
計器用変圧器の制限負荷を考慮して選定される。<br>
制限負荷＝計器用変圧器の温度上昇が規定値を超えることなく使用できる最大負荷。<br>
モールド形の場合、定格負担の２～３倍程度。<br><br>

VT２次側のヒューズは、VT２次側の接地より、下流にする。<br>
接地よりヒューズが上流にあると、ヒューズが切れた際にVT２次側の接地が切り離されてしまう。<br>

