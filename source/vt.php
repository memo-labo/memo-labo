<h2>VTの仕組み</h2>
<img src="images/vt1.svg" style="max-width:500px;" alt="VT 計器用変圧器の原理"><br>

基本原理は変圧器と同じ。<br>
一次巻線に交流電圧を印加すると鉄心に交流磁束が生じ、その磁束によって二次巻線に電圧が誘起される。<br><br>

巻数比によって高圧側の電圧を二次側の低い電圧へ変成し、計器・継電器へ入力する。<br>

<h2>VTを使う理由</h2>
6.6kVなどの高電圧を計器や継電器へ直接入力せず、安全に扱いやすい低い電圧へ変成するため。<br><br>

主な用途<br>
・高圧電圧計の測定入力<br>
・UVR（不足電圧継電器）の電圧検出<br>
・保護継電器・制御回路の電源<br>
・電力量計・電力計などの計測入力<br><br>

VTは計測精度を重視して設計され、接続する計器・継電器の合計負担が定格負担を超えないように選定する。<br>
定格負担・制限負荷は機種ごとに異なるため、銘板・仕様書で確認する。<br>

