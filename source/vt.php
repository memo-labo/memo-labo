<h2>VTの接地</h2>
VT本体の金属外箱や二次回路には、設備区分・使用電圧・適用規格に応じた接地が必要になる。<br>
高圧受電設備では、VT本体と二次回路の接地方式を単線結線図・設計図・電気設備技術基準の解釈などで確認する。<br><br>

特に二次回路の接地点とヒューズの位置関係は重要。<br>
ヒューズ溶断によって二次回路の接地まで切り離される構成になっていないか確認する。<br>

<h2>継電器の電圧入力・制御電源として使用</h2>
VT二次側電圧の利用例<br>
・UVR（不足電圧継電器）の電圧入力・制御回路<br>
・GRなど保護継電器の制御電源<br>
・電圧計・電力計・電力量計<br><br>

接続する機器の負担VAを合計し、VTの定格負担以内であることを確認する。<br>

<h2>VT一次側（高圧側）のヒューズ</h2>
VT一次側には高圧ヒューズが設けられる構成がある。<br>
目的は、VT内部故障や端子部短絡などが主回路事故へ拡大するのを抑えること。<br><br>

ヒューズの定格電流・遮断容量はVTと設備仕様に合わせて選定されるため、一律の値ではなく銘板・設計図・メーカー仕様を確認する。<br>

<h2>VT二次側（低圧側）のヒューズ</h2>
二次回路にもヒューズが使用される構成がある。<br>
計器・継電器の配線短絡などから二次回路を保護する。<br><br>

二次側の接地点とヒューズの配置によっては、ヒューズ溶断時に接地が失われるおそれがあるため、回路図で位置関係を確認する。<br>

