<h2>VTの位置 VCBの電源側 or 負荷側</h2>
VTがVCBより上流（電源側）にある場合<br>
VCBが開放されてもVTには電圧印加されている。<br>
VCB開放状態であっても電圧メーターの確認ができる。<br><br>

VTがVCBより下流（負荷側）にある場合<br>
VCBが開放されるとVTには電圧が印加されない。<br>
VCB開放状態となると電圧メーターで電圧確認ができない。<br><br>

VTがVCBより上流かつVTにて相間短絡が発生した場合<br>
もしPASやUGSの区分開閉器でSO動作による短絡保護があれば、波及事故には至らない。<br>
しかしモールドジスコンやピラージスコンなどSO保護ができない場合、波及事故に至る。<br><br>

予想として、PASやUGSなどの区分開閉器がない需要家の場合、VTをVCBより２次側に設置し、<br>
VCBとGR・OCRを組み合わせる事で、波及事故の発生を防いでいるのかもしれない。<br>


<h2>インバータ回路二次側でのVT使用禁止</h2>
インバータ回路の二次側の電圧波形は方形波（矩形波）となる。<br>
VT二次出力波形はパルス状波形となり正規な電圧が出力されない。<br>
鉄心の磁気飽和により焼損事故に至る可能性がある。<br>
計測したい場合、二次側についてはダイレクトに計測する。<br>


