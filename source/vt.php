<h2>VT 計器用変圧器とは？</h2>
<img src="images/vt1.jpg" style="max-width:700px;"><br><br>


■VTの仕組み<br>
<img src="images/vt1.svg" style="max-width:500px;"><br><br>

鉄心１つと巻線２つから出来ている。<br>
入力側の１次コイルに6.6kVの交流電圧を流す。<br>
すると鉄心の中に磁束が発生する。<br>
発生した磁束は鉄心を通って２次側のコイルに交わる。<br>
２次側コイル内を通過する磁束が変化すると２次側コイルに電圧が発生（電磁誘導作用）<br>
２次側に電圧が誘導される（誘導起電力：磁束が変動する環境下に存在する導体に電位差が生じる現象）<br><br>

■VTを使う理由<br>
6.6kV高圧回路から制御回路に使用しやすい電圧（主にAC110V）に降圧する。<br>
低圧にする理由は、高電圧のままでは計器類や配線など、取り扱いが難しいため。<br>
高圧電圧計の計測用、DGR保護継電器の制御電源、UVRの電圧検出用として使用する。<br>
VTの二次側に電流をあまり流す必要がないので小容量。<br />
一般的に定格負担（VA）は、50VA～200VA程度。<br />
VTは、かつてはPT(Potential Transformer)とも呼ばれていた。<br /><br>

■VTと変圧器の違い<br>
定格負荷以内だと、変圧比の精度が普通の変圧器よりも良い。<br>
定格負荷の2～4倍程度まで耐えることができる。（例：定格50VA / LOAD LIMIT 200VA）<br>
VTはコア（鉄芯）に流れる磁束密度を低く設計してあるらしい。<br>
これは位相差や非誤差を少なくして計器の精度を上げるため。<br>

