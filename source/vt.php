<h2>VT（計器用変圧器）とは？</h2>
VT（Voltage Transformer）は、高圧回路の電圧を計器・保護継電器で扱える低い電圧へ変成するための計器用変成器。<br>
以前はPT（Potential Transformer）と呼ばれることも多かった。<br><br>

6.6kV回路では、二次側を110Vなどの標準的な計器用電圧として使用する例がある。<br>
高圧電圧計、電力計、UVRなどの電圧入力・制御電源などに利用される。<br><br>

