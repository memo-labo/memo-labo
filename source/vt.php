<h2>VTの位置：VCBの電源側か負荷側か</h2>
VTの設置位置によって、VCB開放時に電圧計・継電器へ電圧が残るかどうかが変わる。<br><br>

<strong>VCBより電源側にVTがある場合</strong><br>
VCBを開放してもVT一次側には受電電圧が印加される。<br>
そのためVCB開放状態でもVT二次側の電圧を利用できる。<br><br>

<strong>VCBより負荷側にVTがある場合</strong><br>
VCBを開放するとVT一次側が無電圧となり、二次側電圧もなくなる。<br><br>

どちらが正しいというものではなく、保護方式・計測目的・事故時の切り離し範囲によって決まる。<br>

<h2>インバータ出力側でVTを使う場合の注意</h2>
インバータ出力は商用正弦波と異なり、PWM波形や高調波成分を含む。<br>
一般の商用周波数用VTをそのまま接続すると、正しい測定値が得られない、発熱・磁気飽和などが生じる可能性がある。<br><br>

インバータ出力を測定する場合は、インバータ波形・周波数に対応した計測器やメーカー指定の方法を使用する。<br>

<h2>VT点検時の確認ポイント</h2>
・一次・二次の定格電圧と変圧比<br>
・定格負担と接続負担VA<br>
・一次・二次ヒューズの状態<br>
・二次回路の接地点<br>
・端子の緩み、変色、過熱跡<br>
・VCBとの位置関係と無電圧範囲<br>
・二次側を短絡させない<br>

