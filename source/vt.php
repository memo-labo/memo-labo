<h2>VTと電力用変圧器の違い</h2>
どちらも電磁誘導を利用する変圧器だが、目的が異なる。<br><br>

<table>
<tr><th>項目</th><th>VT</th><th>電力用変圧器</th></tr>
<tr><td>主目的</td><td>計測・保護・制御用の電圧変成</td><td>負荷へ電力を供給</td></tr>
<tr><td>容量</td><td>比較的小さい</td><td>負荷容量に応じて大きい</td></tr>
<tr><td>重視する点</td><td>変比誤差・位相誤差・計測精度</td><td>効率・容量・温度上昇など</td></tr>
</table>

<h2>VTの重要な注意点：二次側を短絡しない</h2>
VT二次側を短絡すると、二次巻線へ大きな電流が流れて巻線や配線を焼損するおそれがある。<br>
VTはCTとは逆に、<strong>二次側短絡が危険</strong>と覚えると整理しやすい。<br><br>

・VT：二次側を短絡させない<br>
・CT：二次側を開放させない<br><br>

