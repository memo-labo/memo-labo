<h2>反相とは？</h2>
モータは一度設置してしまえば相順が逆になることはほぼない。<br>
なので反相要素は不要な場合が多い。<br>
電圧検出の場合、モーター起動前に検出できるが、配線が増える。<br>
電流検出はモータの電流相順を直接監視できて配線を減らせるが起動後でないと確認できない。<br><br>

反相要素が必要なもの<br>
移動用電源のモータなどの理由で接続を変更する頻度が高い場合。<br><br>

モータに流入する電流は本来、正弦波のはず。<br>
しかし水中モータや古いものは、動作が正常でも電流波形が極端に歪んでいるものがある。<br>
モータの電圧波形は一般に歪みが少ない。<br>
反相要素は動作が早いので電流方式だと誤動作の可能性がある。<br>

<h2>カレント・コンバータ</h2>
検出装置には穴が３つ空いている。<br>
ここに低圧動力負荷、R・S・Tをくぐらせる。<br>

<img src="images/3e3.jpg" style="max-width:400px;"><br>

カレント・コンバータの構成要素<br>
①モータ電流をトランジスタ回路で使用しやすい大きさの電流に変換する変流器。<br>
②その変流器二次電流を三相全波整流するダイオード。<br>
③その整流された電流を直流電圧に変換する抵抗器。<br><br>

内蔵されたタップを変更することで抵抗値を変えることができる。<br>
するとモータ電流の広い範囲で使用が可能となる。<br><br>

例<br>
モータ電流：80A<br>
カレント・コンバータ：出力電圧21V<br>
抵抗器：600Ω<br><br>

40A・21V⇒1200Ω<br>
20A・21V⇒2400Ω<br><br>

抵抗値を変更することでカレント・コンバータの出力電圧は常に21Vになる。<br>
モータ・リレー本体が21Vで動作する場合、タップ変更（抵抗値変更）で20A、40A、80Aのいずれでも動作するようにセットできる。<br><br>

カレント・コンバータにモータ電源線を２回巻いた時<br>
モータ電流10Aが流れるとカレント・コンバータからみると20A流れているようにみえる。<br>
すると3Eで20A動作整定タップであっても10Aで動作させることができる。<br>
例えば4回巻いた場合、5A ✕ 4ターン = 20Aになるので試験電流5Aで動作させることができる。<br>

<h2>使用頻度過多（インチング）</h2>
3Eリレーの中には「使用頻度過多」という要素を持つものがある。<br>
ポンプの始動・停止の頻度の回数が異常に多いとポンプの羽根車や軸受に負担がかかる。<br>
これを繰り返すとモーター焼損に至る。<br>
この保護目的でポンプを停止させる機能のこと。<br><br>

使用頻度過多の保護例<br>
・チャタリング運転防止の機能<br>
・定格電流の80%以上で1秒以上運転した場合<br>
・それが30±10秒以内に10回繰り返すと10回目に3Eリレーが動作<br><br>

