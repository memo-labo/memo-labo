<h2>①過負荷要素（過電流要素・時間要素）</h2>
モータが過負荷で過電流が長時間流れるとモータは焼ける。<br>
誘導電動機は一般的に起動時に500％程度の過電流が数秒～数十秒の間流れる。<br>
過電流をただちに検出してモータ電源をしゃ断するとモーターは動かない。<br>
誘導電動機の起動時はリレー不動作としたい。<br><br>

過電流要素<br>
モータに流れている電流が定格値を超えているかどうかを検出<br><br>

時間要素<br>
過電流の大きさと継続時間を考慮してリレーを動作させる<br>
モータの起動時間内であれば動作しないようにするため<br><br>

モータ自身は過電流が流れてもすぐに焼けるわけではない。<br>
なので「反限時特性」を採用した方が運転効率が良い。<br>
※大きな電流が流れた場合は早く動作し、小さな電流だと長い時間で動作する特性<br><br>

■モータの過熱特性と保護曲線<br>
モータリレーの保護曲線 < モータの過熱特性（I^2t）であれば良い。<br>


