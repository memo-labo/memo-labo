<h2>短絡接地器具とは？</h2>

<p><strong>短絡接地器具（アースフック）は、高圧・特別高圧の停電作業で、誤通電・誘導・混触などによる感電を防ぐために電路を短絡接地する安全器具です。</strong></p>

<img src="images/tanraku1.gif" alt="短絡接地器具の例"><br>

<p>停電したように見える電路でも、残留電荷・誘導電圧・誤送電などで再び電位が生じる可能性があります。そのため、開路しただけで安全とは判断しません。</p>

<h2>労働安全衛生規則 第339条のポイント</h2>

<p>停電作業では、開路後に次の措置が求められています。</p>

<ul>
  <li>開閉器の施錠、通電禁止表示、または監視人の配置</li>
  <li>ケーブル・コンデンサなど残留電荷のおそれがある電路の確実な放電</li>
  <li>高圧・特別高圧では検電器具による停電確認</li>
  <li>誤通電・混触・誘導による感電を防ぐため短絡接地器具で確実に短絡接地</li>
</ul>

<p>また復電時は、作業者に感電危険がないことと、<strong>短絡接地器具を取り外したことを確認してから</strong>通電する必要があります。</p>

<h2>基本的な安全の考え方</h2>

<p>短絡接地は、単なる「放電作業」ではなく、作業中の電路を安全電位に保つための措置です。</p>

<p>現場では、作業手順書・設備構成・接地器具メーカーの取扱説明書に従い、次の確認を行います。</p>

<ul>
  <li>開路・施錠・通電禁止表示</li>
  <li>適切な検電器で無電圧確認</li>
  <li>残留電荷の安全な放電</li>
  <li>指定された位置への短絡接地</li>
  <li>作業終了後の器具取り外し・員数確認</li>
</ul>

<p><strong>具体的な取付順序や操作方法は設備・器具によって異なるため、現場の標準作業手順を優先します。</strong></p>

<h2>短絡接地器具で直接大きな残留電荷を放電しない</h2>

<p>短絡接地器具には、放電棒のような電流制限抵抗を持たないものがあります。残留電荷が大きい電路へいきなり接続すると、アークや大きな放電電流が発生するおそれがあります。</p>

<p>ケーブルやコンデンサなど残留電荷が想定される設備は、<strong>メーカー・作業手順で指定された安全な放電方法を先に実施</strong>してから短絡接地します。</p>

<h2>自作・代用品を使わない</h2>

<p><strong>短絡接地器具は自作やブースターケーブルなどの代用品ではなく、対象電圧・想定短絡電流・接続部に適合した専用品を使用します。</strong></p>

<p>事故時には大きな短絡電流が流れる可能性があるため、導体断面積、端子強度、接続金具、絶縁・機械強度などが安全上重要です。</p>

<h2>使用前点検</h2>

<p>労働安全衛生規則では、短絡接地器具について使用開始前に取付金具および接地導線の損傷の有無を点検することが定められています。</p>

<ul>
  <li>接地導線の断線・素線切れ</li>
  <li>被覆の損傷</li>
  <li>クランプ・接続金具の変形や腐食</li>
  <li>圧着部・ボルト部の緩み</li>
</ul>

<h2>復電時の取り外し忘れ防止</h2>

<p>短絡接地器具を取り付けたまま復電すると重大な短絡事故になります。</p>

<p>⇒<a href="tanraku_jiko.php">アースフックの取り外し忘れによる短絡事故</a></p>

<p>復電前は、作業責任者による確認、器具の員数確認、作業者退避、施錠・表示解除の確認などを標準手順に組み込みます。</p>

