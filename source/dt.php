<h2>ダブルスロー（DT）とは？</h2>
ダブルスロー = DT（Double Throw）<br>
双投形電源切替開閉器。DTMC（Double Throw Magnetic Contactor）と呼ばれることもある。<br>
商用電源と非常用発電機電源など、2つの電源を切り替えるための装置。<br><br>

主な動作例<br>
・商用電源が停電 ⇒ 非常用発電機電源へ切替<br>
・商用電源が復電 ⇒ 非常用発電機電源から商用電源へ切替<br><br>

ダブルスローによる切替は無瞬断ではなく、切替時に瞬断を伴う。<br>
無瞬断が必要な負荷には、UPSなど別の対策が必要。<br>

