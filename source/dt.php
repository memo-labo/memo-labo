<h2>ダブルスローとは？</h2>
ダブルスロー = DT（Double Throw）<br>
双投形 電源切替開閉器<br>
DTMC（Double Throw Magnetic Contactor）とも呼ばれる。<br>
２つの電源を切り替えるための装置。<br><br>

動作例<br>
・商用電源⇒停電⇒非常用発電機電源に切り替え<br>
・非常用発電機電源⇒復電⇒商用電源に切り替え<br><br>

無瞬断の切替ではなく、瞬断を伴うので、無瞬断で切り替えたい場合には、下部にUPSが必要。

<h2>ダブルスロー 発電負荷⇒商用負荷 切替時に瞬時停電</h2>
非常用発電機から電力が供給されているエレベーター等で、商用電源の復電により、ダブルスローが発電負荷⇒商用負荷に切り替わるとき、一瞬停電が起こる。<br><br>

その場合、非常系で動いていたエレベーターは一旦停止し、その後、再び商用電源からの電力供給で動作をする。

<h2>ダブルスロー 回路図</h2>

<p>
27の方が商用電源、84の方が非常用発電機電源。<br />
商用電源が生きてると、27に電圧が印加され、27のa接点が閉じ、右隣のb接点が開く。<br />
その結果、A1-A2に電圧が印加され、B1-B2には印加されない。<br /><br />

商用電源が切れると、27に電圧がなくなり、27のa接点が開き、右隣のb接点が閉じる。<br />
その結果、B1-B2に電圧が印加され、A1-A2には印加されない。<br />
</p>


<h2>ダブルスローの切替時間</h2>
「商用」から「発電」に切り替わる時間は約10～20秒<br>
「発電」から「商用」に切り替わる時間は約1～2秒<br><br>

商用から発電に切り替えるには、<br>
商用停電確認⇒発電機始動⇒電圧確立という一連の流れがあり、時間を要する。<br>
発電から商用への切り替えは、商用側の電圧が確認できればすぐに切り替えることができる。<br>

<h2>ダブルスローの配置と意味</h2>

<h3>① 低圧非常用発電機の中</h3>
ダブルスローが低圧非常用発電機の中にあるタイプ。<br>
主にキュービクル内の非常系MCCBをOFFにして、商用電源の停電状態を作り、非常用発電機を起動させる。<br>
発電機内部では、ダブルスロー周辺が赤い障壁で囲まれていることが多い。<br><br>

<h3>② キュービクルの中</h3>
ダブルスローがキュービクル内にあるタイプ。<br>
動力変圧器二次側で27（不足電圧）を検出している場合、LBSまたはVCBを開放して商用電源の停電状態を作り、非常用発電機を起動させる。<br>
この構成ではスコットトランスも一緒に設置され、非常用動力負荷だけでなく、非常用電灯負荷への電源供給も用意されていることが多い。<br><br>

<h3>③ 別の低圧配電盤の中</h3>
屋内電気室＋屋外配電盤のような構成で見かけるタイプ。<br>
機能としては、キュービクル内にダブルスローがある②の構成とほぼ同じ。<br><br>

②・③の構成では、消火設備だけでなくエレベーター（ELV）の非常電源も絡んでいる場合があるので注意が必要。<br>
非常用発電機の起動・停止試験を行う際、ELVを鍵などで停止していないと、電源の切替に合わせてELVが停止・起動を繰り返す場合がある。<br>
試験前に、非常電源で動作する負荷と切替時の影響範囲を確認しておく。<br><br>

DTが非常用発電機の中にあるタイプ<br>
