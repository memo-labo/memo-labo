<h2>月次点検で非常用発電機のMCCBがONのまま手動起動するとどうなる？</h2>

月次点検で非常用発電設備の起動試験を行う際、非常用発電機内部にある出力用MCCBを切らずに起動させてしまった。どうなる？<br><br>

回路図<br>
・発電機⇒発電機内MCCB⇒発電機内DT⇒非常用負荷<br>
・商用電源⇒動力トランス⇒QB内MCCB⇒発電機内DT⇒非常用負荷<br><br>

商用側は停電しないので27動作せずDTは商用側のまま？<br>
この場合、発電機を手動で起動されても何も起きない？<br><br>

実例<br>
まれに商用受電状態なのに発電側に切り替わってしまう発電機もある。<br>
病院において、非発の電圧確立だけで院内設備が停電モードに切り替わる現場もあったらしい。<br>

