ダブルスローは、設備によって設置場所が異なる。<br>
よくある配置は次の3パターン。<br><br>

<h3>① 低圧非常用発電機の中</h3>
ダブルスローが低圧非常用発電機の中にあるタイプ。<br>
主にキュービクル内の非常系MCCBをOFFにして商用電源の停電状態を作り、非常用発電機を起動させる。<br>
発電機内部では、ダブルスロー周辺が赤い障壁で囲まれていることが多い。<br><br>

<img src="images/dt3.jpg" style="max-width:800px;"/><br><br>

<h3>② キュービクルの中</h3>
ダブルスローがキュービクル内にあるタイプ。<br>
動力変圧器二次側で27（不足電圧）を検出している場合、LBSまたはVCBを開放して商用電源の停電状態を作り、非常用発電機を起動させる。<br>
この構成ではスコットトランスも一緒に設置され、非常用動力負荷だけでなく、非常用電灯負荷への電源供給も用意されていることが多い。<br><br>

<img src="images/dt4.jpg" style="max-width:800px;"/><br><br>

<h3>③ 別の低圧配電盤の中</h3>
屋内電気室＋屋外配電盤のような構成で見かけるタイプ。<br>
機能としては、キュービクル内にダブルスローがある②の構成とほぼ同じ。<br><br>

<h3>設置場所による考え方</h3>
例えば電気室が地下、非常用発電機が高層階や屋上にある場合、ダブルスローが発電機内にあると、電気室から発電機まで低圧CVケーブルを長距離引く必要がある。<br>
その分、ケーブル費用・施工性・電圧降下の検討が必要になる。<br><br>

一方、非常用発電機から供給する負荷盤が発電機の近くにある場合は、ダブルスローを発電機側に置く構成も考えやすい。<br>
設備全体の配置によって、ダブルスローの設置場所は変わる。<br><br>

<img src="images/dt5.png" style="max-width:800px;"/><br>

<h2>DTと非常用発電機で起動・切替条件が異なる場合</h2>
ダブルスローが非常用発電機の内部ではなく、キュービクルや別の低圧配電盤に設置されている設備では、DTの切替条件と非常用発電機の起動・停止条件が同じとは限らない。<br><br>

例えば、次のような構成がある。<br>
・DTの商用／非常切替：上流VCBの入・切による停電／復電を検出<br>
・非常用発電機の起動・停止：DTより下流にあるMCCBの入・切による停電／復電を検出<br><br>

このように検出している場所が異なる場合、MCCBだけを切って発電機を起動させても、DT側では商用電源が生きていると判断して非常側へ切り替わらないことがある。<br>
反対に、VCBだけを切った場合に発電機の起動信号まで成立するかどうかも、制御回路の構成によって異なる。<br><br>

そのため、起動・停止試験の前に単線結線図や制御回路図を確認し、<br>
・DTはどこの電圧・接点を見て切り替わるのか<br>
・非常用発電機はどこの電圧・接点を見て起動・停止するのか<br>
・VCB、MCCB、27、不足電圧リレーなどがそれぞれどう連動しているのか<br>
を把握しておく。<br><br>

DTと非常用発電機を一連の設備として起動・切替・復電まで確認する試験では、両方の条件が成立する操作点を選ぶ必要がある。<br>
上記のように上流VCBの入・切でDTと発電機の両方の条件を成立させられる設備であれば、VCBを操作して実際の停電・復電に近い流れで確認する。<br><br>

ただし、設備によってシーケンスやインターロック、非常負荷への影響範囲は異なる。VCBを操作する前に、停電範囲、発電機起動条件、DT切替条件、エレベーター・防災設備などの連動を確認してから試験する。<br>

<h2>切替時の瞬時停電</h2>
ダブルスローは無瞬断切替ではないため、非常用発電機電源から商用電源へ戻るときにも一瞬停電する。<br>
非常系で運転していたエレベーターなどは、一旦停止したあと、商用電源からの供給で再び動作する場合がある。<br><br>

切替時間の目安として、<br>
・商用 ⇒ 発電：停電検出、発電機始動、電圧確立を経るため時間がかかる<br>
・発電 ⇒ 商用：商用側の電圧復帰を確認後に切り替わるため比較的短い<br>
という違いがある。<br>

<h2>非常用発電機の試験時に注意する負荷</h2>
②キュービクル内、③別の低圧配電盤内にダブルスローがある構成では、消火設備だけでなくエレベーター（ELV）の非常電源も絡んでいる場合がある。<br><br>

非常用発電機の起動・停止試験を行う際、ELVを鍵などで停止していないと、電源の切替に合わせてELVが停止・起動を繰り返す場合がある。<br>
試験前に、非常電源で動作する負荷と切替時の影響範囲を確認しておく。<br>

<h2>模擬負荷試験とダブルスロー</h2>
ダブルスローが発電機内にある場合、非常用発電機の模擬負荷試験で負荷試験機を接続しにくい構成になることがある。<br>
試験前に、発電機出力・MCCB・ダブルスロー・非常負荷の接続関係を確認しておく。<br>

<h2>月次点検で非常用発電機を手動起動するときの注意</h2>
月次点検で非常用発電設備の起動試験を行う場合、発電機内部の出力用MCCBやダブルスローの状態を確認してから起動する。<br><br>

回路例<br>
・発電機 ⇒ 発電機内MCCB ⇒ 発電機内DT ⇒ 非常用負荷<br>
・商用電源 ⇒ 動力トランス ⇒ QB内MCCB ⇒ 発電機内DT ⇒ 非常用負荷<br><br>

通常は商用側が生きていれば27が商用電源を検出しているため、発電機を手動起動しただけでは非常側へ切り替わらない構成が多い。<br>
ただし、設備によって制御回路や切替条件が異なるため、発電機の電圧確立だけで停電モードや非常運転モードへ移行する設備もある。<br><br>

病院・ビルなどでは、エレベーターや防災設備など他設備との連動もあるため、試験前に切替条件と影響範囲を確認する。<br>

