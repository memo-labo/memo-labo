例えば電気室が地下、非常用発電機が10階建てビルの屋上にある場合。
ダブルスローが非常用発電機の中にあると、電気室から屋上まで、低圧用CVケーブルを引っ張らなければならない。<br>
すると低圧CVケーブルが長くなり、費用が高くなり、施工が難しく、電圧降下も検討の必要がある。<br>
なので電気室内にダブルスローを設置すれば、電気室から発電機までの低圧ケーブルを節約できる。<br><br>

また、非常用発電機から供給する負荷の盤が、非常用発電機から距離が近くにある場合。<br>
例えば非常用発電機が屋上にあり、そこから供給される盤も屋上にあるような場合。<br>
この場合にはダブルスローは非常用発電機内にあった方が良い。<br>

