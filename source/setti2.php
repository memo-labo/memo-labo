<h2>単独接地か共用接地かを調べる方法</h2>
既設設備で接地系統を確認するときは、図面・接地端子盤・接地線の行先を優先して確認する。<br><br>

停電・無電圧を確実にしたうえで接地端子盤を切り分け、導通や抵抗を測定する方法もあるが、測定値だけで「この接地極は同一」と断定しない。<br>
大地を介した並列経路、鉄骨、配管、ケーブルシースなどで導通が見えることがある。<br><br>

確認の優先順位<br>
1. 単線結線図・接地系統図<br>
2. 接地端子盤の表示<br>
3. 接地線の物理的な行先<br>
4. 停電時の導通・抵抗測定<br>
5. 必要に応じて接地極を切り離した個別測定<br>

<h2>連接接地とは？</h2>
連接接地は、個別に設けた接地極・接地設備を連接線で電気的に接続する方法。<br>
例として、PAS側の接地設備とキュービクル側の接地設備を連接する構成などがある。<br><br>

ただし、零相電流・零相電圧を使う保護回路では、接地線の取り回しや多点接地が測定・保護動作へ影響する場合があるため、SOG・DGR・ZCTなどとの関係も確認する。<br>

