<h2>工作物の金属体を利用した接地工事</h2>
現行の電気設備技術基準の解釈 第18条では、鉄骨造・鉄骨鉄筋コンクリート造・鉄筋コンクリート造の建物の金属体を接地極として利用する場合の条件が定められている。<br><br>

重要なポイント<br>
・構造体を相互に電気的に接続する<br>
・等電位ボンディングを行う<br>
・地絡時の接触電圧を考慮する<br>
・A種・B種として使う場合は追加条件を満たす<br>
・接地線の太さ・施設方法も別途確認する<br><br>

最新条文：<a href="https://www.meti.go.jp/policy/safety_security/industrial_safety/law/files/dengikaishaku.pdf">経済産業省 電気設備の技術基準の解釈</a><br>

<h2>共用接地を見るときのポイント</h2>
・接地抵抗値だけで共用可否を判断しない<br>
・A/B/C/Dそれぞれの接地目的を確認する<br>
・B種を含む場合は混触時の電位上昇・故障電流を確認する<br>
・ELB保護回路と非保護回路の接地共用に注意する<br>
・鉄骨利用では等電位ボンディングと接触電圧を確認する<br>
・SOG、DGR、ZCTなど零相回路の多点接地にも注意する<br>

