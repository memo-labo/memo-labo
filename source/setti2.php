<h2>ELB保護回路と非保護回路の接地共用</h2>
漏電遮断器で保護されている回路と、保護されていない回路の機器接地を無条件に共用すると、非保護回路で地絡したときに共通接地線を通じて他の機器外箱へ危険電圧が現れるおそれがある。<br><br>

内線規程を引用したメーカー技術資料では、ELB保護回路と非保護回路の接地線・接地極は共用しないことを基本とし、低抵抗接地極を使用する場合などの例外が示されている。<br><br>

