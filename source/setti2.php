<h2>共用接地</h2>
<img src="images/setti21.png" alt="" style="max-width:250px;"><br><br>
共用接地とは、各種接地工事の接地線を、共通の接地極につなぐ接地工事のこと。<br>
総合接地抵抗値が10Ω以下の場合、A種、C種、D種は、共用とすることができる。<br>
ただし<a href="b.php">B種接地</a>を共用にした場合、短絡電流と同じ電流が流れてしまうため、単独とするほうが良い。<br><br>

単独接地と共用接地の見分け方<br>
・停電時、接地端子盤にて極側と機器側をすべて切り分ける<br>
・A種とB種の極側をテスターで抵抗測定<br>
・0.1Ω程度であればほぼ直結<br>
・1Ω未満であれば金属的な繋がり<br>
・1Ω以上の場合、単独の可能性<br>
（※新設の現場や古いビル等で実験の余地あり）<br>

<h2>内線規程　1350-13　接地線及び接地極の共用の制限</h2>
<a href="elb.php">漏電遮断器（ELB）</a>で保護されている電路と、保護されていない電路に施設される機器などの接地線及び接地極は共用しないこと。
ただし、2Ω以下の低抵抗の接地極を使用する場合は、この限りではない。<br><br>
※共用接地が2Ω以下であった場合、ELCB用の接地も統合できる。


<h2>連接接地</h2>
連接接地とは、個別に施設した各種接地極の接地線を、連接線で接続する接地工事のこと。<br>
連接接地の例：PASのA種接地と、キュービクルのA種接地を連接接地<br><br>
