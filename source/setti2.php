<h2>C種・D種の接地抵抗値</h2>
電気設備技術基準の解釈では、原則として、<br><br>

・C種接地工事：10Ω以下<br>
・D種接地工事：100Ω以下<br><br>

とされている。<br>
低圧電路で地絡時に0.5秒以内に自動遮断する装置を施設する場合は、C種・D種とも500Ωまで緩和される規定がある。<br><br>

接地抵抗値だけで共用可否を決めるのではなく、接地工事を要求する各条項・設備条件を合わせて確認する。<br>

<h2>建築構造体を共用接地極として使う場合</h2>
鉄骨造・鉄筋コンクリート造などの建物では、条件を満たす鉄骨・鉄筋その他の金属体を、A種・B種・C種・D種などの共用接地極として使用できる規定がある。<br><br>

この方式では、単に鉄骨へ接続するだけではなく、等電位ボンディングを行い、地絡時に構造体や金属設備間の接触電圧が危険な値にならないようにすることが重要。<br><br>

電気設備技術基準の解釈 第18条では、高圧・特別高圧機器のA種接地やB種接地として構造体を利用する場合に、接触電圧などの追加条件が定められている。<br>

<h2>等電位ボンディングとは？</h2>
等電位ボンディングは、人が同時に触れる可能性のある金属部分同士を電気的に接続し、故障時の電位差を小さくする考え方。<br><br>

接地抵抗を小さくすることだけでなく、「人が触れる2つの金属体の間に危険な電圧を生じさせない」ことが目的。<br>
