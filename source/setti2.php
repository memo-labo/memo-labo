<h2>共用接地とは？</h2>
共用接地とは、複数の接地工事・設備を共通の接地極または建築構造体などへ接続し、設備全体として接地を構成する方法。<br><br>

単純に「接地抵抗が○Ω以下ならA種・B種・C種・D種を全部まとめてよい」と考えるのではなく、接地の目的、地絡電流、接触電圧、保護装置、等電位ボンディングなどを含めて設計する。<br><br>

