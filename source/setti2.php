<h2>A種・B種・C種・D種の役割</h2>
<table>
<tr><th>接地</th><th>主な目的・対象</th></tr>
<tr><td>A種</td><td>高圧・特別高圧機器の金属製外箱など</td></tr>
<tr><td>B種</td><td>高圧・特別高圧と低圧を結合する変圧器の低圧側で、混触時の危険を低減</td></tr>
<tr><td>C種</td><td>300Vを超える低圧機器の金属製外箱など</td></tr>
<tr><td>D種</td><td>300V以下の低圧機器の金属製外箱など</td></tr>
</table>
<br>

B種接地は、単なる機器外箱の接地とは目的が異なる。<br>
共用する場合は、混触故障時の電位上昇・地絡電流・保護協調まで含めて確認する。<br>
