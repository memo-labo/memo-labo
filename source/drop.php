<h2>電圧降下の危険性やデメリット</h2>
電圧降下が生じると、本来必要な電圧が不足する。<br>
すると、定格よりも低い電圧で負荷に電源を供給することになる。<br>
例えばパソコンなどの電子機器の場合、電源が維持できなくなり、突然再起動を起こす。<br>
蛍光灯であれば、寿命や光束が低下したりする可能性がある。<br>


<h2>電圧降下の計算</h2>
e = 各端子間の電圧降下（V）<br>
S = 電線の導体断面積（mm^2）<br>
L = 電線の長さ（m）<br>
I = 電流（A）<br><br>

単相２線式の電圧降下<br>
e =（35.6 × L × I）÷（1000 × S）<br><br>

