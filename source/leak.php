<h2>I0だけでは絶縁劣化を判断しにくい例</h2>
次のような設備では、絶縁が健全でもI0cや高調波成分が増えることがある。<br><br>

・インバータ設備が多い<br>
・ノイズフィルタ、EMIフィルタが多い<br>
・長いケーブルが多い<br>
・対地静電容量の大きい機器が多数接続されている<br><br>

このような回路では、通常のクランプメータでI0を測っただけでは、抵抗性漏れ電流I0rの増加を見分けにくい場合がある。<br>

<h2>I0・Iorを測るときのポイント</h2>
単相2線式・単相3線式・三相回路では、対象回路のすべての活線導体を一括してクランプし、差電流を測定する。<br>
保護接地線だけをクランプして接地線電流を見る方法とは目的が異なる。<br><br>

測定時は、<br>
・負荷の運転状態<br>
・インバータの有無<br>
・測定器の周波数特性
・最小分解能
・Ior演算機能の方式
を確認する。<br>

