<h2>I0・I0r（Ior）・I0c（Ioc）とは？</h2>
漏れ電流を考えるときは、実際に絶縁抵抗を通って流れる抵抗成分と、電路の対地静電容量によって流れる容量成分を分けて考えると分かりやすい。<br><br>

<table>
<tr><th>記号</th><th>意味</th></tr>
<tr><td>I0</td><td>零相電流。抵抗成分・容量成分などを含む合成漏れ電流</td></tr>
<tr><td>I0r / Ior</td><td>抵抗成分の漏れ電流。絶縁劣化・地絡と関係が深い有効分</td></tr>
<tr><td>I0c / Ioc</td><td>対地静電容量によって流れる容量性の漏れ電流</td></tr>
</table>
<br>

<img src="images/leak/2.png" style="max-width:400px;" alt="I0・I0r・I0cのベクトル関係"><br>

<h2>I0cは絶縁不良でなくても流れる</h2>
ケーブル、モーター、インバータ、EMIフィルタなどには対地静電容量がある。<br>
交流電圧が加わると、その静電容量を通じて容量性電流I0cが流れる。<br><br>

そのため、I0が大きいからといって、必ずしも絶縁抵抗が低下しているとは限らない。<br>
設備の容量性漏れ電流が大きい場合は、I0r/Iorを分離して確認できる測定器が有効。<br><br>

<img src="images/leak/1.png" style="max-width:600px;" alt="対地静電容量によるI0c漏れ電流"><br>

<h2>漏れ電流の基本式</h2>
抵抗成分を単純な抵抗Rで考えると、<br><br>

I0r = V / R<br><br>

容量成分は、<br><br>

I0c = 2πfCV<br><br>

で表せる。<br><br>

I0rとI0cがほぼ直交する理想化した条件では、合成値は、<br><br>

I0 = √(I0r² + I0c²)<br><br>

と考えられる。<br>
実設備では高調波・位相・複数回路の影響があるため、測定器のIor演算方式や対象回路条件も確認する。<br>

